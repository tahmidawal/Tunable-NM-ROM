"""Generate QUICK.md from runs/<attempt>/result.json (no hand-typed numbers)."""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent


def main(attempt='quick1024'):
    path = HERE / 'runs' / attempt / 'result.json'
    R = json.loads(path.read_text())
    sha = hashlib.sha256(path.read_bytes()).hexdigest()
    audit_path = HERE / 'runs' / attempt / 'audit.json'
    audit = json.loads(audit_path.read_text()) if audit_path.exists() else None
    rows = []
    base = None
    for arm in R['arms']:
        inv = [x for x in R['invocations'] if x['name'] == arm['name']]
        err = np.array([x['same_grid_error'] for x in inv])
        dev = np.median([x['fused_device_seconds'] for x in inv]) * 1e3
        tot = np.median([x['total_seconds'] for x in inv]) * 1e3
        att = [x.get('attempts') for x in inv if x.get('attempts') is not None]
        rows.append((arm, err.max(), np.median(err), R['floors'][str(arm['Rp'])]['worst'], dev, tot,
                     (np.median(att) if att else None)))
        if arm['name'] == 'orig_q256':
            base = dev
    L = [f"# poisson-bank-knob QUICK — nested bank truncation R' of the frozen R=512 Poisson 2D model, {R['intervals']}²",
         '',
         f"Generated by `make_quick.py` from `runs/{attempt}/result.json` (sha256 `{sha[:16]}`). "
         f"Device: {R['gpu']} — **local, indicative only: timings are NOT results** (shared GB10, no burn-in, "
         f"{max(x['rep'] for x in R['invocations']) + 1} reps x {len(R['cohort']['parameters'])} development sources). "
         'Errors are final for this mesh (same-grid relative L2 vs DST truth, worst over the 12 opened development sources).',
         '',
         f"Parity gate (R' = R rotated vs unrotated parent kernel, bar 1e-10): " +
         '; '.join(f"{p['candidate']} {p['worst_field_relative']:.1e} {'PASS' if p['passed'] else 'FAIL'}" for p in R['parity']),
         '']
    if audit:
        L += [f"Independent NumPy check (`pbk_audit_np.py`): {audit['verdict']} — {audit['summary']}", '']
    L += ["| R' | q | arm | worst err % | median err % | bank floor at R' % | device ms (local) | total ms (local) | LM attempts (median) | device ms / parent q=256 |",
          '|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|']
    for arm, w, md, fl, dv, tt, att in rows:
        kind = {'trunc': 'NM-ROM', 'linear': "linear rung q=R'", 'orig': 'parent (unrotated)'}[arm['kind']]
        L.append(f"| {arm['Rp']} | {arm['q']} | {kind} | {w*100:.3f} | {md*100:.3f} | {fl*100:.3f} | {dv:.2f} | {tt:.2f} | "
                 f"{'' if att is None else f'{att:.0f}'} | {dv / base:.2f} |")
    rot = R['rotation']
    L += ['',
          f"Rotation (offline, training fit split at {rot['training_intervals']} intervals, {rot['training_sources']} sources): "
          f"cumulative training energy {', '.join(f'R={k}: {v:.6f}' for k, v in rot['cumulative_energy'].items())}; "
          f"cond(R_G) = {rot['R_G_condition_number']:.2e}; ||L T - I|| = {rot['L_times_T_identity_deviation']:.1e}.",
          '']
    (HERE / 'QUICK.md').write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main(*sys.argv[1:])
