    w("")
    w("1. **Step 0.** The development ROM (`experiments/ns3d-coordnet/rom_mesh.py`, jobs 6859541/6858038/6858031) "
      "computes the advection with an exact precomputed Petrov–Galerkin tensor "
      "$T_{mjk}=\\langle\\phi_m, G_j\\times\\nabla_h\\times G_k\\rangle$ of shape $292\\times64\\times64$ "
      "(292 solenoidal Fourier tests), built on the grid by FFT; no quadrature or EQ. The domain is the periodic unit torus "
      "(Fourier pseudo-spectral FOM with 2/3 dealiasing), so off-mesh rules apply without boundary treatment (DESIGN §0).")
