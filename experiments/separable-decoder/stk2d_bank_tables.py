"""Generate every phase-2a table in STOKES-NOTES.md from
runs/stk2d/stk2d_bank_gates_bank_nu1.json.

Repository rule (CLAUDE.md, "Reports"): never hand-type a number into a
report.  Run:

    /home/tahmid/Dev/.venv/bin/python stk2d_bank_tables.py [path/to/report.json]

and paste the output between the phase-2a generated-block markers.
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(HERE, "runs/stk2d/stk2d_bank_gates_bank_nu1.json")


def e(x, d=3):
    if x is None:
        return "-"
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, float) and x != x:
        return "nan"
    return f"{x:.{d}e}"


def f(x, d=4):
    return "-" if x is None else f"{x:.{d}f}"


def esc(c):
    return str(c).replace("|", "\\|")


def table(head, rows):
    out = ["| " + " | ".join(esc(h) for h in head) + " |",
           "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(esc(c) for c in r) + " |")
    return "\n".join(out)


def main(path=DEFAULT):
    R = json.load(open(path))
    G = R["gates"]
    C = R["config"]
    print(f"<!-- generated by stk2d_bank_tables.py from "
          f"{os.path.basename(path)} (commit {C['git_commit'][:12]}) "
          f"-- do not edit by hand -->")
    print()

    # ---------------------------------------------------------------- S-RICH
    print("### S-RICH -- manifold richness: the verdict this phase exists for\n")
    print(table(["N", "K", "indep. solenoidal response dirs", "required",
                 "centred snapshot rank", "sigma_K/sigma_0",
                 "Jacobian rank of mu->u", "held-out POD-K err",
                 "AFFINE CONTROL centred rank", "affine control POD-K err"],
                [[r["N"], r["K"], r["n_solenoidal_response_dirs"],
                  r["required_dirs"], r["centred_snapshot_rank"],
                  e(r["centred_sv_ratio_K"]), str(r["jacobian_rank"]),
                  e(r["heldout_pod_K_err"]),
                  r["affine_control_centred_rank"],
                  e(r["affine_control_podK_err"])]
                 for r in G["S_RICH"]["rows"]]))
    print()
    print("Held-out POD-R reconstruction error (mass-weighted relative), from "
          "the psi-route bank:\n")
    Rs = sorted(G["S_RICH"]["rows"][0]["heldout_pod_err"], key=int)
    print(table(["N"] + [f"POD-{r}" for r in Rs],
                [[r["N"]] + [e(r["heldout_pod_err"][k]) for k in Rs]
                 for r in G["S_RICH"]["rows"]]))
    print()

    # --------------------------------------------------------------- S-HODGE
    print("### S-HODGE -- force mixture, measured\n")
    print(table(["N", "solenoidal energy frac (min/mean/max)",
                 "gradient energy frac (min/mean/max)",
                 "partition defect", "||Grad_h p||/||f|| (min/mean/max)"],
                [[r["N"],
                  f"{r['sol_frac_min']:.4f} / {r['sol_frac_mean']:.4f} / "
                  f"{r['sol_frac_max']:.4f}",
                  f"{r['grad_frac_min']:.4f} / {r['grad_frac_mean']:.4f} / "
                  f"{r['grad_frac_max']:.4f}",
                  e(r["partition_defect_max"]),
                  f"{r['gradp_over_f_min']:.4f} / {r['gradp_over_f_mean']:.4f}"
                  f" / {r['gradp_over_f_max']:.4f}"]
                 for r in G["S_HODGE"]["rows"]]))
    print()

    # ---------------------------------------------------------------- S-DICT
    print("### S-DICT -- the affine dictionary\n")
    print(table(["N", "Q", "Q_sol", "Q_grad", "rank", "cond",
                 "solenoidal atom div", "gradient atom off-family energy",
                 "solenoidal atom off-family energy",
                 "NEG CTL analytic curl (min/max)"],
                [[r["N"], r["Q"], r["Q_sol"], r["Q_grad"], r["dict_rank"],
                  e(r["dict_cond"]), e(r["sol_atom_div_max"]),
                  e(r["grad_atom_offfamily_max"]),
                  e(r["sol_atom_offfamily_max"]),
                  f"{e(r['analytic_curl_control_min'])} / "
                  f"{e(r['analytic_curl_control_max'])}"]
                 for r in G["S_DICT"]["rows"]]))
    print()

    # -------------------------------------------------------------------- S1
    print("### S1 -- bank divergence per mode, and the 1/sigma_i amplification\n")
    print(table(["N", "R", "snapshot div", "psi route (raw)",
                 "psi route (normalised)", "psi route (reorthogonalised)",
                 "naive route head", "naive route tail",
                 "naive amplification", "sigma_0/sigma_R",
                 "NEG CTL naive (contaminated)", "psi under the same control"],
                [[r["N"], r["R"], e(r["snapshot_div_max"]),
                  e(r["psi_div_max"]), e(r["psi_norm_div_max"]),
                  e(r["psi_qr_div_max"]), e(r["naive_div_head"]),
                  e(r["naive_div_tail"]), e(r["naive_amplification"], 2),
                  e(r["sigma_ratio_tail"], 2),
                  e(r["contaminated_naive_div_max"]),
                  e(r["contaminated_psi_div_max"])]
                 for r in G["S1"]["rows"]]))
    print()
    print(table(["N", "R", "orthonormality (raw Gram POD)",
                 "its (sigma_0/sigma_R)^2 budget",
                 "orthonormality (reorthogonalised)"],
                [[r["N"], r["R"], e(r["orthonormality_max"]),
                  e(r["orthonormality_budget"]),
                  e(r["orthonormality_qr_max"])]
                 for r in G["S1"]["rows"]]))
    print()

    # ---------------------------------------------------------------- S-MEAN
    print("### S-MEAN -- the affine mean\n")
    print(table(["N", "R", "||D ubar||/(||D||||ubar||), psi route",
                 "same, plain snapshot mean",
                 "||ubar - C psibar||/||ubar||",
                 "NEG CTL (+1e-6 gradient)"],
                [[r["N"], r["R"], e(r["mean_psi_div"]), e(r["mean_div"]),
                  e(r["mean_psi_defect"]), e(r["mean_control_div"])]
                 for r in G["S_MEAN"]["rows"]]))
    print()

    # -------------------------------------------------------------------- S2
    print("### S2 -- the test space\n")
    print(table(["N", "M", "||DC||_inf", "||D Phi|| per col, unnormalised",
                 "||D Phi|| per col, mass-normalised", "aggregate",
                 "NEG CTL analytic k!=l (min)", "k==l (max, exact)",
                 "||phi||_M/sqrt(lambda) (min/max)"],
                [[r["N"], r["M"], e(r["struct_DC_inf"]),
                  e(r["phi_div_raw_max"]), e(r["phi_div_norm_max"]),
                  e(r["phi_div_norm_aggregate"]),
                  e(r["analytic_control_offdiag_min"]),
                  e(r["analytic_control_diag_max"]),
                  f"{r['norm_over_sqrt_lambda_min']:.6f} / "
                  f"{r['norm_over_sqrt_lambda_max']:.6f}"]
                 for r in G["S2"]["rows"]]))
    print()

    # -------------------------------------------------------------------- S5
    print("### S5 -- the curl-sine modes are NOT eigenvectors of the no-slip "
          "vector Laplacian\n")
    print(table(["N", "kmax", "modes", "eigres min", "med", "max",
                 "design anchor (min, max)", "0.5 floor asserted?",
                 "NEG CTL even ghosts (max)", "its eps N^2 ceiling",
                 "odd/even separation"],
                [[r["N"], r["kmax"], r["n_modes"], f(r["eigres_min"], 6),
                  f(r["eigres_med"], 6), f(r["eigres_max"], 6),
                  (f"{r['anchor_min']}, {r['anchor_max']}"
                   if r["anchor_min"] is not None else "-"),
                  str(r["anchored"]), e(r["eigres_evenghost_max"]),
                  e(r["evenghost_ceiling"]), e(r["ctl_ratio"], 2)]
                 for r in G["S5"]["rows"]]))
    print()
    print("Secondary diagnostic ||A + Lambda B||/||A|| (note the PLUS: the "
          "convention here is L Phi = -Phi Lambda, so 0 would mean a diagonal "
          "A suffices):\n")
    print(table(["N", "auditor's clamped basis", "design anchor",
                 "the phase-2a bank", "even-ghost control (clamped)",
                 "even-ghost control (bank)"],
                [[r["N"], f(r["aratio_audit_basis"], 6),
                  f(r["aratio_anchor"], 3) if r["aratio_anchor"] else "-",
                  f(r["aratio_bank"], 6) if r["aratio_bank"] else "-",
                  e(r["aratio_audit_basis_evenghost"]),
                  e(r["aratio_bank_evenghost"])
                  if r["aratio_bank_evenghost"] else "-"]
                 for r in G["S5"]["rows"]]))
    print()

    # ---------------------------------------------------------------- S-SPEC
    print("### S-SPEC -- spectrum, rank, and the unreachable R = 64 rung\n")
    print(table(["N", "snapshots", "numerical rank (direct SVD)",
                 "rank via the Gram route", "Gram noise floor",
                 "sigma_{Q_sol}/sigma_0", "sigma_{Q_sol+1}/sigma_0",
                 "rank gap", "R=64 reachable?", "nested-bank max diff"],
                [[r["N"], r["n_snapshots"], r["numerical_rank"],
                  r["numerical_rank_gram_route"], e(r["gram_noise_floor"]),
                  e(r["sigma_Qsol_over_sigma0"]),
                  e(r["sigma_Qsol_plus1_over_sigma0"]),
                  e(r["rank_gap"], 2),
                  str(r["R64_reachable"]), e(r["nested_bank_max_diff"])]
                 for r in G["S_SPEC"]["rows"]]))
    print()
    row = G["S_SPEC"]["rows"][-1]
    sv = row["sigma_over_sigma0"]
    idx = [0, 1, 3, 7, 15, 23, 31, 32, 35, 39]
    idx = [i for i in idx if i < len(sv)]
    print(f"Singular spectrum at N={row['N']} (mass-weighted, "
          f"sigma_i/sigma_0):\n")
    print(table(["i"] + [str(i + 1) for i in idx],
                [["sigma_i/sigma_0"] + [e(sv[i], 4) for i in idx]]))
    print()

    # -------------------------------------------------------------- S-SOLVE
    print("### S-SOLVE -- the factor-once path against the certified solver\n")
    print(table(["N", "n_u", "vs certified (u)", "vs certified (p)",
                 "affine superposition (max / median)",
                 "its h^-2 budget", "cancellation ratio", "factor s",
                 "ms / back-substitution",
                 "NEG CTL: 1e-9-perturbed solution"],
                [[r["N"], r["n_u"], e(r["vs_certified_u_max"]),
                  e(r["vs_certified_p_max"]),
                  f"{e(r['affine_superposition_max'])} / "
                  f"{e(r['affine_superposition_med'])}",
                  e(r["affine_superposition_budget"]),
                  f"{r['affine_cancellation_ratio']:.2f}",
                  f"{r['factor_seconds']:.1f}", f"{r['ms_per_solve']:.0f}",
                  e(r["perturbed_backerr_control"])]
                 for r in G["S_SOLVE"]["rows"]]))
    print()

    S = G["S_SOLVE"]
    print(table(["quantity", "worst over all solves", "rule"],
                [["global backward error", e(S["worst_backward_err"]),
                  f"<= {C['thresholds']['backerr_tol']:g}"],
                 ["momentum block", e(S["worst_mom_resid"]),
                  f"<= {C['thresholds']['backerr_tol']:g}"],
                 ["continuity block (blockwise BW error)",
                  e(S["worst_cont_resid"]),
                  f"<= {C['thresholds']['cont_tol']:g}"],
                 ["continuity, PHASE 1's normalisation",
                  e(S["worst_cont_resid_phase1_diagnostic"]),
                  "DIAGNOSTIC ONLY -- collapses on gradient atoms"],
                 ["mean-zero gauge (normalised)", e(S["worst_gauge_resid"]),
                  f"<= {C['thresholds']['gauge_tol']:g}"],
                 ["mean-zero gauge (raw |1^T p|)", e(S["worst_gauge_raw"]),
                  "RECORDED ONLY -- not scale-free"],
                 ["number of solves", str(S["n_solves"]), "all tracked"]]))
    print()

    print("### Supporting gates\n")
    man = G["MANIFEST"]
    print(table(["gate", "value", "rule"],
                [["PRECOND (asserts / config mismatch / smoke)",
                  f"{G['PRECOND']['debug_asserts_active']} / "
                  f"{len(G['PRECOND']['config_mismatch'])} / "
                  f"{G['PRECOND']['smoke']}",
                  "asserts live, config == frozen contract, smoke=0"],
                 ["S0 (dtype / jax x64 / matmul / backend)",
                  f"{G['S0']['numpy_float64']} / {G['S0']['jax']['x64']} / "
                  f"{G['S0']['jax']['matmul_precision']} / "
                  f"{G['S0']['jax']['backend']}", "all asserted"],
                 ["MANIFEST (missing / row mismatch / non-finite)",
                  f"{len(man['missing_gates'])} / "
                  f"{len(man['row_count_mismatch'])} / "
                  f"{len(man['nonfinite_fields'])}", "all zero"]]))
    print()
    print(f"run: {os.path.basename(path)} | driver rev "
          f"{C['driver_revision']} | complete={R['complete']} "
          f"certified={R.get('certified')} | commit `{C['git_commit'][:12]}` | "
          f"host `{C['hostname']}` | numpy {C['numpy']} scipy {C['scipy']} | "
          f"jax backend `{C['jax']['backend']}` x64={C['jax']['x64']} matmul "
          f"`{C['jax']['matmul_precision']}` | total "
          f"{R.get('total_seconds', 0):.0f} s")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
