"""Generate reports/2026-09-23-burgers-bank-knob.md from checks/bk*-summary.json (audits). No number is typed by hand.

    python reports/generate_report.py
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANE = HERE.parent
MESHES = [256, 512, 1024, 2048, 4096]


def f(x, d=3):
    if x is None:
        return '—'
    if isinstance(x, float):
        return f'{x:,.{d}f}'
    return str(x)


def sp(x):
    return '—' if x is None else f'{x:.2f}×'


def fam(t):
    if t.get('control'):
        return 'control'
    if t['model'] == 'parent':
        return 'parent (unrotated)'
    return {'lin': '(b) linear', 'trunc': '(a) head' if t['q'] == 0 else '(c) head+corr'}[t['model']]


def main():
    out = ['# Burgers 2D: the nested bank truncation $R\'$ as the tunability knob (no retraining)', '']
    sums = {}
    for L in MESHES:
        p = LANE / 'checks' / f'bk{L}-summary.json'
        if p.exists():
            sums[L] = (json.loads(p.read_text()), hashlib.sha256(p.read_bytes()).hexdigest())
    hold = LANE / 'checks' / 'bkh64-summary.json'
    status = 'final' if len(sums) == len(MESHES) and hold.exists() else f'partial ({len(sums)} of {len(MESHES)} meshes landed)'
    out += [f'Status: **{status}**. Generated by `reports/generate_report.py` from `checks/bk*-summary.json` '
            '(independent NumPy audits of the saved fields). Design and the pre-registered setting rule: `DESIGN.md`. '
            'Frozen checkpoint, no retraining; the bank rotation uses training codes only.', '']
    # headline
    out += ['## Selected settings per mesh (pre-registered rule, DESIGN §6)', '',
            '| mesh | job | accurate arm | worst % | median % | GPU ms | FOM (rule) | FOM ms | Table-1 speedup | fast arm | worst % | GPU ms | FOM ≥ as accurate | speedup | current accurate (R\'=512, q=256) worst % / ms | q droppable? | audit |',
            '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for L, (s, _) in sums.items():
        se = s['selection']
        a, fa, cur = se.get('accurate'), se.get('fast'), se.get('current_accurate_arm')
        t1 = se.get('table1') or {}
        qd = se.get('q_droppable') or {}
        out.append(f"| ${L}^2$ | {s['job_id']} | `{a['name'] if a else None}` | {f(a and a['worst_evolved_percent'])} | "
                   f"{f(a and a['median_evolved_percent'])} | {f(a and a['median_gpu_ms'], 1)} | `{t1.get('fom')}` | "
                   f"{f(t1.get('fom_gpu_ms'), 1)} | {sp(t1.get('speedup_gpu'))} | `{fa['name'] if fa else None}` | "
                   f"{f(fa and fa['worst_evolved_percent'])} | {f(fa and fa['median_gpu_ms'], 1)} | "
                   f"`{fa and fa['fom_at_least_as_accurate']}` | {sp(fa and fa['speedup_gpu'])} | "
                   f"{f(cur and cur['worst_evolved_percent'])} / {f(cur and cur['median_gpu_ms'], 1)} | "
                   f"{qd.get('verdict')} | {'accepted' if s['accepted'] else 'FAILED: ' + ', '.join(s['failed_gates'])} |")
    out.append('')
    for L, (s, _) in sums.items():
        se = s['selection']
        for k in ('accurate_if_certificates_ignored', 'fast_if_certificates_ignored'):
            if se.get(k):
                x = se[k]
                out.append(f"- ${L}^2$, {k.replace('_', ' ')}: `{x['name']}` {f(x['worst_evolved_percent'])} %, "
                           f"{f(x['median_gpu_ms'], 1)} ms, certificate **{x['certificate']}** (marked; not selectable).")
        qd = se.get('q_droppable') or {}
        if qd:
            b, bi = qd.get('best_without_q'), qd.get('best_without_q_ignoring_certificates')
            out.append(f"- ${L}^2$, without $q$: best confirmed (a)/(b) arm `{b and b['name']}` "
                       f"{f(b and b['worst_evolved_percent'])} % against the current accurate {f(qd['target_percent'])} %"
                       + (f"; ignoring certificates `{bi['name']}` {f(bi['worst_evolved_percent'])} % ({bi['certificate']})"
                          if bi and (not b or bi['name'] != b['name']) else '') + '.')
    out.append('')
    # full tables
    for L, (s, h) in sums.items():
        out += [f"## ${L}^2$ — attempt `{s['attempt']}`, job {s['job_id']}, {s['gpu']}, commit `{(s['commit'] or '')[:8]}`", '',
                f"Cohort: {s['cohort']} ({s['cohort_cases']} cases). Summary `checks/bk{L}-summary.json` sha256 `{h}`.", '',
                '| family | R\' | q | unknowns | M | rule (m) | worst evolved % | median % | GPU ms | iters (median) | stalled | rule ρ max (cert / confirm) | certificate | fastest FOM ≥ as accurate | FOM ms | speedup |',
                '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
        rows = [t for t in s['table'].values() if t['family'] == 'rom']
        rows.sort(key=lambda t: (fam(t), -t['R_prime']))
        for t in rows:
            out.append(f"| {fam(t)} | {t['R_prime']} | {t['q'] if t['model'] != 'lin' else '—'} | {t['unknowns']} | {t['M']} | "
                       f"`{t['rule']}` ({t['m']}) | {f(t['worst_evolved_percent'])} | {f(t['median_evolved_percent'])} | "
                       f"{f(t['median_gpu_ms'], 1)} | {f(t['total_iterations_median'], 0)} | {t['stalled_exits']} | "
                       f"{f(t['rho_max_cert'], 4)} / {f(t['rho_max_confirmation'], 4)} | {t['certificate']} | "
                       f"`{t.get('fom_at_least_as_accurate')}` | {f(t.get('fom_gpu_ms'), 1)} | {sp(t.get('speedup_gpu'))} |")
        out += ['', '| Newton–BiCGStab setting | worst evolved % | GPU ms | converged |', '|---|---|---|---|']
        for t in sorted([t for t in s['table'].values() if t['family'] == 'fom'], key=lambda t: t['median_gpu_ms'] or 0):
            out.append(f"| `{t['name']}` | {f(t['worst_evolved_percent'], 4)} | {f(t['median_gpu_ms'], 1)} | {t['nonlinear_converged']} |")
        g = s['gates']
        out += ['', 'Gates: ' + ', '.join(f"{k}={v['passed']}" for k, v in g.items()) + '.', '']
        if s['parity']:
            out.append('Parity (rotated $R\'=512$ vs unrotated parent): ' + '; '.join(
                f"`{x['rotated']}` worst {x['worst_relative']:.2e}, integers identical {x['integers_identical']}" for x in s['parity']) + '.')
        oe = g.get('no_order_effect', {})
        out.append(f"Order effect: pooled gap {f(oe.get('pooled_gap'), 4)} (n long {oe.get('pooled_n_long')}), worst evaluable arm "
                   f"{f(oe.get('worst_evaluable_arm_gap'), 4)} over {oe.get('evaluable_arms')} arms.")
        out.append('')
    if hold.exists():
        s = json.loads(hold.read_text())
        h = hashlib.sha256(hold.read_bytes()).hexdigest()
        out += [f"## $4096^2$ held-out (hold64) — job {s['job_id']}, {s['gpu']}", '', f"Summary sha256 `{h}`.", '',
                '| arm | worst evolved % | median % | GPU ms | fastest FOM ≥ as accurate | FOM % | FOM ms | speedup |', '|---|---|---|---|---|---|---|---|']
        for t in sorted([t for t in s['table'].values() if t['family'] == 'rom'], key=lambda t: t['worst_evolved_percent']):
            out.append(f"| `{t['name']}` | {f(t['worst_evolved_percent'])} | {f(t['median_evolved_percent'])} | {f(t['median_gpu_ms'], 1)} | "
                       f"`{t.get('fom_at_least_as_accurate')}` | {f(t.get('fom_worst_evolved_percent'), 4)} | {f(t.get('fom_gpu_ms'), 1)} | {sp(t.get('speedup_gpu'))} |")
        out += ['', 'Gates: ' + ', '.join(f"{k}={v['passed']}" for k, v in s['gates'].items()) + '.', '']
    out += ['## Glossary', '',
            '- **$R\'$** — how many columns of the rotated spatial bank a query uses (of $R=512$). The rotation is computed once, offline, from training codes only, so the first columns carry the most training energy.',
            '- **(a) head** — the nonlinear head alone ($q=0$, 16 unknowns). **(b) linear** — head dropped, the $R\'$ bank coefficients themselves are the unknowns. **(c) head+corr** — head plus $q=\\min(256,R\'-16)$ correction directions.',
            '- **M** — number of weak test functions (sine modes) the residual is projected on. **rule (m)** — the empirical quadrature rule for the advection and its node count.',
            '- **worst / median evolved %** — max over the five evolved output times of $\\lVert u-u_{\\rm ref}\\rVert/\\lVert u_0\\rVert$, reference = tight Newton–BiCGStab at the same mesh; worst / median over the six development cases.',
            '- **GPU ms** — median query time, dense input already on the GPU to six dense output fields on the GPU.',
            '- **ρ max** — largest relative error of the quadrature-tested advection over every state the arm itself reaches on held-out trajectories (5 certification draws / 1 confirmation draw). **confirmed** = ≤ 0.116 on all six.',
            '- **fastest FOM ≥ as accurate / speedup** — the fastest full-order setting in the same job whose worst error is at most the arm\'s; speedup = its GPU ms ÷ the arm\'s.',
            '- **Table-1 speedup** — that ratio for the selected accurate arm. **q droppable?** — whether a confirmed (a) or (b) arm is at least as accurate as the current accurate setting ((c) at $R\'=512$).',
            '- **parity** — the rotated model at $R\'=512$ must reproduce the unrotated model to $10^{-10}$ with identical iteration counts.']
    (HERE / '2026-09-23-burgers-bank-knob.md').write_text('\n'.join(out) + '\n')
    print('written', len(sums), 'meshes')


if __name__ == '__main__':
    main()
