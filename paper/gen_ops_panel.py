# Data-parity accounting (lane ops-tune-grid @4fee6965).  Primitive counts and the measured per-trajectory cost are
# read from the pinned arithmetic re-derivation; every ratio below is recomputed here rather than quoted.
EP = HERE / 'evidence/ops-data-parity-2026-09-22'
MANP = json.loads((EP / 'manifest.json').read_text())
for k, v in MANP.items():
    assert hashlib.sha256((EP / k).read_bytes()).hexdigest() == v['sha256'], k
PAR = (EP / 'for-paper-arithmetic.txt').read_text()
import re as _re


def _num(pat):
    m = _re.search(pat, PAR); assert m, pat
    return float(m.group(1))


def parity_macros():
    op_s = _num(r'operator s/trajectory: median ([0-9.]+)')
    op_traj = int(_num(r'(\d+) cases at pinned fidelity'))
    rom_traj = int(_num(r'(\d+) cases at pinned fidelity: 586135'))
    per_traj = int(_num(r'states available \d+\*(\d+) ='))
    per_case = int(_num(r'operator supervised states \d+\*(\d+) ='))
    rom_states = int(_num(r'state ratio (\d+)/'))
    ratio = _num(r'cost ratio ([0-9.]+)')                       # 127.2 s vs the NM-ROM's 0.19 s (job 2837431's log)
    rom_s = op_s / ratio
    fmt = lambda n: f'{n:,}'.replace(',', r'\,')
    return dict(nParOpTraj=str(op_traj), nParRomTraj=fmt(rom_traj),
                nParTrajRatio=f'{rom_traj / op_traj:.0f}',
                nParOpSec=f'{op_s:.1f}', nParRomSec=f'{rom_s:.2f}', nParCostRatio=f'{round(ratio, -1):.0f}',
                nParOpHours=f'{op_traj * op_s / 3600:.1f}', nParFullHours=f'{rom_traj * op_s / 3600:.0f}',
                nParOpStates=fmt(op_traj * per_case), nParPerCase=str(per_case),
                nParRomStates=fmt(rom_states), nParStatesAvail=fmt(rom_traj * per_traj),
                nParRomJob='2837431')


