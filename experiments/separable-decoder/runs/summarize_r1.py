#!/usr/bin/env python3
"""Round-1 summary tables FROM THE RUN JSONS (never hand-typed).

Usage: python runs/summarize_r1.py runs/<job>/out/*.json > runs/SUMMARY-r1.md
"""
import json
import sys

import numpy as np


def main(paths):
    pois, burg = [], []
    for p in sorted(paths):
        d = json.load(open(p))
        if d["config"].get("round") not in (1, 2):
            continue
        (pois if d["config"]["pde"] == "poisson2d" else burg).append((p, d))

    print("# N=256 push round-1 summary (generated by runs/summarize_r1.py)\n")

    for p, d in pois:
        c = d["config"]
        t = d.get("train", {})
        print(f"## Poisson r{c['round']} (N={c['N']} K={c['k']} R={c['r']} "
              f"steps={c['steps']}, {c.get('gpu','?')}, job "
              f"{c.get('slurm_job')}, arch={c.get('arch_overrides')})\n")
        print(f"train: recon rel-L2 mean {t.get('recon_rel_l2_mean', float('nan')):.3e} "
              f"({t.get('seconds',0):.0f}s)\n")
        print("### Error ladder (rung -> value; held / fresh)\n")
        o = d.get("oracle", {})
        w = d.get("weak_opt", {})
        cohs = list(o.keys())
        if cohs:
            print("| rung | " + " | ".join(cohs) + " |")
            print("|" + "---|" * (1 + len(cohs)))
            print("| train recon (mean) | "
                  + " | ".join(f"{t.get('recon_rel_l2_mean', float('nan')):.3e}"
                               for _ in cohs) + " |")
            print("| oracle (all fields, multi-init) | "
                  + " | ".join(f"{o[cn]['mean']:.3e}" for cn in cohs) + " |")
            for eqn in w:
                print(f"| weak-EQ optimum [{eqn}] (diag) | "
                      + " | ".join(f"{w[eqn][cn]['err_mean']:.3e}"
                                   for cn in cohs) + " |")
            arms_seen = [r["method"] for r in d["rows"]
                         if r.get("tau") == c["taus"][0]
                         and r["cohort"] == cohs[0]]
            for arm in ("cach|ctrl|lm60|zbar", "cach|ctrl|lm60|enc",
                        "cach|ctrl|rst300|enc", "cach|M256|rst300|enc"):
                if arm not in arms_seen:
                    continue
                vals = []
                for cn in cohs:
                    rr = [r for r in d["rows"] if r["method"] == arm
                          and r["cohort"] == cn and r["tau"] == c["taus"][0]]
                    vals.append(f"{rr[0]['err_rel_l2']:.3e}" if rr else "-")
                print(f"| solve [{arm}] tau={c['taus'][0]:.0e} | "
                      + " | ".join(vals) + " |")
        print("\n### Arms (tau=%.0e)\n" % c["taus"][0])
        print("| arm | cohort | err mean | err max | obj/obj0 | ms | jac | "
              "rs | cens% | reasons |")
        print("|" + "---|" * 10)
        for r in d["rows"]:
            if r["tau"] != c["taus"][0]:
                continue
            print(f"| {r['method']} | {r['cohort']} | {r['err_rel_l2']:.3e} | "
                  f"{r['err_rel_l2_max']:.3e} | {r['obj_rel_mean']:.2e} | "
                  f"{r['time_ms']:.3f} | {r['jac_evals']:.1f} | "
                  f"{r['restarts_mean']:.1f} | {r['censored_frac']*100:.0f} | "
                  f"{r['stop_reasons']} |")
        print("\n### FOM CG ladder\n")
        print("| tol | cohort | err mean | err max | ms |")
        print("|" + "---|" * 5)
        for f in d.get("fom", []):
            print(f"| {f['fom_tol']:.0e} | {f['cohort']} | "
                  f"{f['err_rel_l2']:.3e} | {f['err_rel_l2_max']:.3e} | "
                  f"{f['time_ms']:.3f} |")
        print("\n### EQ sets\n")
        print("| set | M | m | rel fit | row p95 | row max | gate0 |")
        print("|" + "---|" * 7)
        for name, e in d.get("eq", {}).items():
            print(f"| {name} | {e['M']} | {e['m']} | {e['rel_fit']:.2e} | "
                  f"{e['row_rel_p95']:.1e} | {e['row_rel_max']:.1e} | "
                  f"{e['gate0']:.1e} |")
        adq = d.get("adq", {}).get("rows", [])
        if adq:
            print("\n### Adaptive quadrature (fresh cohort, per query, "
                  "host NNLS refit INSIDE the reported time)\n")
            print("| src | err | total s | obj/obj0 | EQ p95 | EQ max |")
            print("|" + "---|" * 6)
            for r in adq:
                print(f"| {r['src']} | {r['err_rel_l2']:.3e} | "
                      f"{r['time_s_total']:.1f} | {r['obj_rel']:.2e} | "
                      f"{r['eq_diag']['row_rel_p95']:.1e} | "
                      f"{r['eq_diag']['row_rel_max']:.1e} |")
        g = d.get("gates", {})
        print("\ngates: " + ", ".join(
            f"{k}={v if not isinstance(v, dict) else v.get('rel_dz')}"
            for k, v in g.items()) + "\n")

    for p, d in burg:
        c = d["config"]
        t = d.get("train", {})
        print(f"## Burgers r1 (N={c['N']} K={c['k']} R={c['r']} "
              f"steps={c['steps']}, {c.get('gpu','?')}, job "
              f"{c.get('slurm_job')})\n")
        print(f"train: recon rel-L2 mean {t.get('recon_rel_l2_mean', float('nan')):.3e} "
              f"({t.get('seconds',0):.0f}s)\n")
        print("### e2e arms (END-TO-END: ic fit + rollout + full decode)\n")
        print("| arm | err mean | err max | ic_rel mean/max | e2e ms | jac | "
              "rs | blowups | reasons |")
        print("|" + "---|" * 9)
        for r in d["rows"]:
            if not r["method"].startswith(("cach|", "mesh|")):
                continue
            print(f"| {r['method']} | {r['err_traj_rel_mean']:.3e} | "
                  f"{r['err_traj_rel_max']:.3e} | {r['ic_rel_mean']:.2e}/"
                  f"{r['ic_rel_max']:.2e} | {r['e2e_ms_median']:.2f} | "
                  f"{r['jac_total_mean']:.0f} | {r['restarts_mean']:.0f} | "
                  f"{r['n_blowups']} | {r['stop_reasons']} |")
        print("\n### Splits (median over trajectories, ms)\n")
        sp = d.get("splits", [])
        if sp:
            keys_ic = [k for k in sp[0] if k.startswith("ic_") and k.endswith("_ms")]
            keys_ro = [k for k in sp[0] if k.startswith("roll_") and k.endswith("_ms")]
            print("| split | median ms | notes |")
            print("|---|---|---|")
            for k in keys_ic:
                base = k[:-3]
                rels = [s[f"{base}_rel"] for s in sp]
                jacs = [s[f"{base}_jac"] for s in sp]
                print(f"| {base} | {np.median([s[k] for s in sp]):.2f} | "
                      f"rel mean {np.mean(rels):.2e} max {np.max(rels):.2e}, "
                      f"jac mean {np.mean(jacs):.0f} |")
            for k in keys_ro:
                base = k[:-3]
                jacs = [s[f"{base}_jac"] for s in sp]
                print(f"| {base} | {np.median([s[k] for s in sp]):.2f} | "
                      f"jac mean {np.mean(jacs):.0f} |")
            print(f"| decode | {np.median([s['decode_ms'] for s in sp]):.2f} | |")
        print("\n### Classical ladder (same job, same GPU)\n")
        print("| method | tol | err mean | err max | ms | conv frac |")
        print("|" + "---|" * 6)
        for r in d["rows"]:
            if r["method"] == "fom_newton_tol":
                print(f"| fom_newton_tol | {r['newton_tol']:.0e} | "
                      f"{r['err_traj_rel_mean']:.3e} | "
                      f"{r['err_traj_rel_max']:.3e} | "
                      f"{r['time_ms_median']:.1f} | "
                      f"{r['steps_converged_frac']:.2f} |")
            elif r["method"] == "fom_newton8_truthgen":
                print(f"| truthgen (OVER-SOLVED) | - | "
                      f"{r['err_traj_rel_mean']:.1e} | - | "
                      f"{r['time_ms_median']:.1f} | - |")
        print("\n### Ladder diagnostics\n")
        orc = d.get("oracle", [])
        if orc:
            print("| traj | oracle mean | oracle max | oracle t0 |")
            print("|" + "---|" * 4)
            for r in orc:
                print(f"| {r['traj']} | {r['mean']:.3e} | {r['max']:.3e} | "
                      f"{r['t0']:.3e} |")
        ss_ = d.get("single_step_weak_opt", {}).get("rows", [])
        if ss_:
            print("\nsingle-step weak-opt (from oracle z of true prev state; "
                  "diagnostic):\n")
            print("| traj | t | step err | oracle err at t | reason |")
            print("|" + "---|" * 5)
            for r in ss_:
                print(f"| {r['traj']} | {r['t']} | {r['err']:.3e} | "
                      f"{r['oracle_err']:.3e} | {r['reason']} |")
        print("\n### EQ sets\n")
        print("| set | rel fit | row p95 | row max | gate0 |")
        print("|" + "---|" * 5)
        for name, e in d.get("eq", {}).items():
            print(f"| {name} | {e['rel_fit']:.2e} | {e['row_rel_p95']:.1e} | "
                  f"{e['row_rel_max']:.1e} | {e['gate0']:.1e} |")
        g = d.get("gates", {})
        print("\ngates: " + ", ".join(
            f"{k}={v if not isinstance(v, dict) else v.get('rel_dz')}"
            for k, v in g.items()) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
