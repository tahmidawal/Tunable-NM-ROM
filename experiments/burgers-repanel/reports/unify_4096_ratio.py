"""Apply the paper's full-order rule INSIDE one 4096^2 job, to every tunability-ladder rung.

    python reports/unify_4096_ratio.py            # -> reports/2026-09-22-4096-single-job-ladder.md

Why this exists. The paper prints two different, individually correct ratios for the SAME Burgers fast arm at
4096^2 because two jobs offered different full-order grids: Table 1 prints 10.10x (job 4153483's grid, comparator
`lean_nt1e-3_l1e-3_dt01`) and Table 4's tunability ladder prints 12.9x/13.2x (jobs 4079320/4079321, comparator
`lean_nt3e-3_l3e-3_dt005`). Unifying them across jobs would need a cross-job division, which is forbidden.

It turns out no new job is needed: the `hires-burgers` job 4079320 (and its held-out twin 4079321) ALREADY timed
every ladder rung and BOTH comparators in one allocation. This script applies the rule -- the fastest tested
setting at this mesh whose worst evolved error is at least as small as the rung's -- inside each job separately,
so every rung gets a comparator from its own job and both tables can carry the same number.

Coarse-grid comparators (c1024, c2048) are excluded: the paper compares only against named iterative full-order
solvers at the same mesh.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANE = HERE.parent.parent / 'hires-burgers' / 'checks'
JOBS = [('hb4k04', 'dev6', LANE / 'hb4k04-summary.json'),
        ('hb4kh64', 'hold64', LANE / 'hb4kh64-summary.json')]
# the six rungs Table 4's tunability ladder carries, on the deployed (pred2) optimised path
LADDER = ['q0_M64_scaled_g0p001_fast_clip_lamcarry_pred2',
          'q128_M576_lat64_g0p001_fast_chol_clip_lamcarry_pred2',
          'q256_M544_lat64_g0p001_fast_chol_clip_lamcarry_pred2',
          'q256_M1088_lat64_g0p001_fast_chol_clip_lamcarry_pred2',
          'q256_M1088_lat64_g0p01_fast_chol_clip_lamcarry_pred2',
          'q256_M2176_lat64_g0p001_fast_chol_clip_lamcarry_pred2']


def pick(foms, err):
    ok = [n for n, f in foms.items() if f['nonlinear_converged'] and f['worst_evolved_percent'] <= err]
    return min(ok, key=lambda n: foms[n]['median_gpu_ms']) if ok else None


def main():
    out = ['# $4096^2$: one comparator per ladder rung, from that rung\'s own job', '',
           'Generated by `reports/unify_4096_ratio.py` from the `hires-burgers` audit summaries already on disk; '
           'no number is typed by hand. **No new job was needed**: jobs 4079320 and 4079321 each timed every '
           'ladder rung and every candidate full-order setting -- including both `lean_nt3e-3_l3e-3_dt005` and '
           '`lean_nt1e-3_l1e-3_dt01` -- in ONE allocation.', '',
           'Rule applied: the *fastest* tested Newton--BiCGStab setting at this mesh whose worst evolved error is '
           'at least as small as the rung\'s. Coarse-grid comparators are excluded.', '']
    rows = {}
    for attempt, cohort, p in JOBS:
        d = json.loads(p.read_text())
        t = d['table']
        L = d['intervals']
        foms = {n: x for n, x in t.items() if x['family'] == 'fom' and x.get('mesh', L) == L}
        out += [f'## `{attempt}` — job {d["job_id"]}, {cohort} cohort, {d["gpu"]}, commit `{d["commit"]}`', '',
                '| rung | worst evolved % | ROM GPU ms | ROM complete ms | FOM by the rule | FOM % | FOM GPU ms | '
                'FOM complete ms | speedup GPU | speedup complete |', '|---|---|---|---|---|---|---|---|---|---|']
        for name in LADDER:
            x = t.get(name)
            if x is None:
                out.append(f'| `{name}` | not timed in this job | | | | | | | | |')
                continue
            f = pick(foms, x['worst_evolved_percent'])
            fo = foms[f]
            rows.setdefault(name, {})[attempt] = dict(
                fom=f, speedup_gpu=fo['median_gpu_ms'] / x['median_gpu_ms'],
                speedup_host=fo['median_host_ms'] / x['median_host_ms'])
            out.append('| `%s` | %.4f | %.2f | %.2f | `%s` | %.4f | %.2f | %.2f | %.2f× | %.2f× |' % (
                name, x['worst_evolved_percent'], x['median_gpu_ms'], x['median_host_ms'], f,
                fo['worst_evolved_percent'], fo['median_gpu_ms'], fo['median_host_ms'],
                fo['median_gpu_ms'] / x['median_gpu_ms'], fo['median_host_ms'] / x['median_host_ms']))
        out += ['', 'Every candidate timed in this job:', '',
                '| setting | worst evolved % | GPU ms | complete ms | converged |', '|---|---|---|---|---|']
        for n, f in sorted(foms.items(), key=lambda kv: kv[1]['median_gpu_ms']):
            out.append('| `%s` | %.4f | %.2f | %.2f | %s |' % (n, f['worst_evolved_percent'], f['median_gpu_ms'],
                                                              f['median_host_ms'], f['nonlinear_converged']))
        out += ['']
    (HERE / '2026-09-22-4096-single-job-ladder.md').write_text('\n'.join(out) + '\n')
    (HERE / '4096-single-job-ladder.json').write_text(json.dumps(rows, indent=1) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
