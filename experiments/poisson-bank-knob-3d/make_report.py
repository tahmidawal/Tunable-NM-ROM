w("**Coverage.** Usable in the series' Table-1 time scope: " + ', '.join(f"{'L-shape' if p == 'lshape' else 'cube'} {n}" for p, n in sorted(HAVE)) + '.'
  + (" **Not yet available (provisional report):** " + ', '.join(f"{'L-shape' if p == 'lshape' else 'cube'} {n}" for p, n in MISSING) + '.' if MISSING else ' All eight planned meshes are measured.'))
for e in EXCLUDED:
    og = e['order_gate']
    w('')
    w(f"**Excluded in the {SC[e['scope']]} scope: {e['attempt']} (job {e['job_id']}).** Audit {e['audit']}; failed gates: "
      + ', '.join(k for k, v in e['gates_amended'].items() if not v)
      + f" (order gate: pooled paired ratio {f(og['pooled_paired_ratio'])}, after÷main {f(og['median_after_over_main'])}, "
      f"max arm {f(og['max_arm_paired_ratio'])}, min pairs/arm {og['min_pairs_per_arm']}). "
      f"Median paired after-CG minus control difference by component (ms): host→device input "
      f"{f(e['order_effect_components_ms']['input_seconds'])}, device work {f(e['order_effect_components_ms']['fused_device_seconds'])}, "
      f"device→host output {f(e['order_effect_components_ms']['output_seconds'])}. "
      + (f"The same job passes every gate in the {SC[e['alt']['scope']]} scope (order gate pooled "
         f"{f(e['alt']['order_gate']['pooled_paired_ratio'])}, max arm {f(e['alt']['order_gate']['max_arm_paired_ratio'])}); "
         f"its rows below are given in that scope only." if e['alt']['usable'] else 'No row of this job is used.'))
w('')
w('## Method in one paragraph')
w('')
w("The frozen bank $G\\in\\mathbb{R}^{n\\times R}$ is rotated once, offline and from training states only. Write "
  "$G=Q_GR_G$ at the training mesh and stack $a_i=[Q_G^\\top u_i;\\,R_Gh(z_i)]/\\lVert u_i\\rVert$. The SVD "
  "$A=USV_s^\\top$ gives $T=R_G^{-1}V_s$ and $L=V_s^\\top R_G=T^{-1}$. The columns of $GT$ are then ordered by "
  "training energy. A query at truncation $R'$ decodes $u=(GT)_{:,1:R'}\\,(L_{1:R'}c)$, and its weak residual uses "
  "$BP_{R'}$ with $P_{R'}=T_{:,1:R'}L_{1:R'}$ ($P=I$ exactly at $R'=R$). The *linear rung* drops the head and "
  "solves the least-squares problem $\\min_a\\lVert BT_{:,1:R'}a-f\\rVert$ directly ($q=R'$). It needs more weak "
  "tests than unknowns, $M>R'$. With the L-shape's $M=257$ eigenmode tests it therefore does not exist at "
  "$R'\\in\\{384,512\\}$.")
w('')
w('## Table-1 rows under the pre-registered rule')
w('')
w("The rule was fixed before any job ran (see `DESIGN.md`).")
w('')
w("- **accurate** = the most accurate arm at that mesh.")
w("- **fast** = the cheapest arm whose worst error is at most that of the current paper fast setting "
  "($q=0$, $R'=R$), measured in the same job.")
w("- **Speedup** = time of the fastest tested CG at least as accurate as the accurate arm, divided by the arm's "
  "time, both from the same job.")
w("- **Time scope** = the series' existing Table-1 scope: complete query for the L-shape, GPU query for the cube.")
