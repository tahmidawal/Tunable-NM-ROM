"""Generate RESULTS.md from the saved JSON.  Usage: python summarize.py results/<tag> [out.md]"""
import json
import sys
from pathlib import Path

import numpy as np

here = Path(__file__).parent
tag = Path(sys.argv[1])
ours = json.loads((here / 'ours.json').read_text())
R = {}
for f in sorted(tag.glob('*.json')):
    d = json.loads(f.read_text())
    R[(d['problem'], d['dim'], d['n'], d['solver'])] = d
keys = sorted({(p, dm) for p, dm, _, _ in R}, key=lambda k: ('poisson', 'heat', 'burgers').index(k[0]) * 10 + k[1])
L = []
P = L.append


def ms(x, nd=3):
    if x is None:
        return '-'
    x *= 1e3
    return f'{x:.3g}' if x < 100 else f'{x:.0f}'


def med(d, k):
    try:
        return d['times_s'][k]['median']
    except (KeyError, TypeError):
        return None


def rng(d, k):
    try:
        s = d['times_s'][k]
        return f"{ms(s['median'])} ({ms(s['min'])}-{ms(s['max'])})"
    except (KeyError, TypeError):
        return '-'


def amgx_best(d, tol):
    """Protocol headline: smallest median setup+solve among configs whose external residual <= tol."""
    best = None
    for v in (d or {}).get('results', {}).values():
        if v['tol'] != tol or v.get('status') != 'ok' or not v.get('reached_tol') or not v.get('setup_s'):
            continue
        t = v['setup_s']['median'] + v['solve_s']['median']
        if best is None or t < best[0]:
            best = (t, v)
    return best[1] if best else None


def cg_get(d, tol):
    v = (d or {}).get('results', {}).get(f'{tol:g}')
    return v if v and v.get('solve_s') and v.get('reached_tol') else None


def fail(d):
    if d is None:
        return 'not run'
    if d.get('status') == 'ok':
        return None
    e = (d.get('error') or '') + ' ' + (d.get('stderr_tail') or '')[-300:]
    return f"{d.get('status')} at stage {d.get('failed_stage', '?')}: {' '.join(e.split())[:260]}"


def slope(xs, ys):
    xs, ys = np.log(np.array(xs, float)), np.log(np.array(ys, float))
    return float(np.polyfit(xs, ys, 1)[0]) if len(xs) >= 2 else None


def fs(v):
    return '-' if v is None else f'{v:.2f}'


g = next(iter(R.values()))
P(f'# Sparse-solver solve-only timings ({tag.name})\n')
P('Generated by `summarize.py` from the JSON files in `' + str(tag) + '`; every number below is read from those files.')
P('Protocol: `PROTOCOL.md`.  Times are medians over the timed repeats (warm-up call excluded), milliseconds, float64.\n')
P(f"- GPU: {sorted({d.get('gpu') for d in R.values()})}; host {sorted({d.get('host') for d in R.values()})}; jobs {sorted({d.get('slurm_job') for d in R.values()})}")
P(f"- cuDSS {sorted({d.get('cudss_version') for d in R.values() if d['solver'] == 'cudss'})} (wheel nvidia-cudss-cu12 1.0.0.35), "
  f"AmgX commit {sorted({d.get('amgx_commit') for d in R.values() if d['solver'] == 'amgx'})}, CuPy {sorted({d.get('cupy') for d in R.values() if d.get('cupy')})}, "
  f"NumPy {g.get('numpy')}, SciPy {g.get('scipy')}; 16 CPU threads for the cuDSS reordering")
P('- Right-hand side: all ones.  Matrix assembly and upload are not in any time.\n')

fails, beats, expo = [], [], []
for (p, dm) in keys:
    ns = sorted({n for pp, dd, n, _ in R if (pp, dd) == (p, dm)})
    spd = p != 'burgers'
    ohead = ours['headline'].get(f'{p}{dm}d', {})
    P(f'## {p} {dm}D\n')
    P('### cuDSS (' + ('SPD' if spd else 'general') + ' mode)\n')
    P('| n | unknowns | analysis | factor | solve | refactor | factor nnz | peak device GB | rel. residual | repeats |')
    P('|---|---|---|---|---|---|---|---|---|---|')
    for n in ns:
        d = R.get((p, dm, n, 'cudss'))
        f = fail(d)
        if f:
            fails.append(f'cuDSS {p} {dm}D n={n} ({n**dm:,} unknowns): {f}; device total {((d or {}).get("device_total_bytes") or 0) / 2**30:.0f} GiB, '
                         f'in use at failure {((d or {}).get("device_used_bytes_at_failure") or 0) / 2**30:.1f} GiB, '
                         f'library estimate of device peak {(((d or {}).get("cudss_memory_estimates_bytes") or [0, 0])[1]) / 2**30:.1f} GiB')
        if d is None:
            continue
        pk = d.get('peak_device_bytes') or d.get('peak_device_bytes_first_cycle')
        rr = d.get('relres_max') or (max(d['first_call_relres']) if d.get('first_call_relres') else None)
        src = d if d.get('times_s') else {'times_s': {k: {'median': v, 'min': v, 'max': v} for k, v in (d.get('first_call') or {}).items()}}
        note = '' if d.get('times_s') else ' (first call only)'
        P(f"| {n} | {n**dm:,} | {rng(src, 'analysis')} | {rng(src, 'factor')} | {rng(src, 'solve')} | {rng(src, 'refactor')} | "
          f"{d.get('factor_nnz', '-'):,} | {'-' if not pk else f'{pk / 2**30:.2f}'} | {'-' if rr is None else f'{rr:.1e}'} | {d.get('reps', '-')}{note}{' FAILED' if f else ''} |")
    P('')
    P('### AmgX (fastest shipped configuration that reaches the tolerance) and Jacobi-CG\n')
    P('| n | tol | AmgX config | setup | solve | iterations | rel. residual | CG solve | CG iterations |')
    P('|---|---|---|---|---|---|---|---|---|')
    for n in ns:
        da, dc = R.get((p, dm, n, 'amgx')), R.get((p, dm, n, 'cg'))
        f = fail(da)
        if f:
            fails.append(f'AmgX {p} {dm}D n={n}: {f}')
        if spd and fail(dc):
            fails.append(f'CG {p} {dm}D n={n}: {fail(dc)}')
        for v in (da or {}).get('results', {}).values():
            if v.get('status') != 'ok':
                fails.append(f"AmgX {p} {dm}D n={n} {v['config']} tol {v['tol']:g}: failed at {v.get('failed_stage')}: {' '.join(str(v.get('error')).split())[:200]}")
            elif not v.get('reached_tol'):
                fails.append(f"AmgX {p} {dm}D n={n} {v['config']} tol {v['tol']:g}: did not reach the tolerance (external residual {v.get('relres_max'):.1e}, status {v['solve_status'][-1]}, {v['iterations'][-1]} iterations)")
        for tol in (1e-6, 1e-10):
            b, c = amgx_best(da, tol), cg_get(dc, tol)
            if spd and dc and dc.get('results', {}).get(f'{tol:g}') and not c:
                fails.append(f'CG {p} {dm}D n={n} tol {tol:g}: did not reach the tolerance')
            P(f"| {n} | {tol:g} | {b['config'][:-5] if b else 'none reached tol' if da else 'not run'} | "
              f"{ms(b['setup_s']['median']) if b else '-'} | {ms(b['solve_s']['median']) if b else '-'} | {b['iterations'][-1] if b else '-'} | "
              f"{'-' if not b else format(b['relres_max'], '.1e')} | {ms(c['solve_s']['median']) if c else '-'} | {c['iterations'][-1] if c else '-'} |")
    P('')

    # ---- growth exponents
    def col(fn):
        xs, ys = [], []
        for n in ns:
            v = fn(n)
            if v:
                xs.append(n ** dm); ys.append(v)
        return xs, ys

    series = {
        'cuDSS analysis': lambda n: med(R.get((p, dm, n, 'cudss')) or {}, 'analysis'),
        'cuDSS factor': lambda n: med(R.get((p, dm, n, 'cudss')) or {}, 'factor'),
        'cuDSS solve': lambda n: med(R.get((p, dm, n, 'cudss')) or {}, 'solve'),
        'cuDSS refactor': lambda n: med(R.get((p, dm, n, 'cudss')) or {}, 'refactor'),
        'AmgX setup (1e-6)': lambda n: (amgx_best(R.get((p, dm, n, 'amgx')), 1e-6) or {}).get('setup_s', {}).get('median'),
        'AmgX solve (1e-6)': lambda n: (amgx_best(R.get((p, dm, n, 'amgx')), 1e-6) or {}).get('solve_s', {}).get('median'),
        'AmgX setup+solve (1e-6)': lambda n: (lambda b: b and b['setup_s']['median'] + b['solve_s']['median'])(amgx_best(R.get((p, dm, n, 'amgx')), 1e-6)),
        'CG solve (1e-6)': lambda n: (cg_get(R.get((p, dm, n, 'cg')), 1e-6) or {}).get('solve_s', {}).get('median'),
        'reduced model, accurate (paper)': lambda n: (ohead.get(str(n)) or [None])[0] and ohead[str(n)][0] / 1e3,
        'reduced model, fast (paper)': lambda n: (ohead.get(str(n)) or [None, None])[1] and ohead[str(n)][1] / 1e3,
    }
    for name, fn in series.items():
        xs, ys = col(fn)
        if len(xs) >= 2:
            expo.append((f'{p} {dm}D', name, len(xs), f'{xs[0]:,}-{xs[-1]:,}', slope(xs, ys), slope(xs[-2:], ys[-2:])))

    # ---- comparison with the reduced model
    steps = ours['steps'].get(p)
    P('### Next to the reduced model' + (f' ({steps} linear solves per trajectory: arithmetic estimate, not a measured end-to-end solver)' if steps else ' (one solve per query)') + '\n')
    if p == 'poisson':
        hdr = ['cuDSS solve only (factor reused)', 'cuDSS factor+solve', 'cuDSS analysis+factor+solve', 'AmgX setup+solve 1e-6', 'AmgX solve only 1e-6', 'CG 1e-6']
    elif p == 'heat':
        hdr = [f'cuDSS {steps} solves (factor reused)', f'cuDSS analysis+factor+{steps} solves', f'AmgX setup+{steps} solves 1e-6', f'CG {steps} solves 1e-6']
    else:
        hdr = [f'cuDSS analysis+{steps}x(refactor+solve)', f'cuDSS {steps}x(refactor+solve)', f'cuDSS frozen Jacobian: analysis+factor+{steps} solves', f'AmgX {steps}x(setup+solve) 1e-6',
               f'AmgX frozen: setup+{steps} solves 1e-6']
    P('| n | ' + ' | '.join(hdr) + ' | reduced accurate | reduced fast | paper FOM |')
    P('|---|' + '---|' * (len(hdr) + 3))
    for n in ns:
        d = R.get((p, dm, n, 'cudss')) or {}
        a, f_, s, rf = (med(d, k) for k in ('analysis', 'factor', 'solve', 'refactor'))
        b = amgx_best(R.get((p, dm, n, 'amgx')), 1e-6)
        bs, bv = (b['setup_s']['median'], b['solve_s']['median']) if b else (None, None)
        c = cg_get(R.get((p, dm, n, 'cg')), 1e-6)
        cv = c['solve_s']['median'] if c else None
        ok = s is not None
        if p == 'poisson':
            vals = [s, ok and f_ + s, ok and a + f_ + s, b and bs + bv, bv, cv]
        elif p == 'heat':
            vals = [ok and steps * s, ok and a + f_ + steps * s, b and bs + steps * bv, cv and steps * cv]
        else:
            vals = [ok and a + steps * (rf + s), ok and steps * (rf + s), ok and a + f_ + steps * s, b and steps * (bs + bv), b and bs + steps * bv]
        vals = [v or None for v in vals]
        o = ohead.get(str(n))
        P(f'| {n} | ' + ' | '.join(ms(v) for v in vals) + f" | {o[0] if o else '-'} | {o[1] if o else '-'} | {o[2] if o else '-'} |")
        if o:
            for h, v in zip(hdr, vals):
                if v is None:
                    continue
                for nm, ov in (('accurate', o[0]), ('fast', o[1])):
                    beats.append((f'{p} {dm}D', n, h, v * 1e3, nm, ov, v * 1e3 < ov))
        if p == 'burgers' and dm == 2:
            for r, mf in ours['meshflat'].items():
                if str(n) in mf:
                    ov = sum(mf[str(n)])
                    for h, v in zip(hdr, vals):
                        if v is not None:
                            beats.append((f'{p} {dm}D', n, h, v * 1e3, f'mesh-scaling study width {r} (evolution+reconstruction, H200)', ov, v * 1e3 < ov))
    P('')

P('## Growth exponents (least-squares slope of log time against log unknowns)\n')
P('| problem | quantity | points | unknowns range | slope, all sizes | slope, two largest sizes |')
P('|---|---|---|---|---|---|')
for e in expo:
    P(f'| {e[0]} | {e[1]} | {e[2]} | {e[3]} | {fs(e[4])} | {fs(e[5])} |')
P('')
P('## Every comparison with a reduced-model number from the paper\n')
P('Reduced-model numbers: ' + ours['headline_source'] + '. ' + ours['headline_note'] + ' ' + ours['meshflat_source'] + '. Steps: ' + ours['steps_source'] + '.')
P('For heat and Burgers the solver column is the arithmetic estimate defined in PROTOCOL.md, not a measured trajectory.\n')
P('| problem | n | solver quantity | solver ms | reduced-model number | reduced ms | solver faster? | reduced / solver |')
P('|---|---|---|---|---|---|---|---|')
for b in beats:
    P(f"| {b[0]} | {b[1]} | {b[2]} | {b[3]:.3g} | {b[4]} | {b[5]:.3g} | {'YES' if b[6] else 'no'} | {b[5] / b[3]:.3g} |")
P('')
P('## Failures and sizes that did not fit\n')
for f in fails or ['none']:
    P('- ' + f)
P('')
P('## AmgX, all configurations\n')
P('| problem | n | config | tol | setup | solve | iterations | status | rel. residual (external) | reached tol | peak device GB |')
P('|---|---|---|---|---|---|---|---|---|---|---|')
for (p, dm, n, s), d in sorted(R.items(), key=lambda kv: (kv[0][0], kv[0][1], kv[0][2])):
    if s != 'amgx':
        continue
    for v in d.get('results', {}).values():
        if not v.get('setup_s'):
            P(f"| {p} {dm}D | {n} | {v['config'][:-5]} | {v['tol']:g} | - | - | - | {v.get('status')} at {v.get('failed_stage')} | - | - | - |")
            continue
        P(f"| {p} {dm}D | {n} | {v['config'][:-5]} | {v['tol']:g} | {ms(v['setup_s']['median'])} | {ms(v['solve_s']['median'])} | {v['iterations'][-1]} | "
          f"{v['solve_status'][-1]} | {v['relres_max'] if 'relres_max' in v else max(v['relres']):.1e} | {v.get('reached_tol')} | {v.get('peak_device_bytes', 0) / 2**30:.2f} |")
out = Path(sys.argv[2]) if len(sys.argv) > 2 else here / f'RESULTS-{tag.name}.md'
out.write_text('\n'.join(L) + '\n')
print('wrote', out, len(L), 'lines;', len(R), 'json files')
