"""Generate summary.json and the lane report from the collected audit.json files.

    python experiments/hires-poisson/reports/generate_hires.py

Every number in the report comes from `runs/<attempt>/archive/output/audit.json`, which the
independent NumPy audit wrote on the cluster from the saved fields. Nothing is typed by hand.
"""
import hashlib
import json
from pathlib import Path

LANE = Path(__file__).resolve().parents[1]
OUT = LANE / 'reports'
ATTEMPTS_2D = ['hp2048', 'hp4096', 'hp4096b', 'hp2048b']
ATTEMPTS_3D = ['hp3d128', 'hp3d256']
ATTEMPTS_L = [('hpl1024', 'output'), ('hpl32', 'output'), ('hpl32', 'output2')]


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def pct(x):
    return f'{100 * x:.3f}'


def rows_for(table, selections, headline_variant, mesh_label, job, gpu, status):
    out = []
    sel = {s['rom']: s for s in selections}
    for name, r in table.items():
        s = sel.get(name)
        out.append(dict(mesh=mesh_label, job_id=job, gpu=gpu, status=status, subject=name,
                        family=r['family'], q=r.get('q'), tolerance=r.get('tolerance'),
                        coarse_intervals=r.get('coarse_intervals'), cases=r['cases'],
                        repetitions_per_case=r['repetitions_per_case'],
                        worst_same_grid=r['worst_same_grid'], worst_physical=r['worst_physical'],
                        median_total_ms=r['median_total_ms'], median_device_ms=r['median_device_ms'],
                        median_input_ms=r['median_input_ms'], median_output_ms=r['median_output_ms'],
                        median_iterations=r.get('median_iterations'),
                        median_lm_attempts=r.get('median_lm_attempts'),
                        speedups=None if s is None else {
                            k: (None if s[k] is None else dict(comparator=s[k]['comparator'],
                                                               total=s[k]['speedup_total'],
                                                               device=s[k]['speedup_device']))
                            for k in ('named_cg_1e-2', 'fastest_cg_matched',
                                      'fastest_coarse_matched', 'dst_direct')}))
    return out


def table_md(rows, keep):
    head = ('| subject | worst same-grid % | worst physical % | median total ms | median device ms '
            '| iterations | × vs CG 1e-2 (total / device) | × vs fastest matched CG | × vs matched coarse grid | × vs DST |\n'
            '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n')
    body = ''
    for r in rows:
        if not keep(r):
            continue
        s = r['speedups']

        def f(key, dev=False):
            if not s or s.get(key) is None:
                return '—'
            txt = f"{s[key]['total']:.2f}"
            if dev:
                txt += f" / {s[key]['device']:.1f}"
            if key in ('fastest_cg_matched', 'fastest_coarse_matched'):
                txt += f" (`{s[key]['comparator']}`)"
            return txt
        it = r['median_iterations'] if r['median_iterations'] is not None else r['median_lm_attempts']
        body += (f"| `{r['subject']}` | {pct(r['worst_same_grid'])} | {pct(r['worst_physical'])} | "
                 f"{r['median_total_ms']:.2f} | {r['median_device_ms']:.2f} | "
                 f"{'' if it is None else f'{it:g}'} | {f('named_cg_1e-2', True)} | {f('fastest_cg_matched')} | "
                 f"{f('fastest_coarse_matched')} | {f('dst_direct')} |\n")
    return head + body


def write_report(S, tables):
    """The lane report. Prose carries no hand-typed measurement: every number is formatted here."""
    rows = {(r['attempt'], r['mesh'], r['subject']): r for r in S['rows']}
    head = []
    for v in S['verdicts']:
        r = rows[(v['attempt'], v['mesh'], v['arm'])]
        sp = r['speedups']
        src = next(x for x in S['sources'] if x['attempt'] == v['attempt'])

        def g(k, field='total'):
            return '—' if sp[k] is None else f"{sp[k][field]:.2f}"
        head.append(f"| {v['mesh']} | `{v['arm']}` | {pct(r['worst_same_grid'])} | {r['median_total_ms']:.2f} | "
                    f"{r['median_device_ms']:.2f} | {g('named_cg_1e-2')} | {g('named_cg_1e-2', 'device')} | "
                    f"{g('fastest_cg_matched')} | {g('fastest_coarse_matched')} | {g('dst_direct')} | "
                    f"{'withdrawn: 12-source subset (A8)' if v.get('withdrawn_as_bar_verdict') else ('**met**' if v['bar_met'] else 'missed')} | `{v['attempt']}` / {src['job_id']} / "
                    f"{'audit passed' if src['audit_passed'] else 'AUDIT FAILED'} |")
    floors = '; '.join(f"{b['mesh']} {pct(b['worst'])} %" for b in S['bank_floor'])
    text = f"""# High-resolution Poisson: does the NM-ROM's speedup over CG keep growing at high accuracy?

Lane report of `exp/2026-09-20-hires-poisson` for the 2026-09-20 speed-and-accuracy campaign. Every number below is
generated by `experiments/hires-poisson/reports/generate_hires.py` from the on-cluster independent NumPy audits
(`runs/<attempt>/archive/output/audit.json`); status of each row is in its last column. All sources are **opened
development sources** (nothing was tuned on them in this lane; no sealed cohort was opened), so these are development
measurements, final for this lane's question and not a generalisation claim.

## What was run

Nothing is trained. Frozen checkpoints are evaluated on finer meshes than they were trained on ("frozen-weight mesh
transfer"): the decoder is $u(x) = G(x)\\,[\\,h(z) + C_q y\\,]$ with a coordinate bank $G$, a nonlinear head $h$ and $q$ linear
correction directions, and the query solves $\\min_{{z,y}} \\lVert B\\,[h(z)+C_q y] - f_m \\rVert_2$ over $M$ sine (or, on the
L-shape, discrete-eigenmode) tests with $y$ eliminated exactly. On large meshes the bank is held as row chunks.

```mermaid
flowchart LR
  classDef frozen fill:#dbeafe,stroke:#1e40af,color:#111;
  classDef solved fill:#dcfce7,stroke:#166534,color:#111;
  classDef io fill:#fee2e2,stroke:#991b1b,color:#111;
  classDef ctrl fill:#f3f4f6,stroke:#374151,color:#111;
  S[host f64 source]:::io --> P[project onto M tests]:::solved --> L[LM solve for z, K unknowns]:::solved
  L --> E[exact recovery of q corrections]:::solved --> D[decode: chunked bank times coefficients]:::frozen --> F[host f64 field]:::io
  H[frozen head h]:::frozen --> L
  B[frozen bank G, evaluated at the new mesh]:::frozen --> D
  S --> CG[named FOM: CG on the same mesh]:::ctrl --> F
  S --> DST[control: direct DST / sparse-direct]:::ctrl --> F
  S --> CO[control: coarse-grid solve + interpolation]:::ctrl --> F
```

Blue = frozen (never retrained), green = solved per query, red = identical host copies paid by every subject, grey =
comparators. Every job times all subjects in one allocation on one physical GPU (UUID-guarded), 12 sources × 5
repetitions, randomised order, burn-in, medians.

## Bar verdict per mesh (accurate arm, pre-registered)

| mesh | accurate arm | worst same-grid % | total ms | device ms | × vs CG 1e-2 (total) | (device) | × vs fastest CG with error ≤ ROM's | × vs matched coarse grid | × vs direct solver | bar (≤1 % and ≥5×) | attempt / job / status |
|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---|
{chr(10).join(head)}

Bank projection floors (the error no query on this checkpoint can beat): {floors}.

**Reading.** Against the named same-mesh CG the speedup grows with the mesh at unchanged error, because CG's iteration
count grows with $n$ while the ROM's device time is one bank-times-coefficients product. **The ROM does not beat the
direct transform solver or a coarse-grid solve at its own accuracy on any mesh** (ratios below 1 in the last two speedup
columns): a 1 %-accurate answer to these smooth problems does not need the fine mesh. Total-time ratios are compressed
by the identical f64 host↔device copies; device-only ratios are shown beside them.

{tables}

## Glossary

- **NM-ROM** — nonlinear-manifold reduced-order model: the solution is sought on a low-dimensional learned manifold instead of on the mesh.
- **bank $G$ / head $h$ / corrections $C_q$** — the decoder is a fixed set of $R$ spatial basis functions (bank) combined by coefficients; the head maps $K$ latent unknowns nonlinearly to those coefficients; $q$ extra linear directions ("corrections") are added and solved exactly. `q` in subject names is that count; `q = R` is the purely linear model on the bank (`*_linear*`).
- **frozen-weight mesh transfer** — the trained networks are evaluated at the nodes of a finer mesh; nothing is retrained.
- **bank projection floor** — the error of the best possible combination of bank functions for a given truth field; no solver setting can go below it.
- **worst same-grid %** — largest, over the 12 sources, relative $L^2$ difference to the exact discrete solution on the same mesh. **worst physical %** — the same against a reference solved on a mesh twice as fine (this is what coarse-grid arms are judged by).
- **total ms / device ms** — median wall time from host source array to host solution array / the part between the two host↔device copies.
- **CG 1e-2 (named FOM)** — unpreconditioned conjugate gradient on the same mesh, zero start, stopped at relative residual $10^{{-2}}$; other `cg_*` rows are other tolerances. **fastest CG with error ≤ ROM's** — the quickest tested CG tolerance whose worst physical error does not exceed the ROM arm's.
- **DST / direct solver** — the FFT-based sine-transform solve (square, cube) or CPU sparse-direct SuperLU (L-shape); an exact solver, reported as a labelled control.
- **coarse{{n}}_dst / coarse{{n}}_cg** — solve on an $n$-interval mesh from the point-sampled source, then bi/tri-linear interpolation to the requested mesh (interpolation charged). **matched coarse grid** — the fastest of these whose worst physical error does not exceed the ROM arm's.
- **retained / lean64 / lean32 / leandst / onestart / io32** — speed-loop variants: the unmodified parent kernel; diagnostics moved out of the timed kernel; additionally an f32 bank for the decode (labelled); DST-based source projection (3D); one LM start instead of three (3D); host f32 in/out for every subject alike (labelled contract).
- **iterations** — CG iterations, or LM attempts for ROM rows. **LM** — Levenberg–Marquardt, the damped Gauss–Newton iteration that finds the latent unknowns.
- **parity gate** — a faster variant is accepted only if its field matches the unoptimised path (f64: $10^{{-12}}$ relative and identical solver integers; f32 decode: $10^{{-4}}$).
- **bar** — the campaign's pre-registered success rule: accurate arm worst same-grid error ≤ 1 % (stretch 0.5 %) and speedup ≥ 5 over the named FOM in the same allocation.
"""
    (OUT / '2026-09-20-hires-poisson.md').write_text(text)


def main():
    summary = dict(sources=[], verdicts=[], rows=[], parity=[], bank_floor=[])
    md = []
    for attempt in ATTEMPTS_2D:
        p = LANE / 'runs' / attempt / 'archive' / 'output' / 'audit.json'
        if not p.exists():
            continue
        a = json.loads(p.read_text())
        n = a['intervals']
        label = f'square {n}²'
        status = 'audited (development sources)' if a['passed'] else 'AUDIT GATES FAILED'
        summary['sources'].append(dict(attempt=attempt, path=str(p.relative_to(LANE)), sha256=sha(p),
                                       job_id=a['job_id'], commit=a['commit'], gpu=a['gpu'],
                                       gpu_uuid=a['gpu_uuid'], audit_passed=a['passed'], gates=a['gates'],
                                       error_checks=a['error_checks'],
                                       peak_device_bytes=(a.get('device_memory') or {}).get('peak_bytes_in_use')))
        summary['verdicts'].append(dict(attempt=attempt, mesh=label, **(a['verdict'] or {})))
        summary['bank_floor'].append(dict(attempt=attempt, mesh=label,
                                          worst=a['bank']['projection_floor']['worst'],
                                          median=a['bank']['projection_floor']['median']))
        summary['parity'] += [dict(attempt=attempt, **x) for x in a['parity']]
        rows = rows_for(a['table'], a['selections'], a['headline_variant'], label, a['job_id'], a['gpu'], status)
        summary['rows'] += [dict(attempt=attempt, **r) for r in rows]
        v = a['verdict']
        md.append(f"## {label} — `{attempt}`, job `{a['job_id']}`, {a['gpu']}, source `{a['commit'][:12]}`\n")
        md.append(f"Audit: **{'passed' if a['passed'] else 'FAILED'}** ({a['error_checks']} recomputed errors, "
                  f"worst difference {a['worst_error_difference']:.1e}). Bank projection floor: worst "
                  f"{pct(a['bank']['projection_floor']['worst'])} %. Bar (accurate arm `{v['arm']}` vs `cg_0.01`): "
                  f"worst same-grid {pct(v['worst_same_grid'])} % "
                  f"({'≤' if v['accuracy_bar_1pct'] else '>'} 1 %, stretch 0.5 % "
                  f"{'met' if v['stretch_bar_0p5pct'] else 'missed'}), speedup {v['speedup_total']:.2f}× "
                  f"({'≥' if v['speed_bar_5x'] else '<'} 5) → **{'BAR MET' if v['bar_met'] else 'BAR MISSED'}**.\n")
        md.append(table_md(rows, lambda r: r['family'] in ('nm-rom', 'linear-rom')))
        md.append('\nComparators and controls in the same job:\n')
        md.append(table_md(rows, lambda r: r['family'] not in ('nm-rom', 'linear-rom')))
    for attempt in ATTEMPTS_3D:
        p = LANE / 'runs' / attempt / 'archive' / 'output' / 'audit.json'
        if not p.exists():
            continue
        a = json.loads(p.read_text())
        summary['sources'].append(dict(attempt=attempt, path=str(p.relative_to(LANE)), sha256=sha(p),
                                       job_id=a['job_id'], commit=a['commit'], gpu=a['gpu'],
                                       gpu_uuid=a['gpu_uuid'], audit_passed=a['passed'], gates=a['gates'],
                                       error_checks=a['error_checks'],
                                       peak_device_bytes=(a.get('device_memory') or {}).get('peak_bytes_in_use')))
        summary['parity'] += [dict(attempt=attempt, **x) for x in a['parity']]
        for n, m in a['meshes'].items():
            label = f'cube {n}³'
            status = 'audited (development sources)' if a['passed'] else 'AUDIT GATES FAILED'
            v = m['verdict']
            summary['verdicts'].append(dict(attempt=attempt, mesh=label, **v))
            summary['bank_floor'].append(dict(attempt=attempt, mesh=label, worst=m['mesh']['bank_floor_worst']))
            rows = rows_for(m['table'], m['selections'], a['headline_variant'], label, a['job_id'], a['gpu'], status)
            summary['rows'] += [dict(attempt=attempt, **r) for r in rows]
            md.append(f"## {label} — `{attempt}`, job `{a['job_id']}`, {a['gpu']}, source `{a['commit'][:12]}`\n")
            md.append(f"Audit: **{'passed' if a['passed'] else 'FAILED'}**. Bank floor worst "
                      f"{pct(m['mesh']['bank_floor_worst'])} %. Bar (accurate arm `{v['arm']}` vs `cg_0.01`): "
                      f"worst same-grid {pct(v['worst_same_grid'])} %, speedup {v['speedup_total']:.2f}× → "
                      f"**{'BAR MET' if v['bar_met'] else 'BAR MISSED'}**; fast arm `{v['fast_arm']['arm']}` "
                      f"{pct(v['fast_arm']['worst_same_grid'])} % / {v['fast_arm']['speedup_total']:.2f}×.\n")
            md.append(table_md(rows, lambda r: r['family'] in ('nm-rom', 'linear-rom')))
            md.append('\nComparators and controls in the same job:\n')
            md.append(table_md(rows, lambda r: r['family'] not in ('nm-rom', 'linear-rom')))
    for attempt, sub in ATTEMPTS_L:
        p = LANE / 'runs' / attempt / 'archive' / sub / 'audit.json'
        if not p.exists():
            continue
        a = json.loads(p.read_text())
        n = a['intervals']
        label = f"L-shape {n}² ({a.get('cohort_sources', 12)} sources)"
        status = 'audited (development sources)' if a['passed'] else 'AUDIT GATES FAILED'
        summary['sources'].append(dict(attempt=attempt, path=str(p.relative_to(LANE)), sha256=sha(p),
                                       job_id=a['job_id'], commit=a['commit'], gpu=a['gpu'],
                                       gpu_uuid=a['gpu_uuid'], audit_passed=a['passed'], gates=a['gates'],
                                       error_checks=a['error_checks'],
                                       peak_device_bytes=(a.get('device_memory') or {}).get('peak_bytes_in_use')))
        v = a['verdict']
        # DESIGN A8: a verdict on fewer than the lshape lane's 32 development sources is a subset
        # measurement, not the bar verdict
        subset = a.get('cohort_sources', 12) < 32
        v = dict(v, withdrawn_as_bar_verdict=subset)
        summary['verdicts'].append(dict(attempt=attempt, mesh=label, **v))
        floor = next(m['bank_floor']['worst'] for m in a['arm_setup'] if m['model'] == a['headline_model'])
        summary['bank_floor'].append(dict(attempt=attempt, mesh=label, worst=floor))
        summary['parity'] += [dict(attempt=attempt, **x) for x in a['parity']]
        rows = rows_for(a['table'], a['selections'], None, label, a['job_id'], a['gpu'], status)
        summary['rows'] += [dict(attempt=attempt, **r) for r in rows]
        md.append(f"## {label} — `{attempt}`, job `{a['job_id']}`, {a['gpu']}, source `{a['commit'][:12]}`\n")
        md.append(f"Audit: **{'passed' if a['passed'] else 'FAILED'}** ({a['error_checks']} recomputed errors). "
                  f"Bank floor worst {pct(floor)} % (`{a['headline_model']}`). Bar (accurate arm `{v['arm']}` vs "
                  f"`cg_0.01`): worst same-grid {pct(v['worst_same_grid'])} %, speedup {v['speedup_total']:.2f}× → "
                  f"**{('12-SOURCE SUBSET — NOT A BAR VERDICT (DESIGN A8)' if subset else ('BAR MET' if v['bar_met'] else 'BAR MISSED'))}**; fast arm `{v['fast_arm']['arm']}` "
                  f"{pct(v['fast_arm']['worst_same_grid'])} % / {v['fast_arm']['speedup_total']:.2f}×. "
                  f"The `× vs DST` column is against the CPU sparse-direct solve on this domain.\n")
        md.append(table_md(rows, lambda r: r['family'] == 'nm-rom'))
        md.append('\nComparators and controls in the same job:\n')
        md.append(table_md(rows, lambda r: r['family'] != 'nm-rom'))
    OUT.mkdir(exist_ok=True)
    (OUT / 'summary.json').write_text(json.dumps(summary, indent=1) + '\n')
    (OUT / 'tables.generated.md').write_text('\n'.join(md) + '\n')
    write_report(summary, '\n'.join(md))
    for v in summary['verdicts']:
        print(v)


if __name__ == '__main__':
    main()
