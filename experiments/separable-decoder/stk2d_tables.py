"""Generate every table in STOKES-NOTES.md from runs/stk2d/*.json.

Repository rule (CLAUDE.md, "Reports"): never hand-type a number into a
report.  Run:

    /home/tahmid/Dev/.venv/bin/python stk2d_tables.py [path/to/report.json]

and paste the output between the STOKES-NOTES.md generated-block markers.
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(HERE, "runs/stk2d/stk2d_fom_gates_nu1_M64.json")


def e(x, d=3):
    if x is None:
        return "-"
    if isinstance(x, float) and x != x:
        return "nan"
    return f"{x:.{d}e}"


def esc(c):
    """Markdown table cells cannot contain a bare pipe; norms are written with
    ||.||, so every pipe in a cell or header is escaped."""
    return str(c).replace("|", "\\|")


def table(head, rows):
    out = ["| " + " | ".join(esc(h) for h in head) + " |",
           "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(esc(c) for c in r) + " |")
    return "\n".join(out)


def main(path=DEFAULT):
    R = json.load(open(path))
    G = R["gates"]
    print(f"<!-- generated by stk2d_tables.py from {os.path.basename(path)} "
          f"(commit {R['config']['git_commit'][:12]}) -- do not edit by hand -->")
    print()

    print("### S-FOM -- manufactured solution, odd (no-slip) ghosts\n")
    print(table(["N", "n_u", "n_p", "err_u (mass-rel)", "err_p (mass-rel)",
                 "audit anchor u", "audit anchor p",
                 "||Du||/(||D||||u||)", "lambda", "solve s"],
                [[r["N"], r["n_u"], r["n_p"], e(r["err_u_mass_rel"], 4),
                  e(r["err_p_mass_rel"], 4),
                  e(a["anchor_err_u"], 4) if a else "-",
                  e(a["anchor_err_p"], 4) if a else "-",
                  e(r["div_u_norm"]), e(r["lam"]), f"{r['solve_seconds']:.1f}"]
                 for r in G["S_FOM"]["rows"]
                 for a in [next((x for x in G["S_FOM"]["anchors"]
                                 if x["N"] == r["N"]), None)]]))
    print()
    print(table(["refinement", "observed order u", "observed order p"],
                [[f"{a['coarse']} -> {a['fine']}", f"{a['order']:.4f}",
                  f"{b['order']:.4f}"]
                 for a, b in zip(G["S_FOM"]["orders_u"], G["S_FOM"]["orders_p"])]))
    print()
    print(f"worst order deviation from 2.00: {G['S_FOM']['worst_order_deviation']:.4f} "
          f"(band {G['S_FOM']['band']}); "
          f"worst anchor relative deviation: {e(G['S_FOM']['worst_anchor_rel_dev'])}")
    print()

    print("### S-EXACT -- closed-form discrete solution\n")
    print(table(["N", "||u_h-u_h^exact||/||.||", "||p_h-p_h^exact||/||.||",
                 "predicted err_u", "observed err_u",
                 "predicted err_p", "observed err_p"],
                [[r["N"], e(r["exact_u_rel"]), e(r["exact_p_rel"]),
                  e(r["predicted_err_u"], 6), e(r["observed_err_u"], 6),
                  e(r["predicted_err_p"], 6), e(r["observed_err_p"], 6)]
                 for r in G["S_EXACT"]["rows"]]))
    print()

    print("### S-ADJ -- weighted adjointness\n")
    print(table(["N", "primary", "test-projected", "test-proj (op-norm)",
                 "||M_u Grad + D^T M_p||_F", "negative control"],
                [[r["N"], e(r["adj_primary"]), e(r["adj_test_projected"]),
                  e(r["adj_test_projected_opnorm"]), e(r["adj_defect_fro"]),
                  e(r["adj_negative_control"])]
                 for r in G["S_ADJ"]["rows"]]))
    print()

    print("### S-STRUCT / S-RANK -- operator structure, ranks, kernels\n")
    print(table(["N", "n_u", "n_p", "n_psi", "||D+Grad^T||_inf",
                 "||DC||_inf", "||DC||_max", "||L-L^T||_max"],
                [[r["N"], r["n_u"], r["n_p"], r["n_psi"],
                  e(r["struct_D_plus_GradT_inf"]), e(r["struct_DC_inf"]),
                  e(r["struct_DC_max"]), e(s["L_sym_max"])]
                 for r, s in zip(G["S_STRUCT"]["rows"], G["SYM"]["rows"])]))
    print()
    print(table(["N", "rank D", "expected", "dim ker D", "expected",
                 "rank C", "expected", "SVD s"],
                [[r["N"], r["rank_D"], r["expect_rank_D"], r["dim_ker_D"],
                  r["expect_dim_ker_D"], r["rank_C"], r["expect_rank_C"],
                  f"{r['seconds']:.0f}"] for r in G["S_RANK"]["dense"]]))
    print()
    print(table(["N", "||Grad 1||", "min |U_ii| bordered pressure Laplacian",
                 "min |U_ii| C^T C", "implied rank D", "implied dim ker D",
                 "implied rank C"],
                [[r["N"], e(r["grad_one_norm"]),
                  e(r["bordered_plap_min_absdiagU"]),
                  e(r["CtC_min_absdiagU"]), r["implied_rank_D"],
                  r["implied_dim_ker_D"], r["implied_rank_C"]]
                 for r in G["S_RANK"]["indirect"]]))
    print()

    print("### S-PRESS -- pressure annihilation (bonus)\n")
    print(table(["N", "M", "norm ||Phi^T M_u Grad p||", "same, control basis",
                 "cos_max solenoidal", "cos_max control",
                 "ratio control/solenoidal", "||D Phi|| normalized"],
                [[r["N"], r["M"], e(r["press_annih_norm"]),
                  e(r["press_control_norm"]), e(r["press_cos_max_solenoidal"]),
                  e(r["press_cos_max_control"]),
                  e(r["press_ratio_control_over_sol"]), e(r["D_Phi_norm"])]
                 for r in G["S_ADJ"]["rows"]]))
    print()

    print("### S-FREESLIP -- the deliberate wrong answer\n")
    fs = G["S_FREESLIP"]
    ns = {r["N"]: r for r in G["S_FOM"]["rows"]}
    print(table(["N", "err_u free-slip", "err_u no-slip", "ratio",
                 "err_p free-slip", "wall-adjacent err (free-slip)",
                 "wall-adjacent err (no-slip)"],
                [[r["N"], e(r["err_u_mass_rel"], 4),
                  e(ns[r["N"]]["err_u_mass_rel"], 4),
                  f"{r['err_u_mass_rel'] / ns[r['N']]['err_u_mass_rel']:.1f}x",
                  e(r["err_p_mass_rel"], 4), e(r["err_u_bnd_rel"], 4),
                  e(ns[r["N"]]["err_u_bnd_rel"], 4)] for r in fs["rows"]]))
    print()
    print(table(["refinement", "free-slip order u", "free-slip order p"],
                [[f"{a['coarse']} -> {a['fine']}", f"{a['order']:.4f}",
                  f"{b['order']:.4f}"]
                 for a, b in zip(fs["orders_u"], fs["orders_p"])]))
    print()

    print("### Supporting gates\n")
    print(table(["gate", "worst value", "rule"],
                [["REF (operators vs archived auditor reference)",
                  e(G["REF"]["worst_maxdiff"]), "exactly 0"],
                 ["MF (sparse vs independent matrix-free)",
                  e(G["MF"]["worst_rel"]), "<= 1e-13"],
                 ["SYM (||L - L^T||_max)", e(G["SYM"]["worst"]), "exactly 0"],
                 ["S-NU (||nu u_nu - u_1||/||u_1||)",
                  e(G["S_NU"]["u_scaling_rel"]), "<= 1e-9"],
                 ["S-NU (||p_nu - p_1||/||p_1||)",
                  e(G["S_NU"]["p_invariance_rel"]), "<= 1e-9"]]))
    print()
    c = R["config"]
    print(f"run: {os.path.basename(path)} | commit `{c['git_commit'][:12]}` | "
          f"host `{c['hostname']}` | numpy {c['numpy']} scipy {c['scipy']} | "
          f"jax backend `{c['jax'].get('backend')}` x64={c['jax'].get('x64')} "
          f"matmul `{c['jax'].get('matmul_precision')}` | "
          f"total {R['total_seconds']:.0f} s")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
