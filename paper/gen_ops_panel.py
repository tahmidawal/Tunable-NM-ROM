# DeepONet on 2D Burgers at 256^2 (lane ops-deeponet-b2d @306c939d, job 4179556): accuracy only, no timing claim.
# Same data, split, metric, optimiser, seed and wall budget as the U-Net / Transolver / FNO arms.
ED = HERE / 'evidence/ops-deeponet-b2d-2026-09-22'
MAND = json.loads((ED / 'manifest.json').read_text())
for k, v in MAND.items():
    assert hashlib.sha256((ED / f'{k}.json').read_bytes()).hexdigest() == v['sha256'], k
DS = json.loads((ED / 'summary.json').read_text())
DA = json.loads((ED / 'audit.json').read_text())
assert DA['identical_split_to_fno_job'] and DA['split_hashes_cross_checked_against_archived_manifest']
DROWS = [r for r in DS['rows'] if 'arm' in r and r['cohort'] in ('validation-32', 'diagnosis-8')]
DVAL = {(r['arm'], r['metric']): 100 * r['value'] for r in DROWS if r['cohort'] == 'validation-32'}
DMATCH = {r['arm']: 100 * r['value'] for r in DROWS if r['cohort'] == 'diagnosis-8' and r['metric'] == 'worst_fixed_initial_error'}
DARMS = sorted({r['arm'] for r in DROWS if r['operator'] == 'DeepONet'})
DINFO = {r['arm']: r for r in DROWS}
_pv = DA['persistence_baseline']['validation-32']['fixed_initial']; _pd = DA['persistence_baseline']['diagnosis-8']['fixed_initial']
_D2 = [r for r in DS['rows'] if r.get('metric') == 'D2'][0]
DSHOW = [('DeepONet, small (selected)', 'don-small'), ('DeepONet, medium', 'don-medium'),
         ('DeepONet, refined', 'don-refine'), ('DeepONet, large', 'don-large'),
         ('U-Net, refined', 'unet-refine'), ('Transolver, refined', 'tsol-refine'), ('FNO, large', 'fno-large')]


def deeponet_table():
    L = [r'% GENERATED by paper/gen_ops_panel.py from evidence/ops-deeponet-b2d-2026-09-22 -- do not edit.',
         r'\small', r'\begin{tabular}{@{}llrrrr@{}}', r'\toprule',
         r' & & \multicolumn{3}{c}{Validation, 32 cases} & Matched 8 \\',
         r'\cmidrule(lr){3-5}\cmidrule(l){6-6}',
         r'Arm & Ended by & Mean (\%) & Median (\%) & Worst (\%) & Worst (\%) \\', r'\midrule']
    rows = []
    for label, arm in DSHOW:
        r = DINFO[arm]
        row = [label, r['stop_reason'].replace('_', ' '), e(DVAL[(arm, 'mean_fixed_initial_error')]),
               e(DVAL[(arm, 'median_fixed_initial_error')]), e(DVAL[(arm, 'worst_fixed_initial_error')]), e(DMATCH[arm])]
        L.append(' & '.join(row) + r' \\'); rows.append(row)
    L.append(r'\midrule')
    for row in ([r'NM-ROM (same cohort)', '---', '---', '---', '---', e(100 * _D2['rom'])],
                [r'Persistence control', '---', e(100 * _pv['mean']), e(100 * _pv['median']),
                 e(100 * _pv['maximum']), e(100 * _pd['maximum'])]):
        L.append(' & '.join(row) + r' \\'); rows.append(row)
    L += [r'\bottomrule', r'\end{tabular}']
    return '\n'.join(L) + '\n', rows


def deeponet_macros():
    dm = [DVAL[(a, 'mean_fixed_initial_error')] for a in DARMS]
    others = [DVAL[(a, 'mean_fixed_initial_error')] for a in ('unet-refine', 'tsol-refine', 'fno-large')]
    tr = [100 * DA['arms'][a]['train_loss_at_best'] ** 0.5 for a in DARMS]
    cases = {DA['arms'][a]['training_cases'] for a in DARMS}; assert len(cases) == 1
    stop = {DA['arms'][a]['stop_reason'] for a in DARMS}; assert stop == {'early_stopping'}       # none ran out of budget
    assert all(DA['arms'][a]['train_loss_final'] < DA['arms'][a]['train_loss_at_best'] for a in DARMS)  # training loss still falling
    assert min(dm) > max(others) and min(dm) < 100 * _pv['mean']              # worse than the other families, better than persistence
    # where the panel's discretisation-error comparison does and does not hold (ops-tune-grid correction, 2026-09-22)
    bar = S['fom_discretisation_error_percent']['dense_tight']
    pub = sorted({a for a, _ in DVAL if not a.startswith('don-')})
    below_val = [a for a in pub if DVAL[(a, 'worst_fixed_initial_error')] < bar]
    below_match = [a for a in pub if DMATCH[a] < bar]
    assert len(below_val) >= 1 and len(below_match) == len(pub)          # the bar is not exceeded everywhere off the panel's cohort
    _u = 'unet-refine'
    same_panel = R[_u]['worst_evolved_percent']; same_match = DMATCH[_u]
    return dict(nOpsBarSamePanel=e(same_panel), nOpsBarSameMatch=e(same_match),
                nOpsBarSameGap=f'{same_panel / same_match:.1f}',
                nOpsBarPubArms=str(len(pub)), nOpsBarBelowVal=str(len(below_val)),
                nOpsBarBelowValName=below_val[0].replace('-', '\\mbox{-}') if len(below_val) == 1 else '',
                nOpsBarBelowValErr=e(min(DVAL[(a, 'worst_fixed_initial_error')] for a in below_val)),
                nOpsBarBelowMatch=str(len(below_match)),
                nDonArms=str(len(DARMS)), nDonMeanLo=e(min(dm)), nDonMeanHi=e(max(dm)),
                nDonSelWorst=e(DVAL[('don-small', 'worst_fixed_initial_error')]),
                nDonMatchLo=e(min(DMATCH[a] for a in DARMS)), nDonMatchHi=e(max(DMATCH[a] for a in DARMS)),
                nDonOtherMeanLo=e(min(others)), nDonOtherMeanHi=e(max(others)),
                nDonRomMatch=e(100 * _D2['rom']), nDonPersistMean=e(100 * _pv['mean']),
                nDonVsPersist=f"{100 * _pv['mean'] / min(dm):.1f}", nDonTrainCases=str(cases.pop()),
                nDonTrainRmsLo=e(min(tr)), nDonTrainRmsHi=e(max(tr)),
                nDonPatience=str({DA['arms'][a]['config']['patience'] for a in DARMS}.pop()),
                nDonEpochCap=str({DA['arms'][a]['config']['epochs'] for a in DARMS}.pop()),
                nDonJob=DA['job_id'])




