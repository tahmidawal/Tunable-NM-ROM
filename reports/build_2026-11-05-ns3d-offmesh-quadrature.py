    w("## 5. Online cost, same job, same GPU")
    w("")
    for n in meshes:
        s = data[n]
        t = s["timing"]["fast"]
        k_ = s["timing"]["kernel"]
        cn = s["cnab2"]
        wt, _ = evolved(s["tensor"]["head"]["errors"])
        w(f"### {n}³ ({s['gpu'].split(',')[0]}, job {s.get('job_id')})")
        w("")
        w("| arm | $M$ | median query ms | min–max ms | evolved worst | fastest CNAB2 at least as accurate | its ms | speedup vs that CNAB2 | kernel ms (30 Jacobians) |")
        w("|---|---|---|---|---|---|---|---|---|")
        rows = [("tensor head", "tensor_head", "—", wt, "kernel_tensor")]
        for x in s["timing"]["timed_rules"]:
            e = s["ladder"][x]["net"]["rollouts"]["head"]
            if not e["finite"]:
                continue
            rows.append((f"`net` head `{x}`", f"net_head_{x}", s["ladder"][x]["m"], evolved(e["errors"])[0],
                         f"kernel_{x}" if f"kernel_{x}" in k_ else None))
        ws_, _ = evolved(s["tensor"]["span64"]["errors"])
        rows.append(("tensor span64", "tensor_span64", "—", ws_, None))
        for x in s["config"]["ladder"]["lat"]:
            e = s["ladder"][x]["net"]["rollouts"]["span64"]
            if e["finite"] and f"net_span64_{x}" in t:
                rows.append((f"`net` span64 `{x}`", f"net_span64_{x}", s["ladder"][x]["m"], evolved(e["errors"])[0], None))
        for label, key, m, worst, kk in rows:
            c = comparator(cn, worst, t)
            ms = t[key]["median_ms"]
            w(f"| {label} | {m} | {ms:.2f} | {t[key]['min_ms']:.2f}–{t[key]['max_ms']:.2f} | {pct(worst)} | "
              + (f"CNAB2 {c[0]} steps ({pct(c[2])}) | {c[1]:.2f} | {c[1] / ms:.2f}× |" if c else "none | — | — |")
              + (f" {k_[kk]['median_ms']:.3f} |" if kk else " — |"))
        w("")
        w("CNAB2 ladder in the same block: " + ", ".join(
            f"{st} steps {t[f'CNAB2_s{st}']['median_ms']:.2f} ms" for st in s["config"]["cnab2_steps"]) + ".")
        fl = s["timing"]["flops"]
        w(f"Flop model per Gauss–Newton sweep: tensor {fl['tensor_per_sweep']:,}; quadrature "
          f"{fl['quad_per_sweep_per_point']:,} per point. Offline: tensor build {s['tensor_build_seconds']:.1f} s.")
        w("")

    # ---------------------------------------------------------------- figures
    for n in meshes:
        s = data[n]
        fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), sharey=True)
        cn = s["cnab2"]
        for ax, integ in zip(axes, s["config"]["integrands"]):
            for f in s["config"]["families"]:
                r = rec[n][(integ, f, "head")]
                y = [e[0] if fin else np.nan for e, fin in zip(r["ev"], r["fin"])]
