"""b2d-query-speed: RESULTS.md from the job JSON (PROTOCOL.md section 8). Every number below is read from
results/<attempt>/arms.json (written by analyse.py from result.json), results/<attempt>/ops-*/ and frozen.json.
    python summarise.py   ->  RESULTS.md, results/summary.json
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / 'results'
out, summary = [], {}
P = out.append


def load(att):
    p = RES / att / 'arms.json'
    return json.loads(p.read_text()) if p.exists() else None


def prov(j):
    return (f"job {j['job_id']}, {j['host']}, {j['gpu']}, backend {j['backend']}, commit {j['commit'][:9]}, "
            f"{j['cases']} cases, driver {j['elapsed_seconds']:.0f} s, drift gate "
            f"{'pass' if j['drift']['passed'] else 'FAIL'} (ratios {j['drift']['ratios'][0]:.3f}-{j['drift']['ratios'][1]:.3f}), "
            f"neighbour gate {'pass' if j['neighbour_passed'] else 'FAIL'}")


def ops(att):
    """{arm: [per-seed dict]} from results/<att>/ops-*/"""
    r = {}
    for d in sorted((RES / att).glob('ops-*')):
        for f in sorted(d.glob('*.L256.json')):
            x = json.loads(f.read_text())
            v = x['L256']
            r.setdefault(x['arm'], []).append(dict(seed=x['seed'], median=v['median_percent'], worst=v['worst_percent'],
                                                   ms=v['timing']['median_ms'], p05=v['timing']['p05_ms'],
                                                   p95=v['timing'].get('p95_ms'), gpu=x['gpu'], job=x['job_id'],
                                                   cohort=x['cohort']))
    return r


def table(j, widths=None, label=None):
    """baseline and candidates per width of one job"""
    P('| width | setting | median % | worst % | ms (median) | ms 5-95 % of cases | ms min-max | speedup | median ratio | worst ratio | max case ratio |')
    P('|---|---|---|---|---|---|---|---|---|---|---|')
    rows = []
    for a in sorted((a for a in j['arms'] if a['width']), key=lambda a: (a['width'], a['role'] != 'baseline', a['ms_median'])):
        if widths and a['width'] not in widths:
            continue
        v = a.get('vs_baseline')
        nm = {'baseline': f"baseline (unchanged, gtol {a.get('gtol'):g})" if a['role'] == 'baseline' else ''}.get(a['role'], f"{a['role']}: {a.get('tag') or a['name']}")
        if a['role'] == 'baseline' and v:
            nm = f"baseline text, M={a['M']} {a['rule']} gtol {a['gtol']:g}"
        elif a['M'] != 4 * a['width'] or a['rule'] != 'lat64':
            nm += f" (M={a['M']} {a['rule']})"
        P(f"| {a['width']} | {nm} | {a['median']:.4f} | {a['worst']:.3f} | {a['ms_median']:.2f} | "
          f"{a['ms_case_p05']:.2f}-{a['ms_case_p95']:.2f} | {a['ms_min']:.2f}-{a['ms_max']:.2f} | "
          + (f"{v['speedup']:.2f}x | {v['median_ratio']:.3f} | {v['worst_ratio']:.3f} | {v['max_case_ratio']:.3f} |"
             if v else '1 | 1 | 1 | 1 |'))
        rows.append(dict(width=a['width'], role=a['role'], tag=a.get('tag'), M=a['M'], rule=a['rule'], gtol=a.get('gtol'),
                         median=a['median'], worst=a['worst'], ms=a['ms_median'], p05=a['ms_case_p05'], p95=a['ms_case_p95'],
                         ms_min=a['ms_min'], ms_max=a['ms_max'], identical_to_quick=a['identical_to_quick'],
                         **({k: v[k] for k in ('speedup', 'median_ratio', 'worst_ratio', 'max_case_ratio')} if v else {})))
    fom = [a for a in j['arms'] if a['role'] == 'fom']
    for a in fom:
        P(f"\nReference solver `{a['name']}` in the same job: {a['ms_median']:.2f} ms median "
          f"(5-95 % of cases {a['ms_case_p05']:.2f}-{a['ms_case_p95']:.2f}).")
        rows.append(dict(role='fom', name=a['name'], ms=a['ms_median']))
    if label:
        summary[label] = dict(provenance=prov(j), cohort=j['cohort_name'], cohort_sha256=j['cohort_sha256'], rows=rows)
    return rows


fz = json.loads((HERE / 'frozen.json').read_text()) if (HERE / 'frozen.json').exists() else None
P('# b2d-query-speed: results\n')
P('Generated by `summarise.py` from the job JSON; protocol in `PROTOCOL.md` (written before any outcome). Burgers 2D, '
  '256^2 mesh, frozen bank, linear rung, 50 backward-Euler steps, A100 80GB, single-query latency unless a table says '
  'batched. Error: per case the maximum over the five evolved output times of ||u - u_ref|| / ||u_ref(0)|| against the '
  '`fft_tight` reference, in percent; median and worst over the cohort. "speedup" is baseline ms / setting ms in the '
  'same job; the ratios are setting / baseline. A setting whose error is higher than the baseline is a different '
  'accuracy point, not a speedup of the baseline.\n')

# ------------------------------------------------------------------ final
for att, title in (('ftest64', 'test64 = params_draw(20260916, 64)'), ('ffresh64', 'fresh64 = params_draw(2026111402, 64), sealed until the freeze')):
    j = load(att)
    if not j:
        P(f'## Final: {title}\n\nNot run.\n')
        continue
    P(f'## Final (evaluated once): {title}\n')
    P(prov(j) + f". Cohort SHA-256 {j['cohort_sha256'][:16]}.\n")
    rows = table(j, label=att)
    bad = [r['tag'] for r in rows if r.get('identical_to_quick') is False]
    P(f"\nTimed outputs bitwise identical to the scored outputs: {'all arms' if not bad else 'NOT for ' + ', '.join(map(str, bad))}.")
    if j.get('rejected_nonfinite'):
        P('Non-finite arms: ' + ', '.join(x['name'] for x in j['rejected_nonfinite']) + '.')
    o = ops(att)
    if o:
        P('\nOperators re-timed in the same job on the same GPU (frozen 4,608-trajectory checkpoints, batch 1, '
          '5 repetitions per case after 20 burn-in calls, synchronised; nothing retrained):\n')
        P('| operator | seed | median % | worst % | ms (median) | ms 5 % |')
        P('|---|---|---|---|---|---|')
        osum = {}
        for arm, xs in sorted(o.items()):
            for x in xs:
                P(f"| {arm} | {x['seed']} | {x['median']:.4f} | {x['worst']:.3f} | {x['ms']:.2f} | {x['p05']:.2f} |")
            osum[arm] = dict(median=float(np.median([x['median'] for x in xs])), worst=float(np.median([x['worst'] for x in xs])),
                             ms=float(np.median([x['ms'] for x in xs])), seeds=xs)
            P(f"| {arm} | median of {len(xs)} seeds | {osum[arm]['median']:.4f} | {osum[arm]['worst']:.3f} | {osum[arm]['ms']:.2f} | |")
        summary[att]['operators'] = osum
        P('\nEqual-error comparison on this cohort (ours: narrowest width whose setting has median error at or below the '
          "operator's seed-median error; error and time measured in this job):\n")
        P('| operator | op median % | op worst % | op ms | our width / setting | our median % | our worst % | our ms | op ms / our ms |')
        P('|---|---|---|---|---|---|---|---|---|')
        eq = []
        for arm, s in sorted(osum.items()):
            for role in ('baseline', 'accurate', 'fast'):
                c = sorted((r for r in rows if r.get('role') == role and r['median'] <= s['median']), key=lambda r: r['width'])
                if not c:
                    P(f"| {arm} | {s['median']:.4f} | {s['worst']:.3f} | {s['ms']:.2f} | {role}: none at or below | | | | |")
                    continue
                c = c[0]
                P(f"| {arm} | {s['median']:.4f} | {s['worst']:.3f} | {s['ms']:.2f} | {c['width']} / {role} | {c['median']:.4f} | "
                  f"{c['worst']:.3f} | {c['ms']:.2f} | {s['ms'] / c['ms']:.2f} |")
                eq.append(dict(operator=arm, role=role, width=c['width'], our_median=c['median'], our_worst=c['worst'],
                               our_ms=c['ms'], op_median=s['median'], op_worst=s['worst'], op_ms=s['ms'], ratio=s['ms'] / c['ms']))
        summary[att]['equal_error'] = eq
    elif (RES / att).exists():
        P('\nOperator step: no output (see the job log).')
    if j.get('batched'):
        P('\nBatched throughput (separate measurement: `vmap` over B queries in one call, B cases cycled from the cohort; '
          'ms per batch is wall time of one call, not a latency of a single query):\n')
        P('| setting | B | ms per batch | ms per query | worst % | max error deviation from single-query |')
        P('|---|---|---|---|---|---|')
        for b in j['batched']:
            if 'failed' in b:
                P(f"| {b['name']} | {b['batch']} | failed: {b['failed'][:80]} | | | |")
            else:
                P(f"| {b['name']} | {b['batch']} | {1e3 * b['median_seconds']:.2f} | {b['per_query_ms']:.3f} | "
                  f"{100 * b['worst_error']:.3f} | {b['max_error_deviation_from_single']:.1e} |")
        summary[att]['batched'] = j['batched']
    P('')

# ------------------------------------------------------------------ freeze
if fz:
    P('## Frozen settings (selected on dev38 only, PROTOCOL.md section 5)\n')
    P(f"Source jobs {', '.join(map(str, fz['source_jobs']))}. Equal-error width frozen on dev38: {fz['equal_error_width']} "
      f"(smallest of 128-192 whose accurate setting has dev38 median <= {fz['equal_error_level_percent']} %).\n")
    P('| width | candidates | eligible accurate / fast | accurate | dev median % / worst % / ms | fast | dev median % / worst % / ms |')
    P('|---|---|---|---|---|---|---|')
    for Rp, w in fz['widths'].items():
        f = lambda x: (f"{x['tag']} | {x['dev_median']:.4f} / {x['dev_worst']:.3f} / {x['dev_ms']:.2f}" if x else 'none | ')
        P(f"| {Rp} | {w['candidates']} | {w['accurate_eligible']} / {w['fast_eligible']} | {f(w['accurate'])} | {f(w['fast'])} |")
    P('')
    summary['frozen'] = fz

# ------------------------------------------------------------------ dev
for att, title in (('sello', 'dev38 selection, widths 96-176'), ('selhi', 'dev38 selection, widths 192-512'),
                   ('explore128', 'dev38 exploration, width 128'), ('fdev', 'dev38 rehearsal of the final job'),
                   ('diag512', 'dev38 width-512 diagnosis'), ('diag2', 'dev38 width-512 diagnosis, more tests')):
    j = load(att)
    if not j:
        continue
    P(f'## {title} (`results/{att}`)\n')
    P(prov(j) + '.\n')
    table(j, label=att)
    if j.get('rejected_nonfinite'):
        P('\nRejected (non-finite on a dev case): ' + ', '.join(x['name'] for x in j['rejected_nonfinite']) + '.')
    d = j.get('diagnostics')
    if d and d.get('rows'):
        P('\nNo-solve diagnostics (cond_2 of the reduced operator A, cond_2 of the step Jacobian at t = 0 over the listed '
          'cases, projection floor = least-squares fit of the reference fields in the span of the R\' columns, same error measure):\n')
        P('| width | M | cond(A) | cond(J, t=0) median | floor median % | floor worst % | cases |')
        P('|---|---|---|---|---|---|---|')
        dr = []
        for x in d['rows']:
            cs = x['cases']
            cj = [c['cond_J_t0'] for c in cs if 'cond_J_t0' in c]
            fl = [100 * c['floor_evolved'] for c in cs if 'floor_evolved' in c]
            P(f"| {x['R_prime']} | {x['M']} | {x['cond_A']:.2f} | {np.median(cj):.2f} ({len(cj)}) | "
              + (f"{np.median(fl):.4f} | {max(fl):.4f} | {len(fl)} |" if fl else ' | | |'))
            dr.append(dict(width=x['R_prime'], M=x['M'], cond_A=x['cond_A'], cond_J=float(np.median(cj)) if cj else None,
                           floor_median=float(np.median(fl)) if fl else None, floor_worst=max(fl) if fl else None))
        summary[att]['diagnostics'] = dr
    if j.get('batched'):
        summary[att]['batched'] = j['batched']
    P('')

(HERE / 'RESULTS.md').write_text('\n'.join(out) + '\n')
(RES / 'summary.json').write_text(json.dumps(summary, indent=1) + '\n')
print('\n'.join(out))
