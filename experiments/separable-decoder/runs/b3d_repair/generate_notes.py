"""Generate B3D-REPAIR-NOTES.md from stored JSONs; no hand-entered results."""
import json
from pathlib import Path
import numpy as np


HERE = Path(__file__).resolve().parent
DEST = HERE.parents[1] / 'B3D-REPAIR-NOTES.md'


def stats(x):
    x = np.asarray(x)
    return [x.mean(), np.median(x), np.quantile(x, .95), x.max()]


def row(name, values, gradients=None):
    metrics = ' | '.join(f'{100*v:.4f}%' for v in stats(values))
    nonstationary = '—' if gradients is None else str(int(np.sum(np.asarray(gradients) > 1e-6)))
    return f'| {name} | {metrics} | {nonstationary} |'


def main():
    baseline = json.loads((HERE/'repair_repro33/out/repro33.json').read_text())
    rows = baseline['D4_rows']
    text = [
        '# Burgers 3D: corrected pilot reproduction and representation repair', '',
        'This report covers the approved repair experiment. New diagnostic results are provisional '
        'pending independent review; the original pilot gates remain unchanged. '
        'Tables are generated by `runs/b3d_repair/generate_notes.py` from the stored run JSONs.', '',
        '## Baseline reproduction', '',
        f"Job `{baseline['config']['slurm_job']}` used `{baseline['config']['gpu']}`, "
        f"with N={baseline['config']['N']}, K={baseline['config']['k']}, R={baseline['config']['r']}. "
        'It regenerated the parameter table and truth from the recorded seed, used the unchanged '
        'corrected checkpoint, and passed the operator and lineage controls. '
        'The representation gate still fails. This is a validation experiment, not a test rollout.', '',
        '| Group | Mean error | Median error | 95th-percentile error | Worst error | Nonstationary |',
        '|---|---:|---:|---:|---:|---:|',
    ]
    for label, group in [('All states', rows), ('Initial states', [r for r in rows if r['k']==0]),
                         ('Later states', [r for r in rows if r['k']>0])]:
        text.append(row(label, [r['oracle_full'] for r in group], [r['optimality'] for r in group]))
    text += ['', '## New diagnostics', '',
             'QR provides exact coordinates in the same learned bank. The unrestricted bank fit '
             'is a lower bound on decoder error; the nonlinear multistart fit is a local optimization '
             'diagnostic and is not a certified global optimum. No quadrature or tensor is used '
             'to measure these representation errors.', '']
    found = False
    for path in sorted(HERE.glob('*/out/result.json')):
        data = json.loads(path.read_text())
        if data.get('kind') != 'b3d_repair_diagnostic' or not data.get('complete'):
            continue
        found = True
        label = path.parents[1].name
        c = data['config']
        text += [f'### {label}', '',
                 f"Provisional: job `{c['slurm_job']}`, source `{c['commit']}`, "
                 f"GPU `{c['gpu']}`; independent review has not been completed.", '',
                 '| Measurement | Mean error | Median error | 95th-percentile error | Worst error | Nonstationary |',
                 '|---|---:|---:|---:|---:|---:|']
        states = data['validation_states']
        floors = np.sqrt(np.asarray(states['perpendicular2']) / np.asarray(states['norm2']))
        text.append(row('Unrestricted bank', floors))
        for fit in data['fits']:
            text.append(row(f"Exact-coordinate LM, budget {fit['budget']}", fit['error'], fit['optimality']))
        text += ['', f"Bank condition number: {data['bank']['condition']:.6g}. "
                 f"Maximum relative error change between the two budgets: {data['budget_change_max']:.6g}.", '']
    if not found:
        text += ['No completed new diagnostic has been pulled yet.', '']
    comparison = json.loads((HERE/'reference/parameter_manifest_comparison.json').read_text())
    text += ['## Provenance compatibility amendment', '',
             'The first new diagnostic failed closed because regenerated derived parameters had '
             'different bytes from the archived metadata. Raw random draws and membership matched '
             'exactly. The failed attempt is retained under `diag33`.', '',
             '| Derived quantity | Changed entries | Maximum relative difference |',
             '|---|---:|---:|']
    for key in ['nu', 's_star']:
        d = comparison[key]
        text.append(f"| {key} | {d['different']} | {d['max_relative']:.6g} |")
    text += ['', 'The amended check requires the archived metadata hash to match the checkpoint, '
             'exact raw random draws, and derived positive values differing by no more than eight '
             'float64 machine epsilons. Perturbation controls exercise rejection. '
             'All actual solution data still use regenerated parameters. '
             'The original representation and rollout thresholds were not changed.', '',
             '## Scope and open work', '',
             'These tables do not establish a rollout or speedup. Promotion requires the original '
             'representation gates and operator controls, followed by actual rollout and paired '
             'classical comparisons. No final-test table is used for model selection.', '',
             '## Glossary', '',
             '- **N:** grid nodes per spatial axis; the unknowns are the interior nodes.',
             '- **K:** number of latent variables optimized by the ROM.',
             '- **R / bank:** number of learned spatial features, and their grid evaluation matrix.',
             '- **Error:** relative Euclidean field error on the interior grid.',
             '- **Mean / median / 95th percentile / worst:** summaries over the indicated states; '
             'these are not trajectory-averaged rollout errors.',
             '- **Initial / later:** snapshots at the initial time or subsequent selected times.',
             '- **Nonstationary:** number of selected fits whose normalized gradient exceeds the '
             'unchanged acceptance threshold.',
             '- **QR:** an orthogonal factorization used to compute exact coordinates and bank error.',
             '- **LM / budget:** damped nonlinear least squares and its maximum iteration attempts per start.',
             '- **Multistart:** fitting from several fixed training-derived guesses and choosing minimum error.',
             '- **nu / s_star:** viscosity and the reference-grid initial-field peak normalizer.',
             '- **Provisional:** measured and locally checked, with independent review still outstanding.',
             '- **Promotion:** allowing rollout/cost evaluation only after all preceding acceptance checks.',
             '- **Holdout / validation / test:** data excluded from fitting; validation selects models, '
             'while final test data remain untouched until selection is complete.', '']
    DEST.write_text('\n'.join(text))
    print(DEST)


if __name__ == '__main__':
    main()
