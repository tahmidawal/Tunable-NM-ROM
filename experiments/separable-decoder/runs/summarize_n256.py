#!/usr/bin/env python3
"""Generate the N=256 summary tables FROM THE RUN JSONS (never hand-typed).

Usage: python runs/summarize_n256.py runs/<job>/out/*.json > runs/SUMMARY-n256.md
"""
import json
import sys

import numpy as np


def med(x):
    return float(np.median(x))


def main(paths):
    pois, burg = [], []
    for p in sorted(paths):
        d = json.load(open(p))
        (pois if d["config"]["pde"] == "poisson2d" else burg).append((p, d))

    print("# N=256 separable EQ-decoder summary (generated by "
          "runs/summarize_n256.py)\n")

    if pois:
        print("## Poisson 2D (stationary weak solve)\n")
        print("| cell | K | R | steps | train s | recon mean | oracle held/fresh "
              "| arm | tau | cohort | err mean | err max | ms (proj+solve+dec) "
              "| jac | cens% | reasons |")
        print("|" + "---|" * 16)
        for p, d in pois:
            c = d["config"]
            t = d.get("train", {})
            o = d.get("oracle_test_rel_l2", {})
            ok = list(o.keys())
            orc = "/".join(f"{o[k]['mean']:.2e}" for k in ok) if o else "-"
            for r in d.get("rows", []):
                print(f"| {p.split('/')[-1].replace('.json','')} | {c['k']} | "
                      f"{c['r']} | {c['steps']} | {t.get('seconds',0):.0f} | "
                      f"{t.get('recon_rel_l2_mean',float('nan')):.2e} | {orc} | "
                      f"{r['method']} | {r['tau']:.0e} | {r['cohort']} | "
                      f"{r['err_rel_l2']:.3e} | {r['err_rel_l2_max']:.3e} | "
                      f"{r['time_ms']:.3f} | {r['jac_evals']:.1f} | "
                      f"{r['censored_frac']*100:.0f} | {r.get('stop_reasons')} |")
        print("\n### Poisson FOM CG ladder (same job, same GPU)\n")
        print("| cell | tol | cohort | err mean | err max | ms |")
        print("|" + "---|" * 6)
        for p, d in pois:
            for f in d.get("fom", []):
                print(f"| {p.split('/')[-1].replace('.json','')} | "
                      f"{f['fom_tol']:.0e} | {f['cohort']} | "
                      f"{f['err_rel_l2']:.3e} | {f['err_rel_l2_max']:.3e} | "
                      f"{f['time_ms']:.3f} |")
        print("\n### Poisson gates/diagnostics\n")
        print("| cell | gate0 | f_m proj dev | EQ rel fit | EQ row p95 | "
              "EQ row max |")
        print("|" + "---|" * 6)
        for p, d in pois:
            eq = d.get("eq", {})
            print(f"| {p.split('/')[-1].replace('.json','')} | "
                  f"{d.get('gate0_max_rel_dev',float('nan')):.1e} | "
                  f"{d.get('fm_projection_max_rel_dev',float('nan')):.1e} | "
                  f"{eq.get('rel_fit',float('nan')):.2e} | "
                  f"{eq.get('row_rel_p95',float('nan')):.1e} | "
                  f"{eq.get('row_rel_max',float('nan')):.1e} |")

    if burg:
        print("\n## Burgers 2D (50-step implicit rollout, END-TO-END timing)\n")
        print("| cell | K | R | steps | train s | recon mean | method | "
              "err mean | err max | e2e ms | ic ms | roll ms | dec ms | jac | "
              "ic jac | reasons | blowups |")
        print("|" + "---|" * 17)
        for p, d in burg:
            c = d["config"]
            t = d.get("train", {})
            for r in d.get("rows", []):
                if not r["method"].startswith("sep_"):
                    continue
                print(f"| {p.split('/')[-1].replace('.json','')} | {c['k']} | "
                      f"{c['r']} | {c['steps']} | {t.get('seconds',0):.0f} | "
                      f"{t.get('recon_rel_l2_mean',float('nan')):.2e} | "
                      f"{r['method']} | {r['err_traj_rel_mean']:.3e} | "
                      f"{r['err_traj_rel_max']:.3e} | {r['e2e_ms_median']:.2f} | "
                      f"{r['ic_ms_median']:.2f} | {r['rollout_ms_median']:.2f} | "
                      f"{r['decode_ms_median']:.2f} | {r['jac_total_mean']:.0f} | "
                      f"{r['ic_jac_mean']:.0f} | {r.get('stop_reasons')} | "
                      f"{r['n_blowups']} |")
        print("\n### Burgers classical baselines (same job, same GPU)\n")
        print("| cell | method | newton tol | err mean | err max | ms | "
              "newton iters | steps conv frac |")
        print("|" + "---|" * 8)
        for p, d in burg:
            for r in d.get("rows", []):
                if r["method"] == "fom_newton_tol":
                    print(f"| {p.split('/')[-1].replace('.json','')} | "
                          f"{r['method']} | {r['newton_tol']:.0e} | "
                          f"{r['err_traj_rel_mean']:.3e} | "
                          f"{r['err_traj_rel_max']:.3e} | "
                          f"{r['time_ms_median']:.1f} | "
                          f"{r['newton_iters_mean']:.0f} | "
                          f"{r['steps_converged_frac']:.2f} |")
                elif r["method"] == "fom_newton8_truthgen":
                    print(f"| {p.split('/')[-1].replace('.json','')} | "
                          f"{r['method']} (OVER-SOLVED) | - | "
                          f"{r['err_traj_rel_mean']:.1e} | - | "
                          f"{r['time_ms_median']:.1f} | - | - |")
        print("\n### Burgers gates/diagnostics\n")
        print("| cell | gate0 | IC jit-vs-incumbent | EQ rel fit | EQ row p95 | "
              "EQ row max |")
        print("|" + "---|" * 6)
        for p, d in burg:
            eq = d.get("eq", {})
            print(f"| {p.split('/')[-1].replace('.json','')} | "
                  f"{d.get('gate0_max_rel_dev',float('nan')):.1e} | "
                  f"{d.get('ic',{}).get('jit_vs_incumbent_rel_dev',float('nan')):.1e} | "
                  f"{eq.get('rel_fit',float('nan')):.2e} | "
                  f"{eq.get('row_rel_p95',float('nan')):.1e} | "
                  f"{eq.get('row_rel_max',float('nan')):.1e} |")


if __name__ == "__main__":
    main(sys.argv[1:])
