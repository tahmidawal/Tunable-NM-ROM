"""Tables for the measured cuDSS Burgers stepper (amendment 3, Task A), generated from the saved JSON only.

  python summarize_step.py results/step/h200 > RESULTS-burgers-stepper.md

Reads <dir>/b<dim>d_L<L>.json (stepper.py), ours_burgers.json (the paper's numbers) and, if present,
results/ours/same_gpu.json (our model re-timed on the same GPU type, Task B).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIZES = [(2, 256), (2, 512), (2, 1024), (2, 2048), (2, 4096), (3, 64), (3, 96), (3, 128)]
VARIANT = dict(full='full Newton (refactorise every iteration)', k1='modified Newton (refactorise once per step)',
               k5='refactorise every 5 steps', k10='refactorise every 10 steps', frozen='frozen (one factorisation per trajectory)',
               lin1='linearised (1 iteration per step, no residual test)')


def ms(x):
    return f'{1e3 * x:.4g}'


def pct(x):
    return 'not finite' if x != x or x == float('inf') else f'{100 * x:.4g}'


def label(s):
    nt = 'none' if s['ntol'] is None else f"{s['ntol']:g}"
    return f"{s['variant']}, dt {s['dt']:g}, tol {nt}, mesh {s['mesh_L']}"


def main():
    d = Path(sys.argv[1])
    ours = json.loads((HERE / 'ours_burgers.json').read_text())
    sg_path = HERE / 'results' / 'ours' / 'same_gpu.json'
    same_gpu = json.loads(sg_path.read_text()) if sg_path.exists() else {}
    res = {}
    for dim, L in SIZES:
        p = d / f'b{dim}d_L{L}.json'
        if p.exists():
            res[(dim, L)] = json.loads(p.read_text())
    amg = {}
    for dim, L in SIZES:
        p = d / f'amgx_b{dim}d_L{L}.json'
        if p.exists():
            amg[(dim, L)] = json.loads(p.read_text())
    P = print
    P('# Measured implicit Burgers time-stepper with cuDSS and AmgX (amendments 3 and 4, Task A)')
    P()
    P(f'Generated by `summarize_step.py {sys.argv[1]}` from the saved JSON. Times are whole trajectories (initial field on the '
      'device to six output fields on the device: residual and Jacobian assembly, refactorisations, solves, residual tests, '
      'and restriction/interpolation when the mesh is coarsened). Setup (pattern, symbolic analysis, first factorisation, '
      'kernel compilation) is excluded and listed separately. Errors are the paper metric: max over the five evolved output '
      'times of ||u - reference|| / ||reference(t=0)||, against the paper\'s reference full-order solver run in the same job, '
      'worst and median over the cases. Double precision.')
    P()
    P('## Runs')
    P()
    P('| problem | unknowns | cases | status | GPU | host | job | cuDSS | peak device GB | reference converged | cohort checksum = paper |')
    P('|---|---|---|---|---|---|---|---|---|---|---|')
    for dim, L in SIZES:
        r = res.get((dim, L))
        nm = f'Burgers {dim}D {L}^{dim}'
        if r is None:
            P(f'| {nm} | {(L - 1) ** dim} | | not run | | | | | | | |')
            continue
        ref = r.get('reference', {})
        st = r.get('status')
        if st == 'failed':
            st = f"failed at {r.get('failed_stage')}: {r.get('error', '')[:120]}"
        peak = r.get('peak_device_bytes', r.get('peak_device_bytes_at_failure'))
        P(f"| {nm} | {r.get('unknowns', (L - 1) ** dim)} | {r.get('cases', '')} | {st} | {str(r.get('gpu', '')).split(',')[0]} | "
          f"{r.get('host', '')} | {r.get('slurm_job', '')} | {r.get('cudss_version', '')} | "
          f"{'' if peak is None else f'{peak / 2**30:.1f}'} | {ref.get('all_converged', '')} | "
          f"{ref.get('cohort_sha_matches_paper', 'n/a (3D table carries its own checksum)')} |")
    P()
    P('## Pre-timing checks and setup cost')
    P()
    P('| problem | Jacobian vs finite differences (rel.) | tight full Newton vs paper reference | initial field difference | '
      'pattern ms | analysis ms | first factorisation ms |')
    P('|---|---|---|---|---|---|---|')
    for (dim, L), r in res.items():
        c, s = r.get('checks'), (r.get('setup') or {}).get('1')
        if not c or not s:
            continue
        g = lambda k: next((f'{1e3 * v:.4g}' for kk, v in s.items() if k in kk), '')  # noqa: E731
        P(f"| Burgers {dim}D {L}^{dim} | {c['jacobian_fd_relative']:.2e} | {c['tight_full_newton_vs_reference']:.2e} | "
          f"{c['initial_field_difference']:.1e} | {g('pattern')} | {g('analysis')} | {g('factor')} |")
    P()
    P('## Same mesh, same time step (dt 0.005, 50 steps): every variant')
    P()
    P('Our model (paper values; worst-case error over the paper cohort) is listed under each size. "Unconv." = number of '
      '(case, step) pairs that hit the iteration cap without meeting the tolerance.')
    for (dim, L), r in res.items():
        S = r.get('settings') or {}
        rows = [s for s in S.values() if s.get('group') == 'same-mesh' and s.get('status') == 'ok']
        if not rows:
            continue
        P()
        P(f'### Burgers {dim}D {L}^{dim} ({r["unknowns"]} unknowns, {r["cases"]} cases)')
        P()
        o = ours[f'burgers{dim}d'].get(str(L))
        if o:
            sg = same_gpu.get(f'burgers{dim}d', {}).get(str(L), {})
            for role in ('accurate', 'fast'):
                extra = ''
                if role in sg:
                    extra = (f"; re-timed in this lane on {sg[role]['gpu']}: {sg[role]['ms']:.4g} ms, worst-case "
                             f"{sg[role]['worst_percent']:.4g} %")
                P(f"- ours, {role}: {o[role]['ms']:.4g} ms, worst-case {o[role]['worst_percent']:.4g} %, median "
                  f"{o[role]['median_percent']:.4g} % (paper, {o['gpu']}){extra}")
            P()
        P('| variant | Newton tol | ms median | ms min–max | worst % | median % | Newton its median (max) | refactorisations | '
          'solves | unconv. | refactor / solve / rest ms (case 0, synchronised) |')
        P('|---|---|---|---|---|---|---|---|---|---|---|')
        for s in rows:
            t = s['time_s']
            i = s.get('instrumented_case0')
            split = f"{ms(i['refactor_s'])} / {ms(i['solve_s'])} / {ms(i['rest_s'])}" if i else ''
            P(f"| {VARIANT[s['variant']]} | {'—' if s['ntol'] is None else f'{s['ntol']:g}'} | {ms(t['median'])} | "
              f"{ms(t['min'])}–{ms(t['max'])} | {pct(s['worst_error'])} | {pct(s['median_error'])} | "
              f"{s['newton_total_median']:.0f} ({s['newton_total_max']}) | {s['refactor_median']:.0f} | {s['solve_median']:.0f} | "
              f"{s['unconverged_steps_total']} | {split} |")
    P()
    P('## Accuracy-matched: fastest cuDSS setting whose worst-case error is no worse than ours')
    P()
    P('cuDSS may use any variant, Newton tolerance, time step (0.005, 0.01, 0.025, 0.05) and mesh (same, 2x or 4x coarser, '
      'interpolated back and compared on the target mesh). Selection: smallest median time among settings with worst-case '
      'error <= our worst-case error (paper value). Settings with unconverged steps are selected only in the last column. '
      'Note: our worst case is over the full paper cohort, cuDSS\'s over the number of cases listed under Runs.')
    P()
    P('| problem | ours | ours worst % | ours ms (paper) | ours ms (same GPU, this lane) | cuDSS setting | cuDSS ms median (min–max) | '
      'cuDSS worst % | cuDSS / ours (paper ms) | cuDSS / ours (same GPU) | fastest incl. unconverged |')
    P('|---|---|---|---|---|---|---|---|---|---|---|')
    for (dim, L), r in res.items():
        S = [s for s in (r.get('settings') or {}).values() if s.get('status') == 'ok' and s.get('finite')]
        o = ours[f'burgers{dim}d'].get(str(L))
        if not S or not o:
            continue
        sg = same_gpu.get(f'burgers{dim}d', {}).get(str(L), {})
        for role in ('accurate', 'fast'):
            thr = o[role]['worst_percent'] / 100
            ok = sorted((s for s in S if s['worst_error'] <= thr), key=lambda s: s['time_s']['median'])
            clean = [s for s in ok if s['unconverged_steps_total'] == 0]
            sgm = sg.get(role, {}).get('ms')
            if not clean:
                P(f"| Burgers {dim}D {L}^{dim} | {role} | {o[role]['worst_percent']:.4g} | {o[role]['ms']:.4g} | "
                  f"{'' if sgm is None else f'{sgm:.4g}'} | none meets the error | | | | | |")
                continue
            b = clean[0]
            t = b['time_s']
            other = '' if ok[0] is b else f"{label(ok[0])}: {ms(ok[0]['time_s']['median'])} ms, {pct(ok[0]['worst_error'])} %"
            P(f"| Burgers {dim}D {L}^{dim} | {role} | {o[role]['worst_percent']:.4g} | {o[role]['ms']:.4g} | "
              f"{'' if sgm is None else f'{sgm:.4g}'} | {label(b)} | {ms(t['median'])} ({ms(t['min'])}–{ms(t['max'])}) | "
              f"{pct(b['worst_error'])} | {1e3 * t['median'] / o[role]['ms']:.3g} | "
              f"{'' if sgm is None else f'{1e3 * t['median'] / sgm:.3g}'} | {other} |")
    P()
    P('## Matched grid: all settings')
    for (dim, L), r in res.items():
        S = r.get('settings') or {}
        rows = [s for s in S.values() if s.get('group') == 'matched-grid']
        if not rows:
            continue
        P()
        P(f'### Burgers {dim}D {L}^{dim}')
        P()
        nr = [s['name'] for s in rows if s.get('status') != 'ok']
        if nr:
            P(f"Not run (budget): {len(nr)} of {len(rows)} settings: {', '.join(nr)}")
            P()
        P('| setting | steps | ms median | ms min–max | worst % | median % | Newton its median | refactorisations | unconv. |')
        P('|---|---|---|---|---|---|---|---|---|')
        for s in rows:
            if s.get('status') != 'ok':
                continue
            t = s['time_s']
            P(f"| {label(s)} | {s['steps']} | {ms(t['median'])} | {ms(t['min'])}–{ms(t['max'])} | {pct(s['worst_error'])} | "
              f"{pct(s['median_error'])} | {s['newton_total_median']:.0f} | {s['refactor_median']:.0f} | "
              f"{s['unconverged_steps_total']} |")
    amgx_sections(P, amg, ours, same_gpu)


def amgx_sections(P, amg, ours, same_gpu):
    P()
    P('## AmgX stepper (amendment 4)')
    P()
    if not amg:
        P('Not run.')
        return
    P('Same kernels, Newton loop, timing contract and error metric as the cuDSS stepper; the linear solve is AmgX to a '
      'relative tolerance "lin tol" (zero initial guess). "Setups" = replace coefficients + AmgX setup. '
      'PBICGSTAB_JACOBI_NOAMG is BiCGStab with one block-Jacobi sweep and no multigrid (written by this lane); the others '
      'are shipped AmgX configurations. Sizes not listed were not run.')
    P()
    P('| problem | cases | status | GPU | host | job | AmgX commit | peak device GB | pre-timing check (tight full Newton vs paper reference) |')
    P('|---|---|---|---|---|---|---|---|---|')
    for (dim, L), r in amg.items():
        st = r.get('status')
        if st == 'failed':
            st = f"failed at {r.get('failed_stage')}: {r.get('error', '')[:120]}"
        peak = r.get('peak_device_bytes', r.get('peak_device_bytes_at_failure'))
        ck = '; '.join(f"{k}: {v['tight_full_newton_vs_reference']:.1e} ({'pass' if v['passed'] else 'FAIL'})"
                       for k, v in (r.get('checks') or {}).items())
        P(f"| Burgers {dim}D {L}^{dim} | {r.get('cases', '')} | {st} | {str(r.get('gpu', '')).split(',')[0]} | {r.get('host', '')} | "
          f"{r.get('slurm_job', '')} | {str(r.get('amgx_commit', ''))[:10]} | {'' if peak is None else f'{peak / 2**30:.1f}'} | {ck} |")
    for (dim, L), r in amg.items():
        S = list((r.get('settings') or {}).values())
        if not S:
            continue
        P()
        P(f'### AmgX, Burgers {dim}D {L}^{dim} ({r["cases"]} cases)')
        P()
        bad = [f"{s['name']} ({s.get('status')}{': ' + s['error'][:100] if s.get('error') else ''})" for s in S if s.get('status') != 'ok']
        if bad:
            P('Not completed: ' + '; '.join(bad))
            P()
        P('| configuration | variant | dt | Newton tol | lin tol | ms median | ms min–max | worst % | median % | Newton its median | '
          'linear its median | setups | unconv. | linear solves not converged | setup / solve / rest ms (case 0) |')
        P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
        for s in S:
            if s.get('status') != 'ok':
                continue
            t = s['time_s']
            i = s.get('instrumented_case0')
            split = f"{ms(i['refactor_s'])} / {ms(i['solve_s'])} / {ms(i['rest_s'])}" if i else ''
            P(f"| {s['config']} | {s['variant']} | {s['dt']:g} | {'—' if s['ntol'] is None else f'{s['ntol']:g}'} | {s['ltol']:g} | "
              f"{ms(t['median'])} | {ms(t['min'])}–{ms(t['max'])} | {pct(s['worst_error'])} | {pct(s['median_error'])} | "
              f"{s['newton_total_median']:.0f} | {s['linear_iterations_median']:.0f} | {s['refactor_median']:.0f} | "
              f"{s['unconverged_steps_total']} | {s['linear_not_converged_total']} | {split} |")
    P()
    P('### AmgX, accuracy-matched: fastest setting whose worst-case error is no worse than ours')
    P()
    P('Same selection rule as for cuDSS (settings with unconverged Newton steps excluded). AmgX was run on the same mesh only, '
      'dt 0.005 and 0.01.')
    P()
    P('| problem | ours | ours worst % | ours ms (paper) | ours ms (same GPU, this lane) | AmgX setting | AmgX ms median (min–max) | '
      'AmgX worst % | AmgX / ours (paper ms) | AmgX / ours (same GPU) |')
    P('|---|---|---|---|---|---|---|---|---|---|')
    for (dim, L), r in amg.items():
        S = [s for s in (r.get('settings') or {}).values() if s.get('status') == 'ok' and s.get('finite')]
        o = ours[f'burgers{dim}d'].get(str(L))
        if not o:
            continue
        sg = same_gpu.get(f'burgers{dim}d', {}).get(str(L), {})
        for role in ('accurate', 'fast'):
            thr = o[role]['worst_percent'] / 100
            ok = sorted((s for s in S if s['worst_error'] <= thr and s['unconverged_steps_total'] == 0),
                        key=lambda s: s['time_s']['median'])
            sgm = sg.get(role, {}).get('ms')
            head = (f"| Burgers {dim}D {L}^{dim} | {role} | {o[role]['worst_percent']:.4g} | {o[role]['ms']:.4g} | "
                    f"{'' if sgm is None else f'{sgm:.4g}'} | ")
            if not ok:
                P(head + 'none meets the error | | | | |')
                continue
            b = ok[0]
            t = b['time_s']
            P(head + f"{b['config']}, {b['variant']}, dt {b['dt']:g}, tol {'none' if b['ntol'] is None else f'{b['ntol']:g}'}, lin tol "
              f"{b['ltol']:g} | {ms(t['median'])} ({ms(t['min'])}–{ms(t['max'])}) | {pct(b['worst_error'])} | "
              f"{1e3 * t['median'] / o[role]['ms']:.3g} | {'' if sgm is None else f'{1e3 * t['median'] / sgm:.3g}'} |")


if __name__ == '__main__':
    main()
