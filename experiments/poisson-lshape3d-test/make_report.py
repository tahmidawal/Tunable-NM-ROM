"""poisson-lshape3d-test: write the report from reports/summary.json only (no number is typed by hand).

    python make_report.py   -> reports/2026-09-25-poisson-lshape3d-test-rows.md
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SUMMARY = HERE / 'reports' / 'summary.json'
OUT = HERE / 'reports' / '2026-09-25-poisson-lshape3d-test-rows.md'


def f(x, d=2):
    if x is None:
        return '—'
    if abs(x) >= 100:
        return f'{x:.0f}'
    return f'{x:.{d}f}'


def pct(x):
    if x is None:
        return '—'
    return f'{x:.3f}' if x < 1 else f'{x:.2f}'


def ms(x):
    return '—' if x is None else (f'{x:.3f}' if x < 10 else f'{x:.1f}')


def mesh(r):
    return f"{r['intervals']}²" if r['problem'] == 'lshape' else f"{r['intervals']}³"


def name(p):
    return 'L-shape' if p == 'lshape' else 'Poisson 3D'


def main():
    raw = SUMMARY.read_bytes()
    S = json.loads(raw)
    sha = hashlib.sha256(raw).hexdigest()
    rows = S['rows']
    have = [r for r in rows if r['test']]
    missing = [r for r in rows if not r['test']]
    state = ('final: every row has its test job' if not missing else
             'PROVISIONAL: test jobs still missing for ' + ', '.join(f"{name(r['problem'])} {mesh(r)}" for r in missing))
    L = ['# L-shape and Poisson 3D Table 1 rows on test cases', '',
         f'Table 1 rows for the L-shaped Poisson problem (256²–2048²) and Poisson 3D (128³, 256³), re-measured on '
         f'held-out test cases with the frozen models and the frozen settings, beside the development values printed '
         f'in the paper. State: **{state}**. Every number is generated by `make_report.py` from `reports/summary.json` '
         f'(sha256 `{sha}`), which `make_tables.py` builds from the audited job JSONs.', '',
         'Settings, test cohorts and the full-order-model rule were fixed in `DESIGN.md` (commit `4b08ccb1`, amendment '
         'A1 `39144077`) before any test job ran; nothing was chosen on test cases.', '',
         '## Table 1 format — development vs test', '',
         'Scope: GPU query (the device work of one query, the scope of the paper\'s rows). Speedup = median time of '
         'the row\'s full-order model (FOM) ÷ median time of the arm, both from the same job. Errors are the worst '
         'same-grid relative $L^2$ error over the cohort, in %.', '',
         '| problem | mesh | cohort (cases) | accurate % | accurate × | fast % | fast × | FOM % | FOM setting | '
         'ms accurate / fast / FOM | job | GPU | gates + audit |',
         '|---|---|---|---:|---:|---:|---:|---:|---|---|---|---|---|']
    for r in rows:
        for c in ('development', 'test'):
            e = r[c]
            if e is None:
                L.append(f"| {name(r['problem'])} | {mesh(r)} | test | not collected | | | | | | | | | |")
                continue
            a, fa, fom = e['row']['arms']['accurate'], e['row']['arms']['fast'], e['row']['fom']
            pc = e.get('paper_check')
            note = ''
            if pc is not None:
                note = ' (matches paper)' if all(pc['matches']) else ' (**differs from paper: ' + ', '.join(
                    f'{p}' for p, m in zip(pc['printed'], pc['matches']) if not m) + '**)'
            L.append(f"| {name(r['problem'])} | {mesh(r)} | {c}{note} ({e['cases']}) | {pct(a['worst_pct'])} | "
                     f"{f(a['speedup'], 1)} | {pct(fa['worst_pct'])} | {f(fa['speedup'], 1)} | {pct(fom['worst_pct'])} | "
                     f"CG {fom['tolerance']:g} | {ms(a['ms'])} / {ms(fa['ms'])} / {ms(fom['ms'])} | {e['job_id']} | "
                     f"{e['gpu']} | {'PASS' if e['usable'] else '**FAIL**'} |")
    L += ['', 'Accurate = span $R\'=128$ (linear rung) for both problems. Fast = span $R\'=64$ (L-shape) and '
          'span $R\'=16$ (Poisson 3D). All were frozen on development.', '']
    # R'=32 companion on the cube
    L += ['### Poisson 3D: span $R\'=32$ alongside the frozen fast width $R\'=16$', '',
          'Span $R\'=32$ is the fast width of the paper\'s 32³/64³ rows. It is not a substitute for $R\'=16$.', '',
          '| mesh | cohort | R\'=16 worst % | R\'=16 × | R\'=32 worst % | R\'=32 × | R\'=16 < 5 %? | R\'=32 < 5 %? |',
          '|---|---|---:|---:|---:|---:|---|---|']
    for r in rows:
        if r['problem'] != 'cube':
            continue
        for c in ('development', 'test'):
            e = r[c]
            if e is None:
                continue
            a16, a32 = e['row']['arms']['fast'], e['row']['arms']['also:R32_linear']
            L.append(f"| {mesh(r)} | {c} | {pct(a16['worst_pct'])} | {f(a16['speedup'], 1)} | {pct(a32['worst_pct'])} | "
                     f"{f(a32['speedup'], 1)} | {'yes' if a16['below_fast_criterion'] else '**no**'} | "
                     f"{'yes' if a32['below_fast_criterion'] else '**no**'} |")
    # other scope
    L += ['', '## Complete-query scope (host copies included), same jobs', '',
          '| problem | mesh | cohort | accurate × | fast × | FOM setting | order gate in this scope | usable in this scope |',
          '|---|---|---|---:|---:|---|---|---|']
    for r in rows:
        for c in ('development', 'test'):
            e = r[c]
            if e is None:
                continue
            ro = e['row_other_scope']
            og = e['order_gate']['total_seconds']
            L.append(f"| {name(r['problem'])} | {mesh(r)} | {c} | {f(ro['arms']['accurate']['speedup'], 1)} | "
                     f"{f(ro['arms']['fast']['speedup'], 1)} | CG {ro['fom']['tolerance']:g} | pooled "
                     f"{og['pooled_paired_ratio']:.3f}, max arm {og['max_arm_paired_ratio']:.3f} "
                     f"({'pass' if og['passed'] else '**fail**'}) | {'yes' if e['usable_other_scope'] else '**no**'} |")
    # distribution
    L += ['', '## Beyond the worst case: medians and how many test cases exceed the development worst', '',
          '| problem | mesh | arm | dev worst % | dev median % | test worst % | test median % | test cases above dev worst |',
          '|---|---|---|---:|---:|---:|---:|---|']
    for r in have:
        d, t = r['development'], r['test']
        for role in t['row']['arms']:
            da, ta = d['row']['arms'][role], t['row']['arms'][role]
            L.append(f"| {name(r['problem'])} | {mesh(r)} | {ta['name']} | {pct(da['worst_pct'])} | {pct(da['median_pct'])} | "
                     f"{pct(ta['worst_pct'])} | {pct(ta['median_pct'])} | {t['cases_above_development_worst'][role]} of "
                     f"{t['cases']} |")
    # gates
    L += ['', '## Gates and audit, per job', '',
          '| problem | mesh | cohort | job | GPU | audit | parity | determinism | CG converged | stationary (full R) | '
          'order gate, GPU scope (pooled / after-main / max arm) | profile | guard | result sha256 |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in rows:
        for c in ('development', 'test'):
            e = r[c]
            if e is None:
                continue
            g, og = e['driver_gates'], e['order_gate']['fused_device_seconds']
            ok = lambda b: 'ok' if b else '**FAIL**'
            L.append(f"| {name(r['problem'])} | {mesh(r)} | {c} | {e['job_id']} | {e['gpu']} | {e['audit']} | "
                     f"{ok(g['parity'])} | {ok(g['deterministic'])} | {ok(g['cg_converged'])} | "
                     f"{ok(g['rom_stationary_parent_and_full_R'])} | {og['pooled_paired_ratio']:.3f} / "
                     f"{og['median_after_over_main']:.3f} / {og['max_arm_paired_ratio']:.3f} ({ok(og['passed'])}) | "
                     f"{ok(g['profile_matches_fused'])} | {ok(g['device_guard'])} | `{e['result_sha256'][:16]}…` |")
    L += ['', 'Audit summaries (independent NumPy truth):', '']
    for r in rows:
        for c in ('development', 'test'):
            e = r[c]
            if e is not None:
                L.append(f"- {name(r['problem'])} {mesh(r)} {c} (job {e['job_id']}): {e['audit']}. {e['audit_summary']}")
    # descriptive rule
    L += ['', '## The selection rule re-applied on test (descriptive only; chooses nothing)', '',
          '| problem | mesh | lowest-worst arm | its worst % | cheapest arm ≤ orig_q0 | cheapest arm < 5 % |',
          '|---|---|---|---:|---|---|']
    for r in have:
        dr = r['test']['descriptive_rule_on_this_cohort']
        L.append(f"| {name(r['problem'])} | {mesh(r)} | {dr['accurate']} | {pct(dr['accurate_worst_pct'])} | "
                 f"{dr['fast_le_orig_q0']} | {dr['cheapest_under_5pct'] or '—'} |")
    # all arms
    L += ['', '## Every test evaluation (all arms, GPU scope)', '']
    for r in have:
        t = r['test']
        L += [f"### {name(r['problem'])} {mesh(r)} — test job {t['job_id']} ({t['gpu']}, {t['cases']} cases)", '',
              '| arm | R\' | q | worst % | median % | bank floor(R\') % | ms | own FOM | own × | stationary |',
              '|---|---:|---:|---:|---:|---:|---:|---|---:|---|']
        for s in t['all_arms']:
            st = s.get('stationary')
            L.append(f"| {s['name']} | {s['Rp']} | {s['q']} | {pct(s['worst_pct'])} | {pct(s['median_pct'])} | "
                     f"{pct(t['floors_pct'].get(str(s['Rp'])))} | {ms(s['ms'])} | {s['own_fom'] or '—'} | "
                     f"{f(s['own_speedup'], 1)} | {'' if st is None else str(st['stationary']) + '/' + str(st['invocations'])} |")
        L += ['', '| CG | worst % | median % | ms | iterations (median) | converged |', '|---|---:|---:|---:|---:|---|']
        for s in t['cg']:
            L.append(f"| {s['name']} | {pct(s['worst_pct'])} | {pct(s['median_pct'])} | {ms(s['ms'])} | "
                     f"{s['iterations_median']:.0f} | {s['converged_all']} |")
        L.append('')
    L += ['## Provenance', '',
          f"- Summary: `experiments/poisson-lshape3d-test/reports/summary.json`, sha256 `{sha}`.",
          '- Test jobs: branch `exp/2026-09-25-poisson-lshape3d-test`, namespace '
          '`/cluster/tufts/paralab/tawal01/pl3test_20260925/` (deleted after collection). Each job ran in its own '
          'directory, printed `jax_backend=gpu`, used f64 and highest matmul precision, and was pulled with checksums.',
          '- Development jobs: branch `exp/2026-09-23-poisson-bank-knob-3d` @ `59b67ae2`, the archived results under '
          '`experiments/poisson-bank-knob-3d/runs/`.', '']
    for r in rows:
        for c in ('development', 'test'):
            e = r[c]
            if e is not None:
                L.append(f"- {name(r['problem'])} {mesh(r)} {c}: attempt `{e['attempt']}`, job {e['job_id']}, commit "
                         f"`{(e['commit'] or '')[:10]}`, cohort seed {e['cohort_seed']}, parameters sha256 "
                         f"`{(e['cohort_parameters_sha256'] or '')[:16]}…`, result sha256 `{e['result_sha256']}`.")
    L += ['', '## Caveats', '',
          '- **Cohort size differs for Poisson 3D.** Its test cohort has 64 cases and its development cohort 16, so a '
          'worst-of-64 is compared with a worst-of-16. The medians and the "cases above development worst" column show '
          'how much of the gap is the tail. The L-shape cohorts both have 32 cases.',
          '- **The Poisson 3D test cohort is the paper\'s 32³/64³ test cohort.** It was never used to choose anything at '
          '128³/256³. However, the fast width $R\'=32$ of the 32³/64³ rows was read from its 32³/64³ records under the '
          '"< 5 %" wording (lab log, 2026-09-24).',
          '- **GPU type per row, test vs development** (only same-job ratios are compared, never milliseconds across '
          'jobs): ' + '; '.join(f"{name(r['problem'])} {mesh(r)} {r['test']['gpu']} vs {r['development']['gpu']}"
                                + ('' if r['test']['gpu'] == r['development']['gpu'] else ' (**differs**)')
                                for r in have) + '.',
          '- The L-shape fast arm (span $R\'=64$) is above the paper\'s "< 5 %" fast wording already on development ('
          + ', '.join(pct(r['development']['row']['arms']['fast']['worst_pct']) + ' %' for r in rows if r['problem'] == 'lshape')
          + '). The paper keeps it as a stated exception; this lane does not change it.',
          '', '## Glossary', '',
          '- **Development cohort**: the cases on which settings were chosen and which the paper\'s Table 1 currently '
          'reports.',
          '- **Test cohort**: held-out cases never used to train, select or develop anything. It is evaluated once, '
          'with settings frozen beforehand.',
          '- **Span $R\'$ / linear rung**: the query solves for coefficients of the first $R\'$ columns of the ordered '
          'bank by one least-squares solve (no neural head, no iterations). `R128_linear` is $R\'=128$.',
          '- **$R\'$, $q$ arms**: `R{R\'}_q{q}` uses the neural head plus $q$ correction directions on an $R\'$-column '
          'bank; `orig_q{q}` is the same model before rotation (parity reference).',
          '- **Accurate / fast**: the two NM-ROM settings of a Table-1 row.',
          '- **FOM**: the full-order model, matrix-free GPU conjugate gradients (CG) on the same mesh at a relative-residual '
          'tolerance. The row\'s FOM is the fastest tested tolerance whose worst error is no larger than the accurate '
          'arm\'s.',
          '- **Speedup (×)**: FOM median time ÷ arm median time, from the same job.',
          '- **Own FOM / own ×**: the fastest CG at least as accurate as that particular arm, and the speedup against it.',
          '- **Worst % / median %**: the largest and the median, over cases, of the same-grid relative $L^2$ error against '
          'the exact discrete solution (SuperLU on the L-shape, a sine transform on the cube).',
          '- **Bank floor($R\'$)**: the best error any coefficients of the first $R\'$ columns could reach (the projection '
          'error); no solver can go below it.',
          '- **GPU query / complete query**: device work only, or device work plus the host→device and device→host '
          'copies.',
          '- **Order gate**: a check that an arm is not slowed down when it runs right after a long CG solve '
          '(paired after-CG vs control timings; pooled ratio ≤ 1.10 and each arm ≤ 1.25).',
          '- **Parity**: the rotated full bank reproduces the unrotated model to $10^{-10}$.',
          '- **Audit**: an independent NumPy/SciPy recomputation of every error against its own truth. It also runs '
          'controls that must fail (a swapped case and a perturbed error).',
          '- **Stationary**: the Levenberg–Marquardt (LM) solve ended at a stationary point (head arms only).', '']
    OUT.write_text('\n'.join(L) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
