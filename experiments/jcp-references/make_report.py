def pct(x, nd=4):
    return '—' if x is None else f'{100 * x:.{nd}g} %'


def sci(x, nd=2):
    return '—' if x is None else f'{x:.{nd}e}'


def fx(x, nd=3):
    return '—' if x is None else f'{x:.{nd}f}'


def q(vals):
    v = [x for x in vals if x is not None]
    return (min(v), float(np.median(v)), max(v)) if v else (None, None, None)


def results_of(mode):
    out = {}
    for rd in sorted((HERE / 'runs').glob('*/output/result.json')):
        r = json.loads(rd.read_text())
        if r['config']['mode'] == mode and r.get('complete') and not r.get('SMOKE_OVERRIDE'):
            out[rd.parts[-3]] = r
    return out


