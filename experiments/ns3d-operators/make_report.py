"""Generate the lane report and the combined summary JSON from the panel outputs only.

Usage: make_report.py <report-date> <panel-job> [<panel-job> ...]
Reads runs/<job>/output/{summary.json,audit.json}; writes
reports/<date>-ns3d-operators.md and reports/summary.json. No number is typed by hand.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FAMILY = {'fno': 'FNO', 'unet': 'U-Net', 'transolver': 'Transolver', 'deeponet': 'DeepONet'}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def pct(x):
    return f'{100 * x:.3g}' if x >= 1e-3 else f'{100 * x:.2g}'


def sp(x):
    if x is None:
        return '—'
    s = f'{x:.3g}×'
    return f'*{s}*' if x < 1 else s


def main():
    date, jobs = sys.argv[1], sys.argv[2:]
    combined, lines = {}, []
    lines += [f'# NS 3D: NM-ROM against four neural operators (Table 2 row)', '',
              'Generated by `experiments/ns3d-operators/make_report.py` from the panel summary and audit JSONs; '
              'no number here is typed by hand. Each mesh is one allocation; its status (final, or provisional '
              'if any gate failed) is printed in its heading. All three meshes are final (every gate and the '
              'restricted audit pass). The 32³/64³ cells are **development comparisons**: the NM-ROM setting '
              '(head k=8) was selected by the shift-head lane on these same 16 cases, while every operator choice '
              'was made on a separate validation split. The 96³ cell uses the 32 held-out cases (seed 202609221), '
              'on which no choice was made by either side; its operators were trained partly on H200 and partly '
              'on A100-80G (DESIGN A4), so their 3000 s budgets bought unequal work.', '']
    for job in jobs:
        out = HERE / 'runs' / job / 'output'
        s = json.loads((out / 'summary.json').read_text())
        a = json.loads((out / 'audit.json').read_text())
        n = s['config']['n']
        res, tim = s['results'], s['timing']['arms']
        fom = s['fom_rule']['chosen']
        combined[f'n{n}'] = dict(job=job, job_id=s['job_id'], gpu=s['gpu'], status=s['status'],
                                 summary_sha256=sha(out / 'summary.json'), audit_sha256=sha(out / 'audit.json'),
                                 source_commit=s['source_commit'], cohort=dict(seed=s['config']['eval_seed'],
                                                                                 cases=s['config']['eval_cases']),
                                 fom=dict(arm=fom, steps=res[fom]['steps'],
                                          evolved_worst=res[fom]['stats']['evolved_worst'],
                                          median_ms=tim[fom]['median_ms']),
                                 gates=s['gates'], audit_passed=a['all_passed'], rows={})
        lines += [f'## ${n}^3$ — job {s["job_id"]}, {s["gpu"].split(",")[0]}, status: **{s["status"]}**', '',
                  f'Cohort: seed {s["config"]["eval_seed"]}, {s["config"]["eval_cases"]} cases '
                  f'({"held-out, no choice made on it" if s["config"]["eval_seed"] == 202609221 else "development"}). '
                  f'Comparator (the Table-2 rule): CNAB2 with {res[fom]["steps"]} steps, evolved worst '
                  f'{pct(res[fom]["stats"]["evolved_worst"])} %, {tim[fom]["median_ms"]:.3f} ms. '
                  f'Every speedup below is that time divided by the row\'s time, same job.', '',
                  '| Method | Setting | Params | Worst (%) | Median (%) | GPU ms | Speedup | Training |',
                  '|---|---|---:|---:|---:|---:|---:|---|']

        def row(name, label, setting, params='—', training='—'):
            r = res[name]
            st = r['stats']
            combined[f'n{n}']['rows'][name] = dict(label=label, setting=setting, evolved_worst=st['evolved_worst'],
                                                   evolved_median=st['evolved_median'],
                                                   median_ms=tim[name]['median_ms'],
                                                   speedup=r.get('speedup_vs_fom'))
            lines.append(f'| {label} | {setting} | {params} | {pct(st["evolved_worst"])} | {pct(st["evolved_median"])} '
                         f'| {tim[name]["median_ms"]:.3f} | {sp(r.get("speedup_vs_fom"))} | {training} |')
        row('nmrom_accurate_head_k8', 'NM-ROM accurate', 'head k=8')
        row('nmrom_fast_span16', 'NM-ROM fast', "span R'=16")
        ops = s['operators']
        for fam in ('fno', 'unet', 'transolver', 'deeponet'):
            sel = [nm for nm, m in ops.items() if m['family'] == fam and m['selected']]
            if not sel:
                lines.append(f'| {FAMILY[fam]} | not trained | | | | | | |')
                continue
            nm = sel[0]
            m, tr = ops[nm], ops[nm]['training']
            prov = json.loads((HERE / 'runs' / f"tr{n}_{m['arm']}" / 'output' / 'provenance.json').read_text())
            gpu = prov['environment']['gpu'].replace('NVIDIA ', '')
            row(nm, FAMILY[fam], m['arm'], f"{m['real_parameter_count']:,}",
                f"{tr['epochs_completed']} ep ({tr['optimisation_steps']} steps), best ep {tr['best_epoch']}, "
                f"{tr['stop_reason']}, {gpu}")
        row(fom, 'FOM (CNAB2)', f"{res[fom]['steps']} steps")
        faster = [nm for nm, r in res.items() if r['kind'] == 'cnab2' and nm in tim
                  and tim[nm]['median_ms'] < tim[fom]['median_ms'] and not r['unstable']]
        if faster:
            nxt = max(faster, key=lambda nm: tim[nm]['median_ms'])
            accw = res['nmrom_accurate_head_k8']['stats']['evolved_worst']
            lines += ['', f'Next faster stable CNAB2 setting (not eligible under the rule): {res[nxt]["steps"]} steps, '
                      f'{pct(res[nxt]["stats"]["evolved_worst"])} % ({res[nxt]["stats"]["evolved_worst"] / accw:.3f}× the '
                      f'NM-ROM accurate error), {tim[nxt]["median_ms"]:.3f} ms; against it the NM-ROM accurate setting '
                      f'would be {tim[nxt]["median_ms"] / tim["nmrom_accurate_head_k8"]["median_ms"]:.3g}×.']
        lines += ['', f'Gates: ' + ', '.join(f'{k} {"pass" if v else "FAIL"}' for k, v in s['gates'].items()
                                             if k != 'gated_arms') +
                  f'; independent restricted audit {"pass" if a["all_passed"] else "FAIL"} '
                  f'(perturbed control rejected: {a["perturbed_control_rejected"]}; sampled-estimate max gap '
                  f'{max(x["sampled_max_relative_gap"] for x in a["arms"].values()):.3f}).', '',
                  f'<details><summary>All arms of this job ({len(tim)})</summary>', '',
                  '| Arm | Worst (%) | Median (%) | GPU ms | vs rule FOM | vs matched CNAB2 | drift | order |',
                  '|---|---:|---:|---:|---:|---:|---:|---:|']
        for nm, r in sorted(res.items()):
            if nm not in tim:
                lines.append(f'| {nm} | not finite | | | | | | |')
                continue
            t = tim[nm]
            lines.append(f'| {nm} | {pct(r["stats"]["evolved_worst"])} | {pct(r["stats"]["evolved_median"])} | '
                         f'{t["median_ms"]:.3f} | {sp(r.get("speedup_vs_fom"))} | '
                         f'{sp(r.get("speedup_vs_matched_cnab2"))} ({r.get("matched_cnab2", "—")}) | '
                         f'{t["drift_ratio"]:.3f} | {t["order_ratio"]:.3f} |')
        lines += ['', '</details>', '']
        combined[f'n{n}']['all_operator_arms'] = {nm: dict(m, evolved_worst=res[nm]['stats']['evolved_worst']
                                                           if res[nm]['finite'] else None,
                                                           median_ms=tim.get(nm, {}).get('median_ms'))
                                                  for nm, m in ops.items()}
    lines += ['## Data parity', '',
              'Both sides draw from training seed 202609201, the same 512 trajectories. The operators train on '
              'the 448 whose index is not 7 mod 8 and choose checkpoint and size on the other 64. The head was '
              'fitted on the states (21 frames) of the same 448 and held out the same 64; the bank is the POD '
              'of the first 128 of the 512 (six frames each). An operator sees one input/output pair per '
              'trajectory (initial field and viscosity to five evolved fields). The bank\'s 128 trajectories include '
              '16 that lie in the operators\' validation split, so the trajectories are the same but the exposure '
              'is not identical, and the NM-ROM has no split that is held out from all of its components.', '',
              '## Caveats that travel with these rows', '',
              '- Development comparisons at 32³/64³: the NM-ROM setting was chosen on the evaluation cases.',
              '- 96³: operator training split across GPU types (A4); the panel needed two reruns for memory '
              '(pn96 OOM in PyTorch warm-up, pn96b OOM from held timed outputs; A6, A7), with identical '
              'accuracy passes; only pn96c is reported.',
              '- At 32³ the next faster CNAB2 setting misses the rule by 0.4 % of the NM-ROM error (see the '
              'mesh section); against it the accurate setting would be slower than the full-order solver.',
              '- Timed-output parity in pn32/pn64 compares the error of each timed output with the accuracy '
              'pass (error-metric parity), not the fields themselves (DESIGN A3).',
              '- The audit is restricted: exact recomputation on cases {0, 1, worst} per arm, and 8192-point '
              'sampled estimates elsewhere, which are diagnostic only (they scatter by tens of percent for '
              'localised errors); the truth solver is not re-solved.',
              '- Operators are budget-limited, not converged: 3000 s bought 80 to 760 epochs depending on '
              'family and mesh (Training column).', '',
              '## Glossary', '',
              '- **NM-ROM accurate / fast**: the paper\'s two settings of one frozen model — the $k=8$ head '
              '(accurate) and the span of the first 16 importance-ordered bank functions (fast), both solved in '
              'a co-moving frame with 10 implicit-midpoint steps.',
              '- **FNO, U-Net, Transolver, DeepONet**: neural operators trained here to map the initial velocity '
              'and viscosity to the five later fields in one pass; "Setting" is the size chosen on validation.',
              '- **Worst / Median (%)**: over the cases, of each case\'s largest relative $L^2$ error over the five '
              'evolved output times, relative to the norm of the initial field, on the evaluation grid.',
              '- **GPU ms**: median wall time of one query (initial field on the GPU to six fields on the GPU), '
              'synchronised, over all 9 repetitions of every case.',
              '- **Speedup**: the comparator CNAB2 time divided by the row\'s time in the same job; *italic* '
              'means slower than the comparator.',
              '- **Comparator / rule FOM**: the fastest tested CNAB2 step count whose worst error is no larger '
              'than the NM-ROM accurate setting\'s. **Matched CNAB2**: the fastest one at least as accurate as '
              'that row (context only).',
              '- **CNAB2**: the pseudo-spectral full-order solver (Crank–Nicolson viscous, Adams–Bashforth 2 '
              'advection, 2/3 dealiasing) that also produced the truth at $\\Delta t=0.001$.',
              '- **Training**: epochs evaluated (the last one may be partial) with optimisation steps, the '
              '0-based epoch of the kept checkpoint, and why training stopped (wall_budget = the 3000 s budget ran '
              'out; patience = 250 epochs without a validation improvement).',
              '- **drift / order**: timing gates — median of the last interleaved block over the first, and of '
              'the arm-major block over the interleaved ones; each must be within 1/1.10–1.10.',
              '- **Development comparison**: evaluated on the cases the NM-ROM setting was chosen on.',
              '- **Restricted audit**: an independent NumPy recomputation exact on the saved cases and sampled '
              'elsewhere; the truth solver itself is not re-solved.']
    rep = HERE / 'reports'
    rep.mkdir(exist_ok=True)
    (rep / f'{date}-ns3d-operators.md').write_text('\n'.join(lines) + '\n')
    (rep / 'summary.json').write_text(json.dumps(combined, indent=1) + '\n')
    print(rep / f'{date}-ns3d-operators.md', sha(rep / 'summary.json'))


if __name__ == '__main__':
    main()
