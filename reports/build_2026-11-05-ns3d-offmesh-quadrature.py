GLOSSARY = """## Glossary

- **Advection term.** The nonlinear part of the Navier–Stokes equations, here in rotational form $u\\times\\omega$ with vorticity $\\omega=\\nabla\\times u$.
- **Exact tensor (tensor ROM).** The incumbent: the three-index array $T_{mjk}$ ($292\\times64\\times64$) that gives the tested advection of any bank combination exactly, precomputed on the mesh.
- **Off-mesh quadrature.** Approximating the tested advection integral by a weighted sum over $M$ points $x_q$ that need not be mesh nodes.
- **$M$.** Number of quadrature points. **$M_t$** = 292 is the number of test fields; **$R$** = 64 the bank rank.
- **Rule families.** `lat`: rank-1 lattice with a CBC-searched generating vector; `kor`: Korobov lattice (prime size); `sob`: scrambled Sobol points with equal weights; `gl`: tensor Gauss–Legendre $p^3$; `trap`: tensor periodic trapezoid $p^3$ with a random shift. All have weights summing to one.
- **`net` integrand.** Bank columns and their curls evaluated from the coordinate network itself at the points (mesh-free).
- **`interp` integrand.** Bank columns evaluated from the exact trigonometric interpolant of the mesh bank; its infinite-$M$ limit is exactly the tensor.
- **Continuum target.** The `net` integral with a very fine shifted trapezoid rule ($128^3$ points), checked against $96^3$.
- **$\\rho_a$, $\\rho_J$.** Relative error of the quadrature advection (and of its Jacobian) against the tensor, over the 320 reached states (mid-step coefficients of the tensor head and span64 rollouts).
- **head / span64.** The two reduced models: the frozen k=8 nonlinear head over the bank (primary), and the full linear R=64 span (secondary).
- **Evolved worst / median.** For each of the 16 cases take the largest relative error over the five output times after $t=0$; then the worst case, or the median case.
- **$\\delta_T$.** Largest difference between the quadrature ROM fields and the tensor ROM fields, relative to $\\lVert u_0\\rVert$.
- **$M^\\ast$, $M^\\ast_\\delta$.** Plateau sizes defined in §4.
- **CNAB2.** The full-order solver: Crank–Nicolson for diffusion, second-order Adams–Bashforth for advection, pseudo-spectral on the same mesh; "$N$ steps" is the number of steps over the horizon 0.2.
- **Reference.** CNAB2 with 200 steps ($\\Delta t=10^{-3}$) on the same mesh; it is why "CNAB2 200 steps" reads ≈0.
- **G1–G5.** Pre-registered gates (DESIGN §6): reproduction, positive control, must-fail control, off-grid derivatives, timing.
- **Kernel time.** A jitted loop of 30 Jacobian contractions (one query's Gauss–Newton sweeps), isolating the advection cost from the grid-bound parts of a query.
- **Speedup.** Median time of the fastest stable CNAB2 setting at least as accurate as the arm, divided by the arm's median time, both in the same timing block.
"""


