"""Generate reports/2026-09-2x-burgers3d-span.md and reports/summary.json from the collected, audited records.

Every number in the report comes from the JSON files listed in `SOURCES` (validation selections, held-out selections,
audits, training record); nothing is typed by hand. Usage: python report.py --stamp 2026-09-24
"""
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MESHES = (33, 65, 129)


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def pct(x, d=2):
    return '—' if x is None else f'{100 * x:.{d}f}'


def ms(x):
    return '—' if x is None else f'{x:.2f}'


def sx(x):
    return '—' if x is None else f'{x:.2f}×'


def load(p):
    p = HERE / p
    return json.loads(p.read_text()) if p.exists() else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--stamp', required=True)
    ap.add_argument('--model', default='R512')
    ap.add_argument('--status', default='final')
    a = ap.parse_args()
    src = {}
    tr = load(f'checks/training-{a.model}.json')
    val = {n: load(f'checks/select-A3-n{n}.json') for n in MESHES}
    hist = {t: {n: load(f'checks/select-{t}-n{n}.json') for n in MESHES} for t in ('v1', 'A2', 'A3')}
    ho = {n: load(f'checks/select-heldout-n{n}.json') for n in MESHES}
    aud = {n: load(f'checks/audit-A3-n{n}.json') for n in MESHES}
    auh = {n: load(f'checks/audit-heldout-n{n}.json') for n in MESHES}
    for k, v in [('training', f'checks/training-{a.model}.json')] + \
            [(f'select-{t}-n{n}', f'checks/select-{t}-n{n}.json') for t in ('v1', 'A2', 'A3') for n in MESHES] + \
            [(f'audit-{t}-n{n}', f'checks/audit-{t}-n{n}.json') for t in ('v1',) for n in MESHES] + \
            [(f'select-heldout-n{n}', f'checks/select-heldout-n{n}.json') for n in MESHES] + \
            [(f'audit-A3-n{n}', f'checks/audit-A3-n{n}.json') for n in MESHES] + \
            [(f'audit-heldout-n{n}', f'checks/audit-heldout-n{n}.json') for n in MESHES]:
        if (HERE / v).exists():
            src[k] = dict(path=f'experiments/burgers3d-span/{v}', sha256=sha(HERE / v))
    L = []
    L.append('# Burgers 3D with the ordered bank span: accuracy and speed against Newton–BiCGStab at 32³–128³')
    L.append('')
    L.append(f'Lane `exp/2026-09-23-burgers3d-span`. Status of the numbers: **{a.status}**. Generated by '
             '`experiments/burgers3d-span/report.py` from the JSON records listed at the end; nothing is typed by hand. '
             'Protocol: `experiments/burgers3d-span/DESIGN.md` (pre-registered, revision R1 before any job, amendments '
             'dated there).')
    L.append('')
    # headline
    L.append('## Headline rows (one frozen model per mesh series; Table-1 format)')
    L.append('')
    L.append('Error = worst over cases of the largest relative $L^2$ error at the five evolved output times, normalised '
             'by the initial field. Speedup = the FOM\'s median GPU time divided by the setting\'s, same allocation; '
             'the FOM is the fastest tested Newton–BiCGStab setting at least as accurate as the *accurate* setting '
             '(paper rule; both speedups of a row divide that one time). "own" = against the fastest FOM at least as '
             'accurate as that setting itself.')
    L.append('')
    L.append('| cohort | mesh | accurate setting | err % | ms | speedup (own) | fast setting | err % | ms | speedup (own) | FOM | FOM err % | FOM ms | timing gates |')
    L.append('|---|---|---|---:|---:|---:|---|---:|---:|---:|---|---:|---:|---|')
    for label, S in (('held-out (sealed 923401, 32)', ho), ('validation (923101, 16)', val)):
        for n in MESHES:
            s = S.get(n)
            if not s:
                L.append(f'| {label} | {n - 1}³ | not run | | | | | | | | | | | |')
                continue
            ar, fr, fo = s.get('accurate_row'), s.get('fast_row'), s.get('fom_row')
            L.append(f"| {label} | {n - 1}³ | `{s['accurate']}` | {pct(ar and ar['worst_evolved'])} | {ms(ar and ar['median_ms'])} | "
                     f"{sx(ar and ar['speedup_rule'])} ({sx(ar and ar['speedup_own'])}) | `{s['fast']}` | "
                     f"{pct(fr and fr['worst_evolved'])} | {ms(fr and fr['median_ms'])} | {sx(fr and fr['speedup_rule'])} "
                     f"({sx(fr and fr['speedup_own'])}) | `{s['fom']}` | {pct(fo and fo['worst_evolved'], 3)} | "
                     f"{ms(fo and fo['median_ms'])} | {'pass' if s['timing_gates']['passed'] else 'FAIL (provisional)'} |")
    L.append('')
    for n in MESHES:
        s = ho.get(n)
        if s and s.get('frozen_validation_fom'):
            fr = s.get('frozen_fom_row') or {}
            L.append(f"- {n - 1}³ held-out, FOM frozen on validation `{s['frozen_validation_fom']}`: "
                     f"{pct(fr.get('worst_evolved'), 3)} % at {ms(fr.get('median_ms'))} ms.")
    L.append('')
    # selection history
    L.append('## Selection history on the validation cohort (every panel kept; amendments A2/A3 were written after seeing the earlier panels)')
    L.append('')
    L.append('| panel | mesh | accurate | err % | ms | fast | err % | ms | fast speedup own | stopping rule at 64³ |')
    L.append('|---|---|---|---:|---:|---|---:|---:|---:|---|')
    for t in ('v1', 'A2', 'A3'):
        for n in MESHES:
            s = hist[t].get(n)
            if not s:
                L.append(f'| {t} | {n - 1}³ | not completed | | | | | | | |')
                continue
            ar, fr = s.get('accurate_row') or {}, s.get('fast_row') or {}
            L.append(f"| {t} | {n - 1}³ | `{s['accurate']}` | {pct(ar.get('worst_evolved'))} | {ms(ar.get('median_ms'))} | "
                     f"`{s['fast']}` | {pct(fr.get('worst_evolved'))} | {ms(fr.get('median_ms'))} | {sx(fr.get('speedup_own'))} | "
                     f"{('pass' if s['stopping_rule_pass'] else 'fail') if n == 65 else ''} |")
    L.append('')
    # stopping rule
    L.append('## Stopping rule (DESIGN §10 with R1: own-matched FOM, 64³, validation)')
    L.append('')
    v65 = val.get(65)
    if v65:
        L.append(f"Candidates within 5 % and faster than their own matched FOM at 64³: "
                 f"{', '.join('`' + c + '`' for c in v65['stopping_rule_candidates']) or 'none'}; timing gates "
                 f"{'passed' if v65['timing_gates']['passed'] else 'FAILED'} → stopping rule "
                 f"{'PASSED (held-out opened)' if v65['stopping_rule_pass'] else 'NOT passed'}.")
    L.append('')
    # per mesh arm tables
    for n in MESHES:
        s = val.get(n)
        if not s:
            continue
        L.append(f'## Validation panel {n - 1}³ (job {s["job_id"]}, certificates job {s["cert_job_id"]}, {s["gpu"]})')
        L.append('')
        L.append('| arm | eligible | cert ρ_max | min decoded | worst evolved % | GPU ms | LM its/query | speedup rule | speedup own | own FOM | why not eligible |')
        L.append('|---|---|---:|---:|---:|---:|---:|---:|---:|---|---|')
        for k, r in sorted(s['arms'].items(), key=lambda kv: kv[1]['worst_evolved']):
            L.append(f"| `{k}` | {'yes' if r['eligible'] else 'no'} | {'—' if r['rho_max'] is None else f'{r['rho_max']:.3g}'} | "
                     f"{'—' if r['min_decoded'] is None else f'{r['min_decoded']:.3g}'} | {pct(r['worst_evolved'], 3)} | "
                     f"{ms(r['median_ms'])} | {r['iterations_per_query']:.0f} | {sx(r['speedup_rule'])} | {sx(r['speedup_own'])} | "
                     f"`{r['own_fom']}` | {'; '.join(r['why_not'])} |")
        L.append('')
        L.append('| FOM setting | worst evolved % | GPU ms | hit Newton cap |')
        L.append('|---|---:|---:|---|')
        for k, r in sorted(s['foms'].items(), key=lambda kv: kv[1]['median_ms']):
            L.append(f"| `{k}` | {pct(r['worst_evolved'], 3)} | {ms(r['median_ms'])} | {'yes' if r['capped'] else 'no'} |")
        L.append('')
        g = s['other_gates']
        L.append('Gates: ' + ', '.join(f'{k} = {v:.3g}' if isinstance(v, float) else f'{k} = {v}' for k, v in g.items()) +
                 f"; timing drift {s['timing_gates']['drift']:.3f}, neighbour ROM {s['timing_gates']['neighbour']:.3f}, "
                 f"neighbour FOM {s['timing_gates']['neighbour_fom']:.3f}; bad-rule control not confirmed: "
                 f"{s['bad_control_not_confirmed']}.")
        au = aud.get(n)
        if au:
            L.append('')
            L.append(f"Independent NumPy audit: **{'PASS' if au['passed'] else 'FAIL'}** — " +
                     ', '.join(f"{k}: {v.get('passed') if isinstance(v, dict) else v}" for k, v in au['checks'].items()) + '.')
        L.append('')
    if tr:
        L.append('## The model')
        L.append('')
        b = tr['bank']
        L.append(f"R = {tr['config']['bank_rank']} coordinate bank, selected step {b['selected_step']}, worst bank-validation "
                 f"projection {pct(b['validation_worst_over_groups'], 3)} % (over the three point groups), condition on the "
                 f"65-node grid {b.get('condition_65', float('nan')):.3g}, training {b['seconds'] / 60:.1f} min.")
        L.append('')
        L.append('| mesh | ' + ' | '.join(f"R'={r}" for r in tr['config']['ladder']) + ' | old b3d004 bank (R=256) |')
        L.append('|---|' + '---:|' * (len(tr['config']['ladder']) + 1))
        for n in MESHES:
            f = tr['floors_full'][str(n)]
            old = tr.get('old_bank_floor_full', {}).get(str(n), {})
            L.append(f'| {n - 1}³ | ' + ' | '.join(pct(f[str(r)]['worst'], 3) for r in tr['config']['ladder']) +
                     f" | {pct(old.get('worst'), 3)} |")
        L.append('')
        L.append('Worst full-grid projection error (%) of the 48 bank-validation trajectories (six output times) onto the '
                 'first R\' ordered columns — the floor no span solve can beat.')
        L.append('')
        for k, h in tr.get('heads', {}).items():
            L.append(f"- Head K = {k}: selected step {h['selected_step']}, worst best-found bank-validation error "
                     f"{pct(h['validation_best_found_worst'], 3)} %, worst training error {pct(h['training_error_worst'], 3)} %.")
        L.append('')
    L.append('## Source records')
    L.append('')
    for k, v in src.items():
        L.append(f"- {k}: `{v['path']}` sha256 `{v['sha256']}`")
    L.append('')
    L.append('## Glossary')
    L.append('')
    for t, d in [
        ('accurate / fast setting', 'the most accurate eligible setting / the cheapest eligible setting with worst evolved error ≤ 5 %, chosen on the validation cohort by the pre-registered rule and frozen before the held-out cohort was opened.'),
        ('span_R{R\'}_{rule}', 'a query that solves for the R\' coefficients of the first R\' ordered bank functions.'),
        ('head{K}_R{R\'}_{rule}', 'a query that solves for K latent coordinates of the trained head, decoded through the first R\' ordered bank functions.'),
        ('rule tensor', 'the advection term as a precomputed quadratic form of the coefficients (the backward-difference stencil, which equals the FOM\'s sign-upwind stencil wherever the state is positive); admitted only if certified.'),
        ('rule lat16', 'empirical quadrature: the FOM\'s sign-upwind advection evaluated only on the 15³ lattice x = k/16 with equal weights.'),
        ('exact', 'control arm: the FOM\'s sign-upwind advection on every node (no approximation), untimed, never eligible; shows what the rule changes.'),
        ('_g1e-06', 'the same arm with the Levenberg–Marquardt stopping tolerance 1e-6 instead of 1e-3.'),
        ('cert ρ_max', 'the largest relative error of the rule\'s tested advection against the exact one over every state the deployed solver reached on the certification populations (5 draws of 8 + a confirmation draw of 16 trajectories); certified iff ≤ 0.116 on every draw.'),
        ('min decoded', 'the smallest value of any decoded state on the certification populations (negative values are where the tensor rule departs from the FOM stencil).'),
        ('worst evolved %', 'over cases, the largest ‖u(t) − u_ref(t)‖ / ‖u_ref(0)‖ at t = 0.05 … 0.25; u_ref = same-mesh Newton–BiCGStab with tolerances 1e-10 / 1e-11.'),
        ('GPU ms', 'median over all timed repetitions (two ROM phases, three repetitions per case each) of the query from a dense initial field on the GPU to six dense output fields on the GPU, compilation excluded.'),
        ('FOM `fom_dt…_nt…_lt…`', 'Newton–BiCGStab full-order solver with time step dt, Newton tolerance nt (relative to the previous state\'s norm) and BiCGStab tolerance lt, exact Helmholtz preconditioner in the sine basis.'),
        ('speedup rule / own', 'FOM ms / setting ms against the fastest FOM at least as accurate as the accurate setting / as the setting itself.'),
        ('timing gates', 'drift (median of the second ROM phase over the first within 1.10) and neighbour (invocations following a much longer one no more than 10 % slower), for ROM and FOM invocations; a failing mesh is labelled provisional.'),
        ('eligible', 'certified rule, finite outputs, no failed LM exits, non-stationary exits on at most 1 % of steps.'),
        ('validation / held-out', 'the 16 cases used to choose settings / the 32 sealed cases opened once with the frozen settings.'),
        ('bank floor', 'the projection error onto the span of the bank functions, a lower bound for any span solve.'),
    ]:
        L.append(f'- **{t}**: {d}')
    out = HERE / 'reports' / f'{a.stamp}-burgers3d-span-accuracy-speed.md'
    out.write_text('\n'.join(L) + '\n')
    summary = dict(status=a.status, sources=src, validation=val, heldout=ho,
                   audits={str(n): (aud[n] or {}).get('passed') for n in MESHES},
                   audits_heldout={str(n): (auh[n] or {}).get('passed') for n in MESHES})
    (HERE / 'reports' / 'summary.json').write_text(json.dumps(summary, indent=1) + '\n')
    print(out)


if __name__ == '__main__':
    main()
