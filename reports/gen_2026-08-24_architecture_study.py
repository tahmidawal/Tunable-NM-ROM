"""Generate the data blocks for
reports/2026-08-24-separable-decoder-architecture-and-results.md

Reads ONLY committed run JSONs, across the four scaling-arm worktrees and the
N=256 push worktree. Project rule: never hand-type a number into a report --
run this and paste its output into the GENERATED blocks, or diff to check drift.

    /home/tahmid/Dev/.venv/bin/python reports/gen_2026-08-24_architecture_study.py

NOTE: every worktree carries the inherited N=64 `sepdec_r1/` archive, so any
glob over runs/*/out/ can silently match the WRONG mesh. load_at() asserts the
file's own config N, which is the guard against that.
"""
import glob
import json
import os
import statistics

WT = "/home/tahmid/Dev/pod-ae-nmrom/Tunable-NM-ROM-Claude/worktrees"
PUSH = f"{WT}/2026-08-23-n256-push/experiments/separable-decoder"
ARM = {n: f"{WT}/2026-08-23-sepdec-n{n}/experiments/separable-decoder"
       for n in (128, 256, 512, 1024)}
R1 = f"{WT}/2026-08-22-separable-decoder/experiments/separable-decoder"


def g(d, *keys, default=float("nan")):
    for k in keys:
        if isinstance(d, dict) and d.get(k) is not None:
            return d[k]
    return default


def load_at(pats, N, k=None):
    """First file matching a pattern whose OWN config says N (and k)."""
    for pat in pats:
        for p in sorted(glob.glob(pat)):
            c = json.load(open(p)).get("config", {})
            if int(g(c, "N", default=-1)) != int(N):
                continue
            if k is not None and int(g(c, "k", default=-1)) != int(k):
                continue
            return p, json.load(open(p))
    return None, None


def rows(d):
    return [r for r in d.get("rows", []) if isinstance(r, dict)]


def rel(p):
    return os.path.relpath(p, WT)


print("<!-- GENERATED by reports/gen_2026-08-24_architecture_study.py -- do not hand-edit -->")

# ------------------------------------------------ T1 Poisson scaling
print("\n### T1. Poisson: N-independent ROM cost vs the classical ladder\n")
print("ROM = cached separable arm, K=16, tau=1e-3, held-out cohort. "
      "Baselines are from the SAME job/GPU.\n")
print("| N | ROM ms | ROM err | cheapest CG | cheapest CG at least as accurate | ROM speed-up vs that | other solver in job |")
print("|---|---|---|---|---|---|---|")
SRC_P = [
    (64, [f"{R1}/runs/sepdec_r1/out/sep_poisson_K16_R64.json"]),
    (128, [f"{ARM[128]}/runs/*/out/sep_poisson_K16_*.json"]),
    (256, [f"{ARM[256]}/runs/n256_j4/out/sep_poisson_K16_R64_s200k.json",
           f"{ARM[256]}/runs/*/out/sep_poisson_K16_*.json"]),
    (512, [f"{ARM[512]}/runs/*/out/sep_poisson_K16_*.json"]),
    (1024, [f"{ARM[1024]}/runs/*/out/sep_poisson_N1024_K16_*.json"]),
]
for N, pats in SRC_P:
    p, d = load_at(pats, N, k=16)
    if d is None:
        print(f"| {N} | NOT FOUND | | | | | |")
        continue
    sep = [r for r in rows(d)
           if ("cach" in str(g(r, "method", "arm", default="")))
           and float(g(r, "tau", default=-1)) == 1e-3
           and "fresh" not in str(g(r, "cohort", default="held"))]
    fom = list(d.get("fom", []))
    if not fom:   # some arms store the CG ladder inside rows[] instead
        fom = [r for r in rows(d) if "cg" in str(g(r, "method", default="")).lower()]
    fom = [r for r in fom if "fresh" not in str(g(r, "cohort", default="held"))]
    if not sep or not fom:
        print(f"| {N} | schema miss ({os.path.basename(p)}) | | | | | |")
        continue
    s = sep[0]
    st, se = g(s, "time_ms", "time_ms_median"), g(s, "err_rel_l2", "err_mean")

    def ft(r):
        return g(r, "time_ms", "time_ms_median", default=1e9)

    def fe(r):
        return g(r, "err_rel_l2", "err_rel_l2_mean", default=1e9)

    def kind(r):
        return str(g(r, "fom", "method", default="cg")).lower()
    cg = [r for r in fom if "cg" in kind(r)]
    oth = [r for r in fom if "cg" not in kind(r)]
    cheap = min(cg, key=ft) if cg else None
    iso = [r for r in cg if fe(r) <= se]
    isob = min(iso, key=ft) if iso else None
    cs = f"{ft(cheap):.2f} ms @ {fe(cheap):.1e}" if cheap else "--"
    iss = f"{ft(isob):.2f} ms @ {fe(isob):.1e}" if isob else "none"
    rt = f"**{ft(isob)/st:.2f}x**" if isob else "--"
    os_ = "; ".join(f"{g(r,'fom',default='?')} {ft(r):.2f} ms @ {fe(r):.1e}" for r in oth) or "--"
    print(f"| {N} | {st:.2f} | {se:.3e} | {cs} | {iss} | {rt} | {os_} |")
    print(f"|   | | | | | | <sub>{rel(p)}</sub> |")

# ------------------------------------------------ T2 Burgers scaling
print("\n### T2. Burgers: end-to-end ROM vs the strong classical baseline\n")
print("ROM e2e = IC latent fit + 50 implicit steps + full-grid decode, one job, one GPU.\n")
print("| N | ROM e2e ms | ROM err | cheapest Newton at least as accurate | truth-gen (over-solved) | verdict |")
print("|---|---|---|---|---|---|")
SRC_B = [
    (128, [f"{ARM[128]}/runs/*/out/sep_burgers_K16_*.json"]),
    (256, [f"{ARM[256]}/runs/*/out/sep_burgers_K16_*.json"]),
    (512, [f"{ARM[512]}/runs/*/out/sep_burgers_K16_*.json"]),
    (1024, [f"{ARM[1024]}/runs/*/out/sep_burgers_N1024_K16_*.json"]),
]
for N, pats in SRC_B:
    p, d = load_at(pats, N, k=16)
    if d is None:
        print(f"| {N} | NOT FOUND | | | | |")
        continue
    rr = rows(d)
    sep = [r for r in rr if "cach" in str(g(r, "method", "arm", default=""))]
    if not sep:
        print(f"| {N} | schema miss | | | | |")
        continue
    s = min(sep, key=lambda r: g(r, "e2e_ms_median", "rollout_only_ms_median",
                                 "time_ms_median", default=1e9))
    st = g(s, "e2e_ms_median", "rollout_only_ms_median", "time_ms_median")
    summ0 = (d.get("timing") or {}).get("summary") or {}
    if st != st and "rom_cached_e2e" in summ0:
        st = summ0["rom_cached_e2e"]["median_ms"]
    se = g(s, "err_traj_rel_mean")
    # baseline rows live in rows[] (n128/n256) OR under top-level keys
    # fom_newton_tol + timing.summary (n512) OR fom_tolnewton (n1024).
    nt = [r for r in rr if "newton_tol" in str(g(r, "method", default=""))]
    tg = [r for r in rr if "truthgen" in str(g(r, "method", default=""))
          or "fixed8" in str(g(r, "method", default=""))]
    if not nt:
        alt = d.get("fom_tolnewton") or d.get("fom_newton_tol") or []
        summ = (d.get("timing") or {}).get("summary") or {}
        for r in alt:
            r = dict(r)
            if "time_ms_median" not in r:      # n512: times live in timing.summary
                key = next((k for k in summ if k.startswith("fom_newton")
                            and f"{g(r,'ntol',default=-1):g}" in k), None)
                if key:
                    r["time_ms_median"] = summ[key]["median_ms"]
            if "time_ms_median" in r:
                r["method"] = "fom_newton_tol"
                nt.append(r)
        if not tg and isinstance(d.get("fom_truth"), dict):
            tg = [{"method": "fom_truth", "time_ms_median": d["fom_truth"]["time_ms_median"]}]
        if not tg and "fom_truth_newton8" in summ:
            tg = [{"method": "fom_truth", "time_ms_median": summ["fom_truth_newton8"]["median_ms"]}]

    def nft(r):
        return g(r, "e2e_ms_median", "time_ms_median", default=1e9)

    iso = [r for r in nt if g(r, "err_traj_rel_mean", default=1e9) <= se]
    if iso:
        b = min(iso, key=nft)
        bs = f"{nft(b):.1f} ms @ {g(b,'err_traj_rel_mean'):.1e}"
        verdict = f"classical wins ({st/nft(b):.1f}x slower)" if nft(b) < st else f"**ROM wins {nft(b)/st:.1f}x**"
    else:
        bs = "none in job" if nt else "no strong baseline in job"
        verdict = "incomparable"
    tgs = f"{nft(tg[0]):.0f} ms" if tg else "--"
    print(f"| {N} | {st:.1f} | {se:.3e} | {bs} | {tgs} | {verdict} |")
    print(f"|   | | | | | <sub>{rel(p)}</sub> |")

