HAVE = {(e['problem'], e['intervals']) for e in M}
HAVE_ANY = {(v['e']['problem'], v['e']['intervals']) for v in V}
MISSING = sorted(PLANNED - HAVE_ANY)
M.sort(key=lambda e: (e['problem'] != 'lshape', e['intervals'], e['cohort']))
