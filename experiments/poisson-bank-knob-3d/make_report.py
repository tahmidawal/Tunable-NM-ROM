from __future__ import annotations

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
S = json.loads((HERE / 'reports' / 'summary.json').read_text())
SHA = hashlib.sha256((HERE / 'reports' / 'summary.json').read_bytes()).hexdigest()


def f(x, d=3):
    if x is None:
        return '—'
    return f'{x:.{d}f}' if abs(x) >= 0.01 else f'{x:.2e}'


def sp(x):
    if x is None:
        return '—'
    s = f'{x:.3g}×'
    return f'**{s}**' if x > 1 else s


def label(name):
    if name.startswith('orig_q'):
        return f"$R'=R$, $q={name[6:]}$ (parent)"
    if name.startswith('engine_q'):
        return f"$R'=R$, $q={name[8:]}$ (parent engine)"
    rp, rest = name[1:].split('_')
    if rest == 'linear':
        return f"$R'={rp}$, linear rung ($q=R'$)"
    return f"$R'={rp}$, $q={rest[1:]}$"


def unit(e):
    return f"${e['intervals']}^2$" if e['problem'] == 'lshape' else f"${e['intervals']}^3$"


def prob(e):
    return 'Poisson, L-shape' if e['problem'] == 'lshape' else 'Poisson 3D'


SC = {'total_seconds': 'complete query', 'fused_device_seconds': 'GPU query'}
ALL = [e for e in S['meshes'] if e['role'] in ('table', 'final')]
M = [e for e in ALL if e['usable']]                                  # usable in the series' Table-1 scope
EXCLUDED = [e for e in ALL if not e['usable']]
# a view of each entry in a scope where every gate passed: the Table-1 scope if possible, else the other scope
V = []
for e in ALL:
    if e['usable']:
        V.append(dict(e=e, scope=e['scope'], row=e['row'], arms=e['arms'], og=e['order_gate']))
    elif e['alt']['usable']:
        V.append(dict(e=e, scope=e['alt']['scope'], row=e['alt']['row'], arms=e['alt']['arms'], og=e['alt']['order_gate']))
