"""Generate reports/heat-compare-hires.md and reports/summary.json from runs/pn*/summary.json and
runs/tr*/pull/out/*/result.json. Never hand-type a number into the report: edit this script."""
import hashlib, json, sys
from pathlib import Path

LANE = Path(__file__).resolve().parent.parent
PANELS = [('pn1024', 1024), ('pn2048', 2048), ('pn4096', 4096)]
TRAIN = {1024: 'tr1024a', 2048: 'tr2048'}
SHOW = {'nmrom': 'NM-ROM (ours)', 'linear_bank': 'linear bank (q=R rung)', 'pod': 'POD', 'qm': 'quadratic manifold',
        'operator': 'neural operator', 'control': 'control (not a FOM candidate)', 'fom': 'CN–CG full-order'}
ORDER = ['nmrom', 'linear_bank', 'pod', 'qm', 'operator', 'control', 'fom']


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def fmt_unknowns(x):
    return '—' if x['unknowns'] is None else f"{x['unknowns']:,}"


out, combined = [], dict(schema='heat-compare-hires-report-v1', meshes=[])
out += ['# Heat 2D at high resolution: comparison with other methods (1024², 2048², 4096²)', '',
        'Every method timed in one cluster allocation per mesh on the 16-draw sealed heat cohort of the paper\'s Table 1 '
        '(seed 791099, opened a second time here; no choice was made on it). All numbers below are generated by '
        '`reports/make_report.py` from the per-job `summary.json` files listed under Provenance; status is given per mesh.', '']
for job, n in PANELS:
    p = LANE / 'runs' / job / 'summary.json'
    if not p.exists():
        out += [f'## {n}² — NOT RUN / not collected', '']
        continue
    s = json.loads(p.read_text()); g = s['gates']
    ok = g['all_passed']
    status = 'final (every gate passed)' if ok else 'PROVISIONAL — a gate failed, see Gates'
    combined['meshes'].append(dict(mesh=n, job=job, summary_json=str(p.relative_to(LANE)), summary_sha256=sha(p), status=status,
                                   rows=[{k: x.get(k) for k in ('method', 'family', 'unknowns', 'worst_all_times', 'median_case_max', 'device_ms_median',
                                                                'fom_chosen', 'speedup', 'no_fom_as_accurate', 'speedup_vs_named', 'failures')} for x in s['rows']]))
    out += [f'## {n}² ({s["unknowns"]:,} unknowns) — {status}', '',
            f'Job {s["metadata"]["job_id"]}, GPU `{s["metadata"]["gpu"].split(",")[0]}`, source commit `{s["source_commit"]}`. '
            f'Named FOM `{s["named_fom"]}`.', '',
            '| method | family | unknowns | worst % | median % | GPU ms | FOM chosen | speedup | × named | failed solves |',
            '|---|---|---:|---:|---:|---:|---|---:|---:|---:|']
    rows = s['rows']
    for fam in ORDER:
        sel = [x for x in rows if x['family'] == fam]
        if fam == 'fom':
            sel.sort(key=lambda x: x['device_ms_median'])
        for x in sel:
            sp = '—' if x['speedup'] is None else f"{x['speedup']:.2f}" + ('†' if x.get('no_fom_as_accurate') else '')
            out.append(f"| `{x['method']}` | {SHOW[fam]} | {fmt_unknowns(x)} | {100*x['worst_all_times']:.4f} | {100*x['median_case_max']:.4f} | "
                       f"{x['device_ms_median']:.3f} | {('`'+x['fom_chosen']+'`') if x['fom_chosen'] else '—'} | {sp} | {x['speedup_vs_named']:.2f} | {x['failures']} |")
    if n == 4096:
        out += ['', 'No neural-operator rows at 4096²: not trained at this mesh (DESIGN §6).']
    if s.get('operators_missing'):
        out += ['', f"Operator checkpoints missing at run time: {', '.join(m['name'] for m in s['operators_missing'])}."]
    oe = g['order_effect']
    out += ['', f"Gates: audit passed **{g['audit_passed']}** ({g['audit_failure_count']} failures); order-effect gate **{oe['passed']}** "
            f"(max sentinel deviation {100*oe['max_relative_deviation']:.1f} % vs tolerance {100*oe['tolerance']:.0f} %; positive control deviation "
            f"{100*oe['positive_control_min_relative_deviation']:.0f} %, fails as required: {oe['positive_control_fails_as_required']}); "
            f"NM-ROM reproduces hires-heat h2d-final04: **{g.get('nmrom_reproduces_h2d_final04', {}).get('passed')}** "
            f"(max relative difference {g.get('nmrom_reproduces_h2d_final04', {}).get('max_relative', float('nan')):.2e}); "
            f"summary vs independent recompute: max relative difference {g['summary_vs_audit_recompute_max_relative']:.1e}.", '']
    if s.get('qm'):
        out += ['Quadratic manifold ridge weight chosen on the trajectory-split holdout: ' +
                ', '.join(f"r={r}: γ={v['gamma']:g} ({v['columns']} columns)" for r, v in s['qm'].items()) + '.', '']
    out += ['† no tested CN–CG setting is as accurate as this arm; ratio against the most accurate tested setting (unmatched accuracy; not a bound).', '']

tr = []
for n, job in TRAIN.items():
    d = LANE / 'runs' / job / 'pull' / 'out'
    for f in sorted(d.glob('*/result.json')) if d.exists() else []:
        r = json.loads(f.read_text())
        tr.append(f"| {n}² | {r['name']} | {r['real_parameter_count']:,} | {r['parameter_dtype']} | {r['micro_batch']} | {r['epochs_completed']} | {r['optimisation_steps']} | "
                  f"{r['stop_reason']} | {r['best_epoch']} | {100*r['validation_best_checkpoint']['mean_case_max']:.3f} | {100*r['validation_best_checkpoint']['worst_case_max']:.3f} |")
if tr:
    out += ['## Operator training (validation seed 791001; nothing selected on the evaluation cohort)', '',
            '| mesh | family | parameters | dtype | micro-batch | epochs | steps | stopped by | best epoch | val mean-case-max % | val worst % |',
            '|---|---|---:|---|---:|---:|---:|---|---:|---:|---:|'] + tr + ['']
out += ['## Provenance', '']
for m in combined['meshes']:
    out.append(f"- {m['mesh']}²: `{m['summary_json']}` sha256 `{m['summary_sha256']}`")
out += ['', '## Glossary', '',
        '- **worst %**: over the 16 cases, the largest current-relative L² error over all six output times (t = 0 included), '
        'against the exact same-grid semidiscrete solution (DST). **median %**: median over cases of each case\'s maximum over times.',
        '- **GPU ms**: median over 16 cases × 5 repetitions of the time from a supplied initial field on the GPU to six full fields on the GPU; '
        'each repetition after a 0.15 s GPU burn-in; compilation and offline assembly excluded.',
        '- **FOM chosen**: the fastest tested CN–CG setting (same job) whose worst error is ≤ the arm\'s worst error. **speedup** = its time / the arm\'s time. '
        '**× named** = time of the named FOM (Δt 0.025, rtol 1e-6) / the arm\'s time.',
        '- **CN–CG**: Crank–Nicolson in time, unpreconditioned warm-started conjugate gradients per step, on the same grid; `dt`/`rtol` in the name.',
        '- **NM-ROM**: the paper\'s frozen wide-bank model (bank rank R = 128, latent K = 8); `q` = number of linear corrections; `cn` = weak '
        'Crank–Nicolson stepping; `field_direct_tol1e-4_chol` = the batched fit (each output fitted to the exact flow of the supplied field\'s test moments; '
        'valid because heat is linear and autonomous and the tests are sine eigenfunctions).',
        '- **linear bank**: free coefficients in the span of the same frozen bank (the top rung q = R); not the NM-ROM.',
        '- **POD r**: uncentred POD of the 3072 training snapshots (512 draws × 6 times) computed at the target mesh; `galerkin_cn` / `lspg_cn` = Galerkin / '
        'least-squares Petrov–Galerkin projection of the FOM\'s Crank–Nicolson step (Δt 0.025); `galerkin_exact` = exact reduced exponential.',
        '- **quadratic manifold r**: u = u_ref + V a + W vech(a aᵀ), ridge weight γ chosen by an 80/20 holdout that splits whole training trajectories; '
        'solved with the NM-ROM\'s own solver and contracts (`cn`, `field_direct_tol1e-4_chol`).',
        '- **neural operators**: FNO / U-Net / Transolver / DeepONet trained at the target mesh on the 512 training draws with the Burgers panel\'s '
        'published configurations and a 3000 s wall budget per network; checkpoint = best validation.',
        '- **controls**: exact DST propagation and a 64-interval coarse-grid CN–CG + interpolation; printed for honesty, never used as "FOM chosen".',
        '- **sealed cohort**: the 16 evaluation draws of the paper\'s heat rows; **failed solves**: LM solves that did not reach stationarity, or CG solves that '
        'missed their tolerance.',
        '- **order-effect gate**: a fixed sentinel query timed between every two arms must stay within ±10 % of its median; its positive control (sentinel '
        'timed behind deliberately queued GPU work) must fail that test.']
(LANE / 'reports' / 'heat-compare-hires.md').write_text('\n'.join(out) + '\n')
(LANE / 'reports' / 'summary.json').write_text(json.dumps(combined, indent=1) + '\n')
print('\n'.join(out))
