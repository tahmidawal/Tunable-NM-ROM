           f"3. **Width 512 is worse than width 384** on every statistic (median {P(512)['median']:.4f} % against {P(384)['median']:.4f} %, "
           f"worst {P(512)['worst']:.3f} % against {P(384)['worst']:.3f} %) and slower ({P(512)['ms_median']:.1f} ms). The curve is "
