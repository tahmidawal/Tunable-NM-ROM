w('```mermaid')
w('flowchart LR')
w('  D[frozen coefficient data, 4,608 trajectories]:::frozen --> T[train 12 heads, K x seed]:::trained')
w('  B[frozen R512 bank + rotation]:::frozen --> T')
w('  T --> R[rule selection, Gauss ladder, Q2]:::solved')
w('  B --> R')
w('  R --> A[accuracy + Q1/Q2 at 1024^2, 38 cases]:::solved')
w('  R --> C[timing, A-B-A, 256^2 / 1024^2 / 4096^2]:::solved')
w('  A --> V[verdicts: H-acc-K, Q-LH-dim, Q-LH-cost, F5]:::out')
w('  C --> V')
w('  classDef frozen fill:#e5e7eb,stroke:#374151; classDef trained fill:#dbeafe,stroke:#1e40af;')
