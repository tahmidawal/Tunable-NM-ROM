def bad(x):
    return x is None or (isinstance(x, float) and not np.isfinite(x))


def pct(x):
    return 'n/a' if bad(x) else f'{100 * x:.3g} %'


def g3(x):
    return 'n/a' if bad(x) else f'{x:.3g}'


def hl(lab, cost_linear_over_head=False):
    """Display a registered label with explicit model names (the head is X; linear-over-head cost labels name the
    linear rung as X)."""
    if lab is None:
        return 'n/a'
    lab = str(lab)
    if cost_linear_over_head:
        return lab.replace('X cheaper', 'linear cheaper').replace('X costlier', 'linear costlier')
    return (lab.replace('X more accurate', 'head more accurate').replace('Y more accurate', 'linear more accurate')
            .replace('X dominates', 'head dominates').replace('Y dominates', 'linear dominates')
            .replace('X cheaper', 'head cheaper').replace('X costlier', 'head costlier'))


def cfg(name, sc='BE'):
    return E['configs_1024'].get(f'{name}|{sc}')


def qlabel(c):
    if c is None:
        return 'not run'
    q1 = 'pass' if c['Q1'].get('pass') else 'fail'
    return f"Q1 {q1}, Q2 {c['Q2'].get('label')}"


def table(head, rows):
    out = ['| ' + ' | '.join(h.replace('|', '\\|') for h in head) + ' |', '|' + '---|' * len(head)]
    out += ['| ' + ' | '.join(str(x).replace('|', '\\|') for x in r) + ' |' for r in rows]
    return '\n'.join(out)


