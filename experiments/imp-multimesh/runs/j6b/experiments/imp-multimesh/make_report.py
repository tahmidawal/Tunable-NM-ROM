def plots(D, res):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import itertools
    (HERE / 'plots').mkdir(exist_ok=True)
    sets = [ms for k in (1, 2, 3) for ms in itertools.combinations(C.MESHES, k)]
    fig, axs = plt.subplots(2, 4, figsize=(15, 7))
    qs = np.unique(np.round(np.logspace(0, 4, 41))).astype(int)
    X = 'R384|CNR'
    for ax, ms in zip(axs.ravel(), sets):
        o, c = [], []
        for q in qs:
            st, best, Cx = C.match(D, X, (frozenset(ms), int(q)))
            o.append(Cx)
            c.append(best[0] if best else np.nan)
        ax.loglog(qs, o, label=f'ours {X}', color='#1f5fa8')
        ax.loglog(qs, c, label='cheapest admissible CP', color='#c4561d')
        ax.set_title('+'.join(f'{m}²' for m in ms), fontsize=9)
        ax.set_xlabel('queries per mesh')
        ax.set_ylabel('H200 seconds')
    axs.ravel()[-1].axis('off')
    axs.ravel()[0].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(HERE / 'plots' / 'cost_vs_queries.png', dpi=130)


