"""Build results/summary.json and RESULTS.md from the pulled per-mesh JSON (never typed by hand).

Input: results/raw/t{dim}d{mesh}/{measurement.json, result-timing.json, config-provenance.json, gpu-start.txt,
gpu-trace.csv, node-occupancy-*.txt, <jobid>.out} pulled by pull.sh. Run: python report.py
"""
import csv
import hashlib
import json
from pathlib import Path
from statistics import median

import gates

HERE = Path(__file__).resolve().parent
RAW = HERE / 'results' / 'raw'
MESHES = [(2, 256, '256²'), (2, 512, '512²'), (2, 1024, '1024²'), (2, 2048, '2048²'), (2, 4096, '4096²'),
          (3, 65, '64³'), (3, 129, '128³'), (3, 257, '256³')]
PART_A = {(2, 256), (2, 1024), (2, 4096)}


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def gpu_trace(path, t0_unix):
    """Clock / temperature spread over the measurement window."""
    if not path.exists():
        return None
    rows = []
    for r in csv.reader(path.open()):
        try:
            rows.append(dict(sm=float(r[1].split()[0]), mem=float(r[2].split()[0]), temp=float(r[3]),
                             power=float(r[4].split()[0]), util=float(r[5].split()[0]), thr=r[6].strip()))
        except (ValueError, IndexError):
            continue
    if not rows:
        return None
    col = lambda k: [x[k] for x in rows]
    return dict(samples=len(rows), sm_clock_mhz=[min(col('sm')), median(col('sm')), max(col('sm'))],
                mem_clock_mhz=[min(col('mem')), max(col('mem'))], temperature_c=[min(col('temp')), max(col('temp'))],
                power_w=[min(col('power')), max(col('power'))],
                throttle_reasons_seen=sorted({x['thr'] for x in rows}))


def main():
    closeout = json.loads((HERE / 'vendor' / 'closeout-sealed-matched-fom-timing.json').read_text())['panels']
    out = dict(label='post-closeout timing on exposed validation inputs (2D val32, 3D val64, cases 0-5); timing only; '
                     'not prospective; not part of the sealed confirmation',
               protocol_sha256=sha(HERE / 'PROTOCOL.md'), gates_sha256=sha(HERE / 'gates.py'),
               driver_sha256=sha(HERE / 'timing.py'), meshes={})
    for dim, mesh, label in MESHES:
        task = f't{dim}d{mesh}'
        d = RAW / task
        co = closeout[f'sealed{dim}d{mesh}']
        entry = dict(label=label, part_a=(dim, mesh) in PART_A, closeout=dict(
            job_id=co['job_id'], gpu=co['gpu'], qualified=co['qualified'], reasons=co['reasons'],
            matched_fom=co['matched_fom'], confirm_rom_over_fom=co['confirm_rom_over_fom'],
            fom_ms_with_input_preparation_sensitivity=co['fom_ms_with_input_preparation_sensitivity'],
            rom_confirm_ms=co['subject_timings'][f"rom_lat|{co['quadrature_rule']}"]['confirm_ms'],
            fom_confirm_ms=co['subject_timings'][f"fom|{co['matched_fom']}"]['confirm_ms']))
        if not (d / 'measurement.json').exists():
            entry['status'] = 'missing'
            out['meshes'][task] = entry
            continue
        meas = json.loads((d / 'measurement.json').read_text())
        rt = json.loads((d / 'result-timing.json').read_text())
        prov = json.loads((d / 'config-provenance.json').read_text())
        assert meas['matched_fom'] == co['matched_fom'] and meas['rule'] == co['quadrature_rule'], task
        ev = gates.evaluate(meas)
        disc = {blk: {s: median(1e3 * r['seconds'] for r in meas['invocations'] if r['block'] == blk and r['subject'] == s)
                      for s in meas['subjects']} for blk in ('discard_main', 'discard_confirm')}
        la = [r['loadavg1'] for r in meas['invocations'] if r['block'] in ('main', 'confirm')]
        entry.update(status='complete', job_id=rt['job_id'], host=rt['host'], gpu=rt['gpu'], commit=rt['commit'],
                     same_gpu_type_as_closeout=rt['gpu'] == co['gpu'], config_provenance=prov,
                     validation_accuracy_sanity=rt['accuracy'], driver_gates=rt['gates'],
                     discarded_block_medians_ms=disc, host_loadavg1=[min(la), median(la), max(la)],
                     gpu_trace=gpu_trace(d / 'gpu-trace.csv', meas['measurement_start_unix']),
                     node_occupancy_start=(d / 'node-occupancy-start.txt').read_text().strip().splitlines()
                     if (d / 'node-occupancy-start.txt').exists() else None,
                     **ev)
        out['meshes'][task] = entry
    (HERE / 'results' / 'summary.json').write_text(json.dumps(out, indent=1))
    write_md(out)


def f(x, n=2):
    return '—' if x is None else f'{x:.{n}f}'


def write_md(S):
    M = S['meshes']
    L = []
    L.append('# Post-closeout lattice timing and end-to-end cost on validation inputs\n')
    L.append('Final numbers for this lane, generated by `report.py` from `results/summary.json`. **Every new number here '
             'is measured on exposed validation inputs** (2D `val32`, 3D `val64`, cases 0–5), timing only, with the '
             'frozen closeout settings and the closeout-selected matched spectral solver. It is not prospective and is not '
             'part of the sealed confirmation; the closeout\'s sealed timing verdicts stand as recorded '
             '(PROTOCOL.md §1).\n')
    L.append('## (a) Prepared-input ratio, lattice ROM / matched spectral solver\n')
    L.append('Ratio above one favours the spectral solver. "Closeout (sealed)" is the recorded sealed-panel ratio and '
             'its timing verdict; "this lane" is the same-job confirmation-block ratio on validation inputs.\n')
    L.append('| Mesh | GPU (this lane) | Spectral solver | Closeout (sealed) ratio | Closeout timing | This lane: lattice ms | '
             'spectral ms | ratio | paired per-case range | timing checks |')
    L.append('|---|---|---|---:|---|---:|---:|---:|---|---|')
    for t, e in M.items():
        co = e['closeout']
        cot = 'pass' if co['qualified'] else 'FAIL'
        if e['status'] != 'complete':
            L.append(f"| {e['label']} | — | {co['matched_fom']} | {f(co['confirm_rom_over_fom'])}× | {cot} | — | — | — | — | "
                     f"not measured ({e['status']}) |")
            continue
        p = e['paired_prepared_ratio']
        L.append(f"| {e['label']}{' (a)' if e['part_a'] else ''} | {e['gpu']} | {co['matched_fom']} | "
                 f"{f(co['confirm_rom_over_fom'])}× | {cot} | {f(e['confirm_median_ms']['rom_lat'])} | "
                 f"{f(e['confirm_median_ms']['fom'])} | {f(e['prepared_ratio'])}× | {f(p['minimum'])}–{f(p['maximum'])}× | "
                 f"{'pass' if e['prepared_qualified'] else 'FAIL'} |")
    L.append('\n## (b) Input preparation and end-to-end ratio\n')
    L.append('Preparation: physical case description → prepared input on the GPU, same definition for both solvers '
             '(PROTOCOL.md §3). End to end = confirmation median of preparation + confirmation median of query. The fused '
             'column times preparation and query in one call, as a consistency check.\n')
    L.append('| Mesh | ROM prep ms | ROM query ms | Spectral prep ms | Spectral query ms | Prepared ratio | End-to-end ratio | '
             'Fused e2e ratio | Paired e2e range | e2e checks |')
    L.append('|---|---:|---:|---:|---:|---:|---:|---:|---|---|')
    for t, e in M.items():
        if e['status'] != 'complete':
            L.append(f"| {e['label']} | — | — | — | — | — | — | — | — | not measured |")
            continue
        c, p = e['confirm_median_ms'], e['paired_e2e_ratio']
        L.append(f"| {e['label']} | {f(c['rom_prep'])} | {f(c['rom_lat'])} | {f(c['fom_prep'])} | {f(c['fom'])} | "
                 f"{f(e['prepared_ratio'])}× | {f(e['e2e_ratio'])}× | {f(e['e2e_fused_ratio'])}× | "
                 f"{f(p['minimum'])}–{f(p['maximum'])}× | {'pass' if e['e2e_qualified'] else 'FAIL'} |")
    L.append('\n## Timing checks, every subject\n')
    L.append('Worst within-block drift (main / confirmation) and main-vs-confirmation fold; the limit is 1.10 for all three. '
             'Output agreement ≤1e-12 (queries) or bitwise (preparations).\n')
    L.append('| Mesh | Subject | Main drift | Confirm drift | Fold | Max output diff | IQR (confirm) ms | Pass |')
    L.append('|---|---|---:|---:|---:|---:|---|---|')
    for t, e in M.items():
        if e['status'] != 'complete':
            continue
        for s, v in e['subjects'].items():
            od = max(v['main']['max_output_diff'], v['confirm']['max_output_diff'])
            L.append(f"| {e['label']} | `{s}` | {f(v['main']['block_drift'], 4)} | {f(v['confirm']['block_drift'], 4)} | "
                     f"{f(v['main_confirm_fold'], 4)} | {od:.2e} | {f(v['confirm']['q1_ms'])}–{f(v['confirm']['q3_ms'])} | "
                     f"{'pass' if v['passed'] else 'FAIL'} |")
    L.append('\n## Run provenance and conditions\n')
    L.append('| Mesh | Job | Node | Same GPU type as closeout | SM clock MHz (min/median/max) | Temperature °C | '
             'Host load (min/median/max) | Fused/sum ROM, FOM | Validation ST median error (sanity) |')
    L.append('|---|---|---|---|---|---|---|---|---|')
    for t, e in M.items():
        if e['status'] != 'complete':
            L.append(f"| {e['label']} | — | — | — | — | — | — | — | — |")
            continue
        g = e['gpu_trace'] or {}
        sm = '/'.join(f'{x:.0f}' for x in g.get('sm_clock_mhz', [])) or '—'
        tc = '–'.join(f'{x:.0f}' for x in g.get('temperature_c', [])) or '—'
        la = '/'.join(f'{x:.2f}' for x in e['host_loadavg1'])
        fs = e['fused_over_component_sum']
        acc = e['validation_accuracy_sanity']
        L.append(f"| {e['label']} | {e['job_id']} | {e['host']} | {'yes' if e['same_gpu_type_as_closeout'] else 'NO'} | {sm} | "
                 f"{tc} | {la} | {f(fs['rom'], 3)}, {f(fs['fom'], 3)} | ROM {acc['rom_ST_median']:.4%}, "
                 f"spectral {acc['fom_ST_median']:.4%} |")
    L.append('\n## Glossary\n')
    L.append('- **Lattice ROM query**: the reduced-order model\'s full query (projection of the initial field, reduced '
             'solve, decode onto the 257² or 63³ scoring lattice).\n'
             '- **Matched spectral solver**: the full-order pseudospectral configuration ($N$ modes per direction) that the '
             'closeout selected as the fastest one matching the lattice ROM\'s accuracy on the sealed cohort. Not re-selected.\n'
             '- **Prepared input / preparation**: the solver\'s starting data on the GPU (initial field on the mesh for the '
             'ROM; sine coefficients for the spectral solver), and the work of producing it from the case description.\n'
             '- **Prepared-input ratio**: ROM query time / spectral query time, both from prepared inputs.\n'
             '- **End-to-end ratio**: (ROM preparation + query) / (spectral preparation + query).\n'
             '- **Fused**: preparation and query timed as one call; should equal the component sum within 10%.\n'
             '- **Block drift**: largest deviation of one repetition block\'s median from the median over all blocks.\n'
             '- **Fold**: main-block median vs confirmation-block median, larger over smaller.\n'
             '- **Paired per-case range**: minimum to maximum over the six cases of the per-case ratio.\n'
             '- **Sealed / validation**: sealed cases were opened once in the closeout; validation cases were used for '
             'historical selection and are already exposed.\n'
             '- **ST median error**: median relative trajectory error against the space-time reference, shown only to '
             'confirm the frozen pipeline reproduces on these inputs.\n'
             '- **(a)**: the three 2D meshes whose closeout timing checks failed.\n')
    (HERE / 'RESULTS.md').write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
