"""Generate reports/2026-09-24-burgers2d-speed-small-meshes.md from checks/b*-summary.json and checks/h*-summary.json
(independent NumPy audits of the saved outputs). No number in the report is typed by hand.

    python reports/generate_report.py
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANE = HERE.parent
MESHES = [256, 512, 1024]
OUT = HERE / '2026-09-24-burgers2d-speed-small-meshes.md'


def f(x, d=3):
    if x is None:
        return '—'
    if isinstance(x, float):
        return f'{x:,.{d}f}'
    return str(x)


def sp(x):
    return '—' if x is None else f'{x:.2f}×'


def short(n):
    """Readable knob label from an arm name."""
    if n is None:
        return '—'
    t = n.split('__')[0]
    lab = []
    if '_lin_' in t:
        lab.append(f"R'={t.split('_')[0][1:]} linear")
    else:
        lab.append(f"R'={t.split('_')[0][1:]} q=0 head")
    lab.append('exact 1st step' if '_x1' in t else 'no exact step')
    if '_cap1' in t:
        lab.append('LM cap 1')
    if '_budget1' in t:
        lab.append('LM budget 1')
    impl = n.split('__')[1] if '__' in n else ''
    return ', '.join(lab) + (f' [{impl}]' if impl else '')


def load(prefix):
    out = {}
    for L in MESHES:
        p = LANE / 'checks' / f'{prefix}{L}-summary.json'
        if p.exists():
            out[L] = (json.loads(p.read_text()), hashlib.sha256(p.read_bytes()).hexdigest())
    return out


def main():
    dev, hold = load('b'), load('h')
    final = len(dev) == len(MESHES) and len(hold) == len(MESHES)
    status = 'final' if final else f'PROVISIONAL ({len(dev)} of 3 dev6 meshes, {len(hold)} of 3 held-out meshes landed)'
    o = ['# Burgers 2D at $256^2$–$1024^2$: faster NM-ROM settings from deployment knobs and iterate-preserving engineering',
         '',
         f'Status: **{status}**. Same frozen model (checkpoint `dn256b`, bank rotation `rotation_R512.npz`), no retraining; '
         'settings chosen on dev6 by the pre-registered rule of `DESIGN.md` §6, then run once on the held-out hold64 '
         'cohort. Every number below is generated by `reports/generate_report.py` from the audited summaries '
         '`checks/*-summary.json` (independent NumPy recomputation of the saved outputs). All timings are GPU '
         'milliseconds per query, measured in one allocation per mesh with the Newton–BiCGStab grid, A–B–A order.', '']

    # ---- headline -------------------------------------------------------------------------------------------
    o += ['## Table-1 rows: before (parent settings, parent code) and after (this lane), dev6', '',
          '| mesh | row | setting | worst evolved error | GPU ms | speedup vs FOM | iterations per case |',
          '|---|---|---|---|---|---|---|']
    for L, (s, _) in dev.items():
        se = s['selection']
        t1 = se.get('table1') or {}
        before = se.get('parent_settings_this_job') or {}
        for n, b in before.items():
            if 'budget1' in n:
                continue
            o.append(f"| ${L}^2$ | before | {short(n)} | {f(b['worst_evolved_percent'])} % | {f(b['median_gpu_ms'], 1)} | "
                     f"{sp(b['speedup_vs_table1_fom'])} | {b['total_iterations_per_case']} |")
        for k in ('accurate', 'fast'):
            a = se.get(k)
            if a:
                o.append(f"| ${L}^2$ | **after, {k}** | {short(a['timed_arm'])} ({a['mode']} compile) | "
                         f"{f(a['worst_evolved_percent'])} % | {f(a['median_gpu_ms'], 1)} | "
                         f"**{sp(t1.get(k + '_speedup'))}** | {a['total_iterations_per_case']} |")
        o.append(f"| ${L}^2$ | FOM | `{t1.get('fom')}` (fastest setting+mode at least as accurate as the accurate row) | "
                 f"{f(t1.get('fom_worst_evolved_percent'))} % | {f(t1.get('fom_gpu_ms'), 1)} | 1× | |")
    o.append('')
    for L, (s, sh) in dev.items():
        o.append(f"- ${L}^2$: job {s['job_id']} on {s['gpu']} (`{s['host']}`), commit `{(s['commit'] or '')[:8]}`, "
                 f"{'all gates pass' if s['accepted'] else 'FAILED gates: ' + ', '.join(s['failed_gates'])}; "
                 f"summary sha256 `{sh[:16]}…`; fast bar (the $q=0$ setting re-measured) "
                 f"{f(s['selection']['fast_bar_percent'])} %; knobs {s['selection']['knobs']}, confirmed "
                 f"{s['selection']['confirmed']}.")
    o.append('')

    # ---- held-out ----------------------------------------------------------------------------------------------
    o += ['## Held-out confirmation (hold64, frozen dev6 picks, reported as measured)', '']
    if not hold:
        o += ['Not yet run.', '']
    else:
        o += ['| mesh | row | setting | worst evolved error | median error | GPU ms | speedup vs FOM | job | gates |',
              '|---|---|---|---|---|---|---|---|---|']
        for L, (s, sh) in hold.items():
            se = s['selection']
            t1 = se['table1']
            for k in ('accurate', 'fast'):
                a = se[k]
                o.append(f"| ${L}^2$ | {k} | {short(a['name'])} | {f(a['worst_evolved_percent'])} % | "
                         f"{f(a['median_evolved_percent'])} % | {f(a['median_gpu_ms'], 1)} | {sp(t1.get(k + '_speedup'))} | "
                         f"{s['job_id']} | {'pass' if s['accepted'] else 'FAILED: ' + ', '.join(s['failed_gates'])} |")
            for n, b in se['parent_settings_this_job'].items():
                o.append(f"| ${L}^2$ | parent setting | {short(n)} | {f(b['worst_evolved_percent'])} % | "
                         f"{f(b['median_evolved_percent'])} % | {f(b['median_gpu_ms'], 1)} | {sp(b['speedup_vs_table1_fom'])} | "
                         f"{s['job_id']} | |")
            o.append(f"| ${L}^2$ | FOM | `{t1['fom']}` | {f(t1['fom_worst_evolved_percent'])} % | | "
                     f"{f(t1['fom_gpu_ms'], 1)} | 1× | {s['job_id']} | |")
        o.append('')

    # ---- engineering parity ---------------------------------------------------------------------------------
    o += ['## Engineering: same iterates, less time', '',
          'Parity: the engineered arm against the parent code at the same setting (and every knob\'s two compile modes '
          'against each other): all six output fields and all 51 internal states within the relative bar, identical '
          'per-step LM iterations, exit reasons and rejected-step counts on every dev case.', '',
          '| mesh | engineered arm | reference arm | worst relative difference | integers identical | pass |',
          '|---|---|---|---|---|---|']
    for L, (s, _) in dev.items():
        for p in s['gates']['parity']['pairs']:
            if p['parent'].endswith('__parent'):
                o.append(f"| ${L}^2$ | {short(p['engineered'])} | {short(p['parent'])} | {p['worst_relative']:.1e} | "
                         f"{p['integers_identical']} | {p['passed']} |")
        allp = s['gates']['parity']['pairs']
        o.append(f"| ${L}^2$ | all {len(allp)} pairs (incl. graphs vs default for every knob) | | "
                 f"{max(p['worst_relative'] for p in allp):.1e} | {all(p['integers_identical'] for p in allp)} | "
                 f"{s['gates']['parity']['passed']} |")
    o += ['', '| mesh | setting | parent code, default compile (ms) | engineered, default compile (ms) | engineered, graphs (ms) | factor (parent / best engineered) |',
          '|---|---|---|---|---|---|']
    for L, (s, _) in dev.items():
        for n, b in (s['selection'].get('parent_settings_this_job') or {}).items():
            e = b.get('engineered_same_knob') or {}
            d0 = next((v['ms'] for k, v in e.items() if k.endswith('__eng')), None)
            d1 = next((v['ms'] for k, v in e.items() if k.endswith('__eng_graphs')), None)
            best = min([x for x in (d0, d1) if x is not None] or [None]) if (d0 or d1) else None
            o.append(f"| ${L}^2$ | {short(n)} | {f(b['median_gpu_ms'], 1)} | {f(d0, 1)} | {f(d1, 1)} | "
                     f"{sp(b['median_gpu_ms'] / best) if best else '—'} |")
    o.append('')

    # ---- section 6.3 ---------------------------------------------------------------------------------------
    g = next((s['selection'].get('general_path_section_6_3') for L, (s, _) in dev.items()
              if s['selection'].get('general_path_section_6_3')), None)
    if g:
        L = next(L for L, (s, _) in dev.items() if s['selection'].get('general_path_section_6_3'))
        o += [f'## Paper §6.3: the fast solver path against the general path it replaced (${L}^2$, dev6, one allocation)', '',
              'Fast path: Cholesky on the damped normal equation, clipped step, damping carried between steps, quadratic '
              'predictor, analytic Jacobian (the parent code at the Table-1 fast setting, $R\'=128$ linear, $M=512$, lattice '
              'EQ). General path: forward-mode (`jacfwd`) Jacobian, LU, over-long steps rejected, damping restarted every '
              'step, two-way linear predictor, unfused residual/Jacobian evaluation (`varpro.make_block_lm`), same residual, '
              'rule, gtol and budget. It is a reconstruction of the general solver on the linear rung, so $X$ is the factor '
              'of the whole solver-policy change.', '',
              '| path | GPU ms | worst evolved error | per-case errors (%) | LM iterations per case |', '|---|---|---|---|---|',
              f"| general | {f(g['general_ms'], 1)} | {f(g['general_worst_evolved_percent'])} % | "
              f"{[round(x, 3) for x in g['general_per_case']]} | {g['general_iterations']} |",
              f"| fast | {f(g['fast_path_ms'], 1)} | {f(g['fast_path_worst_evolved_percent'])} % | "
              f"{[round(x, 3) for x in g['fast_per_case']]} | {g['fast_iterations']} |", '',
              f"**X = {g['X']:.2f}** (general / fast, medians over A1 ∪ A2). Pre-registered same-error criterion "
              f"({g['same_error_criterion'].split(': ')[1]}): **{g['same_error']}**.", '']

    # ---- all knobs ---------------------------------------------------------------------------------------------
    o += ['## Every candidate knob (dev6)', '']
    for L, (s, _) in dev.items():
        o += [f'### ${L}^2$', '',
              '| knob | worst % | median % | ms (faster mode) | other mode ms | certificate ($k\\ge\\max(j,1)$) | ρ max cert / conf | $k\\ge j+1$ | iterations per case | budget exits | own FOM | own speedup |',
              '|---|---|---|---|---|---|---|---|---|---|---|---|']
        ks = sorted(s['knobs'].values(), key=lambda k: k['worst_evolved_percent'])
        for k in ks:
            om = list(k['other_mode_ms'].values())
            o.append(f"| {short(k['timed_arm'])} ({k['mode']}) | {f(k['worst_evolved_percent'])} | "
                     f"{f(k['median_evolved_percent'])} | {f(k['median_gpu_ms'], 1)} | {f(om[0] if om else None, 1)} | "
                     f"{k['certificate']} | {f(k['rho_max_cert'])} / {f(k['rho_max_confirmation'])} | "
                     f"{k['certificate_k_ge_j_plus_1']} | {k['total_iterations_per_case']} | {k['budget_exits']} | "
                     f"`{k['own_fom']}` | {sp(k['own_speedup'])} |")
        o.append('')
        o += ['| FOM setting (mode) | worst % | GPU ms | Newton iterations per case |', '|---|---|---|---|']
        for n, t in sorted(((n, t) for n, t in s['table'].items() if t['family'] == 'fom' and t['timed']),
                           key=lambda x: x[1]['median_gpu_ms']):
            o.append(f"| `{n}` | {f(t['worst_evolved_percent'])} | {f(t['median_gpu_ms'], 1)} | {t['newton_iterations_per_case']} |")
        o.append('')

    # ---- gates -------------------------------------------------------------------------------------------------
    o += ['## Gates', '']
    for tag, sums in (('dev6', dev), ('held-out', hold)):
        for L, (s, _) in sums.items():
            gs = s['gates']
            dr, nb = gs.get('drift_ABA', {}), gs.get('neighbour', {})
            o.append(f"- {tag} ${L}^2$ (job {s['job_id']}): "
                     + ', '.join(f"{k} {'✓' if v['passed'] else '✗'}" for k, v in gs.items())
                     + f"; worst drift {f(dr.get('worst'))}, worst neighbour ratio {f(nb.get('worst'))} "
                       f"({nb.get('evaluable')} evaluable, not evaluable: {len(nb.get('not_evaluable') or [])}).")
    o.append('')
    o += ['## What failed, was retracted, or is provisional', '',
          '- See `PROGRESS.md` for the job-by-job record; anything listed there as failed or cancelled is not in the '
          'tables above.', '']

    # ---- glossary ---------------------------------------------------------------------------------------------
    o += ['## Glossary', '',
          '- **NM-ROM**: the nonlinear-manifold reduced-order model; here the frozen Burgers model whose state is a '
          'combination of $R\'$ columns of a learned, rotated coordinate bank.',
          '- **FOM**: the full-order model, backward Euler with Newton–BiCGStab on the same mesh; 15 tolerance/time-step '
          'settings, each compiled in two modes.',
          '- **$R\'$ (span width)**: how many leading columns of the rotated bank the ROM uses. **Linear rung**: the ROM '
          'solves directly for the $R\'$ coefficients. **$q=0$ head**: the ROM solves for a 16-dimensional latent code '
          'mapped to the coefficients by the trained head.',
          '- **$M$**: number of sine test functions in the weak residual ($4R\'$ here). **$m$**: number of quadrature '
          'nodes. **Lattice EQ (`lat64`)**: the empirical-quadrature rule on a uniform $63\\times63$ sub-lattice.',
          '- **Exact first step (x1)**: the first time step uses the exact all-node residual instead of the quadrature.',
          '- **LM**: Levenberg–Marquardt, the damped Gauss–Newton solver run at every time step. **LM cap 1**: at most one '
          'LM iteration per time step (a deployment knob). **Budget exits**: time steps that ended because the cap was '
          'reached before the stopping test was met.',
          '- **Engineering (E1–E3)**: rewrites that compute the same numbers in a different order (separable test-matrix '
          'products, an analytic Jacobian for the exact step). **Compile mode**: `default`, or `graphs` (XLA command '
          'buffers/CUDA graphs). Both are applied to ROM and FOM alike; each subject\'s faster mode is used.',
          '- **Parity**: the check that engineered code reproduces the parent code\'s iterates (relative difference and '
          'identical integer diagnostics).',
          '- **Worst evolved error**: the largest over the dev cases of the largest over the five evolved output times of '
          '$\\lVert u-u_{\\rm ref}\\rVert/\\lVert u_0\\rVert$, with $u_{\\rm ref}$ the tight FOM on the same mesh.',
          '- **dev6**: the six opened development cases used for selection. **hold64**: 64 held-out cases never used for '
          'any choice.',
          '- **Certificate**: the quadrature check $\\rho\\le 0.116$ on states reached on a separate population (5 draws + '
          '1 confirmation draw); $k\\ge\\max(j,1)$ is the primary state set, $k\\ge j+1$ the stricter reading.',
          '- **Fast bar**: the worst evolved error of the paper\'s previous fast setting ($R\'=512$, $q=0$), re-measured in '
          'the same job; the fast row is the cheapest certified setting at least that accurate.',
          '- **Speedup**: FOM milliseconds divided by ROM milliseconds, with one FOM time per mesh (the fastest FOM '
          'setting and mode at least as accurate as the accurate row). **Own speedup**: against the fastest FOM at least '
          'as accurate as that knob itself.',
          '- **A–B–A**: ROM arms timed (A1), then all FOM settings (B), then the ROM arms again (A2). **Drift gate**: A2/A1 '
          'median within 1.10. **Neighbour gate**: per subject, time after a long predecessor over time after a short '
          'one, case-controlled, at most 1.10.',
          '- **§6.3 X**: general solver path time over fast solver path time at the same setting.', '']
    OUT.write_text('\n'.join(o) + '\n')
    print(OUT)


if __name__ == '__main__':
    main()
