"""Generate the burgers3d-retry report and summary JSON from the recorded JSONs (no hand-typed numbers).

    python report3.py --status final|provisional
Inputs (lane dir): checks/model-choice.json, checks/select-val-n{n}.json, checks/select-heldout-n{n}.json,
checks/audit-{val,heldout}-n{n}.json, selection.json. Output: reports/<date>-burgers3d-retry-accuracy-speed.md and
reports/summary.json.
"""
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MESHES = (65, 129, 257)
CELLS = {65: '64³', 129: '128³', 257: '256³'}


def load(p):
    p = HERE / p
    return json.loads(p.read_text()) if p.exists() else None


def pct(x):
    return '—' if x is None else f'{100 * x:.2f}'


def ms(x):
    return '—' if x is None else f'{x:.2f}'


def sx(x):
    return '—' if x is None else f'{x:.2f}×'


def rho(x):
    return '—' if x is None else f'{x:.3g}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--status', required=True)
    ap.add_argument('--date', default='2026-09-24')
    a = ap.parse_args()
    mc = load('checks/model-choice.json')
    summary = dict(lane='exp/2026-09-23-burgers3d-retry', status=a.status, model_choice=mc, meshes={})
    L = []
    L.append('# Burgers 3D retry: one frozen model, accurate and fast settings against Newton–BiCGStab at 64³–256³\n')
    L.append(f'Lane `exp/2026-09-23-burgers3d-retry`. Status of the numbers: **{a.status}**. Generated by '
             '`experiments/burgers3d-retry/report3.py` from the selection, audit and panel JSONs listed at the end; '
             'nothing is typed by hand. Protocol: `experiments/burgers3d-retry/DESIGN.md` (sections 1–9, revision R1, '
             'amendments dated there).\n')
    # headline
    L.append('## Headline rows (sealed held-out cohort 923901 × 32; H200; one frozen model)\n')
    L.append('Error = worst over cases of the largest relative $L^2$ error at the five evolved output times, normalised '
             'by the initial field. Speedup = FOM median GPU time / setting median GPU time, same job. Paper rule: '
             'the FOM is the fastest tested Newton–BiCGStab setting at least as accurate as the *accurate* setting; '
             '"own" = against the fastest FOM at least as accurate as that setting.\n')
    L.append('| mesh | accurate setting | worst % | median % | ms | speedup (own) | fast setting | worst % | median % | ms | '
             'speedup (own) | FOM (paper rule) | FOM worst % | FOM ms | gates | lane success |')
    L.append('|---|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---|---:|---:|---|---|')
    for n in MESHES:
        s = load(f'checks/select-heldout-n{n}.json')
        v = load(f'checks/select-val-n{n}.json')
        au = load(f'checks/audit-heldout-n{n}.json')
        summary['meshes'][str(n)] = dict(heldout=s, validation=v, audit_heldout_passed=None if au is None else au['passed'])
        if s is None:
            L.append(f'| {CELLS[n]} | not run | | | | | | | | | | | | | | |')
            continue
        ar, fr = s['accurate_row'] or {}, s['fast_row'] or {}
        fo = s['fom_row'] or {}
        L.append(f"| {CELLS[n]} | `{s['accurate']}` | {pct(ar.get('worst_evolved'))} | {pct(ar.get('median_evolved'))} | "
                 f"{ms(ar.get('median_ms'))} | {sx(ar.get('speedup_rule'))} ({sx(ar.get('speedup_own'))}) | `{s['fast']}` | "
                 f"{pct(fr.get('worst_evolved'))} | {pct(fr.get('median_evolved'))} | {ms(fr.get('median_ms'))} | "
                 f"{sx(fr.get('speedup_rule'))} ({sx(fr.get('speedup_own'))}) | `{s['fom']}` | {pct(fo.get('worst_evolved'))} | "
                 f"{ms(fo.get('median_ms'))} | {'pass' if s['timing_gates']['passed'] else 'FAIL'} | "
                 f"{'yes' if s.get('lane_success') else 'no'} |")
    L.append('')
    for n in MESHES:
        s = load(f'checks/select-heldout-n{n}.json')
        if s and s.get('frozen_validation_fom'):
            fr = s.get('frozen_fom_row') or {}
            L.append(f"- {CELLS[n]} held-out, FOM frozen on validation `{s['frozen_validation_fom']}`: "
                     f"{pct(fr.get('worst_evolved'))} % at {ms(fr.get('median_ms'))} ms; job {s['job_id']}, {s['gpu']}.")
    L.append('')
    L.append('## Verdict (lane-success gate, DESIGN R1-1: both frozen settings eligible on held-out, fast ≤ 5 %, both '
             'paper-rule speedups > 1, all gates)\n')
    for n in MESHES:
        s = load(f'checks/select-heldout-n{n}.json')
        if s:
            ar, fr = s['accurate_row'], s['fast_row']
            L.append(f"- **{CELLS[n]}: {'POSITIVE' if s['lane_success'] else 'NEGATIVE'}** — accurate {pct(ar['worst_evolved'])} % at "
                     f"{sx(ar['speedup_rule'])}, fast {pct(fr['worst_evolved'])} % at {sx(fr['speedup_rule'])} (own-matched "
                     f"{sx(fr['speedup_own'])}) against `{s['fom']}`.")
    L.append('\nEvery headline arm is a linear span of the ordered bank (no head passed the admission bar); the nonlinear head '
             'contributes nothing to this row.\n')
    # validation
    L.append('## Validation (cohort 923801 × 64): the settings rule\n')
    L.append('| mesh | accurate | worst % | ms | speedup (own) | fast | worst % | ms | speedup (own) | FOM | FOM worst % | FOM ms | '
             'gates | panel job | cert jobs |')
    L.append('|---|---|---:|---:|---:|---|---:|---:|---:|---|---:|---:|---|---|---|')
    for n in MESHES:
        v = load(f'checks/select-val-n{n}.json')
        if v is None:
            L.append(f'| {CELLS[n]} | not run |||||||||||||| ')
            continue
        ar, fr, fo = v['accurate_row'] or {}, v['fast_row'] or {}, v['fom_row'] or {}
        L.append(f"| {CELLS[n]} | `{v['accurate']}` | {pct(ar.get('worst_evolved'))} | {ms(ar.get('median_ms'))} | "
                 f"{sx(ar.get('speedup_rule'))} ({sx(ar.get('speedup_own'))}) | `{v['fast']}` | {pct(fr.get('worst_evolved'))} | "
                 f"{ms(fr.get('median_ms'))} | {sx(fr.get('speedup_rule'))} ({sx(fr.get('speedup_own'))}) | `{v['fom']}` | "
                 f"{pct(fo.get('worst_evolved'))} | {ms(fo.get('median_ms'))} | {'pass' if v['timing_gates']['passed'] else 'FAIL'} | "
                 f"{v['job_id']} | {v['cert_job_id']} |")
    L.append('')
    # per-mesh arm tables
    for n in MESHES:
        v = load(f'checks/select-val-n{n}.json')
        if v is None:
            continue
        L.append(f"### Validation arms, {CELLS[n]} (job {v['job_id']}, {v['gpu']})\n")
        L.append('| arm | eligible | ρ_max | worst % | median % | ms | speedup rule | speedup own | own FOM | why not eligible |')
        L.append('|---|---|---:|---:|---:|---:|---:|---:|---|---|')
        for k, r in sorted(v['arms'].items(), key=lambda kv: kv[1]['worst_evolved']):
            L.append(f"| `{k}` | {'yes' if r['eligible'] else 'no'} | "
                     f"{rho(r['rho_max'])} | "
                     f"{pct(r['worst_evolved'])} | {pct(r.get('median_evolved'))} | {ms(r['median_ms'])} | {sx(r['speedup_rule'])} | "
                     f"{sx(r['speedup_own'])} | `{r['own_fom']}` | {'; '.join(r['why_not'])} |")
        L.append('')
        L.append('| FOM setting | worst % | ms |')
        L.append('|---|---:|---:|')
        for k, f in sorted(v['foms'].items(), key=lambda kv: kv[1]['median_ms']):
            L.append(f"| `{k}` | {pct(f['worst_evolved'])} | {ms(f['median_ms'])} |")
        L.append('')
    # audits
    L.append('## Audits\n')
    for tag in ('val', 'heldout'):
        for n in MESHES:
            au = load(f'checks/audit-{tag}-n{n}.json')
            if au:
                L.append(f"- {tag} {CELLS[n]}: NumPy audit **{'PASS' if au['passed'] else 'FAIL'}** — " +
                         ', '.join(f"{k}: {v.get('passed') if isinstance(v, dict) else v}" for k, v in au['checks'].items()))
    if mc:
        L.append(f"\nModel choice (DESIGN §4): **{mc.get('chosen')}**; head: {mc.get('head')}. "
                 f"Floors: {json.dumps(mc.get('floors'))}")
    L.append('\n## Glossary\n')
    L.append('- **Span R′ / head K**: a solve in the first R′ columns of the importance-ordered bank (linear), or in K latent '
             'coordinates through the nonlinear head.')
    L.append('- **`fsc` / `fsh`**: the fixed-sweep solver (adaptive LM on the first 3 steps, then one LM sweep per step) for '
             'the span (with the cached predictor) and for the head.')
    L.append('- **dt**: the reduced model\'s backward-Euler step (the reference uses 0.005).')
    L.append('- **worst / median %**: over cases, the largest relative error at t = 0.05…0.25, normalised by the initial field.')
    L.append('- **ms**: median GPU time of one query (dense initial field on the GPU → six dense output fields).')
    L.append('- **FOM**: Newton–BiCGStab with the exact Helmholtz preconditioner, named by its step, Newton tolerance and '
             'linear tolerance.')
    L.append('- **Paper-rule speedup / own-matched speedup**: FOM time over the setting\'s time, with the FOM matched to the '
             'accurate setting / to that setting.')
    L.append('- **ρ**: the tensor rule\'s relative error in the tested advection on reached states; confirmed if ≤ 0.116 '
             'on every certification draw.')
    L.append('- **Validation / held-out**: 64 cases used to choose settings / 32 sealed cases opened once.')
    L.append('- **Lane success**: both frozen settings eligible on held-out, fast ≤ 5 %, both paper-rule speedups > 1, all gates.')
    L.append('- **A–B–A / gates**: ROM, FOM, ROM timing blocks in one job; drift and two-sided neighbour ratios within 1.10; '
             'timed outputs equal the untimed run.')
    out = HERE / 'reports' / f'{a.date}-burgers3d-retry-accuracy-speed.md'
    out.parent.mkdir(exist_ok=True)
    out.write_text('\n'.join(L) + '\n')
    sj = HERE / 'reports' / 'summary.json'
    sj.write_text(json.dumps(summary, indent=1) + '\n')
    print(out, hashlib.sha256(sj.read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
