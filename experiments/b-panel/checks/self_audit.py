"""Written self-audit standing in for the Codex report audit (quota exhausted until 2026-09-19 11:33).

    python checks/self_audit.py --audit runs/<a>/audit.json ... --recheck checks/<a>-recheck.json ...
        --out reports/self-audit-<what>.md

Every claim the report makes is listed with the JSON field it rests on and the check that was run
against it. Numbers are read from the JSONs, never typed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def f(x, d=4):
    return 'n/a' if x is None else (f'{x:.{d}f}' if isinstance(x, float) else str(x))


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--audit', nargs='+', required=True)
    p.add_argument('--recheck', nargs='+', default=[])
    p.add_argument('--out', required=True)
    a = p.parse_args()
    L = []
    W = L.append
    W('# Self-audit of the b-panel report (Codex substitute)\n')
    W('The lane protocol asks for an independent Codex audit of the final report against the raw JSONs. '
      'The account quota is exhausted until 2026-09-19 11:33 (DESIGN.md §A1, coordinator notice), so this '
      'file substitutes for it: every claim, the JSON field it rests on, and the check run against it. '
      'It is generated by `checks/self_audit.py`; no number in it is typed by hand.\n')
    rech = {}
    for r in a.recheck:
        j = json.loads(Path(r).read_text())
        rech[j.get('job_id') or Path(r).name] = (Path(r).name, j)
    for path in a.audit:
        au = json.loads(Path(path).read_text())
        digest = hashlib.sha256(Path(path).read_bytes()).hexdigest()[:16]
        W(f"## {au['intervals']}² — job `{au['job_id']}`, attempt `{au['attempt']}`, `{au['gpu']}`\n")
        W(f"Audit file `{Path(path).name}` (SHA256 `{digest}…`), driver result SHA256 `{au['result_sha256'][:16]}…`.\n")
        red = [x for x in au['arms'] if x['family'] in ('rom', 'fast', 'pod', 'free') and x['admissible']]
        nd = au['nondominated']['gpu_evolved']
        nred = [x for x in red if x['arm'] in set(nd['admissible'])]
        best = min(red, key=lambda z: z['worst_evolved_percent']) if red else None
        eq = [x for x in au['arms'] if x['quadrature'] == 'eq']
        rows = [
            ('every gate passed', 'checks[*].passed, failed',
             f"{sum(1 for v in au['checks'].values() if isinstance(v, dict) and v.get('passed') is True)} passed, "
             f"{sum(1 for v in au['checks'].values() if isinstance(v, dict) and v.get('passed') is None)} not applicable "
             f"(no two rule sets share a file; no cross-job comparator at this mesh), "
             f"{sum(1 for v in au['checks'].values() if isinstance(v, dict) and v.get('passed') is False)} failed; "
             f"audit failed-list = {au['failed'] or 'none'}",
             'recomputed by audit_panel.py from the saved fields, not read from the driver verdict'),
            ('the backend was a GPU', "checks['backend_gpu']",
             str((au['checks'].get('backend_gpu') or {}).get('detail')),
             'the job asserts jax_backend=gpu in the preflight or exits 42'),
            ('no subject was dropped', 'dropped', f"{len(au['dropped'])} dropped",
             'the OOM-drop rule records every drop; an empty list means every declared subject was timed'),
            ('reduced subjects on the admissible frontier', "nondominated.gpu_evolved.admissible",
             f"{len(nred)} of {len(red)} reduced subjects: {', '.join(x['arm'] for x in nred) or 'none'}",
             'domination recomputed in audit_panel.nondominated over (median_gpu_ms, worst_evolved_percent)'),
            ('most accurate reduced subject', 'arms[*].worst_evolved_percent',
             f"{best['arm']} at {f(best['worst_evolved_percent'])} % and {f(best['median_gpu_ms'], 1)} ms" if best else 'none',
             'minimum over admissible reduced arms; errors recomputed from the saved fields'),
            ('rule sets carried', 'rules[*].rule_set',
             ', '.join(sorted({str(x.get('rule_set') or x.get('kind')) for x in au.get('rules', [])})) or 'none',
             'each rule file SHA256 is checked against inputs/PROVENANCE.json in-job'),
            ('EQ arms whose construction is not confirmed', 'arms[*].rule_status',
             ', '.join(f"{x['arm']} ({x['rule_status'] or 'blank'})" for x in eq
                       if not str(x.get('rule_status') or '').startswith('confirmed')) or 'none',
             'the status travels from the exporting lane\'s PROVENANCE.json into every row and caption'),
        ]
        for name, lad in au['ladders'].items():
            if lad:
                rows.append((f'ladder `{name}` monotone on evolved times', f"ladders.{name}.monotone_evolved",
                             f"{lad['monotone_evolved']} ({' → '.join(f(v) for v in lad['worst_evolved_percent'])})",
                             'monotonicity recomputed from the audited per-rung errors'))
        for t in au.get('transfer', []):
            rows.append((f"transferred rule q = {t['q']} certification", 'transfer[*].certification',
                         f"ρ max {f(t['certification']['rho_max'])}, ρ 95 {f(t['certification']['rho_p95'])}, "
                         f"basis {t['basis']}, {t['fit_states_used']} fit states",
                         'certified in-job on held-out reachable states disjoint from the fit set and the cases'))
        key = str(au['job_id'])
        if key in rech:
            fn, j = rech[key]
            rows.append(('second independent code path agrees', f'`{fn}`',
                         f"worst relative difference against the audit {j.get('worst_relative_difference_against_audit')}, agrees = {j.get('agrees_with_audit')}",
                         'checks/recheck_headline.py imports neither audit_panel.py, the driver, nor JAX'))
        W('| claim | JSON field | value | check |')
        W('|---|---|---|---|')
        for r in rows:
            W('| ' + ' | '.join(str(c).replace('|', '\\|') for c in r) + ' |')
        W('')
    Path(a.out).write_text('\n'.join(L) + '\n')
    print('WROTE', a.out)


if __name__ == '__main__':
    main()
