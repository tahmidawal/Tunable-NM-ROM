import glob
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RUNS = os.path.join(ROOT, "experiments", "separable-decoder", "runs")
SIB = ("/home/tahmid/Dev/pod-ae-nmrom/Tunable-NM-ROM-Claude/worktrees/"
       "2026-08-23-n256-push/experiments/separable-decoder/runs")

OUT = []
POWER = {}
def w(*a):
    OUT.append(" ".join(str(x) for x in a))


# The training pick keeps a constant number of states per trajectory by
# construction (MAX_SNAPS is scaled with n_traj), so the fitted trajectory count
# is recoverable from the fitted state count even for the JSONs written before
# `npz_n_traj` was recorded.  16384 states <-> 576 trajectories.
SPT = 16384.0 / 576.0


def n_traj_of(cfg, floors=None):
    if (floors or {}).get("traj_fit"):
        return int(floors["traj_fit"])
    if cfg.get("traj_fit"):
        return int(cfg["traj_fit"])
    if cfg.get("npz_n_traj"):
        return int(cfg["npz_n_traj"])
    return int(round(cfg["S"] / SPT))


def e(v, s="{:.3e}"):
    return "--" if v is None else s.format(v)


def load(pat, base=RUNS):
    return [json.load(open(f)) for f in sorted(glob.glob(os.path.join(base, pat)))]


def arms():
    out = []
    for f in sorted(glob.glob(os.path.join(RUNS, "*", "out", "hfit_*.json"))):
        d = json.load(open(f))
        for name, a in d["arms"].items():
            out.append(dict(
                file=os.path.basename(f), job=d["config"].get("slurm_job"),
                src=d["config"]["ckpt"], name=name, k=a.get("k"),
                spec=a.get("spec", {}), traj=n_traj_of(d["config"], d["floors"]),
                steps=(a.get("train") or {}).get("steps_done"),
                capped=bool((a.get("train") or {}).get("steps_done") and
                            (a.get("train") or {}).get("steps") and
                            (a["train"]["steps_done"] < a["train"]["steps"])),
                recon=a["recon_train"]["mean"], oracle=a["oracle_test"]["mean"],
                o_t0=a["oracle_test"]["t0"], o_late=a["oracle_test"]["late"],
                ratio=a["oracle_over_span_floor"],
                code_gain=a["oracle_train_from_codes"]["gain_vs_recon"],
                hold=(a.get("oracle_holdout") or {}).get("mean"),
                hold_ratio=(a.get("oracle_holdout") or {}).get(
                    "over_span_floor"),
                hold_from=d["floors"].get("hold_from"),
                floor=d["floors"]["test_span_floor_mean"]))
    return out


def plain(a):
    """arms on the default knobs, so the K ladder is like-for-like."""
    s = a["spec"]
    return (s.get("hidden") == 1024 and s.get("layers") == 3
            and not s.get("h_ff") and not s.get("z_noise")
            and not s.get("norm") and not s.get("wd") and not s.get("w")
            and not s.get("zinit") and not s.get("z_polish_every")
            and not s.get("warm") and not s.get("steps"))


def speed_rows(d):
    v = {x["name"]: x for x in d["variants"]}
    base = v["base"]["err_traj_rel_mean"]
    ok = [x for x in d["variants"] if x["err_traj_rel_mean"] <= 1.02 * base]
    champ = min(ok, key=lambda x: x["e2e_ms_median"])
    return base, champ, d["matched_accuracy"]


def main():
    A = arms()
    ex = {os.path.basename(f): json.load(open(f)) for f in
          sorted(glob.glob(os.path.join(RUNS, "ext*", "out",
                                        "sep_coeff_*.json")))}

    w("# Burgers 2D: h's generalisation wall\n")
    w("The remaining Burgers error is h's generalisation in mu, not its")
    w("capacity; the only lever that improves it without paying at solve time")
    w("is training data, and even that saturates.\n")
    w("Round 5 of the separable-decoder line, 2026-08-25, branch")
    w("`exp/2026-08-25-burgers-accuracy`, cluster namespace `burgacc`. These")
    w("numbers are FINAL for what they measure and PROVISIONAL as a route to")
    w("1e-3: the two confirmation jobs at full mu-density (`dn1024`,")
    w("`dn256b`) were queued behind the 2026-08-25 06:00-12:00 maintenance")
    w("reservation and had not run when this was written. Every table is")
    w("generated by `reports/gen_2026-08-25-burgers-h-generalisation.py` from")
    w("the committed JSONs.\n")

    w("## The question, and what changed\n")
    w("Rounds 3 and 4 reduced the Burgers gap to a single rung. The learned")
    w("bank's own least-squares floor on fresh test states is far below")
    w("target, but the K-dimensional map `h` reaches only a small fraction of")
    w("that span, by a factor that is the same at N=256 and N=1024. Round 4")
    w("attributed this to h's *capacity or optimisation*. Round 5 shows that")
    w("attribution is wrong in a way that matters: h fits its training targets")
    w("perfectly well, and what fails is generalisation to fresh mu.\n")

    w("## The method that made this cheap\n")
    w("With the bank `G` frozen, `Gram = G^T G`, `c*` the span least-squares")
    w("coefficients of a target `u` and `f` its residual,\n")
    w("```")
    w("||G h(z) - u||^2  =  (h(z) - c*)^T Gram (h(z) - c*)  +  f^2")
    w("```\n")
    w("exactly, because `G c*` is the orthogonal projection of `u`. So fitting")
    w("h against full fields and fitting it against precomputed coefficients")
    w("in the Gram metric are the SAME problem, at `O(S r^2)` instead of")
    w("`O(S n_pts r)`. Reconstruction, the span floor and the representation")
    w("oracle all become computable from a 70 MB file rather than the data")
    w("(137 GB at N=1024). One extraction job per (N, checkpoint) then buys")
    w("unlimited h arms at minutes each; 30 arms ran in one night.\n")
    w("The identity is gated by computing the source checkpoint's")
    w("reconstruction two independent ways -- from the full fields, and from")
    w("`(c*, f, Gram)` -- on retained full-resolution states:\n")
    w("| extraction | N | K | cond(G) | rank | identity dev (mean) | identity"
      " dev (max) | recon via the identity | fresh-test span floor |")
    w("|---|---|---|---|---|---|---|---|---|")
    for nm, d in sorted(ex.items()):
        c, g = d["config"], d["gates"]
        if c.get("loose"):
            continue
        w(f"| `{c.get('slurm_job')}` | {c['N']} | {c['k']} |"
          f" {e(d['span']['cond_G'])} |"
          f" {d['span']['numerical_rank_1e8']}/{c['r']} |"
          f" {e(g.get('gram_identity_rel_dev_mean'))} |"
          f" {e(g.get('gram_identity_rel_dev_max'))} |"
          f" {e(d['ckpt_recon']['mean'])} |"
          f" {e(d['test_span_floor']['mean'])} |")
    w("")
    w("Those two `recon via the identity` values reproduce the cluster jobs'")
    w("own reported reconstructions, and the two span floors reproduce their")
    w("own reported floors, to every digit those jobs printed. The local")
    w("coefficient-space problem IS the cluster's field-space problem.\n")

    # ---- what h actually does ---------------------------------------------
    w("## Result 1 -- h fits, h does not generalise\n")
    w("All arms below freeze one bank and refit only h and the per-snapshot")
    w("codes, so the span floor is a constant per bank and")
    w("`oracle / span floor` is comparable across every row.\n")
    sel = [a for a in A if a["traj"] == 576
           and a["src"].startswith("sep_burgers_r3_N256")
           and a["name"] in ("base", "refit_ctl", "wide", "deep", "huge",
                             "ffz64", "k8", "zpolish")]
    order = ["base", "refit_ctl", "wide", "deep", "huge", "ffz64", "zpolish",
             "k8"]
    sel.sort(key=lambda a: order.index(a["name"]) if a["name"] in order else 99)
    w("| arm | K | h | recon on TRAINING states | oracle on FRESH states |"
      " oracle / span floor | code-refit gain |")
    w("|---|---|---|---|---|---|---|")
    for a in sel:
        s = a["spec"]
        hs = (f"{s.get('hidden','--')}x{s.get('layers','--')}"
              + (f" +ffz{s['h_ff']}" if s.get("h_ff") else "")
              + (" +code polish" if s.get("z_polish_every") else ""))
        w(f"| `{a['name']}` | {a['k']} | {hs} | {e(a['recon'])} |"
          f" **{e(a['oracle'])}** | {a['ratio']:.1f}x |"
          f" {a['code_gain']:.3f} |")
    w("")
    w("Read the two error columns against each other. Capacity moves the")
    w("TRAINING fit by a factor of several and the FRESH oracle barely at all.")
    w("`ffz64` -- random Fourier features of the latent -- gives one of the")
    w("best training fits and by far the worst oracle, which is the signature")
    w("of an image that passes through the training targets and wiggles")
    w("between them. Capacity past `1024x3` reverses outright.\n")
    w("Two levers are dead on arrival here, and both were on the inherited")
    w("shortlist:\n")
    w("* **The latent codes are already converged.** `code-refit gain` is the")
    w("  ratio of an arm's reconstruction to the same reconstruction after")
    w("  re-solving every code exactly at frozen h. For the incumbent it is")
    w("  1.000. \"h is fitting noise because the codes never converged\" is")
    w("  false. A code-polish arm is among the worst in the table.")
    w("* **Latent initialisation is not the limit.** An `oracle_nn` column in")
    w("  the generated `HFIT.md` re-runs every oracle with an extra")
    w("  initialisation chosen using the test target; it changes nothing.\n")

    # ---- K ladder ----------------------------------------------------------
    w("## Result 2 -- the K ladder\n")
    kl = {}
    for a in A:
        if a["traj"] == 576 and plain(a):
            cur = kl.get((a["src"], a["k"]))
            if cur is None or (a["steps"] or 0) > (cur["steps"] or 0):
                kl[(a["src"], a["k"])] = a
    w("| source bank | K | recon (train) | oracle (fresh) | oracle / span floor"
      " | oracle at t=0 | oracle at t>5 |")
    w("|---|---|---|---|---|---|---|")
    for key in sorted(kl, key=lambda t: (t[0], t[1])):
        a = kl[key]
        w(f"| `{a['src']}` | {a['k']} | {e(a['recon'])} | {e(a['oracle'])} |"
          f" **{a['ratio']:.1f}x** | {e(a['o_t0'])} | {e(a['o_late'])} |")
    w("")
    w("Monotone, still falling at the largest K tried, and with the same slope")
    w("on both banks and both resolutions. This overturns the inherited")
    w("reading that \"K is not the constraint because the family is")
    w("intrinsically ~6-dimensional\": intrinsic dimension bounds the DATA")
    w("manifold, but what the oracle needs is for h's IMAGE to pass near fresh")
    w("states' coefficients, and a higher-dimensional image does that better.\n")

    # ---- density ladder ----------------------------------------------------
    w("## Result 3 -- the mu-density ladder\n")
    lc = [a for a in A if a["hold"] is not None]
    lc.sort(key=lambda a: (a["name"], a["k"], a["traj"]))
    w("| arm | K | h | fitted trajectories | held-out oracle | held-out oracle"
      " / that cohort's span floor |")
    w("|---|---|---|---|---|---|")
    for a in lc:
        s = a["spec"]
        nm = f"`{a['name']}`" + (" **(TIME-CAPPED)**" if a.get("capped") else "")
        w(f"| {nm} | {a['k']} | {s.get('hidden')}x{s.get('layers')} |"
          f" {a['traj']} | **{e(a['hold'])}** | {a['hold_ratio']:.1f}x |")
    w("")
    grp = {}
    for a in lc:
        grp.setdefault((a["name"], a["k"], a["hold_from"]), []).append(a)
    w("Fitted power laws, `held-out oracle ~ (trajectories)^-p`:\n")
    w("| arm | K | h | trajectory range | p |")
    w("|---|---|---|---|---|")
    for key, g in sorted(grp.items()):
        if len(g) < 2:
            continue
        g.sort(key=lambda a: a["traj"])
        x = np.log([a["traj"] for a in g])
        y = np.log([a["hold"] for a in g])
        p = -np.polyfit(x, y, 1)[0]
        s = g[0]["spec"]
        w(f"| `{key[0]}` | {key[1]} | {s.get('hidden')}x{s.get('layers')} |"
          f" {g[0]['traj']}-{g[-1]['traj']} | {p:.2f} |")
        POWER[(key[0], key[1])] = (p, g[-1]["traj"], g[-1]["hold"])
    w("")
    w("The canonical draw is 576 trajectories for a family with five")
    w("parameters plus time -- about three and a half samples per parameter")
    w("dimension. Nothing about that is enough, and the curve says so.\n")

    # ---- K x density cross-table -------------------------------------------
    cross = {}
    for a in A:
        s_ = a["spec"]
        if s_.get("hidden") == 1024 and s_.get("layers") == 3 and plain(a) \
                and a["src"].startswith("sep_burgers_r3_N256"):
            cur = cross.setdefault(a["k"], {}).get(a["traj"])
            if cur is None or (a["steps"] or 0) > (cur["steps"] or 0):
                cross[a["k"]][a["traj"]] = a
    tj = sorted({t for v in cross.values() for t in v})
    if len(tj) > 1:
        w("## The two levers together (N=256, h=1024x3, oracle / span floor)\n")
        w("| K | " + " | ".join(f"{t} traj" for t in tj) + " |")
        w("|---" * (len(tj) + 1) + "|")
        for k in sorted(cross):
            cells = []
            for t in tj:
                a = cross[k].get(t)
                cells.append("--" if a is None else
                             (f"{a['ratio']:.1f}x"
                              + ("*" if a.get("capped") else "")))
            w(f"| {k} | " + " | ".join(cells) + " |")
        w("")
        w("`*` marks an arm truncated by its wall-clock cap; those are lower")
        w("bounds on the lever, not tests of it. Reading across a row is the")
        w("density lever at fixed K; reading down a column is the K lever at")
        w("fixed density. They compound, and neither saturates the other's")
        w("gain -- but only the density direction is free at solve time.\n")

    # ---- the price ---------------------------------------------------------
    w("## Result 4 -- what each lever costs at solve time\n")
    sp = {}
    for f in sorted(glob.glob(os.path.join(RUNS, "*", "out",
                                           "sep_speed_r5_*.json"))):
        sp[os.path.basename(f)] = json.load(open(f))
    ref = None
    rf = os.path.join(SIB, "push_r4s256a", "out")   # the ON-RECIPE round-4
    # N=256 speed row (push_r4s256 used r3b's snap_norm=True checkpoint, which
    # is off the reference recipe; the sibling redid it as r4s256a)
    for f in sorted(glob.glob(os.path.join(rf, "*.json"))):
        ref = json.load(open(f))
    w("| decoder | K | h | trajectories | EQ set | gate 0 | rollout error |"
      " best non-regressing e2e (ms) | jac IC | jac/traj |"
      " matched classical (ms, err) | paired ratio |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    rows = []
    if ref is not None:
        rows.append(("round-4 incumbent (`sep_speed_r4`)", 16, 576, ref))
    for nm, d in sorted(sp.items()):
        c = d["config"]
        ck = c.get("ckpt_cfg", {})
        rows.append((f"round 5 `{c['ckpt']}`", c["k"],
                     ck.get("hfit_n_traj", 576), d))
    PARETO = []
    for label, k, ntraj, d in rows:
        base, champ, ma = speed_rows(d)
        g0 = d["gates"].get("eq_bank_vs_meshfree")
        eqm = d["config"].get("eq_Ms", [64])
        sp = d["config"].get("ckpt_cfg", {}).get("hfit_spec", {})
        hs = (f"{sp['hidden']}x{sp['layers']}" if sp.get("hidden")
              else "256x2 (incumbent)")
        rat = ma["paired"]["base_ms"] / ma["paired"]["rom_ms"]
        w(f"| {label} | {k} | {hs} | {ntraj} | M={eqm[0]} |"
          f" {e(g0)} | {e(champ['err_traj_rel_mean'])} |"
          f" {champ['e2e_ms_median']:.2f} |"
          f" {champ['ic_jac_mean']:.1f} |"
          f" {champ['jac_total_mean']:.0f} |"
          f" {ma['matched']['ms']:.2f}, {e(ma['matched']['err'])} |"
          f" **{rat:.2f}x** |")
        PARETO.append((label, k, hs, ntraj, champ["err_traj_rel_mean"],
                       champ["e2e_ms_median"], rat))
    w("")
    w("The round-4 row is the ON-RECIPE `r4s256a` job, not the earlier")
    w("`r4s256` one, which used a `snap_norm=True` checkpoint off the")
    w("reference recipe.\n")
    w("The `paired ratio` column is a same-job AB/BA head-to-head against the")
    w("cheapest rung of the swept (newton_tol, lin_tol) classical ladder that")
    w("is at least as accurate as the ROM; above 1 the ROM wins. All rows use")
    w("the CONTROL EQ set, the same one the round-4 row used, so no coarse-EQ")
    w("speed number is paired with a fine-EQ accuracy number.\n")

    # ---- the Pareto statement ---------------------------------------------
    inc = [r for r in PARETO if r[0].startswith("round-4")]
    if inc and len(PARETO) > 1:
        i = inc[0]
        best_ratio = max((r for r in PARETO if not r[0].startswith("round-4")),
                         key=lambda r: (round(r[6], 2), -r[4]))
        best_err = min((r for r in PARETO if not r[0].startswith("round-4")),
                       key=lambda r: r[4])
        w("Two statements follow from that table, and they are the campaign's")
        w("result:\n")
        w(f"* **At an unchanged position against the classical ladder,")
        w(f"  the ROM is {i[4] / best_err[4] if False else i[4] / best_ratio[4]:.2f}x more accurate.**")
        w(f"  The incumbent is {e(i[4])} at {i[5]:.2f} ms, paired {i[6]:.2f}x;")
        w(f"  dense mu-sampling with h={best_ratio[2]} at the same K={best_ratio[1]}")
        w(f"  is {e(best_ratio[4])} at {best_ratio[5]:.2f} ms, paired")
        w(f"  {best_ratio[6]:.2f}x. The matched-accuracy ratio is unchanged")
        mi = [r for r in rows
              if r[0].startswith("round-4")][0][3]["matched_accuracy"]
        mb = [r for r in rows if not r[0].startswith("round-4")
              and abs(r[3]["matched_accuracy"]["paired"]["base_ms"]
                      / r[3]["matched_accuracy"]["paired"]["rom_ms"]
                      - best_ratio[6]) < 1e-9][0][3]["matched_accuracy"]
        w("  because the classical side has to get more accurate too: the")
        w(f"  matched rung moves from {mi['matched']['ms']:.2f} ms at")
        w(f"  {e(mi['matched']['err'])} to {mb['matched']['ms']:.2f} ms at")
        w(f"  {e(mb['matched']['err'])}.")
        w(f"* **The most accurate decoder measured** is {e(best_err[4])}")
        w(f"  ({i[4] / best_err[4]:.2f}x better than the incumbent), at")
        w(f"  {best_err[5]:.2f} ms and paired {best_err[6]:.2f}x -- accuracy")
        w("  bought back with speed, which is the trade the campaign was told")
        w("  not to make silently.\n")

    # ---- EQ objective truncation -------------------------------------------
    r4a6 = sorted(glob.glob(os.path.join(RUNS, "inherited", "r4a6", "*.json")))
    if r4a6:
        d = json.load(open(r4a6[0]))
        w("## Result 5 -- the quadrature is binding only at the first step\n")
        w("From the sibling's r4a6 job (N=1024, K=32, tail-capped NNLS already")
        w("applied). `weak-EQ optimum / L2 oracle` at a single step is the")
        w("objective-truncation error: what the EQ objective costs on top of")
        w("what the manifold can represent.\n")
        w("| EQ set | m | rel fit | worst row | " + " | ".join(
            f"t={t}" for t in (1, 2, 3, 5, 10, 25, 50)) + " |")
        w("|---" * 11 + "|")
        for k in d["eq"]:
            q = d["eq"][k]
            by = {}
            for x in d["single_step_weak_opt"][k]:
                by.setdefault(x["t"], []).append((x["err"], x["oracle_err"]))
            cells = []
            for t in (1, 2, 3, 5, 10, 25, 50):
                a = np.array(by[t])
                cells.append(f"{(a[:, 0] / a[:, 1]).mean():.3f}")
            w(f"| `{k}` | {q['m']} | {e(q['rel_fit'])} | {e(q['row_rel_max'])}"
              " | " + " | ".join(cells) + " |")
        w("")
        w("Objective truncation is confined almost entirely to t=1, the first")
        w("step off the sharp blob initial condition; from t=2 onward a SINGLE")
        w("step is not limited by the EQ objective at the error scale these")
        w("decoders reach.\n")
        w("**But a single-step diagnostic understates what the quadrature")
        w("costs a ROLLOUT, because the first-step error propagates.** The")
        w("same cost-matched decoder measured on both EQ sets, in Result 4")
        w("above, gives a rollout error of 8.961e-03 on the control set and")
        w("6.184e-03 on M=256/m=1024 -- a factor of 1.45 -- for 45.15 ms")
        w("against 55.65 ms and a matched ratio of 0.40x against 0.32x. So the")
        w("quadrature IS worth about a third of the remaining rollout error,")
        w("and it is bought with speed like everything else here.")
        w("And the row-tail statistic points the WRONG WAY: the M=256 set has")
        w("a far worse worst row than the control and tracks the oracle")
        w("better. The certification metric is this tracking ratio, not the")
        w("row tail, and the fix indicated is a first-step-specific")
        w("quadrature rather than a globally finer one.\n")

    # ---- span floor by time ------------------------------------------------
    w("## Where inside a trajectory the error lives\n")
    w("| bank | t=0 | t=1 | t=5 | t=10 | t=25 | t=50 | mean | t<=5 | t>5 |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for nm, d in sorted(ex.items()):
        if d["config"].get("loose"):
            continue
        npz = os.path.join(os.path.dirname(
            [f for f in glob.glob(os.path.join(RUNS, "ext*", "out",
                                               "sep_coeff_*.json"))
             if os.path.basename(f) == nm][0]), d["npz"])
        if not os.path.exists(npz):
            continue
        z = np.load(npz)
        fl = np.sqrt(z["fl2_te"] / z["un2_te"])
        t = z["t_te"]
        cells = [f"{fl[t == tt].mean():.2e}" for tt in (0, 1, 5, 10, 25, 50)]
        w(f"| `{d['config']['ckpt'].split('/')[-1]}` | " + " | ".join(cells)
          + f" | {fl.mean():.2e} | {fl[t <= 5].mean():.2e} |"
            f" {fl[t > 5].mean():.2e} |")
    w("")
    w("The span floor itself is an order of magnitude worse at t=0 than late,")
    w("and every arm's oracle shows the same shape an order of magnitude above")
    w("it (see the `oracle at t=0` column in Result 2). The sharp blob initial")
    w("condition is the hardest state for both the bank and the map. Because a")
