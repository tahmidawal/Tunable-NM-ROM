"""results/tables.md from the lane's JSONs (no hand-typed numbers except the stored comparison rows, which are read
from the nfrom-baseline lane's test.json and the PROTOCOL section 7 constants with their sources).

  report.py --lane DIR --nfrom-test PATH
"""
import argparse, glob, json, os

PAPER = [  # PROTOCOL.md section 7 (stored rows; sources in nfrom-baseline reports/tables.md)
    ("paper span R'=384 (job 4319328)", 0.875, 0.026, 45.2),
    ("paper span R'=96", 3.846, 0.529, 14.2),
    ("paper head k=16 (job 4327396)", 4.097, 0.672, 32.4),
]


def fmt(x, d=3):
    return '-' if x is None else (f'{x:.{d}f}' if abs(x) < 1000 else f'{x:,.0f}')


def main():
    a = argparse.ArgumentParser(); a.add_argument('--lane'); a.add_argument('--nfrom-test'); a = a.parse_args()
    R = os.path.join(a.lane, 'results')
    lines = ['# Official CROM and CoLoRA on Burgers 2D 256: test64 tables', '',
             'Generated by `code/report.py` from `results/test/*.json`, `results/selection.json`, `results/train/*`. '
             'Metric: per case max over t=0.05..0.25 of |u-u_ref|_2/|u0|_2; worst and median over the 64 test cases (%). '
             'Time: batch-1 query on A100 80GB, median (ms).', '',
             '## Test cohort (64 cases)', '', '| row | precision | worst % | median % | ms/query (median) | p5-p95 ms | timing schedule | validation worst % |',
             '|---|---|---|---|---|---|---|---|']
    rows = []
    for f in sorted(glob.glob(os.path.join(R, 'test', '*.json'))):
        d = json.load(open(f))
        for r in d['results']:
            s = r['selection']
            if 'arm' in s:
                name = f"official CROM-{s['arm']} {s['name']} {s['setting']} ({s['role']})"
            else:
                name = f"official CoLoRA-D {s['name']} k={s['k']} ({s['role']})"
            rows.append((name, s['dtype'], r['test']['worst_percent'], r['test']['median_percent'], r['ms_full']['median'],
                         f"{fmt(r['ms_full']['p5'], 1)}-{fmt(r['ms_full']['p95'], 1)}", f"{r['timing_warmup']} warm-up, {r['timing_repetitions']} rep", s['worst_percent'],
                         d.get('job_id'), d.get('gpu')))
    for x in rows:
        lines.append(f'| {x[0]} | {x[1]} | {fmt(x[2])} | {fmt(x[3])} | {fmt(x[4], 1)} | {x[5]} | {x[6]} | {fmt(x[7])} |')
    lines += ['', 'Jobs / GPUs: ' + '; '.join(sorted({f'{x[8]} ({x[9]})' for x in rows})), '',
              '## Comparison rows (same cohort, metric, GPU type; stored)', '', '| row | worst % | median % | ms/query |', '|---|---|---|---|']
    if a.nfrom_test and os.path.exists(a.nfrom_test):
        for r in json.load(open(a.nfrom_test))['results']:
            s = r['selection']
            lines.append(f"| re-implementation {s['arm']}-style k={s['k']} {s['role']} ({s['dtype']}) | {fmt(r['test']['worst_percent'])} | {fmt(r['test']['median_percent'])} | {fmt(r['ms_full']['median'], 1)} |")
    for p in PAPER:
        lines.append(f'| {p[0]} | {fmt(p[1])} | {fmt(p[2])} | {fmt(p[3], 1)} |')
    sel = json.load(open(os.path.join(R, 'selection.json')))
    lines += ['', '## Validation (32 trajectories), every setting run', '', '| method | config | arm/setting | precision | complete | worst % | median % | rough ms |', '|---|---|---|---|---|---|---|---|']
    for r in sel['all_crom_validation_rows']:
        lines.append(f"| CROM | {r['name']} | {r['arm']} {r['setting']} | {r['dtype']} | {r['complete']} ({r['cases'][1]-r['cases'][0]}) | {fmt(r['worst_percent'])} | {fmt(r['median_percent'])} | {fmt(r['rough_ms'], 1)} |")
    for r in sel['all_colora_validation_rows']:
        lines.append(f"| CoLoRA-D | {r['name']} (k={r['k']}) | hyper-network | {r['dtype']} | True (32) | {fmt(r['worst_percent'])} | {fmt(r['median_percent'])} | {fmt(r['rough_ms'], 1)} |")
    lines += ['', '## Offline training', '', '| run | steps | GPU | wall h | notes |', '|---|---|---|---|---|']
    for f in sorted(glob.glob(os.path.join(R, 'train', '*.json'))):
        t = json.load(open(f))
        lines.append(f"| {t.get('name')} | {t.get('steps')} | {t.get('gpu')} | {fmt(t.get('train_seconds', 0) / 3600, 2)} | {t.get('notes', '')} |")
    open(os.path.join(R, 'tables.md'), 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
