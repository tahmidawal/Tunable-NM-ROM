"""Generate the burgers-repanel report from the audit summaries. No number in the report is typed by hand.

    python reports/generate_report.py            # -> reports/2026-09-22-burgers-repanel.md + reports/summary.json

Reads every `checks/br*-summary.json` that exists and writes one report; meshes that have not landed are
listed as outstanding rather than omitted silently.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANE = HERE.parent
ROLE_LABEL = {
    'optimised_accurate': 'NM-ROM accurate, optimised path',
    'optimised_fast': 'NM-ROM fast ($q=0$), optimised path',
    'preoptimisation_accurate': 'accurate, PRE-optimisation (the arm the paper prints)',
    'preoptimisation_fast': 'fast, PRE-optimisation (the arm the paper prints)',
    'optimised_on_the_papers_own_rule': "accurate, optimised path on the paper's OWN quadrature rule",
}
ORDER = ['optimised_accurate', 'preoptimisation_accurate', 'optimised_on_the_papers_own_rule',
         'optimised_fast', 'preoptimisation_fast']


def f(x, n=2):
    return '—' if x is None else f'{x:,.{n}f}'


def main():
    subs = {}
    for p in sorted(LANE.glob('checks/br*-summary.json')):
        d = json.loads(p.read_text())
        subs[d['intervals']] = (d, p)
    out = ['# Burgers 2D at $256^2$, $512^2$ and $1024^2$: the panel re-timed on the solver path we actually use',
           '',
           'Status: **%s**. Generated by `reports/generate_report.py` from `checks/br*-summary.json` (independent '
           'NumPy audits of the saved fields); no number below is typed by hand. Design and gates: `DESIGN.md`.'
           % ('final' if len(subs) == 3 else f'partial — {len(subs)} of 3 meshes landed'), '']
    out += ['## How to read these numbers', '',
            'Each mesh below is ONE cluster job in ONE allocation. Within it, the NM-ROM arms, the '
            'pre-optimisation arm the paper currently prints, and the Newton--BiCGStab candidate grid were all '
            'timed against each other in a randomised, burn-separated, synchronised panel with five retained '
            'repetitions over six development cases, so every speedup is a single-job row ratio.', '',
            '**What this licenses:** the ratios *between arms of the same job*, and the statement that the '
            'optimised path reaches the same error as the pre-optimisation arm in less time.', '',
            '**What it does not license:** comparing an absolute millisecond figure here with one printed in the '
            'paper from a different job. The $1024^2$ pre-optimisation dense arm is the clearest case — it is the '
            'identical computation (its error matches the published value to 1.8e-13, see the tripwire) but it '
            'takes 68.7 s on this A100-80G against the 22.05 s b-panel job 3789572 printed. Same arithmetic, '
            'different hardware. That gap is exactly why the control was re-run inside this job instead of being '
            'quoted across jobs.', '',
            '**No retraining, no re-certification:** the frozen checkpoint, quadrature rules and cohorts of the '
            'existing panels are reused unchanged; rule certificates are carried verbatim from `burgers-eqcert` '
            'and are not re-derived here.', '']
    if not subs:
        out += ['No audited job has landed yet.', '']
    for L in sorted(subs, reverse=True):
        d, p = subs[L]
        v = d['verdict']
        out += [f'## ${L}^2$ — attempt `{d["attempt"]}`, job {d["job_id"]}, {d["gpu"]}, commit `{d["commit"]}`', '',
                'Cohort: %s (%d cases). Error convention: %s. Every number in this block comes from ONE job and '
                'ONE allocation; every speedup is that row\'s own FOM ms divided by that row\'s own ROM ms.'
                % (d['cohort'], d['cohort_cases'], v['error_convention']), '',
                '| role | arm | $m$ | worst evolved % | median evolved % | GPU ms | complete ms | FOM by the paper '
                'rule (full grid) | FOM GPU ms | FOM % | speedup GPU | speedup complete |',
                '|---|---|---|---|---|---|---|---|---|---|---|---|']
        for role in ORDER:
            r = v['rows'].get(role)
            if not r:
                continue
            out.append('| %s | `%s` | %s | %s | %s | %s | %s | `%s` | %s | %s | %s | %s |' % (
                ROLE_LABEL[role], r['arm'], r['m'], f(r['worst_evolved_percent'], 4),
                f(r['median_evolved_percent'], 4), f(r['rom_gpu_ms'], 2), f(r['rom_host_ms'], 2), r['fom'],
                f(r['fom_gpu_ms'], 2), f(r['fom_worst_evolved_percent'], 4), f(r['speedup_gpu'], 3),
                f(r['speedup_host'], 3)))
        out += ['', 'Same rows against the **b-panel candidate grid only** (the grid the paper\'s current rows were '
                    'selected from, audited implementation, no `lean` settings):', '',
                '| role | FOM | FOM GPU ms | speedup GPU |', '|---|---|---|---|']
        for role in ORDER:
            r = v['rows'].get(role)
            if not r or not r.get('by_grid'):
                continue
            g = r['by_grid'].get('b_panel', {})
            out.append('| %s | `%s` | %s | %s |' % (ROLE_LABEL[role], g.get('fom'), f(g.get('fom_gpu_ms'), 2),
                                                    f(g.get('speedup_gpu'), 3)))
        out += ['', '### Measured gain of the optimised solver path', '',
                '| comparison | pre-optimisation ms | optimised ms | ratio (GPU) | ratio (complete) | error before % | '
                'error after % |', '|---|---|---|---|---|---|---|']
        for g in v['optimisation_gain']:
            out.append('| %s | %s | %s | %s× | %s× | %s | %s |' % (
                g['label'], f(g['preoptimisation_gpu_ms'], 2), f(g['optimised_gpu_ms'], 2), f(g['gpu_ratio'], 2),
                f(g['host_ratio'], 2), f(g['preoptimisation_worst_evolved_percent'], 4),
                f(g['optimised_worst_evolved_percent'], 4)))
        pg = v['parity']
        out += ['', '### Parity gate', '',
                'Bar %g relative, with identical per-step iteration counts and stop reasons. **%s**' % (
                    pg['bar'], 'PASSED' if pg['passed'] else 'FAILED'), '',
                '| optimised arm | audited twin | worst relative | integers identical | passed |',
                '|---|---|---|---|---|']
        for x in pg['pairs']:
            out.append('| `%s` | `%s` | %.2e | %s | %s |' % (x['fast'], x['base'], x['worst_relative'],
                                                             x['integers_identical'], x['passed']))
        tw = d['gates'].get('reproduces_the_printed_error_of_the_paper_row', {})
        if tw.get('arms'):
            out += ['', '### Tripwire: does the pre-optimisation arm return the error the paper prints?', '',
                    'Where this job rebuilds the printed arm exactly — same mesh, cohort, quadrature rule, '
                    'tolerance and kernel — its error must come back at the published value. This is the check '
                    'that the lane is re-timing the *same setting* and not a different one.', '',
                    '| arm rebuilt here | paper arm (row) | printed % | measured % | relative difference | passes |',
                    '|---|---|---|---|---|---|']
            for x in tw['arms']:
                out.append('| `%s` | `%s` (row %s) | %.6f | %s | %s | %s |' % (
                    x['arm'], x['paper_arm'], x['row'], x['expected'],
                    ('%.6f' % x['got']) if x['got'] is not None else '—',
                    ('%.2e' % x['relative_difference']) if x.get('relative_difference') is not None else '—', x['ok']))
        oe = d['gates'].get('no_order_effect_between_arms', {})
        if oe:
            out += ['', '### Order effect inside the panel %s' % ('— **FAILS, reported as a finding**'
                                                                 if not oe['passed'] else '(passes)'), '',
                    'Every arm split by whether the invocation immediately before it took more or less than 1 s of '
                    'GPU time. Worst relative gap: **%.1f %%** (bar 5 %%). The randomised panel contains a '
                    'pre-optimisation arm three orders of magnitude slower than the optimised ones, and the 0.25 s '
                    'burn-in does not fully isolate it: an arm drawn straight after a long one runs measurably '
                    'slower. The rows above use the median over all repetitions; the arms whose split is based on '
                    'one or two samples are noise, but the large-sample ones are real.' % (100 * oe['worst_relative_difference']), '',
                    '| arm | median after a $\\ge 1$ s neighbour (ms) | n | median after a short one (ms) | n | gap |',
                    '|---|---|---|---|---|---|']
            for x in sorted(oe['per_arm'], key=lambda y: -y['relative_difference'])[:10]:
                out.append('| `%s` | %s | %d | %s | %d | %.1f %% |' % (
                    x['arm'], f(x['median_after_a_long_arm_ms'], 2), x['n_after_long'],
                    f(x['median_after_a_short_arm_ms'], 2), x['n_after_short'],
                    100 * x['relative_difference']))
        out += ['', '### Every timed arm', '',
                '| arm | family | worst evolved % | GPU ms | complete ms | stalled | FOM by rule | speedup |',
                '|---|---|---|---|---|---|---|---|']
        for n, t in sorted(d['table'].items(), key=lambda kv: (kv[1]['family'], kv[1]['median_gpu_ms'])):
            out.append('| `%s` | %s | %s | %s | %s | %s | `%s` | %s |' % (
                n, t['family'], f(t['worst_evolved_percent'], 4), f(t['median_gpu_ms'], 2), f(t['median_host_ms'], 2),
                t.get('stalled_exits', t.get('stalled_steps')), t.get('fom_by_paper_rule', ''),
                f(t.get('speedup_gpu'), 3)))
        out += ['', '### Quadrature-rule certificates (carried, not re-derived)', '']
        for k, s_ in (v.get('rule_status') or {}).items():
            out.append(f'- `{k}`: {s_}')
        out += ['', 'Audit gates: %s. Failed: %s.' % (
            ', '.join(f'{k}={x["passed"]}' + ('' if x.get('applicable', True) else ' (n/a)')
                      for k, x in d['gates'].items()), d['failed_gates'] or 'none'),
            '', f'Summary: `{p.relative_to(LANE)}`.', '']
    missing = [L for L in (1024, 512, 256) if L not in subs]
    if missing:
        out += ['## Outstanding', '', 'Not landed: ' + ', '.join(f'${L}^2$' for L in missing) +
                '. The paper\'s fallback for those meshes is its existing audited "confirmed rule" rows from '
                '`burgers-eqcert` (0.091× at $512^2$, 0.32× at $1024^2$).', '']
    out += ['## Glossary', '',
            '- **arm** — one complete, separately timed way of answering the same query: a reduced-order model at '
            'a given setting, or the full-order solver at a given tolerance.',
            '- **pre-optimisation arm** — the solver path the paper\'s current rows were timed on: LU on the damped '
            'normal matrix, no trust-radius clipping, no damping carry-over, no quadratic predictor, unfused '
            'residual and Jacobian.',
            '- **optimised path** — the same model with those five changes applied. Each was measured and '
            'parity-gated when it was introduced (`experiments/hires-burgers/SPEED-LOG.md`).',
            '- **$q$, $M$** — $q$ is the number of correction directions the reduced model carries; $M$ is the '
            'number of fixed weak test functions the residual is projected onto.',
            '- **$m$** — the number of quadrature nodes the empirical rule evaluates the advection at, out of the '
            '$(L-1)^2$ interior nodes of the mesh.',
            '- **quadrature rule** (`scaled`, `lat64`, `exact`) — which nodes and weights approximate the advection '
            'term. `scaled` transfers a fitted rule from $256^2$ with rescaled weights; `lat64` is a uniform '
            '$63\\times63$ sub-lattice with equal weights; `exact` uses every interior node (no rule).',
            '- **exact first step** (`_x1`) — the first time step uses the exact residual, the rest the rule.',
            '- **worst / median evolved %** — the relative error at the five evolved output times, measured against '
            'the full-order solution on the same mesh at tolerance $10^{-6}$; worst and median over the six '
            'development cases.',
            '- **GPU ms / complete ms** — GPU ms times the query with the input already on the GPU and the six '
            'outputs left there; complete ms adds the host upload of the input and the host copy of the outputs.',
            '- **the paper rule (FOM by the rule)** — the full-order comparator for a row is the *fastest* tested '
            'Newton–BiCGStab setting whose worst error is at least as small as that row\'s.',
            '- **b-panel grid / lean grid** — the two sets of full-order settings in play. The b-panel grid is the '
            'implementation the $256^2$–$1024^2$ rows were selected from; `lean` is the same discretisation and '
            'solver without a per-Newton diagnostic, used by the $2048^2$/$4096^2$ rows.',
            '- **parity gate** — an optimised arm that only changes the kernel or the matrix factorisation must '
            'reproduce the audited arm\'s field to $10^{-9}$ *and* take identical iterations. Arms that change the '
            'iterates by design (clipping, damping carry-over, predictor, exact first step) are not parity arms; '
            'they are judged on their directly measured error.',
            '- **stalled** — a step that exited on its budget, on a tiny step, or on a rejected trial step rather '
            'than on the convergence test. Any non-zero count is a warning.',
            '- **held-out $\\rho$** — the relative error the quadrature rule makes on states it was not fitted to; '
            'a rule is certified when it stays under the bar on every held-out draw. Certificates here are '
            'carried from the `burgers-eqcert` lane, not re-derived.', '']
    (HERE / '2026-09-22-burgers-repanel.md').write_text('\n'.join(out))
    (HERE / 'summary.json').write_text(json.dumps(
        {str(L): dict(attempt=d['attempt'], job_id=d['job_id'], commit=d['commit'], gpu=d['gpu'],
                      failed_gates=d['failed_gates'], verdict=d['verdict']) for L, (d, _) in subs.items()},
        indent=1) + '\n')
    print(HERE / '2026-09-22-burgers-repanel.md')


if __name__ == '__main__':
    main()
