# ------------------------------------------------ T7 nonlinear vs linear
print("\n### T7. What the nonlinearity buys: K nonlinear coefficients vs R linear modes\n")
fp = f"{PUSH}/runs/pod_floor/pod_floor_N256_burgers.json"
rp = f"{PUSH}/runs/push_r2_burgers/out/sep_burgers_r2_K16_R512.json"
if os.path.exists(fp) and os.path.exists(rp):
    import numpy as np
    sv = np.asarray(json.load(open(fp))["burgers"]["svals"], dtype=float)
    en = sv ** 2
    tot = en.sum()

    def pod_floor(R):
        return float(np.sqrt(max(en[R:].sum(), 0.0) / tot))

    rd = json.load(open(rp))
    K = int(rd["config"]["k"])
    recon = float(g(rd["train"], "recon_raw_mean", "final_rel_mse"))
    eq = [R for R in range(1, len(sv)) if pod_floor(R) <= recon]
    print(f"- trained **K={K}** separable decoder, reconstruction **{recon:.3e}** "
          f"(`{rel(rp)}`)")
    print(f"- linear **POD rank {K}** floor on the same family: **{pod_floor(K):.3e}** "
          f"({pod_floor(K)/recon:.1f}x worse)")
    print(f"- smallest linear POD rank matching that reconstruction: **{eq[0] if eq else 'n/a'}**")
    print(f"\n  => {K} nonlinear coefficients are worth about **{eq[0] if eq else '?'} "
          f"linear basis functions** on this family.")
