"""Build `runs/hybrid_points.json` (the flat output schema) and SUMMARY_TABLES.md
from the raw cell reports.  EVERY table in README.md is generated by this script;
none is hand-typed.

Usage: python wsf_summarize.py [runs_dir]
"""
from __future__ import annotations

import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "runs")

SCHEMA = ["pde", "N", "rom_tau", "fom_tau", "t_rom_ms", "t_decode_ms", "t_fom_ms",
          "t_total_ms", "t_fom_baseline_ms", "iters_from_rom", "iters_from_baseline",
          "err_rel_l2_rom", "err_final", "speedup_vs_fom", "seed", "gpu",
          "jax_backend", "commit"]


def load_reports():
    out = []
    for p in sorted(glob.glob(os.path.join(RUNS, "**", "*.json"), recursive=True)):
        if os.path.basename(p) == "hybrid_points.json":
            continue
        try:
            d = json.load(open(p))
        except Exception:
            continue
        if isinstance(d, dict) and "rows" in d and "provenance" in d:
            out.append((p, d))
    return out


def flat_points(reports):
    pts = []
    for p, d in reports:
        for r in d["rows"]:
            row = {k: r.get(k) for k in SCHEMA}
            # keep every extra diagnostic too -- the schema is the MINIMUM
            row.update({k: v for k, v in r.items() if k not in row})
            row["source_json"] = os.path.relpath(p, HERE)
            row["complete"] = bool(d.get("complete"))
            pts.append(row)
    return pts


def fmt(x, spec=".3g"):
    if x is None:
        return "--"
    if isinstance(x, float):
        return format(x, spec)
    return str(x)


def table(rows, cols, headers=None, specs=None):
    headers = headers or cols
    specs = specs or {}
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(fmt(r.get(c), specs.get(c, ".3g"))
                                       for c in cols) + " |")
    return "\n".join(lines)


def taulabel(t):
    return "converged" if not t else f"{t:g}"


def split_roles(rows, key):
    """(consolidated, merged) where `consolidated` holds ONLY the rows measured
    sequentially in one job on one GPU -- the only legitimate source for any
    CROSS-N wall-clock statement -- and `merged` prefers the fanned-out panel row
    for each configuration (identical iteration counts, more test cases) and falls
    back to the consolidated row when a panel is missing."""
    role = lambda r: r.get("run_role") or "consolidated"   # the script default
    cons = [r for r in rows if role(r) == "consolidated"]
    pan = [r for r in rows if role(r) == "panel"]
    merged = {key(r): r for r in cons}
    merged.update({key(r): r for r in pan})
    return cons, list(merged.values())


def role_consistency(rows, key, fields):
    """Panel and consolidated runs use the same seed and the same deterministic
    solvers, so every ITERATION COUNT must agree exactly.  Any disagreement means
    the two runs are not measuring the same thing and the fan-out cannot be
    trusted; it is reported rather than hidden."""
    role = lambda r: r.get("run_role") or "consolidated"
    cons = {key(r): r for r in rows if role(r) == "consolidated"}
    pan = {key(r): r for r in rows if role(r) == "panel"}
    out = []
    for k in sorted(set(cons) & set(pan), key=str):
        for f in fields:
            a, b = cons[k].get(f), pan[k].get(f)
            if a is None or b is None:
                continue
            out.append(dict(key=str(k), field=f, consolidated=a, panel=b,
                            abs_diff=abs(a - b)))
    return out


def main():
    reports = load_reports()
    pts = flat_points(reports)
    os.makedirs(RUNS, exist_ok=True)
    with open(os.path.join(RUNS, "hybrid_points.json"), "w") as f:
        json.dump(pts, f, indent=1)
    print(f"wrote {os.path.join(RUNS, 'hybrid_points.json')} ({len(pts)} rows from "
          f"{len(reports)} reports)")

    Pall = [r for r in pts if r["pde"] == "poisson2d"]
    Ball = [r for r in pts if r["pde"] == "burgers2d"]
    pkey = lambda r: (r["N"], r["rom_tau"], r["fom_tau"])
    bkey = lambda r: (r["N"], r["fom_tau"])
    Pcons, P = split_roles(Pall, pkey)
    Bcons, B = split_roles(Ball, bkey)
    md = ["# Generated tables -- ROM-warm-started FOM",
          "",
          "Every number below is produced by `wsf_summarize.py` from the JSONs in "
          "`runs/`.  Do not edit by hand.", ""]

    if Pall:
        md += ["## Poisson-2D", "",
               "> WALL-CLOCK tables (P1-P3) use ONLY the `consolidated` run -- every N "
               "measured sequentially in one job on one GPU.  Iteration counts and "
               "accuracy (P4) come from the fanned-out per-N panels where available; "
               "P5 checks that the two agree.", ""]
    if Pcons:
        P = Pcons
        Ns = sorted({r["N"] for r in P})
        fts = sorted({r["fom_tau"] for r in P}, reverse=True)
        rts = sorted({r["rom_tau"] for r in P}, reverse=True)
        md += ["### P1. Total hybrid time vs the pure-FOM baseline (ms), consolidated run", ""]
        for ft in fts:
            md += [f"**tau_FOM = {ft:g}**", ""]
            hdr = ["N", "FOM baseline"] + [f"rom_tau={taulabel(t)}" for t in rts]
            lines = ["| " + " | ".join(hdr) + " |",
                     "|" + "|".join("---" for _ in hdr) + "|"]
            for n in Ns:
                sub = {r["rom_tau"]: r for r in P if r["N"] == n and r["fom_tau"] == ft}
                if not sub:
                    continue
                base = fmt(list(sub.values())[0]["t_fom_baseline_ms"], ".4g")
                cells = [fmt(sub[t]["t_total_ms"], ".4g") if t in sub else "--" for t in rts]
                lines.append("| " + " | ".join([str(n), base] + cells) + " |")
            md += lines + [""]
        md += ["### P2. Best hybrid per N (over the ROM tolerance ladder)", ""]
        rows = []
        for ft in fts:
            for n in Ns:
                sub = [r for r in P if r["N"] == n and r["fom_tau"] == ft]
                if not sub:
                    continue
                b = min(sub, key=lambda r: r["t_total_ms"])
                rows.append(dict(fom_tau=ft, N=n, best_rom_tau=taulabel(b["rom_tau"]),
                                 t_fom_baseline_ms=b["t_fom_baseline_ms"],
                                 t_total_ms=b["t_total_ms"],
                                 speedup_vs_fom=b["speedup_vs_fom"],
                                 iters_from_rom=b["iters_from_rom"],
                                 iters_from_baseline=b["iters_from_baseline"],
                                 iter_saving_frac=b.get("iter_saving_frac")))
        md += [table(rows, ["fom_tau", "N", "best_rom_tau", "t_fom_baseline_ms",
                            "t_total_ms", "speedup_vs_fom", "iters_from_rom",
                            "iters_from_baseline", "iter_saving_frac"],
                     ["tau_FOM", "N", "best rom_tau", "FOM (ms)", "hybrid (ms)",
                      "speedup", "CG iters (ROM)", "CG iters (zero)", "iter saving"],
                     {"t_fom_baseline_ms": ".4g", "t_total_ms": ".4g",
                      "speedup_vs_fom": ".3f", "iters_from_rom": ".1f",
                      "iters_from_baseline": ".1f", "iter_saving_frac": ".3f"}), ""]
        md += ["### P3. Cost breakdown and ROM quality (tau_FOM = "
               f"{min(fts):g})", ""]
        rows = [r for r in P if r["fom_tau"] == min(fts)]
        rows.sort(key=lambda r: (r["N"], -r["rom_tau"]))
        for r in rows:
            r["rom_tau_lbl"] = taulabel(r["rom_tau"])
        md += [table(rows, ["N", "rom_tau_lbl", "t_pre_ms", "t_rom_ms", "t_decode_ms",
                            "t_fom_ms", "t_total_ms", "t_fom_baseline_ms",
                            "err_rel_l2_rom", "rom_rel_residual",
                            "rom_err_Anorm_ratio", "err_final"],
                     ["N", "rom_tau", "pre (ms)", "ROM (ms)", "decode (ms)",
                      "CG (ms)", "total (ms)", "FOM (ms)", "ROM rel-L2",
                      "ROM rel resid", "ROM A-norm err", "final err"],
                     {k: ".4g" for k in ("t_pre_ms", "t_rom_ms", "t_decode_ms",
                                         "t_fom_ms", "t_total_ms", "t_fom_baseline_ms")}), ""]
        P = [r for r in Pall if True]
        P = split_roles(Pall, pkey)[1]
        Ns = sorted({r["N"] for r in P})
        fts = sorted({r["fom_tau"] for r in P}, reverse=True)
        rts = sorted({r["rom_tau"] for r in P}, reverse=True)
        md += ["### P4. CG iterations, warm start vs zero start "
               "(panel runs where available; hardware-independent)", ""]
        rows = []
        for ft in fts:
            for n in Ns:
                for t in rts:
                    s = [r for r in P if r["N"] == n and r["fom_tau"] == ft
                         and r["rom_tau"] == t]
                    if s:
                        r = dict(s[0]); r["rom_tau_lbl"] = taulabel(t)
                        rows.append(r)
        md += [table(rows, ["fom_tau", "N", "rom_tau_lbl", "iters_from_baseline",
                            "iters_from_rom", "iter_saving_frac",
                            "rom_err_Anorm_ratio", "rom_rel_residual"],
                     ["tau_FOM", "N", "rom_tau", "CG iters (zero)", "CG iters (ROM)",
                      "iter saving", "ROM A-norm err ratio", "ROM rel resid"],
                     {"iters_from_baseline": ".1f", "iters_from_rom": ".1f",
                      "iter_saving_frac": ".4f"}), ""]
        cc = role_consistency(Pall, pkey, ["iters_from_rom", "iters_from_baseline",
                                           "err_rel_l2_rom", "err_final"])
        bad = [c for c in cc if c["abs_diff"] > 1e-12 * max(abs(c["consolidated"]), 1.0)]
        md += ["### P5. Panel vs consolidated consistency "
               f"({len(cc)} compared, {len(bad)} disagreements)", ""]
        md += [table(bad[:40] if bad else
                     [dict(key="all compared quantities", field="-", consolidated="-",
                           panel="-", abs_diff=0.0)],
                     ["key", "field", "consolidated", "panel", "abs_diff"]), ""]

    if Ball:
        md += ["## Burgers-2D", "",
               "> Wall-clock rows (B2) use ONLY the `consolidated` run; iteration counts "
               "(B1) and solver health (B3) come from the per-N panels where available.", ""]
    if B:
        Ns = sorted({r["N"] for r in B})
        fts = sorted({r["fom_tau"] for r in B}, reverse=True)
        md += ["### B1. Newton and BiCGStab iterations per 50-step trajectory", ""]
        rows = []
        for ft in fts:
            for n in Ns:
                s = [r for r in B if r["N"] == n and r["fom_tau"] == ft]
                if s:
                    rows.append(s[0])
        md += [table(rows, ["fom_tau", "N", "iters_from_baseline", "iters_from_extrap",
                            "iters_from_rom", "lin_iters_from_baseline",
                            "lin_iters_from_extrap", "lin_iters_from_rom"],
                     ["tau_FOM", "N", "Newton (prev)", "Newton (extrap)", "Newton (ROM)",
                      "BiCGStab (prev)", "BiCGStab (extrap)", "BiCGStab (ROM)"],
                     {k: ".1f" for k in ("iters_from_baseline", "iters_from_extrap",
                                         "iters_from_rom")}), ""]
        crows = []
        for ft in sorted({r["fom_tau"] for r in Bcons}, reverse=True):
            for n in sorted({r["N"] for r in Bcons}):
                sub = [r for r in Bcons if r["N"] == n and r["fom_tau"] == ft]
                if sub:
                    crows.append(sub[0])
        md += ["### B2. Wall clock (ms) and the hybrid total, consolidated run", ""]
        md += [table(crows, ["fom_tau", "N", "t_fom_baseline_ms", "t_fom_extrap_ms",
                            "t_fom_ms", "t_rom_ic_ms", "t_rom_rollout_ms",
                            "t_decode_ms", "t_total_ms", "speedup_vs_fom"],
                     ["tau_FOM", "N", "FOM (prev)", "FOM (extrap)", "FOM (from ROM)",
                      "ROM IC", "ROM rollout", "decode", "hybrid total", "speedup"],
                     {k: ".4g" for k in ("t_fom_baseline_ms", "t_fom_extrap_ms",
                                         "t_fom_ms", "t_rom_ic_ms", "t_rom_rollout_ms",
                                         "t_decode_ms", "t_total_ms")}
                     | {"speedup_vs_fom": ".3f"}), ""]
        md += ["### B3. Accuracy and solver health", ""]
        md += [table(rows, ["fom_tau", "N", "err_rel_l2_rom", "err_final",
                            "err_final_baseline", "bicgstab_breakdowns",
                            "newton_flags_nonzero"],
                     ["tau_FOM", "N", "ROM rel-L2", "hybrid err vs FOM",
                      "baseline err vs FOM", "BiCGStab breakdowns",
                      "non-zero Newton flags"]), ""]

    with open(os.path.join(HERE, "SUMMARY_TABLES.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print(f"wrote {os.path.join(HERE, 'SUMMARY_TABLES.md')}")

    # ---- headline numbers, printed so the README prose can be checked against them
    if Pcons:
        print("\nPOISSON headline (consolidated run, one GPU):")
        for ft in sorted({r['fom_tau'] for r in Pcons}, reverse=True):
            best = {}
            for n in sorted({r["N"] for r in Pcons}):
                sub = [r for r in Pcons if r["N"] == n and r["fom_tau"] == ft]
                if sub:
                    b = min(sub, key=lambda r: r["t_total_ms"])
                    best[n] = b
            wins = [n for n, b in best.items() if b["speedup_vs_fom"] > 1.0]
            print(f"  tau_FOM={ft:g}: crossover N = "
                  f"{min(wins) if wins else 'none in the ladder'}; "
                  + "  ".join(f"N{n}:{b['speedup_vs_fom']:.2f}x"
                              f"@rom_tau={taulabel(b['rom_tau'])}"
                              for n, b in best.items()))
    if Bcons:
        print("\nBURGERS headline (consolidated run, one GPU):")
        for r in sorted(Bcons, key=lambda r: (-r["fom_tau"], r["N"])):
            print(f"  tau={r['fom_tau']:g} N={r['N']}: Newton "
                  f"{r['iters_from_baseline']:.1f} (prev) / "
                  f"{r['iters_from_extrap']:.1f} (extrap) / "
                  f"{r['iters_from_rom']:.1f} (ROM); hybrid "
                  f"{r['t_total_ms']:.0f} ms vs FOM {r['t_fom_baseline_ms']:.0f} ms "
                  f"({r['speedup_vs_fom']:.2f}x)")


if __name__ == "__main__":
    main()
