def pct(x):
    return "—" if x is None else f"{100 * x:.3f} %"


def sci(x, d=1):
    return "—" if x is None else f"{x:.{d}e}"


def evolved(errors):
    e = np.asarray(errors, dtype=float)[:, 1:].max(axis=1)
    return float(e.max()), float(np.median(e))


def mstar(sizes, worst, median, w_t, d_t, finite, tol=1.05):
    order = np.argsort(sizes)
    best = None
    for j in range(len(order) - 1, -1, -1):
        i = order[j]
        if not (finite[i] and worst[i] <= tol * w_t and median[i] <= tol * d_t):
            break
        best = int(sizes[i])
    return best


def mstar_delta(sizes, delta, finite, tol=1e-4):
    order = np.argsort(sizes)
    best = None
    for j in range(len(order) - 1, -1, -1):
        i = order[j]
        if not (finite[i] and delta[i] <= tol):
            break
        best = int(sizes[i])
    return best


def load(runs):
    data = {}
    for n in MESHES:
        p = runs / f"q{n}" / "output" / "summary.json"
        if p.exists():
            s = json.loads(p.read_text())
            s["_sha"] = hashlib.sha256(p.read_bytes()).hexdigest()
            s["_jobdir"] = f"q{n}"
            data[n] = s
    return data


def comparator(cnab, worst, timing):
    """Fastest stable CNAB2 setting with evolved worst <= worst (parent's rule)."""
    best = None
    for st, e in cnab.items():
        if e["stats"] is None or e["unstable"]:
            continue
        if e["stats"]["evolved_worst"] <= worst:
            ms = timing[f"CNAB2_s{st}"]["median_ms"]
            if best is None or ms < best[1]:
                best = (st, ms, e["stats"]["evolved_worst"])
    return best


