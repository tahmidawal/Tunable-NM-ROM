"""Stage only committed Heat3D source into one isolated, hash-pinned attempt."""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT=Path(__file__).resolve().parents[3]
LANE='experiments/paper-h3d'
NAMESPACE='/cluster/tufts/paralab/tawal01/paper_h3d_20260920'
FILES=['DESIGN.md','config.json','common.py','train.py','rom.py','run.py','audit.py','cluster/stage.py','cluster/collect.py','operators/__init__.py','operators/models3d.py','operators/training.py','operators/heat_adapter.py','operators/smoke.py','operators/train_smoke.py','operators/README.md']
FILES += ['operators/extra_models3d.py','operators/extra_smoke.py','operators/extra_train_smoke.py',
          'operators/upstream/PROVENANCE.json','operators/upstream/Physics_Attention.py',
          'operators/upstream/prior_families.py','operators/upstream/LICENSE']
FILES += ['frozen.py']
FILES += ['head_pca_diagnostic.py','audit_head.py','audit_panel.py']
FILES += ['coverage_train.py','audit_coverage.py','operators/pretrained_deeponet.py','final_freeze.py','audit_states.py']
FILES += ['audit_pretraining.py','iterative_cg.py','audit_cg.py','archive_storage.py','retain_fields.py']


def main():
    p=argparse.ArgumentParser();p.add_argument('attempt');p.add_argument('--config',default='config.json');a=p.parse_args()
    assert a.attempt.isalnum(),a.attempt
    out=ROOT/LANE/'runs'/a.attempt;out.mkdir(parents=True,exist_ok=False)
    remote=f'{NAMESPACE}/{a.attempt}'
    commit=subprocess.check_output(['git','-C',str(ROOT),'rev-parse','HEAD'],text=True).strip()
    proof=[]
    cfg=json.loads((ROOT/LANE/a.config).read_text())
    files=FILES+([Path(cfg['final_freeze_path']).name] if cfg.get('evaluation_cohort')=='final' else [])
    companion=None
    if cfg.get('companion_config_file'):
        companion=json.loads((ROOT/LANE/Path(cfg['companion_config_file']).name).read_text())
        files += [Path(cfg['companion_config_file']).name]
        if companion.get('evaluation_cohort')=='final':files += [Path(companion['final_freeze_path']).name]
    for name in files:
        source_name=a.config if name=='config.json' else name
        path=f'{LANE}/{source_name}'
        blob=subprocess.check_output(['git','-C',str(ROOT),'show',f'{commit}:{path}'])
        assert blob==(ROOT/path).read_bytes(),f'uncommitted source: {path}'
        dest=out/'code'/name;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(blob)
        proof.append(dict(path=path,staged=str(dest.relative_to(out)),sha256=hashlib.sha256(blob).hexdigest()))
    (out/'COMMIT.txt').write_text(commit+'\n')
    (out/'PROVENANCE.json').write_text(json.dumps(dict(source_commit=commit,files=proof,remote=remote),indent=2)+'\n')
    cfg=json.loads((out/'code/config.json').read_text())
    if cfg.get('frozen_source_attempt'):
        import sys
        sys.path.insert(0,str(ROOT/LANE))
        import frozen
        frozen.stage_inputs(ROOT,cfg['frozen_source_attempt'],out/cfg['frozen_input_directory'],cfg)
        if companion is not None:
            assert companion['frozen_input_directory']!=cfg['frozen_input_directory']
            frozen.stage_inputs(ROOT,companion['frozen_source_attempt'],out/companion['frozen_input_directory'],companion)
    script='''#!/bin/bash
#SBATCH --job-name=ctol_h3d_920___ATTEMPT__
#SBATCH --partition=gpu
#SBATCH --qos=normal
#SBATCH --gres=gpu:a100:1
#SBATCH --exclude=pax007
#SBATCH --cpus-per-task=8
#SBATCH --mem=64G
#SBATCH --time=02:00:00
#SBATCH --output=__REMOTE__/job.out
#SBATCH --error=__REMOTE__/job.err
set -euo pipefail
TASK_ROOT=__REMOTE__
PY=/cluster/tufts/paralab/tawal01/ae-research/venv/bin/python
export JAX_ENABLE_X64=true JAX_DEFAULT_MATMUL_PRECISION=highest
export XLA_PYTHON_CLIENT_PREALLOCATE=false
export OPENBLAS_NUM_THREADS=8 OMP_NUM_THREADS=8 MKL_NUM_THREADS=8
export TMPDIR="$TASK_ROOT/tmp" XDG_CACHE_HOME="$TASK_ROOT/cache"
mkdir -p "$TMPDIR" "$XDG_CACHE_HOME" "$TASK_ROOT/out"
cd "$TASK_ROOT"
sha256sum -c SOURCE.sha256
export SOURCE_COMMIT=$(cat COMMIT.txt)
echo "source_commit=$SOURCE_COMMIT job_id=$SLURM_JOB_ID"
nvidia-smi --query-gpu=name,uuid,memory.total,driver_version --format=csv
df -h /cluster/tufts/paralab
"$PY" -c "import jax,sys; b=jax.default_backend(); print(f'jax_backend={b}',flush=True); sys.exit(0 if b=='gpu' else 42)"
# Training data is generated by run.py from the committed parameter seeds.
set +e
"$PY" code/__DRIVER__ --config code/config.json --out out
RUN_STATUS=$?
set -e
find out -type f -print0 | sort -z | xargs -0 sha256sum > OUTPUTS.sha256
echo "run_exit=$RUN_STATUS"
exit "$RUN_STATUS"
'''.replace('__REMOTE__',remote).replace('__ATTEMPT__',a.attempt).replace('__DRIVER__',cfg.get('driver','run.py'))
    if cfg.get('driver')=='coverage_train.py':script=script.replace('#SBATCH --time=02:00:00','#SBATCH --time=03:00:00')
    if companion is not None:
        assert companion['confirmation_role']=='independent_seed_accuracy'
        first='RUN_STATUS=$?\nset -e'
        second='RUN_STATUS=$?\nif [ "$RUN_STATUS" -eq 0 ]; then\n  "$PY" code/run.py --config '+cfg['companion_config_file']+' --out out/seedB\n  RUN_STATUS=$?\nfi\nset -e'
        assert first in script;script=script.replace(first,second)
    (out/'run.sbatch').write_text(script)
    source=[]
    for f in sorted(out.rglob('*')):
        if f.is_file():source.append(f'{hashlib.sha256(f.read_bytes()).hexdigest()}  {f.relative_to(out)}')
    (out/'SOURCE.sha256').write_text('\n'.join(source)+'\n')
    print(json.dumps(dict(local=str(out),remote=remote,commit=commit,files=proof),indent=2))


if __name__=='__main__':main()
