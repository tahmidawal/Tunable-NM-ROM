w('')
w('Plan item C5 (PLAN-v2) asks whether the nonlinear head earns the paper\'s "nonlinear manifold" wording. This lane trains '
  'matched heads of latent size $K\\in\\{4,8,16,32\\}$ (three seeds each) on the frozen R512 bank with the incumbent\'s '
  'recipe, and compares the head ROM with the linear-span ROM of the same bank at matched online dimension ($r=K$) and at '
  'equal online cost.')
