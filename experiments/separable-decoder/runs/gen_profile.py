#!/usr/bin/env python3
"""PROFILE.md and the round-4 speed tables, FROM THE RUN JSONS ONLY.

    python runs/gen_profile.py runs/push_r4s*/out/*.json > PROFILE.md
"""
import json
import os
import sys

import numpy as np


def f(x, p=3):
    return "--" if x is None else f"{x:.{p}e}"


def nm(s):
    return s.replace("|", "/")


def main(paths):
    runs = []
    for p in sorted(paths):
        d = json.load(open(p))
        if d.get("config", {}).get("kind") != "profile+speed":
            continue
        runs.append((p, d))
    runs.sort(key=lambda pd: -pd[1]["config"]["N"])

    print("# Where the online solve actually spends its time\n")
    print("Generated by `runs/gen_profile.py` from the committed round-4 "
          "speed JSONs (`runs/push_r4s*/out/*.json`). Nothing is hand-typed.\n")
    print("Each job loads an ALREADY-TRAINED round-3 checkpoint and varies "
          "only the solve path. The decoder is frozen throughout, so a variant "
          "that changes the error is changing the method, not the model, and "
          "is reported as such.\n")

    for p, d in runs:
        c = d["config"]
        N, K, R = c["N"], c["k"], c["r"]
        sh = d["profile"]["shapes"]
        print(f"## N={N} (K={K}, R={R}) on {c.get('gpu')} -- job "
              f"`{c.get('slurm_job')}`, checkpoint `{c['ckpt']}`\n")
        print(f"Quadrature points m={sh['m_quadrature']}, grid {sh['n_grid']} "
              f"points, readout bank {sh['G_all_bytes']/1e6:.1f} MB, stencil "
              f"bank {sh['G_st_bytes']/1e6:.3f} MB. "
              f"{d['config']['n_test']} fresh test trajectories, "
              f"{c['reps']} timed repetitions in balanced order.\n")

        print("### Gates\n")
        print("| gate | bar | value |")
        print("|---|---|---|")
        g = d["gates"]
        print(f"| gate 0 (cached vs incumbent meshfree operators) | <=1e-12 | "
              f"{f(d['eq']['ctrl']['gate0'])} |")
        print(f"| cached bank vs meshfree full-interior decode | <=1e-12 | "
              f"{f(g['eq_bank_vs_meshfree'])} |")
        print(f"| configurable-stall LM step vs incumbent, at stall=1e-12 | "
              f"exactly 0 | {g['step_variant_vs_incumbent_at_1e-12']:.1f} |")
        print(f"| Gram-space IC fit vs full-grid IC fit, latent deviation | "
              f"-- | {f(g['ic_gram_vs_full_latent_dev'])} |")
        print(f"| Gram-space IC fit vs full-grid IC fit, \\|\\|r\\|\\| relative "
              f"difference | -- | {f(g['ic_gram_vs_full_resnorm_rel'])} |")
        print()

        print("### Cost breakdown by ablation (median of the timed repetitions)\n")
        print("| component | ms |")
        print("|---|---|")
        ab = d["profile"]["ablation_ms"]
        for k, v in sorted(ab.items(), key=lambda kv: -kv[1]["median_ms"]):
            print(f"| `{k}` | {v['median_ms']:.4f} |")
        b = {int(k.replace("lm_step_budget", "")): v["median_ms"]
             for k, v in ab.items() if k.startswith("lm_step_budget")}
        if len(b) >= 2:
            xs = np.array(sorted(b)); ys = np.array([b[x] for x in xs])
            slope, icept = np.polyfit(xs, ys, 1)
            print(f"\nOne LM time step, fitted over budgets "
                  f"{[int(v) for v in xs]}: **{icept*1e3:.0f} us fixed + "
                  f"{slope*1e3:.0f} us per LM iteration** "
                  f"(R^2 = {np.corrcoef(xs, ys)[0,1]**2:.4f}).")
            print(f"\nThe round-3 rollout runs 50 steps at about 5.1 LM "
                  f"iterations each, which this LINEAR EXTRAPOLATION puts at "
                  f"{50*(icept + 5.1*slope):.1f} ms against a measured "
                  f"`rollout_extrap` of {ab['rollout_extrap']['median_ms']:.1f} ms.")
        print()

        print("### What kind of bound is it? (from the COMPILED artefact)\n")
        print("| compiled function | FLOPs | bytes accessed | FLOP/byte | "
              "fusions |")
        print("|---|---|---|---|---|")
        for k, v in d["profile"]["cost_analysis"].items():
            if "error" in v:
                print(f"| `{k}` | -- | -- | -- | {v['error']} |")
                continue
            ai = v["flops"] / v["bytes_accessed"] if v["bytes_accessed"] else 0
            print(f"| `{k}` | {v['flops']:.3e} | {v['bytes_accessed']:.3e} | "
                  f"{ai:.2f} | {v['n_fusion']} |")
        if "weak_residual_and_jacobian" in d["profile"]["cost_analysis"]:
            ca = d["profile"]["cost_analysis"]["weak_residual_and_jacobian"]
            if "error" not in ca:
                ms = ab["weak_residual_and_jacobian"]["median_ms"]
                print(f"\nThe residual-and-Jacobian evaluation moves "
                      f"{ca['bytes_accessed']/1e6:.2f} MB and does "
                      f"{ca['flops']/1e6:.2f} MFLOP in {ms:.4f} ms, i.e. "
                      f"{ca['bytes_accessed']/ms*1e-9:.1f} GB/s and "
                      f"{ca['flops']/ms*1e-9:.2f} GFLOP/s. Both are orders of "
                      f"magnitude below what the device can sustain, and the "
                      f"compiled module contains {ca['n_fusion']} fusions for "
                      f"that much arithmetic: the cost is the NUMBER OF "
                      f"KERNELS, not bandwidth and not arithmetic.")
        print()

        print("### Speed variants (frozen decoder; error must not move)\n")
        print("| variant | e2e ms | vs base | traj err mean | IC jac | "
              "rollout jac | stop reasons |")
        print("|---|---|---|---|---|---|---|")
        base = [v for v in d["variants"] if v["name"] == "base"][0]
        for v in sorted(d["variants"], key=lambda v: v["e2e_ms_median"]):
            print(f"| `{v['name']}` | {v['e2e_ms_median']:.2f} | "
                  f"{base['e2e_ms_median']/v['e2e_ms_median']:.2f}x | "
                  f"{f(v['err_traj_rel_mean'])} | {v['ic_jac_mean']:.1f} | "
                  f"{v['jac_total_mean']:.0f} | {v['stop_reasons']} |")
        print(f"\nChampion rule: {c.get('champion_rule')}\n")

        print("### Classical ladder in the same job, and matched accuracy\n")
        print("| newton_tol | lin_tol | ms | traj err mean | Newton its |")
        print("|---|---|---|---|---|")
        for r in sorted([r for r in d["rows"]
                         if r.get("method") == "fom_newton_tol_pc"],
                        key=lambda r: r["time_ms_median"]):
            print(f"| {r['newton_tol']:.0e} | {r['lin_tol']:.0e} | "
                  f"{r['time_ms_median']:.1f} | {f(r['err_traj_rel_mean'])} | "
                  f"{r['newton_iters_mean']:.1f} |")
        ma = d.get("matched_accuracy", {})
        m, pr = ma.get("matched"), ma.get("paired")
        print(f"\nFastest non-regressing ROM variant `{nm(ma.get('rom_arm',''))}`: "
              f"{f(ma.get('rom_err'))} at {ma.get('rom_e2e_ms', float('nan')):.2f} ms.")
        if m:
            print(f"\nCheapest classical rung at least as accurate: "
                  f"newton_tol={m['newton_tol']:.0e}, lin_tol={m['lin_tol']:.0e} "
                  f"-> {m['ms']:.1f} ms at {f(m['err'])}.")
        if pr:
            rr = pr["base_ms"] / pr["rom_ms"]
            print(f"\n**Paired AB/BA:** ROM {pr['rom_ms']:.2f} ms vs classical "
                  f"{pr['base_ms']:.2f} ms = **{rr:.2f}x** "
                  f"({'ROM wins' if rr > 1 else 'classical wins'}).")
        print()

        if d.get("batch_sweep"):
            print("### Amortization curve\n")
            subs = sorted({e["subject"] for e in d["batch_sweep"]})
            Bs = sorted({e["batch"] for e in d["batch_sweep"]})
            print("| batch | " + " | ".join(f"`{nm(s)}` ms/query" for s in subs)
                  + " |")
            print("|" + "---|" * (1 + len(subs)))
            for B in Bs:
                cells = []
                for s in subs:
                    e = [x for x in d["batch_sweep"]
                         if x["batch"] == B and x["subject"] == s]
                    cells.append(f"{e[0]['amortized_ms']:.2f}" if e else "--")
                print(f"| {B} | " + " | ".join(cells) + " |")
            print()


if __name__ == "__main__":
    main(sys.argv[1:])
