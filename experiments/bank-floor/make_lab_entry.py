"""Generate the final lab-log entry from reports/summary.json and the audits. No hand-typed numbers.
usage: make_lab_entry.py > LAB-ENTRY-final.md
"""
import json
import subprocess
import sys
from pathlib import Path

H = Path(__file__).resolve().parent
sys.path.insert(0, str(H / 'reports'))
import verdicts  # noqa: E402
S = json.loads((H / 'reports/summary.json').read_text())
A = {p.stem: json.loads(p.read_text())['passed'] for p in (H / 'checks').glob('*audit.json')}
man = json.loads((H / 'CKPT-MANIFEST.json').read_text())
commit = subprocess.check_output(['git', '-C', str(H), 'rev-parse', 'HEAD'], text=True).strip()
p = lambda x: f'{100 * x:.4f}'
rp, rb, sp, sb = (S.get(k, {}) for k in ('rep_poisson', 'rep_burgers', 'solve_poisson', 'solve_burgers'))
order = ('inc512', 'ft512', 'pod512', 'cat1024', 'pod1024', 'cat2048', 'pod2048')

L = ['', '## 2026-09-21',
     '### bank-floor — FINAL: the floor is a rank problem; an optimal (POD) rank-1024 bank puts both PDEs below 0.1 % on the confirmation cohorts, the learned coordinate banks reach sub-0.2 % on Poisson only, and on Burgers every accurate full-bank solve is roughly two to three orders of magnitude slower than the Newton FOM at matched accuracy', '',
     f'Supersedes the INTERIM 1 entry above for every number. Worktree `worktrees/2026-09-20-bank-floor`, branch `exp/2026-09-20-bank-floor` at `{commit}`; namespace `/cluster/tufts/paralab/tawal01/bankfloor_20260920/` (empty). Eight-job cap, seven used: '
     + '; '.join(f"{k} = {v['attempt']} job {v['job']}" for k, v in S['sources'].items())
     + '. Failed/partial attempts kept with logs: bfp01 4052480, bfb01 4052482 (single-Gram POD assert), bfb02 4053195 (eigh OOM), bfp02 4053735 (died scoring after training; its POD and ft512 rows are the audited Poisson Phase-1 source). Every log has `jax_backend=gpu`, f64, matmul `highest`, A100 80GB. Independent NumPy audits: '
     + ', '.join(f"{k} {'PASS' if v else 'FAIL'}" for k, v in sorted(A.items())) + '.', '']
if rp and sp:
    L += ['**Poisson 2D, 255 intervals — worst floor dev12 % / full-bank solved dev12 % / solved confirm256 % / total ms (same allocation, 7 reps, medians):** '
          + '; '.join(f"`{t}` {p(rp[t]['primary_worst'])} / {p(sp[t + '_weak']['worst']['dev12'])} / {p(sp[t + '_weak']['worst']['confirm256'])} / {sp[t + '_weak']['median_total_ms']:.3f}"
                      for t in order if t + '_weak' in sp)
          + '. Comparators: ' + '; '.join(f"`{k}` {p(v['worst']['dev12'])} % at {v['median_total_ms']:.3f} ms" for k, v in sp.items() if v['kind'].startswith('fom'))
          + '. The solve reaches the floor on every bank. Against the named CG the linear ROM is an order of magnitude faster at better accuracy; the direct DST and the coarse-grid DST are faster than every ROM, so no speedup over an efficient direct solver is claimed.', '']
if rb:
    L += ['**Burgers 2D, 256 intervals — worst floor dev6 % / hold64 %'
          + (' / full-bank dense solved dev6 all-times % / evolved % / confirm all-times % / total ms (5 reps)' if sb else '') + ':** '
          + '; '.join(f"`{t}` {p(rb[t]['primary_worst'])} / {p(rb[t]['large_worst']['hold64'])}"
                      + (f" / {p(sb[t + '_full']['worst_all']['dev6'])} / {p(sb[t + '_full']['worst_evolved']['dev6'])} / {p(sb[t + '_full']['worst_all']['confirm'])} / {sb[t + '_full']['median_total_ms']:.0f}"
                         if sb and t + '_full' in sb else '') for t in order) + '.'
          + (' FOM rows in the same job: ' + '; '.join(f"`{k}` {p(v['worst_all']['dev6'])} % at {v['median_total_ms']:.1f} ms" for k, v in sb.items() if v['kind'].startswith('fom')) + '.' if sb else ''), '']
V = verdicts.rows(S)
inc_b, inc_p = sb.get('inc512_full'), sp.get('inc512_weak')
L += ['**The incumbents generalise worse than their quoted floors.** Burgers `inc512`: floor '
      + f"{p(rb['inc512']['primary_worst'])} % on dev6 but {p(rb['inc512']['large_worst']['hold64'])} % on hold64, and its full-bank "
      + f"solve is {p(inc_b['worst_all']['confirm'])} % on the confirmation cohort. Poisson `inc512`: {p(rp['inc512']['primary_worst'])} % dev12, "
      + f"{p(inc_p['worst']['confirm256'])} % solved on confirm256. The 0.39 % / 0.74 % figures are six- and twelve-case numbers.", '']
L += ['**Verdicts (generated by `reports/verdicts.py`; worst of primary and confirmation cohort; FOM comparators chosen per row at matched-or-better accuracy):** '
      + '; '.join(f"{r['pde']} `{r['bank']}`{'' if r['learned'] else ' (grid-bound POD)'}: {p(max(r['solved_primary'], r['solved_confirm']))} % at "
                  f"{r['ms']:.3g} ms = {r['cost_vs_incumbent']:.2f}× inc, lane {'PASS' if r['lane_success'] else 'fail'}"
                  f"{' (stretch PASS)' if r['lane_stretch'] else ''}, {r['speedup_vs_named']:.3g}× vs `{r['named']}`, {r['speedup_vs_fastest']:.3g}× vs `{r['fastest']}`"
                  for r in V) + '.', '']
L += ['**Gate P1 (≥ 3× primary, ≥ 2× large cohorts):** '
      + '; '.join(f"{n}: promoted " + ', '.join(f'`{k}`' for k, v in S[key].items() if v['p1_promoted'] and not any(x in k for x in ('raw', '_sub')))
                  for key, n in (('rep_poisson', 'Poisson'), ('rep_burgers', 'Burgers')) if S.get(key)) + '.', '',
      (H / 'LAB-ENTRY-prose.md').read_text().strip(), '',
      '**Checkpoints (git-ignored `experiments/bank-floor/ckpt/`, manifest `experiments/bank-floor/CKPT-MANIFEST.json`):** '
      + '; '.join(f"`{k}` {v['bytes'] / 1e6:.0f} MB sha256 `{v['sha256'][:16]}…`" for k, v in man.items() if 'fields' not in k) + '.', '',
      'Report (generated): `experiments/bank-floor/reports/2026-09-21-bank-floor-vs-rank-vs-online-cost.md`; machine summary `experiments/bank-floor/reports/summary.json`. Not pushed, not merged.', '']
print('\n'.join(L))
