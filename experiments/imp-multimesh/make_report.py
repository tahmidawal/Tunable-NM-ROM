def f(x, d=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return 'n/a'
    if isinstance(x, (int, np.integer)):
        return str(x)
    a = abs(x)
    if a != 0 and (a < 1e-3 or a >= 1e5):
        return f'{x:.{d - 1}e}'
    return f'{x:.{d}g}'


def esc(x):
    return str(x).replace('|', '\\|')


def pct(x):
    return 'n/a' if x is None else f'{100 * x:.3g} %'


