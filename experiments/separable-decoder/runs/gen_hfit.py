#!/usr/bin/env python3
"""Generate HFIT.md from the committed round-5 h-refinement JSONs.

Nothing here is hand-typed: every number is read out of runs/*/out/hfit_*.json
(and the extraction JSONs for the floors and gates).  Usage:

    /home/tahmid/Dev/.venv/bin/python runs/gen_hfit.py > HFIT.md
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SEP = os.path.dirname(HERE)


# The training pick keeps a constant number of states per trajectory by
# construction (MAX_SNAPS is scaled with n_traj), so the fitted trajectory count
# is recoverable from the fitted state count even for the JSONs written before
# `npz_n_traj` was recorded.  16384 states <-> 576 trajectories.
SPT = 16384.0 / 576.0


def n_traj_of(cfg, floors=None):
    if (floors or {}).get("traj_fit"):
        return int(floors["traj_fit"])
    if cfg.get("traj_fit"):
        return int(cfg["traj_fit"])
    if cfg.get("npz_n_traj"):
        return int(cfg["npz_n_traj"])
    return int(round(cfg["S"] / SPT))


def fmt(v, s="{:.3e}"):
    return "--" if v is None else s.format(v)


def main():
    out = []
    w = out.append
    w("# Round 5 -- refining h in the frozen bank's coefficient space\n")
    w("Generated by `runs/gen_hfit.py` from the committed round-5 JSONs. "
      "Nothing is hand-typed.\n")
    w("Every arm below freezes the bank `g` of one trained checkpoint and "
      "refits only `h` and the per-snapshot codes, against the EXACT whitened "
      "objective of `sep_hfit.py` -- identity (*), not an approximation of the "
      "field-space loss. So the span least-squares floor is one constant per "
      "checkpoint and **`oracle / span floor` is the number to read**: it is "
      "the factor by which the map h fails to reach into the span it was "
      "given, and it is the only rung round 3/4 left open.\n")

    # ---- extraction gates ---------------------------------------------------
    ex = sorted(glob.glob(os.path.join(HERE, "ext*", "out",
                                       "sep_coeff_*.json")))
    if ex:
        w("## Extraction gates (the identity itself)\n")
        w("The checkpoint's reconstruction computed two independent ways -- "
          "from the full fields, and from `(c*, floor, Gram)` -- on 64 "
          "retained full-resolution training states.\n")
        w("| job | N | K | cond(G) | rank | identity dev (mean) | identity dev "
          "(max) | recon via (*) | fresh test span floor |")
        w("|---|---|---|---|---|---|---|---|---|")
        for f in ex:
            d = json.load(open(f))
            c, g = d["config"], d["gates"]
            w(f"| `{d['config'].get('slurm_job')}` | {c['N']} | {c['k']} | "
              f"{fmt(d['span']['cond_G'])} | "
              f"{d['span']['numerical_rank_1e8']}/{c['r']} | "
              f"{fmt(g.get('gram_identity_rel_dev_mean'))} | "
              f"{fmt(g.get('gram_identity_rel_dev_max'))} | "
              f"{fmt(d['ckpt_recon']['mean'])} | "
              f"{fmt(d['test_span_floor']['mean'])} |")
        w("")

    # ---- arms ---------------------------------------------------------------
    files = sorted(glob.glob(os.path.join(HERE, "*", "out", "hfit_*.json")))
    rows = []
    floors = {}
    gates = []
    for f in files:
        d = json.load(open(f))
        src = d["config"]["ckpt"]
        floors[src] = d["floors"]
        gates.append((os.path.basename(f), d["gates"]))
        for name, a in d["arms"].items():
            rows.append(dict(
                job=d["config"].get("slurm_job"), src=src, name=name,
                k=a.get("k"), spec=a.get("spec", {}),
                steps=a.get("train", {}).get("steps_done"),
                spec_steps=a.get("spec", {}).get("steps"),
                capped=bool((a.get("train") or {}).get("steps_done") and
                            (a.get("train") or {}).get("steps") and
                            (a["train"]["steps_done"] < a["train"]["steps"])),
                recon=a["recon_train"]["mean"],
                recon_max=a["recon_train"]["max"],
                oracle=a["oracle_test"]["mean"],
                oracle_max=a["oracle_test"]["max"],
                o_t0=a["oracle_test"]["t0"],
                o_early=a["oracle_test"]["early"],
                o_late=a["oracle_test"]["late"],
                ratio=a["oracle_over_span_floor"],
                o_nn=a["oracle_test_nn"]["mean"],
                code_gain=a["oracle_train_from_codes"]["gain_vs_recon"],
                secs=a.get("seconds"),
                traj_fit=n_traj_of(d["config"], d["floors"]),
                hold=(a.get("oracle_holdout") or {}).get("mean"),
                hold_ratio=(a.get("oracle_holdout") or {}).get(
                    "over_span_floor"),
                n_hold=d["floors"].get("n_hold"),
                floor=d["floors"]["test_span_floor_mean"]))
    if not rows:
        w("_No arm JSONs found yet._")
        print("\n".join(out))
        return
    rows.sort(key=lambda r: r["ratio"])
    w("## Arms, sorted by oracle / span floor (lower is better)\n")
    for src in sorted(floors):
        fl = floors[src]
        w(f"Source checkpoint `{src}`: train span floor "
          f"{fmt(fl['train_span_floor_mean'])}, fresh-test span floor "
          f"**{fmt(fl['test_span_floor_mean'])}**.\n")
    w("| arm | K | h | traj | steps | recon (train) | oracle (fresh) | "
      "oracle/floor | oracle t=0 | oracle t>5 | oracle_nn | held-out oracle | "
      "code-refit gain | s |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        sp = r["spec"]
        hs = f"{sp.get('hidden', '--')}x{sp.get('layers', '--')}"
        if sp.get("h_ff"):
            hs += f" +ffz{sp['h_ff']}@{sp.get('h_ff_scale', 1.0)}"
        extra = []
        for kk in ("norm", "wd", "w", "zinit", "z_polish_every", "warm"):
            if sp.get(kk):
                extra.append(f"{kk}={sp[kk]}")
        if extra:
            hs += " (" + ", ".join(extra) + ")"
        hold = ("--" if r["hold"] is None else
                f"{fmt(r['hold'])} ({r['hold_ratio']:.1f}x)")
        nm = f"`{r['name']}`" + (" **(TIME-CAPPED)**" if r.get('capped') else "")
        w(f"| {nm} | {r['k']} | {hs} | {r['traj_fit']} | "
          f"{r['steps']} | {fmt(r['recon'])} | **{fmt(r['oracle'])}** | "
          f"{r['ratio']:.1f}x | {fmt(r['o_t0'])} | "
          f"{fmt(r['o_late'])} | {fmt(r['o_nn'])} | {hold} | "
          f"{r['code_gain']:.3f} | {r['secs']:.0f} |")
    w("")
    w("Columns: `recon (train)` is the per-snapshot relative L2 over the "
      "training states with their own fitted codes; `oracle (fresh)` is the "
      "per-state representation oracle on fresh-seed test trajectories, "
      "started from the mean training code and a training-only encoder -- the "
      "same two inits the r3/r4 cluster drivers use. `oracle_nn` additionally "
      "allows an init picked using the test target and is an UPPER BOUND on "
      "what better initialisation could buy, never quoted as the oracle. "
      "`code-refit gain` re-solves the codes exactly at frozen h on a 2048-"
      "state subsample: a value of 1.000 means the codes had already "
      "converged.\n")
    # ---- K ladder and trajectory learning curve ----------------------------
    kl = {}
    for r in rows:
        if r["traj_fit"] == 576 and not r["spec"].get("h_ff") \
                and not r["spec"].get("z_noise") \
                and r["spec"].get("hidden") == 1024 \
                and r["spec"].get("layers") == 3 \
                and not r["spec"].get("norm") and not r["spec"].get("wd") \
                and not r["spec"].get("w") and not r["spec"].get("zinit") \
                and not r["spec"].get("z_polish_every") \
                and not r["spec"].get("steps"):
            cur = kl.get((r["src"], r["k"]))
            if cur is None or (r["steps"] or 0) > (cur["steps"] or 0):
                kl[(r["src"], r["k"])] = r
    if kl:
        w("## The K ladder (h = 1024x3, all other knobs at their defaults)\n")
        w("| source bank | K | recon (train) | oracle (fresh) | oracle/floor |")
        w("|---|---|---|---|---|")
        for (src, k) in sorted(kl, key=lambda t: (t[0], t[1])):
            r = kl[(src, k)]
            w(f"| `{src}` | {k} | {fmt(r['recon'])} | {fmt(r['oracle'])} | "
              f"**{r['ratio']:.1f}x** |")
        w("")
    lc = [r for r in rows if r["hold"] is not None]
    if lc:
        w("## Trajectory learning curve (held-out cohort, never fitted)\n")
        w("| arm | K | h | fitted trajectories | held-out oracle | "
          "held-out oracle / that cohort's span floor | n states |")
        w("|---|---|---|---|---|---|---|")
        for r in sorted(lc, key=lambda z: (z["name"], z["traj_fit"])):
            sp = r["spec"]
            w(f"| `{r['name']}` | {r['k']} | "
              f"{sp.get('hidden')}x{sp.get('layers')} | {r['traj_fit']} | "
              f"**{fmt(r['hold'])}** | {r['hold_ratio']:.1f}x | "
              f"{r['n_hold']} |")
        w("")
    w("## Reparameterisation gates\n")
    w("| file | whitening round-trip | q == L^T h |")
    w("|---|---|---|")
    for nm, g in gates:
        w(f"| `{nm}` | {fmt(g['whitening_round_trip'])} | "
          f"{fmt(g['q_equals_LT_h'])} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
