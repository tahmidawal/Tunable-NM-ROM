"""Generate reports/2026-11-03-ns3d-pod-match.md from the lane's pulled run JSONs.

Every number in the report comes from experiments/ns3d-pod-match/runs/*/output/**.json; the
gates are recomputed here from the floors (not copied from the driver's verdict) and the two
are required to agree. The fixed prose is in this script; every number is substituted. Usage:
  /home/tahmid/Dev/.venv/bin/python reports/build_2026-11-03-ns3d-pod-match.py [--runs DIR]
"""
from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANE = ROOT / "experiments/ns3d-pod-match"
MESHES = ("32", "64", "96")
ARMS = (("bank_a", "(a) A3 recipe: VP + band penalty"), ("bank_b", "(b) POD-guided regression"))


def pct(x, d=3):
    return "n/a" if x is None else f"{100 * x:.{d}f} %"


def sci(x, d=2):
    return "n/a" if x is None else f"{x:.{d}e}"


def load(runs, job):
    p = runs / job / "output" / "summary.json"
    return json.loads(p.read_text()) if p.exists() else None


def recompute_gates(s, R=64):
    f = s["floors"]
    ratio = {m: f[m][f"coordnet_R{R}"]["evolved_worst"] / f[m]["parent_pod_R64"]["evolved_worst"] for m in MESHES}
    fl = [f[m][f"coordnet_R{R}"]["evolved_worst"] for m in MESHES]
    orth = {m: f[m]["bank"]["orthonormality_before_lowdin"] for m in MESHES}
    g1 = all(r <= 1.5 for r in ratio.values())
    g2 = max(fl) / min(fl) <= 1.25
    g3 = all(orth[m] <= 1e-3 for m in ("64", "96"))
    return dict(ratio=ratio, spread=max(fl) / min(fl), orth=orth, g1=g1, g2=g2, g3=g3, all=g1 and g2 and g3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=Path, default=LANE / "runs")
    ap.add_argument("--out", type=Path, default=ROOT / "reports/2026-11-03-ns3d-pod-match.md")
    args = ap.parse_args()
    S = {job: load(args.runs, job) for job, _ in ARMS}
    roms = {n: (json.loads((args.runs / f"dev{n}/output/mesh/summary.json").read_text())
                if (args.runs / f"dev{n}/output/mesh/summary.json").exists() else None) for n in MESHES}
    L = []
    w = L.append
    G = {}
    for job, _ in ARMS:
        s = S[job]
        if s is None or "floors" not in s or "bank" not in s["floors"].get("96", {}):
            G[job] = None
            continue
        G[job] = recompute_gates(s)
        drv = s["gates"].get("verdict")
        mine = "pass" if G[job]["all"] else "fail"
        if s["status"] == "final" and drv != mine:
            raise SystemExit(f"{job}: driver verdict {drv} != recomputed {mine}")

    w("# NS 3D: does a properly trained coordinate-network bank reach the POD-64 floor?")
    w("")
    w("Lane `exp/2026-11-03-ns3d-pod-match` (pre-registration `experiments/ns3d-pod-match/DESIGN.md` + §A1). "
      "Two staged (Adam → L-BFGS) fits of the parent lane's curl-of-MLP coordinate-network bank at $R=64$, "
      "judged against pre-registered floor gates on the 16 development cases. **Numbers are final for this lane** "
      "(development cohort only; the test cohort 202609221 was not opened). Generated by "
      "`reports/build_2026-11-03-ns3d-pod-match.py` from the pulled run JSONs; no number is typed by hand.")
    w("")
    # ---------------------------------------------------------------- verdict
    w("## Verdict")
    w("")
    w("| arm | job | status | G1 floor ≤ 1.5× POD-64 (all meshes) | G2 floor max/min ≤ 1.25 | G3 pre-Löwdin ≤ 1e-3 (64³, 96³) | bank passes |")
    w("|---|---|---|---|---|---|---|")
    for job, name in ARMS:
        s, g = S[job], G[job]
        if s is None:
            w(f"| {name} | — | not run / not pulled | | | | |")
            continue
        if g is None:
            w(f"| {name} | {s.get('job_id')} | {s.get('status')} (no gate inputs) | — | — | — | no verdict |")
            continue
        yn = lambda b: "PASS" if b else "FAIL"
        w(f"| {name} | {s.get('job_id')} | {s['status']} | {yn(g['g1'])} (worst {max(g['ratio'].values()):.2f}×) "
          f"| {yn(g['g2'])} ({g['spread']:.3f}) | {yn(g['g3'])} ({sci(g['orth']['64'])}, {sci(g['orth']['96'])}) "
          f"| **{'yes' if g['all'] and s['status'] == 'final' else 'no'}** |")
    w("")
    # ---------------------------------------------------------------- floors
    w("## Projection floors per mesh (oracle centroid, development evolved worst)")
    w("")
    w("| mesh | POD-64 (parent recipe, in-job) | same-data POD-64 | arm (a) R=64 | (a)/POD | arm (b) R=64 | (b)/POD | parent pilot bank (reference, parent lane) |")
    w("|---|---|---|---|---|---|---|---|")
    pilot_src = LANE.parent / "ns3d-coordnet/runs"
    pf = {}
    for n in MESHES:
        p = pilot_src / f"dev{n}/output/mesh/summary.json"
        if p.exists():
            pf[n] = json.loads(p.read_text())["floors"]["coordnet_R64"]["evolved_worst"]
    for n in MESHES:
        row = [f"{n}³"]
        ref = None
        for job, _ in ARMS:
            s = S[job]
            if s and n in s.get("floors", {}):
                ref = s["floors"][n]
                break
        row.append(pct(ref["parent_pod_R64"]["evolved_worst"]) if ref else "n/a")
        row.append(pct(ref["same_data_pod_R64"]["evolved_worst"]) if ref else "n/a")
        for job, _ in ARMS:
            s = S[job]
            e = s["floors"].get(n, {}) if s else {}
            if "coordnet_R64" in e:
                row += [pct(e["coordnet_R64"]["evolved_worst"]),
                        f"{e['coordnet_R64']['evolved_worst'] / e['parent_pod_R64']['evolved_worst']:.2f}×"]
            else:
                row += ["n/a", ""]
        row.append(pct(pf.get(n)))
        w("| " + " | ".join(row) + " |")
    w("")
    w("The parent pilot bank's floors are read from the parent lane's dev jobs (`experiments/ns3d-coordnet/runs/dev*/`).")
    w("")
    # ---------------------------------------------------------------- objective vs optimum
    w("## Training objective against its optimum")
    w("")
    w("VP objective = fraction of the weighted training data outside the bank's span (exact, NumPy SVD), raw sampled bank and $P_{48}$-projected bank; optimum = the same-data weighted POD (Eckart–Young). Parent pilot (30-min Adam): 5.19e-05 vs 3.73e-07.")
    w("")
    w("| arm | stage | steps / iterations | training objective | VP raw | VP projected | VP raw / optimum | band fraction > 10 | stop |")
    w("|---|---|---|---|---|---|---|---|---|")
    for job, name in ARMS:
        s = S[job]
        if not s:
            continue
        for st in s.get("stages", []):
            n_ = st.get("steps", st.get("iterations", ""))
            w(f"| {name} | {st['stage']} | {n_} | {sci(st['objective']['total'], 3)} | {sci(st['vp_exact_raw'], 3)} | "
              f"{sci(st['vp_exact_projected'], 3)} | {st['vp_raw_over_optimum']:.2f} | {sci(st['band_fraction_above_10'])} | {st.get('stop', '')} |")
        if s.get("eckart_young_optimum") is not None:
            w(f"| {name} | optimum | | | {sci(s['eckart_young_optimum'], 3)} | | 1.00 | | |")
    w("")
    for job, name in ARMS:
        s = S[job]
        if not s or not s.get("stages"):
            continue
        st0 = s["stages"][0]
        extra = ""
        if len(s["stages"]) > 1:
            st1 = s["stages"][1]
            extra = (f" L-BFGS: {st1.get('iterations')} iterations, {st1.get('linesearch_evaluations')} line-search "
                     f"evaluations in {st1.get('seconds', 0) / 3600:.2f} h, objective {sci(st1.get('start_value'), 3)} → "
                     f"{sci(st1['objective']['total'], 3)}.")
        w(f"- {name}: Adam {st0.get('steps')} steps at {1e3 * st0.get('seconds_per_step', 0):.0f} ms/step "
          f"({st0.get('seconds', 0) / 3600:.2f} h).{extra}")
        if "column_rel_error_grid" in s["stages"][-1]:
            c = s["stages"][-1]["column_rel_error_grid"]
            picks = ", ".join(f"column {i} {c[i - 1]:.2e}" for i in (1, 8, 16, 32, 48, 64) if i <= len(c))
            w(f"  Per-column relative regression error on the 48³ grid (bank of record): {picks}; worst {max(c):.2e}.")
    w("")
    # ---------------------------------------------------------------- one-bank diagnostics
    w("## One bank on three meshes: diagnostics")
    w("")
    w("| arm | mesh | pre-Löwdin deviation | same-data POD, same statistic (control) | Löwdin change | cross-mesh worst column vs 32³ | prefix floors R'=8/16/32/48 | Adam-stage R=64 floor | no-centring control |")
    w("|---|---|---|---|---|---|---|---|---|")
    for job, name in ARMS:
        s = S[job]
        if not s:
            continue
        for n in MESHES:
            e = s.get("floors", {}).get(n, {})
            if "bank" not in e:
                continue
            pre = " / ".join(pct(e[f"coordnet_R{r}"]["evolved_worst"], 2) if f"coordnet_R{r}" in e else "–" for r in (8, 16, 32, 48))
            ad = e.get("adam_stage", {})
            adv = pct(ad["coordnet_R64"]["evolved_worst"]) if "coordnet_R64" in ad else ad.get("error", "n/a")
            cm = e.get("cross_mesh_vs_smallest", {}).get("worst_column")
            w(f"| {name} | {n}³ | {sci(e['bank']['orthonormality_before_lowdin'])} | {sci(e.get('same_data_pod_G3_statistic'))} | "
              f"{sci(e['bank']['lowdin_relative_change'])} | {sci(cm) if cm is not None else '—'} | {pre} | {adv} | "
              f"{pct(e.get('coordnet_no_centring', {}).get('evolved_worst'), 1)} |")
    w("")
    for job, name in ARMS:
        s = S[job]
        if s and "derivatives" in s.get("floors", {}).get("32", {}):
            d32 = s["floors"]["32"]["derivatives"].get("worst_column")
            d64 = s["floors"].get("64", {}).get("derivatives", {}).get("worst_column")
            w(f"- {name}: autodiff vs spectral derivative of the raw sampled bank, worst column: 32³ {sci(d32)}, 64³ {sci(d64)} "
              f"(parent pilot 1.75e-01 at 32³, 2.0e-02 at 64³; diagnostic of band-limitedness).")
    w("")
    # ---------------------------------------------------------------- ROM
    w("## Development ROM")
    w("")
    if not any(roms.values()):
        w("Not run: by the pre-registered stop rule (DESIGN §5), the ROM runs only for a bank that passes G1–G3.")
    else:
        w("| mesh | job | coordnet head k=8 | its bank floor | head / floor | POD head (paper) | head / POD head | frame-zero control | 96³ speed-up vs CNAB2 |")
        w("|---|---|---|---|---|---|---|---|---|")
        for n in MESHES:
            r = roms[n]
            if r is None:
                w(f"| {n}³ | not run | | | | | | | |")
                continue
            ch = r["rollouts"]["coordnet_head_k8"]["stats"]["evolved_worst"]
            fl = r["floors"]["coordnet_R64"]["evolved_worst"]
            ph = r["rollouts"]["pod_head_k8"]["stats"]["evolved_worst"]
            sp = r["comparators"].get("coordnet_head_k8", {}).get("speedup")
            w(f"| {n}³ | {r.get('job_id')} | {pct(ch)} | {pct(fl)} | {ch / fl:.2f} | {pct(ph)} | {ch / ph:.2f} | "
              f"{pct(r['control_frame_zero']['evolved_worst'], 1)} | {'' if sp is None else f'{sp:.2f}×'} |")
    w("")
    # ---------------------------------------------------------------- provenance
    w("## Provenance")
    w("")
    for job, name in ARMS:
        s = S[job]
        if s:
            w(f"- {name}: job {s.get('job_id')}, {s.get('gpu')}, commit {s.get('source_commit')}, "
              f"elapsed {s.get('elapsed_seconds', 0) / 3600:.2f} h, failures {s.get('failures')}.")
    for n in MESHES:
        if roms[n]:
            w(f"- dev{n}: job {roms[n].get('job_id')}, {roms[n].get('gpu')}, status {roms[n].get('status')}, failures {roms[n].get('failures')}.")
    w("")
    # ---------------------------------------------------------------- glossary
    w("## Glossary")
    w("")
    for term, text in (
        ("bank", "the fixed spatial basis (64 vector fields) in which the reduced model's state lives."),
        ("coordinate network / coordnet bank", "one neural network that returns the 64 fields at any point, so the same bank can be read on any grid (32³, 64³, 96³)."),
        ("POD-64", "the best 64-field linear basis for a set of snapshots; the reference here is built per mesh from 128 training trajectories (the paper's recipe)."),
        ("same-data POD-64", "the POD of this lane's own pooled training data on the 48³ training grid: the optimum the network fits aim at."),
        ("projection floor (oracle centroid)", "the error of the best reconstruction of a true development state in the bank, after centring it on its true energy centroid; reported as the worst over cases of the worst over output times after t=0."),
        ("G1 / G2 / G3", "the pre-registered gates: floor within 1.5× POD-64 at every mesh; floors within a factor 1.25 across meshes; the bank as read at 64³/96³ within 1e-3 of orthonormal before clean-up."),
        ("pre-Löwdin deviation", "largest entry of BᵀB − I for the sampled, projected, ordered bank B before it is symmetrically orthonormalised; measures whether the network reads the same on that mesh as on the training grid."),
        ("VP objective, optimum", "fraction of the weighted training data that lies outside the bank's span; its smallest possible value over all 64-dimensional subspaces (Eckart–Young) is the optimum."),
        ("band fraction > 10", "fraction of the bank's energy at Fourier wave numbers with max|k_i| > 10, which a 32³ grid cannot carry."),
        ("arm (a) / arm (b)", "the two training recipes: (a) the parent's planned A3 recipe (VP objective + band penalty); (b) regression of each network field onto the corresponding POD mode with value and gradient targets off the grid."),
        ("Adam / L-BFGS", "first-order and quasi-Newton optimisers; each arm ran Adam then L-BFGS on the same objective."),
        ("prefix R'", "the first R' fields of the ordered bank."),
        ("no-centring control", "projection without the centroid shift; must be large (> 5 %), which shows the frame does the work."),
        ("head k=8, frame-zero control, CNAB2", "the ROM's 8-number nonlinear decoder on top of the bank; the same ROM with the moving frame switched off (must fail); the full-order pseudo-spectral solver used as truth and as speed comparator."),
        ("development cohort", "16 cases (seed 202609202) used for every check here; the test cohort stays closed."),
    ):
        w(f"- **{term}**: {text}")
    args.out.write_text("\n".join(L) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
