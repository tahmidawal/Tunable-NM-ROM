#!/usr/bin/env python3
"""Cross-resolution speed AND accuracy table, FROM THE RUN JSONS ONLY.

    python runs/gen_cross_resolution.py runs/push_*/out/*.json > CROSS-RESOLUTION.md

Speed columns come from the round-4 speed sweeps (`kind == profile+speed`),
accuracy columns from the training runs (rounds 3 and 4).  Rows are joined on
(N, architecture); a row whose architecture differs from the reference
K=16 / R=512 / G_HIDDEN=1024 single-scale recipe is MARKED, because the old
scaling-study checkpoints at N=128 and N=512 are the rank-capped R=64 / R=96
decoders and must not be read as points on the same curve.
"""
import json
import os
import sys

import numpy as np

REF = dict(k=16, r=512, g_hidden=1024)


def f(x, p=3):
    return "--" if x is None else f"{x:.{p}e}"


def g(x, p=2):
    return "--" if x is None else f"{x:.{p}f}"


def arch_of(c):
    a = c.get("arch_overrides", {}) or {}
    return dict(k=c.get("k"), r=c.get("r"), g_hidden=a.get("g_hidden", 128),
                h_hidden=a.get("h_hidden", 128), h_layers=a.get("h_layers", 2),
                ff="multi" if a.get("ff_scales") else "single",
                snap_norm=bool(c.get("snap_norm")),
                w_early=c.get("w_early", 1.0), z_polish=c.get("z_polish", 0),
                eq_tail=bool(c.get("eq_tail", False)))


def astr(a):
    s = (f"K{a['k']}/R{a['r']}/g{a['g_hidden']}/h{a['h_hidden']}x"
         f"{a['h_layers']}/{a['ff']}")
    for k, dflt in (("snap_norm", False), ("w_early", 1.0), ("z_polish", 0),
                    ("eq_tail", False)):
        if a.get(k) != dflt:
            s += f"/{k}={a[k]}"
    return s


def is_ref(a):
    return all(a[k] == v for k, v in REF.items())


def champ_row(d):
    rows = [r for r in d["rows"] if r.get("method", "").startswith(("cach", "mesh"))]
    want = "cach|ctrl|ic_enc|roll_extrap|t1e-9"
    for r in rows:
        if r["method"] == want:
            return r
    return min(rows, key=lambda r: r["err_traj_rel_mean"]) if rows else None


def batch_at(d, B, prefix):
    e = [x for x in d.get("batch_sweep", [])
         if x["batch"] == B and x["subject"].startswith(prefix)]
    return min(e, key=lambda x: x["amortized_ms"]) if e else None


def main(paths):
    speed, train = [], []
    for p in sorted(paths):
        try:
            d = json.load(open(p))
        except Exception:
            continue
        c = d.get("config", {})
        if not d.get("complete"):
            continue
        if c.get("kind") == "profile+speed":
            speed.append((p, d))
        elif c.get("round") in (3, 4) and c.get("pde") == "burgers2d":
            train.append((p, d))

    print("# Speed and accuracy across resolutions\n")
    print("Generated by `runs/gen_cross_resolution.py` from the committed run "
          "JSONs. Nothing is hand-typed.\n")
    print("The reference recipe is **K=16, R=512, G_HIDDEN=1024 (= 2R, which "
          "is what lifts the bank rank cap), single-scale Fourier features, "
          "point-pool trainer, 300k steps**. Any row on a different "
          "architecture is marked in the `arch` column and is NOT a point on "
          "the same curve.\n")
    print("`optimized` = the fastest solve-path variant whose trajectory error "
          "stays within 1.02x of the base arm (Gram-space IC fit + adaptive "
          "stall threshold). The decoder is identical between `base` and "
          "`optimized`; only the solve path differs.\n")

    print("## S1. Speed across resolutions\n")
    print("| N | arch | ROM base ms | ROM optimized ms | ROM err | "
          "matched classical ms | its err | single-query ratio (paired) | "
          "batch-16 ROM ms/q | batch-16 classical ms/q | batch-16 ratio | "
          "jac/step | gate 0 |")
    print("|" + "---|" * 13)
    for p, d in sorted(speed, key=lambda pd: pd[1]["config"]["N"]):
        c = d["config"]
        a = arch_of(c.get("ckpt_cfg", {}))
        base = [v for v in d["variants"] if v["name"] == "base"][0]
        ma = d.get("matched_accuracy", {})
        pr = ma.get("paired")
        opt = [v for v in d["variants"] if v["name"] == ma.get("rom_arm")]
        opt = opt[0] if opt else None
        b16r = batch_at(d, 16, "rom|" + str(ma.get("rom_arm", "")))
        b16f = batch_at(d, 16, "fom")
        ratio16 = (b16f["amortized_ms"] / b16r["amortized_ms"]
                   if (b16r and b16f) else None)
        mark = "" if is_ref(a) else " **(off-curve)**"
        print(f"| {c['N']} | `{astr(a)}`{mark} | {g(base['e2e_ms_median'])} | "
              f"{g(ma.get('rom_e2e_ms'))} | {f(ma.get('rom_err'))} | "
              f"{g(ma['matched']['ms']) if ma.get('matched') else '--'} | "
              f"{f(ma['matched']['err']) if ma.get('matched') else '--'} | "
              f"{(g(pr['base_ms']/pr['rom_ms']) + 'x') if pr else '--'} | "
              f"{g(b16r['amortized_ms']) if b16r else '--'} | "
              f"{g(b16f['amortized_ms']) if b16f else '--'} | "
              f"{(g(ratio16) + 'x') if ratio16 else '--'} | "
              f"{g(opt['jac_total_mean']/50.0, 2) if opt else '--'} | "
              f"{f(d['eq']['ctrl']['gate0'])} |")
    have = {d["config"]["N"] for _, d in speed}
    miss = [n for n in (128, 256, 512, 1024) if n not in have]
    if miss:
        print(f"\n**Missing from the curve:** N = "
              f"{', '.join(str(m) for m in miss)} (no round-4 speed sweep on a "
              f"reference-architecture checkpoint yet).")
    print()

    print("## S2. Amortization curve (ms per query, optimized ROM vs the "
          "matched classical rung)\n")
    Bs = sorted({e["batch"] for _, d in speed for e in d.get("batch_sweep", [])})
    if Bs:
        print("| N | subject | " + " | ".join(f"B={b}" for b in Bs) + " |")
        print("|" + "---|" * (2 + len(Bs)))
        for p, d in sorted(speed, key=lambda pd: pd[1]["config"]["N"]):
            ma = d.get("matched_accuracy", {})
            for lbl, pref in (("ROM optimized", "rom|" + str(ma.get("rom_arm", ""))),
                              ("ROM base", "rom|base"),
                              ("classical (matched)", "fom")):
                cells = []
                for B in Bs:
                    e = batch_at(d, B, pref)
                    cells.append(g(e["amortized_ms"]) if e else "--")
                print(f"| {d['config']['N']} | {lbl} | " + " | ".join(cells) + " |")
        print()

    print("**Caveat on the batched columns, stated because it works in the "
          "ROM's favour.** Both sides are `vmap`ped over queries, and a "
          "`vmap` of a `lax.while_loop` runs until EVERY lane has finished, so "
          "each batched solve pays its batch's worst-case iteration count. "
          "That penalises the classical solver much more than the ROM, "
          "because a classical iteration is expensive and a latent LM "
          "iteration is not -- visible above as the classical per-query cost "
          "getting WORSE from B=1 to B=2 at N=1024. A production many-query "
          "classical solver would let queries terminate independently "
          "(separate streams, or a batched solve with per-lane exit), so the "
          "batched ratios here are an upper bound on the ROM's advantage, not "
          "a measurement of the best possible classical batching.\n")

    print("## S3. Accuracy ladder across resolutions\n")
    print("Every rung on fresh test trajectories except reconstruction, which "
          "is on the training states. `span LS floor` is the unconstrained "
          "R-coefficient least-squares floor of the LEARNED bank -- the best "
          "any map h could reach inside the span it was given.\n")
    print("| N | arch | job | recon | span LS floor | oracle (K-dim) | "
          "rollout err | oracle / span floor | steps |")
    print("|" + "---|" * 9)
    for p, d in sorted(train, key=lambda pd: (pd[1]["config"]["N"],
                                              str(arch_of(pd[1]["config"])))):
        c, t = d["config"], d.get("train", {})
        a = arch_of(c)
        orc = d.get("oracle", [])
        om = float(np.mean([o["mean"] for o in orc])) if orc else None
        sp = d.get("span", {}).get("ls_floor_mean")
        cr = champ_row(d)
        mark = "" if is_ref(a) else " **(off-curve)**"
        gap = (om / sp) if (om and sp) else None
        print(f"| {c['N']} | `{astr(a)}`{mark} | `{c.get('slurm_job')}` | "
              f"{f(t.get('recon_rel_l2_mean'))} | {f(sp)} | {f(om)} | "
              f"{f(cr['err_traj_rel_mean']) if cr else '--'} | "
              f"{(g(gap, 1) + 'x') if gap else '--'} | "
              f"{t.get('steps_done')} |")
    print()


if __name__ == "__main__":
    main(sys.argv[1:])
