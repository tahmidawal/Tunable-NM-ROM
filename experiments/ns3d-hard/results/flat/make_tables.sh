#!/usr/bin/env bash
# Regenerate results/flat/tables.md from the job JSONs (no hand-typed numbers).
set -euo pipefail
cd "$(dirname "$0")/../.."
R=results/flat; S=../../../2026-11-11-ns3d-hard-rank/experiments/ns3d-hard/results
join() { local out=""; for f in "$@"; do [ -f "$f" ] && out="${out:+$out+}$f"; done; echo "$out"; }
{
echo "# Split timing of the frozen fresh-cohort arms (seed 0) and the replicate-1 timing rerun"
echo
echo "Generated by results/flat/make_tables.sh from the job JSONs in results/flat/. ENC = centroid + centring"
echo "shift + projection of the initial field; FIT = initial code (reduced); SOLVE = reduced online solve;"
echo "DEC = reconstruction of the six output fields (frame by frame, as the reported query); FULL = the"
echo "source query as reported in Table G1 (monolithic); DECB = DEC with one batched matmul (not in FULL)."
echo "FULL ratio / SOLVE-only ratio = matched solver (any mesh, solve-only, as selected in fresh_s0b) divided"
printf "%b\n" "by ROM FULL / ROM SOLVE, all from the same interleaved block. solver e2e = the same solver configuration\nincluding truncation of the initial field to its mesh and spectral transfer of the six outputs to mesh n\n(both sides then deliver fields on the n^3 grid); e2e/FULL = that time divided by ROM FULL."
echo
echo "## A100 80 GB PCIe (the GPU type of fresh_s0b)"
echo
python3 split_table.py split "$(join $R/split_a100/split.json $R/split_a100b/split.json $R/split_a100c/split.json)"
echo
echo "## H200 (only GPU that holds the 256^3 rank-192 basis in f64)"
echo
python3 split_table.py split "$(join $R/split_h200/split.json $R/split_h200b/split.json $R/split_h200e/split.json $R/split_h200f/split.json)"
echo
echo "## Replicate-1 fresh-cohort comparison: timing reruns"
echo
python3 split_table.py rerun $(ls $S/fresh_s1/compare.json $S/fresh_s1b/compare.json $R/fresh_s1c/compare.json 2>/dev/null)
} > $R/tables.md
echo "wrote $R/tables.md"
