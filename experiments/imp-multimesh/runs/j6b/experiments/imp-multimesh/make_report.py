def f(x, d=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return 'n/a'
    if isinstance(x, (int, np.integer)):
        return str(x)
    a = abs(x)
    if a != 0 and (a < 1e-3 or a >= 1e5):
        return f'{x:.{d - 1}e}'
    return f'{x:.{d}g}'


def pct(x):
    return 'n/a' if x is None else f'{100 * x:.3g} %'


def a100_validation():
    log = A100_LOG.read_text()
    st = lambda n: float(re.search(rf'step +{n}/300000 .*\[(\d+)s\]', log).group(1))
    done = float(re.search(r'done: recon.*\[(\d+)s\]', log).group(1))
    rs = (st(15000) - st(5000)) / 10000
    rf = (st(300000) - st(295000)) / 5000
    tau = (st(295000) - st(290000)) - 5000 * rf
    T = st(1) + 289999 * rs + tau + 10000 * rf + (done - st(300000))
    return dict(rho_sub=rs, rho_full=rf, tau=tau, projected=T, recorded=10684.65, rel=T / 10684.65 - 1)


