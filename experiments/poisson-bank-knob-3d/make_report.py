w('|---|---|---|---|---:|---:|---|---:|---:|---|---|---|')
for e in sorted(ALL, key=lambda e: (e['problem'] != 'lshape', e['intervals'])):
    a = e['alt']; r2 = a['row']
    w(f"| {prob(e)} | {unit(e)} | {SC[a['scope']]} | {label(r2['accurate'])} | {f(r2['accurate_worst_pct'])} | "
      f"{sp(r2['accurate_speedup'])} | {label(r2['fast'])} | {f(r2['fast_worst_pct'])} | {sp(r2['fast_speedup'])} | "
      f"CG rtol {r2['fom'].split('_')[1] if r2['fom'] else '—'} | {f(a['order_gate']['pooled_paired_ratio'])} / "
      f"{f(a['order_gate']['max_arm_paired_ratio'])} | {'yes' if a['usable'] else 'NO'} |")
w('')
w('## Where the speed comes from')
w('')
w("The selected arms change two things at once relative to the paper's settings: the truncation $R'$, and the "
  "family (NM-ROM with the head, or the linear rung with the head dropped). The table separates the two. "
  "*Truncation gain* = the time of the same-family arm at $R'=R$ divided by the selected arm's time; it is the part "
  "that $R'$ alone buys. *vs paper setting* = the time of the paper's arm at the same $q$ (for the cube at $n\\le64$ "
  "this is the dense-projection `poisson.engine`, elsewhere the unrotated parent) divided by the selected arm's "
  "time. At $32^3$ and $64^3$ the accurate arm is the full-rank ($R'=R=128$) linear rung: its gain over the paper "
  "setting comes from dropping the head (no LM) and from the DST query route, not from truncation. The L-shape "
  "linear rung has no full-rank counterpart ($M=257<R$), so its truncation gain is not defined.")
w('')
w('| problem | mesh | setting | selected arm | ms | same family at $R\'=R$ | ms | truncation gain | paper arm | ms | vs paper setting |')
w('|---|---|---|---|---:|---|---:|---:|---|---:|---:|')
for v in sorted(V, key=lambda v: (v['e']['problem'] != 'lshape', v['e']['intervals'])):
    e = v['e']
    A = {a['name']: a for a in v['arms']}
    R_full = max(a['Rp'] for a in v['arms'])
    for which in ('accurate', 'fast'):
        name = v['row'][which]
        a = A[name]
        if a['family'] == 'linear-rung':
            twin = f'R{R_full}_linear'
        else:
            twin = f"R{R_full}_q{a['q']}"
        tw = A.get(twin)
        # the paper's own accurate rank for this row (Table 1 as of 2026-09-22), and q = 0 for fast
        qq = 96 if e['problem'] == 'cube' else (64 if e['intervals'] <= 512 else 128)
        if which == 'fast':
            qq = 0
        paper = f'engine_q{qq}' if f'engine_q{qq}' in A else f'orig_q{qq}'
        pa = A.get(paper)
        w(f"| {prob(e)} | {unit(e)} ({SC[v['scope']]}) | {which} | {label(name)} | {f(a['ms'])} | {label(twin) if tw else 'n/c'} | "
          f"{f(tw['ms']) if tw else '—'} | {sp(tw['ms'] / a['ms']) if tw else '—'} | {label(paper) if pa else '—'} | "
          f"{f(pa['ms']) if pa else '—'} | {sp(pa['ms'] / a['ms']) if pa else '—'} |")
