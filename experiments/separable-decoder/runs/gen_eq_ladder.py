"""Generate EQ-LADDER.md from sep_eq_ladder_*.json files.

Usage:  python runs/gen_eq_ladder.py runs/lad*/out/sep_eq_ladder_*.json > EQ-LADDER.md

Every number in the output comes from the JSONs; nothing is typed by hand.
"""
import json
import sys
import numpy as np

KEYS = [("b_resid", "(b) resid"), ("b_lin", "  lin part"), ("b_adv", "  adv part"),
        ("c1_grad", "(c1) grad"), ("c1_cos", "  cos"), ("c1_abs", "  abs"),
        ("c2_hess", "(c2) hess"), ("c3_step", "(c3) LM step"), ("c3_cos", "  cos"),
        ("c3_gn", "  GN step")]
BUCKETS = [(0, 0), (1, 1), (2, 2), (3, 4), (5, 9), (10, 24), (25, 50)]


def fmt(v, cos=False):
    if v is None:
        return "—"
    return f"{v:.4f}" if cos else f"{v:.2e}"


def agg(recs, key, stat):
    vals = [r[key] for r in recs if key in r]
    if not vals:
        return None
    if stat == "mean":
        return float(np.mean(vals))
    if stat == "median":
        return float(np.median(vals))
    return float(np.min(vals)) if "cos" in key else float(np.max(vals))


def main(paths):
    out = []
    out.append("# EQ fidelity ladder — sampled quadrature vs exact full-grid weak form\n")
    out.append("Generated by `runs/gen_eq_ladder.py` from the JSONs listed at the end. "
               "Each rung compares a solver quantity computed with the m-node NNLS "
               "quadrature (what runs online) against the same quantity on the full "
               "interior grid. (b) residual, split into its linear part (Φᵀu terms, "
               "could be exact) and advection part (ΦᵀN(u), needs sampling), each "
               "relative to ‖R_f‖; (c1) gradient JᵀR; (c2) normal operator JᵀJ; (c3) "
               "the damped LM step at the solver's own λ. `cos` is the cosine between "
               "sampled and full vectors (1 = same direction). Rows are means over "
               "all recorded states in the time bucket; `n` counts states.\n")
    for p in paths:
        d = json.load(open(p))
        c = d["config"]
        out.append(f"\n## {c['ckpt']} — N={c['N']}, K={c['k']}, R={c['r']}"
                   f"{'' if d.get('complete') else '  (INCOMPLETE)'}\n")
        out.append(f"GPU {c.get('gpu')} · backend {c.get('backend')} · job "
                   f"{c.get('slurm_job')} · n_test {c['n_test']} · stall {c['stall']} "
                   f"· extrap {c['extrap']} · tail-capped NNLS {c.get('eq_tail')}\n")
        out.append("\n**EQ sets and gates**\n\n| set | M | m | NNLS rel fit | row p95 | row max | gate 0 | gate F | gate L | gate A |\n|---|---|---|---|---|---|---|---|---|---|")
        gF_glob = (d.get("gates") or {}).get("gateF")
        for name, e in d["eq"].items():
            M = e.get("m", 0) // c["eq_m_factor"]
            out.append(f"| {name} | {M} | {e.get('m')} | {fmt(e.get('rel_fit'))} | "
                       f"{fmt(e.get('row_rel_p95'))} | {fmt(e.get('row_rel_max'))} | "
                       f"{fmt(e.get('gate0'))} | {fmt(e.get('gateF', gF_glob))} | "
                       f"{fmt(e.get('gateL'))} | {fmt(e.get('gateA'))} |")
        if d.get("rollout"):
            out.append("\n**ROM rollouts used for the solver-path states** (full-grid "
                       "error vs truth; sanity, not the headline accuracy protocol)\n\n"
                       "| set | traj | ν | rollout err (mean over t) | t=0 | t=1 | t=50 | LM iterates | stop reasons |\n|---|---|---|---|---|---|---|---|---|")
            for r in d["rollout"]:
                rs = {}
                for x in r["reasons"]:
                    rs[x] = rs.get(x, 0) + 1
                out.append(f"| {r['eq']} | {r['traj']} | {r['nu']:.3e} | "
                           f"{r['err_mean']:.3e} | {r['err_per_t'][0]:.2e} | "
                           f"{r['err_per_t'][1]:.2e} | {r['err_per_t'][-1]:.2e} | "
                           f"{r['n_iters_total']} | {rs} |")
        recs = d["records"]
        for kind, title in (("solver", "Solver-path states (every LM iterate of the ROM rollout; off-manifold)"),
                            ("heldout", "HELD-OUT fit-side iterates (training rollouts; excluded from every row build)"),
                            ("oracle", "Oracle states (full-grid LS code of the truth state; on-manifold)"),
                            ("train", "Training snapshots")):
            rk = [r for r in recs if r["kind"] == kind]
            if not rk:
                continue
            out.append(f"\n**{title}**\n")
            hdr = "| set | t | n | " + " | ".join(k[1] for k in KEYS) + " |"
            out.append(hdr)
            out.append("|" + "---|" * (3 + len(KEYS)))
            for name in d["eq"]:
                for lo, hi in BUCKETS:
                    rs = [r for r in rk if r["eq"] == name and lo <= r["t"] <= hi]
                    if not rs:
                        continue
                    tl = f"{lo}" if lo == hi else f"{lo}–{hi}"
                    cells = [fmt(agg(rs, k, "mean"), cos="cos" in k) for k, _ in KEYS]
                    out.append(f"| {name} | {tl} | {len(rs)} | " + " | ".join(cells) + " |")
                # worst case row
                rs = [r for r in rk if r["eq"] == name]
                cells = [fmt(agg(rs, k, "max"), cos="cos" in k) for k, _ in KEYS]
                out.append(f"| {name} | **worst** | {len(rs)} | " + " | ".join(cells) + " |")
            if kind == "oracle":
                out.append("\n(a) recon error at the oracle code, on the m nodes "
                           "(quadrature-weighted RMS) vs on the full grid:\n\n"
                           "| set | t | n | recon full | recon on nodes (w-RMS) | recon on nodes (plain) | ratio nodes/full |\n|---|---|---|---|---|---|---|")
                for name in d["eq"]:
                    for lo, hi in BUCKETS:
                        rs = [r for r in rk if r["eq"] == name and lo <= r["t"] <= hi]
                        if not rs:
                            continue
                        tl = f"{lo}" if lo == hi else f"{lo}–{hi}"
                        f_ = agg(rs, "a_recon_full", "mean")
                        p_ = agg(rs, "a_recon_pts", "mean")
                        u_ = agg(rs, "a_recon_pts_unweighted", "mean")
                        out.append(f"| {name} | {tl} | {len(rs)} | {fmt(f_)} | {fmt(p_)} | "
                                   f"{fmt(u_)} | {p_/f_ if f_ else float('nan'):.2f} |")
    out.append("\n---\nSources:\n")
    for p in paths:
        out.append(f"- `{p}`")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1:])
