import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RECON = os.path.join(HERE, "runs/stk2d/stk2d_recon_gate_recon_nu1.json")
ROM = os.path.join(HERE, "runs/stk2d/stk2d_rom_gates_rom_nu1.json")


def e(x, d=3):
    if x is None:
        return "-"
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, float) and x != x:
        return "nan"
    return f"{x:.{d}e}"


def f(x, d=3):
    return "-" if x is None else f"{x:.{d}f}"


def esc(c):
    return str(c).replace("|", "\\|")


def table(head, rows):
    out = ["| " + " | ".join(esc(h) for h in head) + " |",
           "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(esc(c) for c in r) + " |")
    return "\n".join(out)


def verdict_block():
    """The stop-gate verdict, generated so no number in it is hand-typed.
    Printed on its own so the report can lead with it."""
    RC = json.load(open(RECON))
    Gc, Cc = RC["gates"], RC["config"]
    v = Gc["S_RECON"]["verdict"]
    RM = json.load(open(ROM)) if os.path.exists(ROM) else None
    print(f"<!-- generated by stk2d_rom_tables.py verdict from "
          f"{os.path.basename(RECON)} (commit {Cc['git_commit'][:12]}) "
          f"-- do not edit by hand -->")
    print()
    print(f"**VERDICT: {'PASS' if v['passed'] else 'FAIL -- PHASE 2b STOPS'}.** "
          f"At the predeclared primary rung (N={v['N']}, R={v['R']}, "
          f"K={v['K']}, training form `{v['mode']}`, fit cohort {v['n_fit']}), "
          f"the held-out nonlinear reconstruction oracle reads "
          f"**{v['oracle_agg']:.4e}** in aggregate against POD-{v['K']}'s "
          f"{v['podK_agg']:.4e} -- a **{v['gain_agg']:.2f}x** gain against a "
          f"required 3x -- and **{v['oracle_median']:.4e}** in the per-case "
          f"median against POD-{v['K']}'s {v['podK_median']:.4e}, a "
          f"**{v['gain_median']:.2f}x** gain.  The per-case maximum is "
          f"{v['oracle_max']:.4e}.")
    print()
    pod16 = pod8 = None
    for r in Gc["S_REGR"]["rows"]:
        if r["N"] == v["N"]:
            pod16 = r["pod_reorth_route"].get("16")
            pod8 = r["pod_reorth_route"].get("8")
    if pod16:
        where = ("BELOW" if v["oracle_agg"] < pod16 else "ABOVE")
        print(f"**Where the head actually stops.** This is the question phase "
              f"2a could not answer, and the answer is a number: the finite "
              f"MLP head stops at {v['oracle_agg']:.3e} aggregate, which is "
              f"{where} the same bank's linear POD-16 error of {pod16:.3e} "
              f"(by a factor of {max(v['oracle_agg'], pod16) / min(v['oracle_agg'], pod16):.2f}) "
              f"and {v['podK_agg'] / v['oracle_agg']:.2f}x better than "
              f"POD-{v['K']} at {v['podK_agg']:.3e}.  It is NOT anywhere near "
              f"POD-32's bank-span ceiling, and phase 2a's remark that the "
              f"head had 'ten orders of headroom' is exactly the overclaim "
              f"the verification flagged: the headroom is real, the head does "
              f"not reach it.")
        print()

def s7c_prose():
    """One generated sentence on whether the direct G-span control won, so the
    claim in the report's opening is a measurement and not an expectation."""
    RM = json.load(open(ROM))
    rows = RM["gates"]["S7"]["rows"]
    won_err = all(r["err"]["gspan_direct"]["agg"] <= r["err"]["nl_qf"]["agg"]
                  for r in rows)
    won_time = all(r["times"]["rom_gspan_direct"]["median"]
                   <= r["times"]["rom_qf_nonlinear"]["median"] for r in rows)
    worst = max(rows, key=lambda r: r["err"]["gspan_direct"]["agg"])
    ratio_e = [r["err"]["nl_qf"]["agg"] / max(r["err"]["gspan_direct"]["agg"],
                                              1e-300) for r in rows]
    ratio_t = [r["times"]["rom_qf_nonlinear"]["median"]
               / r["times"]["rom_gspan_direct"]["median"] for r in rows]
    print(f"**It was predicted to win, and it did.** Across the whole mesh "
          f"ladder the direct $G$-span solve is more accurate than the "
          f"nonlinear arm by {min(ratio_e):.2g}x to {max(ratio_e):.2g}x "
          f"(worst-mesh aggregate held-out error {worst['err']['gspan_direct']['agg']:.3e} "
          f"at N={worst['N']}) and cheaper by {min(ratio_t):.0f}x to "
          f"{max(ratio_t):.0f}x per query. "
          f"{'Both comparisons hold at every mesh.' if won_err and won_time else 'NOT every comparison holds at every mesh; see the S7 and S6 tables.'} "
          f"**That is the expected outcome — not a failure of the machinery "
          f"and not a result.**")


def main():
    RC = json.load(open(RECON))
    RM = json.load(open(ROM))
    Gc, Cc = RC["gates"], RC["config"]
    Gm, Cm = RM["gates"], RM["config"]
    print(f"<!-- generated by stk2d_rom_tables.py from "
          f"{os.path.basename(RECON)} (commit {Cc['git_commit'][:12]}) and "
          f"{os.path.basename(ROM)} (commit {Cm['git_commit'][:12]}) "
          f"-- do not edit by hand -->")
    print()

    # ================================================== THE STOP GATE =======
    v = Gc["S_RECON"]["verdict"]
    print("### S-RECON -- THE STOP GATE, and its verdict\n")
    print(table(["quantity", "value"],
                [["configuration",
                  f"N={v['N']}, R={v['R']}, K={v['K']}, training form "
                  f"`{v['mode']}`, fit cohort {v['n_fit']}"],
                 ["held-out oracle, AGGREGATE", e(v["oracle_agg"], 4)],
                 [f"POD-{v['K']}, aggregate", e(v["podK_agg"], 4)],
                 ["required (POD-K / 3), aggregate", e(v["required_agg"], 4)],
                 ["gain, aggregate", f"{v['gain_agg']:.2f}x"],
                 ["held-out oracle, PER-CASE MEDIAN", e(v["oracle_median"], 4)],
                 [f"POD-{v['K']}, per-case median", e(v["podK_median"], 4)],
                 ["required (POD-K median / 3)", e(v["required_median"], 4)],
                 ["gain, per-case median", f"{v['gain_median']:.2f}x"],
                 ["held-out oracle, per-case max", e(v["oracle_max"], 4)],
                 ["**VERDICT**", "**PASS**" if v["passed"] else
                  "**FAIL -- PHASE 2b STOPS**"]]))
    print()

    print("Per mesh and per R, with both negative controls (all on the "
          "identical held-out cohort in the identical mass-weighted norm):\n")
    rows = []
    for r in Gc["S_RECON"]["rows"]:
        rows.append([r["N"], r["R"], r["K"], r["n_params"],
                     e(r["oracle"]["agg"]), e(r["oracle"]["median"]),
                     e(r["oracle"]["max"]),
                     e(r["oracle_train_cohort"]["agg"]),
                     e(r["pod_K"]["agg"]), e(r["pod_R"]["agg"]),
                     e(r["truncation_floor_agg"]),
                     f"{r['gain_over_podK_agg']:.2f}x",
                     f"{r['gain_over_podK_median']:.2f}x",
                     e(r["linear_control"]["agg"]),
                     e(r["untrained_control"]["agg"])])
    print(table(["N", "R", "K", "head params", "oracle agg", "oracle med",
                 "oracle max", "oracle (train cohort)", "POD-K", "POD-R",
                 "POD-R truncation floor", "gain agg", "gain med",
                 "NEG CTL linear head", "NEG CTL untrained head"], rows))
    print()

    print("### S-SELECT -- which training form, chosen on a VALIDATION cohort\n")
    print(table(["training form", "N", "R", "head params", "final rel-MSE",
                 "validation oracle (rel)", "validation oracle (median)",
                 "train s"],
                [[r["mode"], r["N"], r["R"], r["n_params"],
                  e(r["train_rel_mse"]), e(r["val_oracle_rel"]),
                  e(r["val_oracle_median"]), f"{r['seconds']:.0f}"]
                 for r in Gc["S_SELECT"]["rows"]]))
    print(f"\nselected: `{Gc['S_SELECT']['selected']}`\n")

    print("### S-METRIC / S-REGR / S-AFFINE -- the three supporting gates\n")
    rows = []
    for m, rg, a in zip(Gc["S_METRIC"]["rows"], Gc["S_REGR"]["rows"],
                        Gc["S_AFFINE"]["rows"]):
        rows.append([m["N"], e(m["identity_dev_max"]), e(m["perp_rel"]),
                     e(rg["dev_gated"]), e(rg["dev_R32"]),
                     e(rg["pod_raw_route"]["8"], 4),
                     e(rg["pod_certified"]["8"], 4),
                     e(a["affine_coeff_dev"]), e(a["budget"])])
    print(table(["N", "S-METRIC identity dev", "||perp||/||x|| at R=32",
                 "S-REGR worst dev (R<32)", "S-REGR dev at R=32 (recorded)",
                 "POD-8 here", "POD-8 certified (phase 2a)",
                 "S-AFFINE coeff dev", "its 1e-14 N^2 budget"], rows))
    print()

    # ========================================================== S4 =========
    print("### S4 -- the quadrature-free residual vs an INDEPENDENT full-grid path\n")
    print(table(["N", "R", "M", "states", "resid rel", "resid "
                 "cancellation-aware", "Jacobian cancellation-aware",
                 "pressure-elimination rung", "Phi vs matrix-free",
                 "NEG CTL even ghosts", "NEG CTL dropped mean",
                 "NEG CTL A + 1e-10"],
                [[r["N"], r["R"], r["M"], r["n_states"],
                  e(r["resid_rel_max"]), e(r["resid_canc_max"]),
                  e(r["jac_canc_max"]), e(r["press_elim_max"]),
                  e(r["phi_vs_matrixfree"]), e(r["ctl_evenghost"]),
                  e(r["ctl_dropped_mean"]), e(r["ctl_perturbed_A"])]
                 for r in Gm["S4"]["rows"]]))
    print()

    # ========================================================== S7 =========
    print("### S7 -- the three controls and the nonlinear arm (held-out error)\n")
    orc = {(x["N"], x["R"]): x["oracle"]["agg"]
           for x in Gc["S_RECON"]["rows"]}
    rows = []
    for r in Gm["S7"]["rows"]:
        er = r["err"]
        rows.append([r["N"], r["R"], r["M"],
                     e(er["nl_qf"]["agg"]), e(er["nl_qf"]["median"]),
                     e(er["podK"]["agg"]), e(er["podR_galerkin"]["agg"]),
                     e(er["gspan_direct"]["agg"]),
                     e(er.get("nl_qf_first8", {}).get("agg")),
                     e(er.get("nl_full", {}).get("agg")),
                     e(er.get("nl_eq", {}).get("agg")),
                     f"{r['lm_iters_median']:.0f}", r["rank_A"],
                     f(r["cond_A"], 2), e(orc.get((r["N"], r["R"])))])
    print(table(["N", "R", "M", "nonlinear QF", "nonlinear QF (median)",
                 "(a) POD-K", "(b) POD-R Galerkin", "(c) direct G-span",
                 "nonlinear QF, first 8 only", "nonlinear, full-grid residual",
                 "nonlinear, EQ residual", "LM iters (median, all starts)",
                 "rank A", "cond A",
                 "decoder reconstruction ceiling (oracle)"], rows))
    print("\nThe full-grid and EQ nonlinear arms run on the FIRST 8 held-out "
          "cases only, because each of their LM iterations is O(n_u); the "
          "quadrature-free arm is repeated on the same 8 for a like-for-like "
          "column.  They exist to show the residual DEFINITION agrees, not to "
          "add accuracy information.")
    print()

    # ========================================================== S6 =========
    print("### S6 -- online cost per query, balanced-order timing\n")
    keys = [("fom_backsub", "FOM back-substitution (as this cell's solver reports it)"),
            ("fom_backsub_bare", "FOM back-substitution, bare (no backward-error bookkeeping)"),
            ("rom_qf_nonlinear", "ROM, quadrature-free residual"),
            ("rom_fullgrid_nonlinear", "ROM, full-grid residual"),
            ("rom_eq_nonlinear", "ROM, EQ residual"),
            ("rom_gspan_direct", "direct G-span solve (S7c)"),
            ("rom_podK_direct", "POD-K direct solve (S7a)"),
            ("rom_podR_galerkin", "POD-R Galerkin (S7b)"),
            ("rom_qf_nonlinear_NONAFFINE",
             "ROM, quadrature-free, NON-AFFINE force (separate arm)")]
    rows = []
    for k, label in keys:
        row = [label]
        for r in Gm["S6"]["rows"]:
            t = r["times"].get(k)
            row.append(f"{t['median']*1e3:.3f}" if t else "-")
        rows.append(row)
    print(table(["ms per query"] + [f"N={r['N']}" for r in Gm["S6"]["rows"]],
                rows))
    print()
    print("Offline cost, and the EQ arm's setup, timed separately:\n")
    print(table(["N", "QF precompute (A, b_q, Phi^T M_u L ubar) s",
                 "EQ setup (design + greedy + NNLS) s", "FOM factorisation s",
                 "EQ machinery exactness (all faces, unit weights)",
                 "Phi^T M_u Grad p on FOM pressures (S3 field path)",
                 "affine-vs-physical force discrepancy"],
                [[r["N"], f(r["offline"]["qf_precompute_s"], 2),
                  f(r["offline"]["eq_setup_s"], 1),
                  f(r["offline"]["fom_factor_s"], 1),
                  e(r["eq"]["machinery_exact"]),
                  e(r["press_elim_fom_pressure"]),
                  e(r["nonaffine_force_discrepancy"])]
                 for r in Gm["S6"]["rows"]]))
    print()
    print("The EQ arm against node budget (the fitted rule is a MEASUREMENT, "
          "not a gate):\n")
    rows = []
    for r in Gm["S6"]["rows"]:
        for m, d in sorted(r["eq"]["budgets"].items(), key=lambda kv: int(kv[0])):
            rows.append([r["N"], d["m"], d["n_ext"],
                         f"{d['n_lattice_x']}/{d['n_lattice_y']}",
                         e(d["fit_residual"]), e(d["heldout_resid_err"]),
                         e(d["heldout_resid_err_med"]),
                         e(d["collapsed_A_err"]), e(d["w_min"]), e(d["w_max"])])
    print(table(["N", "nodes m", "stencil rows touched", "x/y lattice split",
                 "NNLS fit residual", "held-out residual err (max)",
                 "(median)", "||A_EQ - A||/||A||", "w min", "w max"], rows))
    print()

    # ========================================================== S8 =========
    print("### S8 -- the M ladder and the conditioning of A J_h(z)\n")
    print(table(["N", "R", "M", "M >= R", "rank(A J_h) min", "max",
                 "sigma_min/sigma_max (min)", "(median)", "states"],
                [[r["N"], r["R"], r["M"], r["M_ge_R"], r["AJ_rank_min"],
                  r["AJ_rank_max"], e(r["AJ_sv_ratio_min"]),
                  e(r["AJ_sv_ratio_median"]), r["n_states"]]
                 for r in Gm["S8"]["rows"]]))
    print()
    print("Near-collision conditioning -- the coincident-blob case is INCLUDED "
          "in the domain, not excluded (one M rung shown per mesh):\n")
    rows = []
    for r in Gm["S8"]["rows"]:
        if not r["near_collision"] or r["M"] != Cm["m_main"]:
            continue
        for d in r["near_collision"]:
            rows.append([r["N"], r["M"], f"{d['separation']:g}",
                         d["family_jacobian_rank"], e(d["family_sv_ratio"]),
                         d["AJ_rank"], e(d["AJ_sv_ratio"]),
                         e(d["rom_coeff_err"]), e(d["gspan_coeff_err"])])
    print(table(["N", "M", "blob separation", "family Jacobian rank",
                 "family sigma_min/sigma_max", "rank(A J_h)",
                 "A J_h sigma_min/sigma_max", "nonlinear ROM coeff err",
                 "direct G-span coeff err"], rows))
    print()

    # ========================================================== S9 =========
    print("### S9 -- the R frontier, K fixed at 8, against the M ladder\n")
    rows = []
    for r in Gm["S9"]["rows"]:
        if r["nl_qf"] is None:
            rows.append([r["N"], r["R"], r["M"], r["n_params"], "-", "-", "-",
                         "-", "-", "NOT RUN (M < R)"])
            continue
        rows.append([r["N"], r["R"], r["M"], r["n_params"],
                     e(r["truncation_floor"]), e(r["nl_qf"]["agg"]),
                     e(r["nl_qf"]["median"]), e(r["podK"]["agg"]),
                     e(r["gspan_direct"]["agg"]),
                     f"{r['lm_iters_median']:.0f}"])
    print(table(["N", "R", "M", "head params", "POD-R truncation floor",
                 "nonlinear QF (agg)", "(median)", "(a) POD-K",
                 "(c) direct G-span", "LM iters"], rows))
