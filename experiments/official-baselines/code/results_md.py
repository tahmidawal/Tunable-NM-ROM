"""RESULTS.md for the official CROM / CoLoRA lane, generated from saved JSON only.

  results_md.py --lane DIR --qs-summary PATH --nfrom-test PATH [--unmeasured JSON]

Reads: results/test/*.json (the single test64 evaluation per family), results/selection.json (frozen selection),
results/val/*.json and results/grid/*.json (validation), results/train/*.json, results/floor.json,
the query-speed lane's results/summary.json (our method and FNO/U-Net on test64, cited, not re-run) and the
nfrom-baseline lane's results/test.json (re-implementations, cited). --unmeasured: JSON list of
{"row": ..., "reason": ...} for families or rows that could not be evaluated faithfully.
"""
import argparse, glob, json, os


def f(x, d=3):
    if x is None:
        return '-'
    if x == float('inf'):
        return 'inf'
    return f'{x:,.0f}' if abs(x) >= 1000 else f'{x:.{d}f}'


def main():
    a = argparse.ArgumentParser()
    a.add_argument('--lane'); a.add_argument('--qs-summary'); a.add_argument('--nfrom-test'); a.add_argument('--unmeasured')
    a = a.parse_args()
    R = os.path.join(a.lane, 'results')
    L = []
    P = L.append
    P('# Official CROM and CoLoRA on Burgers 2D 256: test64 results')
    P('')
    P("Final numbers. The authors' released CROM and CoLoRA code (pinned commits, PROTOCOL.md section 2), trained once, "
      'selected on validation by the frozen rule of PROTOCOL.md (sections 4, 5.2; amendments A1, A2), then evaluated **once** on '
      'test64 = params_draw(20260916, 64). Generated by `code/results_md.py` from the JSON in `results/`; no number is typed by hand.')
    P('')
    P('Error metric (identical to the paper method\'s test64 numbers): per case $\\max_{k} \\lVert u(t_k)-u_{\\rm ref}(t_k)\\rVert_2 / '
      '\\lVert u_0\\rVert_2$ over the five output times $t_k = 0.05,\\dots,0.25$ on the $257^2$ grid, in float64 against the '
      '`fft_tight` backward-Euler reference; worst and median over the 64 cases, in percent. Time: batch-1 query, one process, '
      'synchronised, warm-up excluded.')
    P('')

    # ---------------- official test rows
    tests = []
    for p in sorted(glob.glob(os.path.join(R, 'test', '*.json'))):
        d = json.load(open(p))
        for r in d['results']:
            s = r['selection']
            if s.get('arm'):
                name = f"official CROM-{s['arm']} {s['name']} GN `{s['setting']}` ({s['role']})"
            else:
                name = f"official CoLoRA-D {s['name']} k={s.get('k')} ({s['role']})"
            tests.append(dict(name=name, dtype=s['dtype'], worst=r['test']['worst_percent'], median=r['test']['median_percent'],
                              nonfinite=r['test'].get('nonfinite', 0), ms=r['ms_full']['median'], p5=r['ms_full']['p5'], p95=r['ms_full']['p95'],
                              sched=f"{r['timing_warmup']} warm-up, {r['timing_repetitions']} x 64", val=s['worst_percent'],
                              job=d.get('job_id'), gpu=d.get('gpu'), file=os.path.relpath(p, a.lane)))
    unmeasured = json.load(open(a.unmeasured)) if a.unmeasured and os.path.exists(a.unmeasured) else []

    P('## Test64: official baselines next to the existing comparators')
    P('')
    P('| method | row | precision | worst % | median % | ms / query (median) | ms p5-p95 | GPU | source |')
    P('|---|---|---|---|---|---|---|---|---|')
    for t in tests:
        P(f"| official baseline | {t['name']} | {t['dtype']} | {f(t['worst'])} | {f(t['median'])} | {f(t['ms'], 2)} | "
          f"{f(t['p5'], 1)}-{f(t['p95'], 1)} | {t['gpu']} | job {t['job']}, `{t['file']}` |")
    for u in unmeasured:
        P(f"| official baseline | {u['row']} | - | unmeasured | unmeasured | unmeasured | - | - | {u['reason']} |")
    qs = json.load(open(a.qs_summary))['ftest64']
    src = 'b2d-query-speed `results/summary.json` (cited, not re-run): ' + qs['provenance']
    for r in qs['rows']:
        if r['role'] == 'accurate' and r.get('width') in (176, 192, 384):
            P(f"| paper method | width {r['width']}, accurate ({r['tag']}) | float32 | {f(r['worst'])} | {f(r['median'], 4)} | {f(r['ms'], 2)} | "
              f"{f(r['p05'], 2)}-{f(r['p95'], 2)} (case) | A100 80GB PCIe | job 7220630 |")
    for arm, nm in (('F0', 'FNO (F0), median of 3 seeds'), ('U0', 'U-Net (U0), median of 3 seeds')):
        m = qs['operators'][arm]
        P(f"| neural operator | {nm} | float32 | {f(m['worst'])} | {f(m['median'], 4)} | {f(m['ms'], 2)} | - | A100 80GB PCIe | job 7220630 |")
    if a.nfrom_test and os.path.exists(a.nfrom_test):
        d = json.load(open(a.nfrom_test))
        for r in d['results'][:4] + d['results'][6:8]:
            s = r['selection']
            P(f"| re-implementation | {'CROM' if s['arm'] == 'C' else 'CoLoRA'}-style k={s.get('k', 16)} {s['role']} | {s['dtype']} | {f(r['test']['worst_percent'])} | "
              f"{f(r['test']['median_percent'])} | {f(r['ms_full']['median'], 1)} | - | {d.get('gpu')} | nfrom-baseline job {d.get('job_id')} |")
    P('')
    P('Our-method and operator rows: ' + src + '.')
    P('')

    # ---------------- verdicts (computed, not typed)
    ours = {r['width']: r for r in qs['rows'] if r['role'] == 'accurate' and r.get('width') in (176, 192, 384)}
    P('## Head-to-head (computed from the rows above)')
    P('')
    P('Each official row against each paper-method accurate setting: "better"/"worse" on worst error, median error and time.')
    P('')
    P('| official row | vs width | worst | median | time |')
    P('|---|---|---|---|---|')
    cmp = lambda x, y: 'better' if x < y else ('worse' if x > y else 'equal')
    for t in tests:
        for w, r in sorted(ours.items()):
            P(f"| {t['name']} ({t['dtype']}) | {w} | {cmp(t['worst'], r['worst'])} ({f(t['worst'])} vs {f(r['worst'])}) | "
              f"{cmp(t['median'], r['median'])} ({f(t['median'])} vs {f(r['median'], 4)}) | {cmp(t['ms'], r['ms'])} ({f(t['ms'], 2)} vs {f(r['ms'], 2)} ms) |")
    P('')
    # ---------------- selection
    sel = json.load(open(os.path.join(R, 'selection.json')))
    P('## Frozen selection (validation only)')
    P('')
    P('| family | role | config | arm / GN setting | precision | val worst % | val median % | val rough ms |')
    P('|---|---|---|---|---|---|---|---|')
    for k in ('crom', 'colora'):
        for s in sel[k]:
            P(f"| {k} | {s['role']} | {s['name']} | {(s.get('arm') or 'hyper-network')} {s.get('setting') or ''} | {s['dtype']} | "
              f"{f(s['worst_percent'])} | {f(s['median_percent'])} | {f(s['rough_ms'], 1)} |")
    P('')
    P('## Validation (first 32 validation trajectories), every setting run')
    P('')
    P('| family | config | arm / setting | precision | cases | worst % | median % | rough ms / query | jobs |')
    P('|---|---|---|---|---|---|---|---|---|')
    for r in sel['all_crom_validation_rows']:
        lab = f"{r['cases'][1] - r['cases'][0]}" + ('' if r['complete'] else ' (partial: projected > 6 GPU-h)')
        P(f"| CROM | {r['name']} | {r['arm']} `{r['setting']}` {tuple(r['gn'])} | {r['dtype']} | {lab} | {f(r['worst_percent'])} | "
          f"{f(r['median_percent'])} | {f(r['rough_ms'], 0)} | {', '.join(r['jobs'])} |")
    for r in sel['all_colora_validation_rows']:
        P(f"| CoLoRA-D | {r['name']} (k={r['k']}) | hyper-network | {r['dtype']} | 32 | {f(r['worst_percent'])} | {f(r['median_percent'])} | "
          f"{f(r['rough_ms'], 2)} | - |")
    fl = json.load(open(os.path.join(R, 'floor.json')))
    P('')
    P(f"Network-free floor of CROM's released explicit integrator (forward Euler on the exact field, PROTOCOL 5.3, job {fl['job_id']}, "
      f"32 validation trajectories): worst {f(fl['worst_percent'])} %, median {f(fl['median_percent'])} % "
      f"(substeps per 0.005: {fl['substeps_per_0p005']['min']}-{fl['substeps_per_0p005']['max']}). CROM-E cannot go below this on this benchmark, whatever the training.")
    P('')
    P('## Offline training')
    P('')
    P('| run | steps | GPU | wall h | final training loss | job / notes |')
    P('|---|---|---|---|---|---|')
    for p in sorted(glob.glob(os.path.join(R, 'train', '*.json'))):
        t = json.load(open(p))
        P(f"| {t.get('name')} | {t.get('steps'):,} | {t.get('gpu')} | {f(t.get('train_seconds', 0) / 3600, 2)} | {f(t.get('loss_last_10pct'), 4)} | {t.get('job_id')}; {t.get('notes') or 'CoLoRA relative loss, mean of last 10 % of steps'} |")
    P('')
    # ---------------- paste-ready rebuttal text (numbers read from the rows above)
    def row(pred):
        x = [t for t in tests if pred(t)]
        return x[0] if x else None
    col = row(lambda t: 'CoLoRA-D K16-deep' in t['name'] and t['dtype'] == 'float32')
    d7 = row(lambda t: 'CoLoRA-D D7 ' in t['name'])
    ce = row(lambda t: 'CROM-E' in t['name'])
    ci = row(lambda t: 'CROM-I' in t['name'])
    w176, w384 = ours[176], ours[384]
    P('## Paste-ready rebuttal text')
    P('')
    txt = []
    if col:
        txt.append(f"We ran the authors' released CoLoRA code (data-driven variant, the only one released) on our Burgers 2D $256^2$ benchmark, "
                   f"selected its configuration on validation only and scored it once on the same 64 held-out test cases and A100 80GB GPU as our method: "
                   f"the selected $k=16$ model reaches {f(col['worst'], 2)} % worst / {f(col['median'], 2)} % median error at {f(col['ms'], 2)} ms per query "
                   f"(authors' default configuration: {f(d7['worst'], 2)} % / {f(d7['median'], 2)} %), versus {f(w176['worst'], 2)} % / {f(w176['median'], 2)} % at "
                   f"{f(w176['ms'], 2)} ms (width 176) and {f(w384['worst'], 2)} % / {f(w384['median'], 3)} % at {f(w384['ms'], 2)} ms (width 384) for ours.")
        txt.append("CoLoRA-D is given the five generating parameters of each case rather than the initial field, so it cannot be queried for an "
                   "initial condition outside that parametrisation; our method and CROM start from the initial field.")
    if ce and ci:
        txt.append(f"We also ran the authors' released CROM code: as released (explicit time stepping) its selected model reaches "
                   f"{f(ce['worst'], 1)} % worst / {f(ce['median'], 1)} % median at {f(ce['ms'] / 1000, 0)} s per query, and with its released Gauss-Newton solver "
                   f"applied to our backward-Euler residual {f(ci['worst'], 1)} % / {f(ci['median'], 1)} % at {f(ci['ms'] / 1000, 1)} s per query.")
    elif ci:
        txt.append(f"We also ran the authors' released CROM code with its released Gauss-Newton solver on our backward-Euler residual: "
                   f"{f(ci['worst'], 1)} % worst / {f(ci['median'], 1)} % median at {f(ci['ms'] / 1000, 1)} s per query; the as-released explicit variant is "
                   + '; '.join(u['reason'] for u in unmeasured) + '.')
    txt.append("Not measured: CoLoRA's equation-driven (Neural Galerkin) variant, whose code is not released; float32 variants of CROM, which "
               "fail on validation; and any configuration beyond the pre-declared grid (one training run per configuration, no tuning on test).")
    for t_ in txt:
        P(t_)
        P('')
    extra = os.path.join(R, 'notes.md')
    if os.path.exists(extra):
        P(open(extra).read())
    open(os.path.join(a.lane, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
